GLYPH_WIDTH = 5
GLYPH_HEIGHT = 7
GLYPH_ADVANCE = 6   # 5 列 + 1 列字距


def text_width(text: str, scale: int = 2) -> int:
    """文本像素宽度（scale=1 时为点阵原始宽度）。"""
    if not text:
        return 0
    return (len(text) * GLYPH_ADVANCE - 1) * scale


def text_height(scale: int = 2) -> int:
    """文本像素高度。"""
    return GLYPH_HEIGHT * scale


def draw_text(surface, text: str, x: int, y: int, color: Sequence[int],
              scale: int = 2) -> int:
    """把文本画到 surface 上，返回绘制后的右边界 x。

    只用整数常量与像素矩形，不依赖字体引擎 —— 同样的输入必得同样的像素。
    """
    import pygame  # 局部导入：本模块只被渲染层使用

    scale = max(1, int(scale))
    cursor = x
    for ch in text:
        glyph = _GLYPHS.get(ch)
        if glyph is None:
            glyph = _GLYPHS.get(ch.lower())
        if glyph is None:
            glyph = _GLYPHS["?"]
        for col, bits in enumerate(glyph):
            for row in range(GLYPH_HEIGHT):
                if bits & (1 << row):
                    pygame.draw.rect(
                        surface, color,
                        (cursor + col * scale, y + row * scale, scale, scale))
        cursor += GLYPH_ADVANCE * scale
    return cursor
