#!/usr/bin/env python3
"""register_crons.py — materialize cron schedules for this installation.

Reads cron-templates.json (next to this script's parent directory), replaces
every /ABSOLUTE/PATH/TO/swarm-arena placeholder with the real skill root,
writes register_crons.json beside it, and prints ready-to-paste crontab lines.

CLI: python3 register_crons.py [--write] [--user crontab]
"""

import argparse
import json
import os
import sys

PLACEHOLDER = "/ABSOLUTE/PATH/TO/swarm-arena"


def materialize(skill_root):
    templates_path = os.path.join(skill_root, "cron-templates.json")
    with open(templates_path) as f:
        templates = json.load(f)
    jobs = []
    for job in templates.get("jobs", []):
        jobs.append({
            "name": job.get("name"),
            "description": job.get("description"),
            "schedule": job.get("schedule"),
            "command": (job.get("command") or "").replace(PLACEHOLDER, skill_root),
            **({"alternate_schedules": job["alternate_schedules"]}
               if job.get("alternate_schedules") else {}),
        })
    return jobs


def crontab_lines(jobs, mode="paper"):
    lines = ["# swarmArena — generated by register_crons.py",
             "# Install with: crontab -e  (paste the lines below)",
             "# Ensure the host timezone matches your expectation (daily summary is meant for 00:00 UTC)."]
    for job in jobs:
        schedule = job["schedule"]
        alt = (job.get("alternate_schedules") or {})
        if mode == "paper" and alt.get("paper"):
            schedule = alt["paper"]
        lines.append("# [%s] %s" % (job["name"], job["description"] or ""))
        lines.append("%s %s" % (schedule, job["command"]))
    return lines


def main(argv=None):
    parser = argparse.ArgumentParser(description="Materialize cron schedule for this install")
    parser.add_argument("--write", action="store_true", default=True,
                        help="write register_crons.json (default)")
    parser.add_argument("--mode", default="paper", choices=("paper", "live"),
                        help="paper uses the gentler 5-minute scan cadence")
    parser.add_argument("--print-only", action="store_true",
                        help="only print crontab lines, do not write the file")
    args = parser.parse_args(argv)

    skill_root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    jobs = materialize(skill_root)

    if not args.print_only:
        out_path = os.path.join(skill_root, "register_crons.json")
        with open(out_path, "w") as f:
            json.dump({"skill_root": skill_root, "jobs": jobs}, f, indent=2)
            f.write("\n")

    print("\n".join(crontab_lines(jobs, mode=args.mode)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
