def meta_reflect():
    p = load_patterns()
    hist = p.get("strategy_history", [])
    if len(hist) < 1:
        print("ℹ️ 尚无足够历史做元反思，仅打印当前权重")
        print(json.dumps(p.get("meta_weights", {}), ensure_ascii=False, indent=2))
        return p
    # 统计：build 类是否比 repair 类更易产出让能力图增长？
    recent = hist[-3:]
    build_ok = sum(1 for h in recent if h.get("kind") == "build" and h.get("closed"))
    repair_ok = sum(1 for h in recent if h.get("kind") == "repair" and h.get("closed"))
    w = p.setdefault("meta_weights", {})
    # 若 build 成功率更高 -> 提升 web_trend_weight / novelty_bias
    if build_ok + repair_ok > 0:
        if build_ok >= repair_ok:
            w["web_trend_weight"] = round(min(0.9, w["web_trend_weight"] + 0.05), 2)
            w["novelty_bias"] = round(min(0.6, w["novelty_bias"] + 0.05), 2)
        else:
            w["local_gap_weight"] = round(min(0.8, w["local_gap_weight"] + 0.05), 2)
    save_patterns(p)
    print(f"🔄 元反思完成：build_ok={build_ok} repair_ok={repair_ok}")
    print("新权重：", json.dumps(w, ensure_ascii=False))
    return p


