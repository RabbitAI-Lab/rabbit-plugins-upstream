def record(move, effect, gap_id=None, closed=False, kind=None):
    p = load_patterns()
    entry = {
        "cycle": p["iterations"],
        "time": now_iso(),
        "move": move,
        "effect": effect,
        "gap_id": gap_id,
        "closed": closed,
        "kind": kind,
    }
    p.setdefault("strategy_history", []).append(entry)
    # 若缺口被关闭：写入持久化的 closed_gaps 集合（detect_gaps 会跳过，避免循环空转）
    if gap_id and closed:
        if isinstance(gap_id, dict):
            gap_id = gap_id.get("id") or gap_id.get("gap_id") or str(gap_id)
        cg = p.get("closed_gaps")
        if not isinstance(cg, list):   # self_patch#72：防 int/dict 误写致 append 崩溃
            cg = p["closed_gaps"] = []
        if gap_id not in cg:
            cg.append(gap_id)
    # 若缺口被关闭，更新 known_gaps 状态
    if gap_id:
        for g in p.get("known_gaps", []):
            if g["id"] == gap_id:
                g["status"] = "closed" if closed else g.get("status", "open")
    save_patterns(p)
    print(f"📝 已记录第 {entry['cycle']} 轮动作：{move} -> {effect}")
    return p


