def discover_teachers():
    """枚举可作为『教师』的其他模型/专家技能：有实质内容(SKILL.md + references/ 或
    scripts/ 或较长正文)，排除元进化自身、蒸馏技能与被蒸馏出的学生(meta-*)，避免自己教自己。"""
    teachers = []
    for md in glob.glob(os.path.join(SKILLS_DIR, "*", "SKILL.md")):
        skill = os.path.basename(os.path.dirname(md))
        if skill.startswith("_") or skill in ("meta-evolver", "model-distillation"):
            continue
        if skill.startswith("meta-"):
            continue  # 已是被蒸馏出的学生，不再当教师
        body = _read(md)
        has_refs = os.path.isdir(os.path.join(os.path.dirname(md), "references"))
        has_scripts = os.path.isdir(os.path.join(os.path.dirname(md), "scripts"))
        if len(body) < 800 and not (has_refs or has_scripts):
            continue  # 太薄，不值得蒸馏
        teachers.append({
            "name": skill,
            "size": len(body),
            "has_refs": has_refs,
            "has_scripts": has_scripts,
        })
    return teachers


