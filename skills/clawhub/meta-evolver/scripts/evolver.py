def sense():
    p = load_patterns()
    caps = {}
    for md in glob.glob(os.path.join(SKILLS_DIR, "*", "SKILL.md")):
        skill = os.path.basename(os.path.dirname(md))
        if skill.startswith("_"):
            continue
        lp = os.path.join(os.path.dirname(md), "learned_patterns.json")
        ops, fails, succ = 0, 0, 0.0
        if os.path.exists(lp):
            try:
                d = json.load(open(lp, encoding="utf-8"))
                ops = d.get("total_ops", 0)
                fails = d.get("total_fails", 0)
                succ = (ops - fails) / ops if ops else 0.0
            except Exception:
                pass
        body = ""
        try:
            body = open(md, encoding="utf-8").read().lower()
        except Exception:
            pass
        has_learner = os.path.exists(
            os.path.join(os.path.dirname(md), "scripts", "learner.py")
        )
        # 只跟踪本项目已接入自进化闭环(learner.py)的技能，避免把 400+ 生态市场技能
        # 当成待进化目标、导致无限灌 learner 的空转（这是此前"暂停感"的根因）
        if not has_learner:
            continue
        caps[skill] = {
            "ops": ops,
            "fails": fails,
            "success_rate": round(succ, 3),
            "has_learner": has_learner,
            # 记录正文，供 plan 阶段判断"是否已覆盖某能力"（避免重复构建）
            "body": body,
            "name_l": skill.lower(),
        }
    p["global_capabilities"] = caps
    p["last_sense"] = now_iso()

    # —— 自动对账：已解决的条件把陈旧 known_gaps 标记为关闭，避免 plan 在
    #    已解决的缺口上空转（这是此前"退化成 evolve 扩散空转"的根因之一）——
    closed = _closed_gap_ids(p)
    for g in p.get("known_gaps", []):
        gid = g["id"]
        if gid in closed or g.get("status") == "closed":
            continue
        kind = g.get("kind")
        if kind == "evolve":
            sk = gid.split(":", 1)[1] if ":" in gid else ""
            c = caps.get(sk)
            if c and c.get("has_learner"):
                g["status"] = "closed"
                closed.add(gid)
        elif kind == "repair":
            sk = gid.split(":", 1)[1] if ":" in gid else ""
            c = caps.get(sk)
            if c and c["ops"] >= 3 and c["success_rate"] >= 0.7:
                g["status"] = "closed"
                closed.add(gid)
    p["closed_gaps"] = list(closed)

    # 扫描本地已有工具二进制（自找资源的一部分）
    tools = scan_local_tools()
    p["resource_index"] = tools
    p["teacher_index"] = discover_teachers()  # 跨模型蒸馏：可蒸馏的教师源
    save_patterns(p)
    return p


def scan_local_tools():
    """在常见位置探测可用工具，作为后续构建技能时可复用的资源。"""
    candidates = {
        "7z": ["7z.exe", "7za.exe"],
        "unrar": ["unrar.exe", "UnRAR.exe"],
        "ffmpeg": ["ffmpeg.exe", "ffmpeg"],
        "pandoc": ["pandoc.exe", "pandoc"],
        "node": ["node.exe", "node"],
        "python": ["python.exe", "python3"],
    }
    roots = [os.path.expanduser("~"), "C:/", "D:/", os.path.expanduser("~/Downloads")]
    found = []
    for name, bins in candidates.items():
        hit = None
        for r in roots:
            for b in bins:
                cand = os.path.join(r, b)
                if os.path.exists(cand):
                    hit = cand
                    break
                # 一层子目录
                try:
                    for sub in os.listdir(r):
                        if os.path.isfile(os.path.join(r, sub, b)):
                            hit = os.path.join(r, sub, b)
                            break
                except Exception:
                    pass
            if hit:
                break
        if hit:
            found.append({"type": "binary", "name": name, "path": hit})
    return found


