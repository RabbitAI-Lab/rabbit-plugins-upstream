#!/usr/bin/env python3
"""
Paper Analyzer - extracts structure from downloaded PDFs.

Extraction is real: text is pulled from the PDF via pypdf (or PyPDF2/pymupdf
if installed). If a PDF cannot be parsed it is reported as UNEXTRACTABLE.
Nothing is invented: absent text yields an explicit gap, never a guess.

Usage:
    python paper_analyzer.py -i "./lit/*.pdf" --mode deep -o ./analysis
    python paper_analyzer.py -i ./lit --mode quick
"""

from __future__ import annotations

import argparse
import glob as globmod
import json
import re
import sys
from datetime import datetime
from pathlib import Path

SECTION_HINTS = {
    "contribution": r"contribut|our (?:main )?(?:result|approach)|we propose",
    "method": r"method|algorithm|approach|framework|formulation",
    "theory": r"theorem|lemma|proof|bound|regret|convergence|guarantee",
    "experiments": r"experiment|dataset|baseline|ablation|empirical",
    "limitations": r"limitation|future work|open problem|cannot|fail",
}

MATH_RE = re.compile(r"\\(?:begin\{(theorem|lemma|proposition|definition|corollary)\}|"
                     r"(?:mathbb|mathcal|mathbf)\{?[A-Za-z]\}?)")


def _loader():
    for mod in ("pypdf", "PyPDF2", "fitz"):
        try:
            return mod, __import__(mod)
        except ImportError:
            continue
    return None, None


def extract_text(path: Path, max_pages: int) -> tuple[str, int]:
    name, lib = _loader()
    if lib is None:
        raise RuntimeError("no PDF backend: install pypdf (pip install pypdf)")
    if name == "fitz":
        doc = lib.open(str(path))
        npages = doc.page_count
        chunks = [doc[i].get_text() for i in range(min(npages, max_pages))]
        return "\n".join(chunks), npages
    reader = lib.PdfReader(str(path))
    npages = len(reader.pages)
    chunks = [reader.pages[i].extract_text() or "" for i in range(min(npages, max_pages))]
    return "\n".join(chunks), npages


def guess_title(text: str, fallback: str) -> str:
    for line in text.splitlines()[:25]:
        s = line.strip()
        if 20 <= len(s) <= 160 and not s.lower().startswith(("abstract", "arxiv", "http")):
            return " ".join(s.split())
    return fallback


def analyse(text: str, path: Path, npages: int) -> dict:
    lower = text.lower()
    sections = {}
    for key, pat in SECTION_HINTS.items():
        hits = [m.start() for m in re.finditer(pat, lower)]
        sections[key] = {"mentions": len(hits), "present": len(hits) >= 3}
    symbols = sorted({s if isinstance(s, str) else s[0] for s in MATH_RE.findall(text)})
    words = len(text.split())
    return {
        "file": path.name,
        "pages": npages,
        "extracted_chars": len(text),
        "word_count": words,
        "title_guess": guess_title(text, path.stem),
        "sections": sections,
        "math_macros": symbols[:60],
        "has_theorem_env": any(t in text for t in
                               ("begin{theorem}", "begin{lemma}", "begin{proposition}")),
        "unextractable": words < 50,
    }


def render_md(r: dict) -> str:
    if r["unextractable"]:
        return (f"# {r['file']}\n\n"
                "**Status: UNEXTRACTABLE** - fewer than 50 words of text could be\n"
                "pulled from this PDF (most likely a scanned image).\n"
                "No content is inferred. Run OCR first.\n")
    lines = [f"# {r['title_guess']}", "",
             f"- File: `{r['file']}`",
             f"- Pages: {r['pages']}",
             f"- Extracted words: {r['word_count']}",
             f"- Formal theorem environment: {'yes' if r['has_theorem_env'] else 'no'}", "",
             "## Section signals (keyword frequency, not semantic judgement)", ""]
    for k, v in r["sections"].items():
        lines.append(f"- {k}: {v['mentions']} mentions"
                     f"{'  [likely present]' if v['present'] else ''}")
    if r["math_macros"]:
        lines += ["", "## Math macros detected", "",
                  ", ".join(f"`{m}`" for m in r["math_macros"][:40])]
    lines += ["", "---", "Auto-generated by phd-research-companion 2.4.0"]
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser(description="Analyse PDFs and extract paper structure")
    ap.add_argument("--input", "-i", nargs="+", required=True,
                    help="PDF paths, globs, or directories")
    ap.add_argument("--mode", choices=["quick", "deep"], default="quick")
    ap.add_argument("--output-dir", "-o", default="./analysis")
    ap.add_argument("--max-pages", type=int, default=12)
    args = ap.parse_args()

    paths: list[Path] = []
    for spec in args.input:
        p = Path(spec)
        if p.is_dir():
            paths += sorted(p.glob("*.pdf"))
        elif any(ch in spec for ch in "*?["):
            paths += [Path(x) for x in globmod.glob(spec)]
        elif p.exists():
            paths.append(p)
    paths = sorted(set(paths))

    if not paths:
        print("No PDF inputs matched.", file=sys.stderr)
        return 2

    out_dir = Path(args.output_dir).expanduser().resolve()
    out_dir.mkdir(parents=True, exist_ok=True)

    results, failed = [], []
    for p in paths:
        try:
            text, npages = extract_text(p, args.max_pages)
            r = analyse(text, p, npages)
            if args.mode == "deep":
                m = re.search(r"abstract\s*(.{200,1200}?)", text, re.I | re.S)
                r["abstract_guess"] = " ".join(m.group(1).split())[:900] if m else ""
            results.append(r)
            (out_dir / f"analysis-{p.stem}.md").write_text(render_md(r), encoding="utf-8")
            print(f"ok   {p.name} ({r['word_count']} words)")
        except Exception as e:  # noqa: BLE001
            failed.append(f"{p.name}: {type(e).__name__}: {e}")
            print(f"FAIL {p.name}: {e}", file=sys.stderr)

    if not results:
        print(f"\nNo PDF could be analysed. {len(failed)} failure(s):", file=sys.stderr)
        for f in failed:
            print(f"  - {f}", file=sys.stderr)
        return 2

    unex = [r["file"] for r in results if r["unextractable"]]
    matrix = ["# Analysis comparison matrix", "",
              f"Generated: {datetime.now().isoformat(timespec='seconds')}",
              f"Papers analysed: {len(results)} | failed: {len(failed)} | "
              f"unextractable: {len(unex)}", "",
              "| File | Pages | Words | Theorem env | Theory signal | Experiment signal |",
              "|---|---:|---:|:-:|---:|---:|"]
    for r in results:
        matrix.append(
            f"| {r['file']} | {r['pages']} | {r['word_count']} | "
            f"{'yes' if r['has_theorem_env'] else 'no'} | "
            f"{r['sections']['theory']['mentions']} | "
            f"{r['sections']['experiments']['mentions']} |")
    if unex:
        matrix += ["", "## Unextractable (likely scanned, OCR required)", ""]
        matrix += [f"- {u}" for u in unex]
    if failed:
        matrix += ["", "## Failures", ""] + [f"- {f}" for f in failed]
    (out_dir / "analysis-comparison-report.md").write_text("\n".join(matrix), encoding="utf-8")
    (out_dir / "analysis-index.json").write_text(
        json.dumps({"generated": datetime.now().isoformat(timespec="seconds"),
                    "results": results, "failures": failed}, indent=2), encoding="utf-8")

    print(f"\nAnalysed {len(results)} paper(s); {len(unex)} unextractable; {len(failed)} failed.")
    print(f"Report: {out_dir / 'analysis-comparison-report.md'}")
    return 0 if not (failed or unex) else 1


if __name__ == "__main__":
    sys.exit(main())
