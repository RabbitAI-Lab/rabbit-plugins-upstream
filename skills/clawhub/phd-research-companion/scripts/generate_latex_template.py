#!/usr/bin/env python3
"""
LaTeX Template Generator for Academic Papers

Emits LaTeX that actually compiles (plain-string templates with %%TOKEN%%
substitution -- deliberately NOT f-strings, which is what broke v1.x).

Supported venues: IEEEtran, ACM-Trans, NeurIPS, ICLR, JMLR, plain article.
Tracks: --track theory (proof-first skeleton) | empirical (experiment-first).

Usage:
    python generate_latex_template.py --journal JMLR --title "..." -a "A" -a "B" -o ./out
"""

from __future__ import annotations

import argparse
import sys
from datetime import datetime
from pathlib import Path

VENUES = {
    "ieee": {
        "documentclass": "IEEEtran",
        "options": "journal",
        "bib": "IEEEtran",
        "cite": r"\usepackage{cite}",
    },
    "acm": {
        "documentclass": "acmart",
        "options": "acmlarge,anonymous",
        "bib": "ACM-Reference-Format",
        "cite": "",
    },
    "neurips": {
        "documentclass": "article",
        "options": "",
        "bib": "plainnat",
        "cite": r"\usepackage[numbers]{natbib}",
        "pre": r"\usepackage[final]{neurips_2025}",
    },
    "iclr": {
        "documentclass": "article",
        "options": "",
        "bib": "plainnat",
        "cite": r"\usepackage[numbers]{natbib}",
        "pre": r"\usepackage{iclr2025_conference}",
    },
    "jmlr": {
        "documentclass": "jmlr2e",
        "options": "",
        "bib": "plainnat",
        "cite": r"\usepackage[numbers]{natbib}",
    },
    "article": {
        "documentclass": "article",
        "options": "11pt",
        "bib": "plain",
        "cite": "",
    },
}

VENUE_ALIASES = {
    "ieee-tifs": "ieee", "ieee-tip": "ieee", "ieee-tkde": "ieee",
    "ieee transaction": "ieee", "ieee": "ieee",
    "acm-tissec": "acm", "acm-tois": "acm", "acm": "acm",
    "neurips": "neurips", "nips": "neurips",
    "iclr": "iclr",
    "jmlr": "jmlr",
    "colt": "jmlr", "alt": "jmlr",
}

THEORY_BODY = r"""
\section{Preliminaries}

%% Notation table first: every symbol used later must appear here.
\begin{table}[t]
\centering
\caption{Notation used throughout the paper.}
\label{tab:notation}
\begin{tabular}{@{}ll@{}}
\toprule
Symbol & Meaning \\
\midrule
$\mathcal{X}$ & instance space \\
$\mathcal{H}$ & hypothesis class \\
$\eta$ & step size / learning rate \\
\bottomrule
\end{tabular}
\end{table}

\section{Main Result}

\begin{theorem}[Main theorem]
\label{thm:main}
%% state it
\end{theorem}

\begin{proof}
%% full proof, not a sketch
\end{proof}

\section{Proof Outline}
%% Dependency chain: Lemma -> Proposition -> Theorem.
%% Each numbered statement must be referenced at least once.

\section{Lower Bound / Tightness}
%% Required for CCF-A / JMLR: show the bound cannot be improved.

\appendix
\section{Deferred Proofs}
\section{Auxiliary Lemmas}
"""

EMPIRICAL_BODY = r"""
\section{Method}

\begin{algorithm}[t]
\caption{Proposed method}
\label{alg:main}
\begin{algorithmic}[1]
\STATE \textbf{Input}: data $\mathcal{D}$
\STATE \textbf{Output}: model $\hat{f}$
\end{algorithmic}
\end{algorithm}

\section{Experimental Setup}

\subsection{Datasets}
\subsection{Baselines}
\subsection{Metrics}

\section{Results}

\begin{table}[t]
\centering
\caption{Comparison against baselines.}
\label{tab:main}
\begin{tabular}{@{}lcc@{}}
\toprule
Method & Metric 1 & Metric 2 \\
\midrule
Baseline A & -- & -- \\
\textbf{Ours} & \textbf{--} & \textbf{--} \\
\bottomrule
\end{tabular}
\end{table}

\subsection{Ablation Study}
\subsection{Robustness Analysis}

\section{Limitations}

\appendix
\section{Additional Experimental Results}
"""

TEMPLATE = r"""%% %%TITLE%%
%% Generated by phd-research-companion %%VERSION%%
%% Venue: %%VENUE%%   Track: %%TRACK%%
%% Generated: %%DATE%%

\documentclass[%%OPTIONS%%]{%%CLASS%%}
%%PRE%%

\usepackage[T1]{fontenc}
\usepackage{amsmath,amssymb,amsthm,mathtools}
\usepackage{graphicx}
\usepackage{booktabs}
\usepackage[utf8]{inputenc}
\usepackage{hyperref}
%%CITE%%

\newtheorem{theorem}{Theorem}
\newtheorem{lemma}[theorem]{Lemma}
\newtheorem{proposition}[theorem]{Proposition}
\newtheorem{corollary}[theorem]{Corollary}
\theoremstyle{definition}
\newtheorem{definition}[theorem]{Definition}
\newtheorem{assumption}[theorem]{Assumption}

\title{%%TITLE%%}
\author{%%AUTHORS%%}

\begin{document}
\maketitle

\begin{abstract}
%%ABSTRACT%%
\end{abstract}

\begin{keywords}
%%KEYWORDS%%
\end{keywords}

\section{Introduction}
%% state the problem, the obstruction, and the contribution %%

\subsection{Contributions}
\begin{itemize}
\item Contribution 1.
\item Contribution 2.
\item Contribution 3.
\end{itemize}

\section{Related Work}
%% organise by methodology, not by chronology %%
%%BODY%%

\section{Conclusion}

\bibliographystyle{%%BIBSTYLE%%}
\bibliography{references}

\end{document}
"""


def resolve_venue(journal: str) -> str:
    key = (journal or "").strip().lower()
    if key in VENUES:
        return key
    for alias, target in VENUE_ALIASES.items():
        if alias in key:
            return target
    return "article"


class LaTeXTemplateGenerator:
    def __init__(self, output_dir: Path):
        self.output_dir = Path(output_dir)
        self.output_dir.mkdir(parents=True, exist_ok=True)

    def generate(self, venue: str, title: str, authors, track: str,
                 keywords: str, abstract: str) -> str:
        cfg = VENUES[resolve_venue(venue)]
        parts = []
        for i, a in enumerate(authors or ["Author One"]):
            parts.append(f"{a.strip()}\\thanks{{Affiliation / email.}}")
        author_block = " \\and ".join(parts) if len(parts) > 1 else parts[0]

        body = THEORY_BODY if track == "theory" else EMPIRICAL_BODY
        opts = cfg["options"] or ""

        out = TEMPLATE
        for token, value in [
            ("%%TITLE%%", title),
            ("%%VENUE%%", resolve_venue(venue)),
            ("%%TRACK%%", track),
            ("%%DATE%%", datetime.now().strftime("%Y-%m-%d")),
            ("%%OPTIONS%%", opts),
            ("%%CLASS%%", cfg["documentclass"]),
            ("%%PRE%%", cfg.get("pre", "")),
            ("%%CITE%%", cfg["cite"]),
            ("%%AUTHORS%%", author_block),
            ("%%ABSTRACT%%", abstract),
            ("%%KEYWORDS%%", keywords),
            ("%%BIBSTYLE%%", cfg["bib"]),
            ("%%BODY%%", body),
            ("%%VERSION%%", "2.4.0"),
        ]:
            out = out.replace(token, value)
        return out

    def save(self, content: str, filename: str) -> Path:
        p = self.output_dir / filename
        p.write_text(content, encoding="utf-8")
        return p

    def write_companion_files(self, filename: str, venue: str):
        bib = self.output_dir / "references.bib"
        if not bib.exists():
            bib.write_text(
                "%% Populate from 01-literature-survey/*.bibtex\n"
                "%% WARNING: entries must be verified against the source venue\n"
                "%% before submission. Unverified entries must be removed.\n",
                encoding="utf-8")
        req = self.output_dir / "template-requirements.md"
        cfg = VENUES[resolve_venue(venue)]
        req.write_text(
            "# Required to compile\n\n"
            f"- Main file: `{filename}`\n"
            f"- Document class: `{cfg['documentclass']}`\n"
            f"- Bibliography: `references.bib` with `\\bibliographystyle{{{cfg['bib']}}}`\n"
            "- Figures: vector (pdf/eps) at >= 300 DPI equivalent\n\n"
            "```bash\npdflatex -interaction=nonstopmode "
            f"{filename}\nbibtex {Path(filename).stem}\n"
            f"pdflatex -interaction=nonstopmode {filename}\n"
            f"pdflatex -interaction=nonstopmode {filename}\n```\n",
            encoding="utf-8")


def main() -> int:
    ap = argparse.ArgumentParser(
        description="Generate a compiling LaTeX skeleton for a target venue")
    ap.add_argument("--journal", "-j", default="article",
                    help="Target venue (IEEEtran, ACM, NeurIPS, ICLR, JMLR, article)")
    ap.add_argument("--title", "-t", default="Paper Title")
    ap.add_argument("--authors", "-a", nargs="+", default=["Author One"])
    ap.add_argument("--track", choices=["theory", "empirical"], default="theory",
                    help="theory = proof-first skeleton; empirical = experiment-first")
    ap.add_argument("--keywords", default="keyword one; keyword two")
    ap.add_argument("--abstract", default="TODO: 150-250 word abstract.")
    ap.add_argument("--output-dir", "-o", default=".")
    ap.add_argument("--filename", default="main.tex")
    args = ap.parse_args()

    gen = LaTeXTemplateGenerator(Path(args.output_dir).expanduser().resolve())
    content = gen.generate(args.journal, args.title, args.authors,
                           args.track, args.keywords, args.abstract)
    path = gen.save(content, args.filename)
    gen.write_companion_files(args.filename, args.journal)

    print(f"LaTeX template: {path}")
    print(f"Venue: {resolve_venue(args.journal)}  Track: {args.track}")
    print(f"Companion files: references.bib, template-requirements.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
