#!/usr/bin/env python3
"""
Proof Ledger - the dependency DAG of every claim in the paper.

A claim is one of: theorem, lemma, proposition, corollary, conjecture,
definition, assumption. Its status is one of:
    open        - stated, not proved
    conditional - proved only under an assumption that is itself open
    proven      - proved, with a pointer to the proof artifact
    refuted     - counterexample found

The ledger refuses to mark a claim `proven` unless every claim it depends on
is itself `proven`: no circular or unsupported promotion.

Usage:
    python proof_ledger.py --init 02-methodology-dev
    python proof_ledger.py -d 02-methodology-dev --add L1 lemma "bound on B1" --status proven \
        --proof proofs/lemma1.tex
    python proof_ledger.py -d 02-methodology-dev --add T1 theorem "main" --depends L1,L2
    python proof_ledger.py -d 02-methodology-dev --set T1 proven
    python proof_ledger.py -d 02-methodology-dev --report
"""

from __future__ import annotations

import argparse
import json
import sys
from datetime import datetime
from pathlib import Path

KINDS = ("theorem", "lemma", "proposition", "corollary",
         "conjecture", "definition", "assumption")
STATUSES = ("open", "conditional", "proven", "refuted")
TERMINAL_PROVEN = "proven"

FILE = "claims.json"


def load(ledger_dir: Path) -> dict:
    p = ledger_dir / FILE
    if not p.exists():
        return {"created": datetime.now().isoformat(timespec="seconds"), "claims": {}}
    return json.loads(p.read_text(encoding="utf-8"))


def save(ledger_dir: Path, data: dict) -> None:
    ledger_dir.mkdir(parents=True, exist_ok=True)
    (ledger_dir / FILE).write_text(json.dumps(data, indent=2), encoding="utf-8")


def deps_of(claim: dict) -> list[str]:
    return list(claim.get("depends_on") or [])


def find_cycles(claims: dict) -> list[list[str]]:
    cycles, seen = [], set()

    def walk(node, path):
        if node in path:
            cycles.append(path[path.index(node):] + [node])
            return
        if node in seen:
            return
        for d in deps_of(claims.get(node, {})):
            if d in claims:
                walk(d, path + [node])
        seen.add(node)

    for cid in claims:
        walk(cid, [])
    return [c for c in cycles if len(c) > 1]


def missing_deps(claims: dict) -> dict[str, list[str]]:
    return {cid: [d for d in deps_of(c) if d not in claims]
            for cid, c in claims.items() if any(d not in claims for d in deps_of(c))}


def unproven_support(claims: dict) -> dict[str, list[str]]:
    out = {}
    for cid, c in claims.items():
        bad = [d for d in deps_of(c)
               if d in claims and claims[d].get("status") != TERMINAL_PROVEN]
        if bad:
            out[cid] = bad
    return out


def report_markdown(data: dict) -> str:
    claims = data.get("claims", {})
    cycles = find_cycles(claims)
    miss = missing_deps(claims)
    unsup = unproven_support(claims)

    by_status = {s: [c for c in claims.values() if c.get("status") == s] for s in STATUSES}
    lines = ["# Proof Ledger", "",
             f"Generated: {datetime.now().isoformat(timespec='seconds')}",
             f"Claims: {len(claims)}", ""]
    for s in STATUSES:
        lines.append(f"- {s}: {len(by_status[s])}")
    lines.append("")

    if cycles:
        lines += ["## CIRCULAR DEPENDENCIES", ""]
        lines += ["- " + " -> ".join(c) for c in cycles]
        lines.append("")
    if miss:
        lines += ["## REFERENCES TO NON-EXISTENT CLAIMS", ""]
        for cid, ds in miss.items():
            lines.append(f"- {cid} depends on unknown: {', '.join(ds)}")
        lines.append("")

    lines += ["## Claims", "", "| ID | Kind | Status | Depends on | Proof artifact |",
              "|---|---|---|---|---|"]
    for cid in sorted(claims):
        c = claims[cid]
        lines.append(f"| {cid} | {c.get('kind','')} | {c.get('status','')} | "
                     f"{', '.join(deps_of(c)) or '-'} | {c.get('proof') or '-'} |")
    lines.append("")

    lines += ["## Statements", ""]
    for cid in sorted(claims):
        c = claims[cid]
        lines.append(f"### {cid} ({c.get('kind','')}) - {c.get('status','')}")
        lines.append(f"{c.get('statement','') or '_statement not recorded_'}")
        if c.get("proof"):
            lines.append(f"\nProof: `{c['proof']}`")
        lines.append("")

    lines += ["---", "Generated by phd-research-companion 2.4.0"]
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser(description="Claim ledger for a theory paper")
    # -p is accepted as an alias: `check`/`audit` use -p for the project dir
    ap.add_argument("-d", "-p", "--dir", default="02-methodology-dev")
    ap.add_argument("--init", action="store_true", help="initialise an empty ledger")
    ap.add_argument("--add", metavar="ID", help="add or replace a claim")
    ap.add_argument("--kind", choices=KINDS, default="lemma")
    ap.add_argument("--statement", default="")
    ap.add_argument("--depends", "--deps", default="",
                    help="comma-separated claim IDs")
    ap.add_argument("--status", choices=STATUSES, default="open")
    ap.add_argument("--proof", default="", help="path to proof artifact (tex/pdf)")
    ap.add_argument("--set", metavar="ID", dest="set_id", help="change status of a claim")
    ap.add_argument("--to", choices=STATUSES, dest="set_status")
    ap.add_argument("--report", action="store_true")
    ap.add_argument("--strict", action="store_true",
                    help="exit 1 if cycles, dangling deps, or unproven support exist")
    args = ap.parse_args()

    ledger_dir = Path(args.dir).expanduser().resolve()

    if args.init:
        ledger_dir.mkdir(parents=True, exist_ok=True)
        save(ledger_dir, {"created": datetime.now().isoformat(timespec="seconds"),
                          "claims": {}})
        print(f"initialised ledger at {ledger_dir / FILE}")
        return 0

    data = load(ledger_dir)

    if args.add:
        deps = [d.strip() for d in args.depends.split(",") if d.strip()]
        data["claims"][args.add] = {
            "kind": args.kind, "statement": args.statement,
            "depends_on": deps, "status": args.status,
            "proof": args.proof or None,
            "updated": datetime.now().isoformat(timespec="seconds"),
        }
        save(ledger_dir, data)
        print(f"claim {args.add} recorded ({args.kind}, {args.status})")
        return 0

    if args.set_id:
        if args.set_id not in data["claims"]:
            print(f"error: unknown claim {args.set_id}", file=sys.stderr)
            return 2
        new_status = args.set_status or data["claims"][args.set_id]["status"]
        if new_status == TERMINAL_PROVEN:
            blockers = [d for d in deps_of(data["claims"][args.set_id])
                        if d not in data["claims"]
                        or data["claims"][d].get("status") != TERMINAL_PROVEN]
            if blockers:
                print(f"refusing: {args.set_id} depends on unproven/unknown "
                      f"{', '.join(blockers)}", file=sys.stderr)
                print("mark it `conditional` instead, or prove the dependencies first.",
                      file=sys.stderr)
                return 1
        data["claims"][args.set_id]["status"] = new_status
        data["claims"][args.set_id]["updated"] = datetime.now().isoformat(timespec="seconds")
        save(ledger_dir, data)
        print(f"{args.set_id} -> {new_status}")
        return 0

    if args.report or not any([args.init, args.add, args.set_id]):
        out = ledger_dir / "proof-ledger.md"
        ledger_dir.mkdir(parents=True, exist_ok=True)
        out.write_text(report_markdown(data), encoding="utf-8")
        claims = data.get("claims", {})
        print(f"claims: {len(claims)}  "
              f"proven: {sum(1 for c in claims.values() if c.get('status')=='proven')}  "
              f"open: {sum(1 for c in claims.values() if c.get('status')=='open')}")
        print(f"report: {out}")
        problems = bool(find_cycles(claims) or missing_deps(claims)
                        or unproven_support(claims))
        return 1 if (args.strict and problems) else 0


if __name__ == "__main__":
    sys.exit(main())
