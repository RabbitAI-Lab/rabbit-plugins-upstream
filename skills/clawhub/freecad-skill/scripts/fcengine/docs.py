"""Markdown reference generated from the catalog (pure Python)."""

from __future__ import annotations

import json
from typing import List, Optional

from . import catalog

CATEGORY_TITLES = {
    "solid": "Solids",
    "profile": "Profiles",
    "partdesign": "PartDesign",
    "assembly": "Assemblies",
    "boolean": "Booleans",
    "feature": "Features",
    "pattern": "Patterns",
    "transform": "Transforms",
    "edit": "Editing",
    "query": "Queries",
    "output": "Output",
}


def _param_row(p: catalog.Param) -> str:
    constraints = []
    if p.choices:
        constraints.append(" \\| ".join(f"`{c}`" for c in p.choices))
    for key, sym in (("gt", ">"), ("ge", "≥"), ("le", "≤")):
        v = getattr(p, key)
        if v is not None:
            constraints.append(f"{sym} {v:g}")
    if p.min_items:
        constraints.append(f"≥ {p.min_items} items")
    if p.expr:
        constraints.append("`=expr` ok")
    default = "" if p.default is None else f"`{json.dumps(p.default)}`"
    req = "**yes**" if p.required else ""
    return f"| `{p.name}` | {p.type} | {req} | {default} | {'; '.join(constraints)} | {p.doc} |"


def op_markdown(op: catalog.Op) -> str:
    lines = [f"### `{op.name}`", "", op.summary, ""]
    lines += ["| Param | Type | Required | Default | Constraints | Description |", "|---|---|---|---|---|---|"]
    lines += [_param_row(p) for p in op.params]
    if op.one_of:
        lines += ["", "Give exactly one of: " + "; ".join(", ".join(f"`{x}`" for x in g) for g in op.one_of) + "."]
    if op.notes:
        lines += ["", op.notes]
    if op.example:
        lines += ["", "```json", json.dumps(op.example), "```"]
    return "\n".join(lines)


def operations_markdown(names: Optional[List[str]] = None) -> str:
    ops = catalog.OPS if not names else [catalog.OPS_BY_NAME[n] for n in names]
    out = [
        "# Operations reference",
        "",
        "<!-- Generated by `python3 scripts/fcskill.py describe --markdown`. Do not edit by hand. -->",
        "",
        'Units: millimetres and degrees. Every step is `{"op": "<name>", ...params}`; any step may add',
        '`"expect": {...}` (see [`check`](#check)) and `"comment"`.',
        "",
    ]
    for cat in catalog.CATEGORIES:
        group = [o for o in ops if o.category == cat]
        if not group:
            continue
        out += [f"## {CATEGORY_TITLES[cat]}", ""]
        for op in group:
            out += [op_markdown(op), ""]
    return "\n".join(out).rstrip() + "\n"


def summary_table() -> str:
    """One line per op, for SKILL.md."""
    rows = ["| Op | Purpose |", "|---|---|"]
    for op in catalog.OPS:
        rows.append(f"| `{op.name}` | {op.summary.split('. ')[0].rstrip('.')}. |")
    return "\n".join(rows)
