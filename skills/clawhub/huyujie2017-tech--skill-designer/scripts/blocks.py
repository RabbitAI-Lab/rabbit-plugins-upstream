def build_block(b: dict) -> str:
    def fmt_field(f: str) -> str:
        # 字段中以 # 开头表示小节标题，不作为列表项
        if f.lstrip().startswith("#"):
            return f
        # 缩进字段原样输出，作为上一项的子列表（如澄清协议四型）
        if f[:1].isspace():
            return f
        return f"- {f}"

    fields = "\n".join(fmt_field(f) for f in b["fields"])
    checks = "\n".join(f"- ☐ {c}" for c in b["checklist"])
    return f"""# {b['title']}

> 结构公式：`{b['formula']}`

## 填空字段

{fields}

## 验收 checklist

{checks}

> 填写说明与示例见 references/blueprint-template.md 对应小节。
"""
