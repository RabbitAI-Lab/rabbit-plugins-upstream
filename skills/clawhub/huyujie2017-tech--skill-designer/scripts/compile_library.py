#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""compile_library.py — 知识库编译器（ADR-001 阶段1 措施 1.2）

一句话
────────────────────────────────────────────────────────────────────
**权威源（library/*.json）→ 全部 markdown 视图（生成物）**。
从此「改一条条目要同步 5 处派生视图」这件事**在结构上不可能发生**——
因为 5 处视图全是本编译器的输出（DP-208 源头拦截 / DP-204 单一事实源）。

它消灭了什么（现状证据）
────────────────────────────────────────────────────────────────────
  · 条目库「四方一致性」（分片条数 = 视图一声明 = 速查表行数 = 头部计数）此前靠人工，
    已**复发三次**；本编译器把它变成每次运行的产物属性。
  · 速查表「支撑条目」列此前是**手写的旧编号缩写**（`D-027 404 405 407 409`），
    与条目区「来源」行是同一事实的两份手抄——现改为由 explains 生成。
  · 占位符残留、漏渲染 → **立即抛错**（拒绝静默产出半成品）。

两件必须分清的事（否则会给自己挖坑）
────────────────────────────────────────────────────────────────────
  **① 生成段 vs 静态段**：只有「派生数据」由本编译器生成（ID 列表 / 条数 / 速查表行 /
  支撑条目列 / 条目正文）。**人工润色的静态文案**（怎么用 / 标签体系 / 旧编号映射 /
  准入判据 / 注入协议 / DP 速查表其余三列）留在骨架里**逐字不动**——它们不是派生数据，
  把它们变成生成物 = 凭空扩大责任面，且会丢掉润色文案（= 功能减弱）。

  **② 规范化是**有意的**：生成物与旧 markdown 有两处系统差异，均为有意**——
    (a) 条目分隔统一为一个空行（旧文 `---` 与空行混用）；
    (b) 视图一/视图二/速查表里的 ID **不再加粗**（旧文用 `**D-127**` 标「新条目」）。
  理由：(b) 的加粗正是本项目记录过的 **grep 漏匹配坑源头**；「哪些是新增」由 ID 区间与
  CHANGELOG 承载，不该由排版承载。**内容零损失**（diff 分类可逐条核对）。

用法
────────────────────────────────────────────────────────────────────
    python scripts/compile_library.py --check          # 只核对，报 diff（默认）
    python scripts/compile_library.py --check --report outputs/compile-diff.txt
    python scripts/compile_library.py --write          # 写回全部生成物
    python scripts/compile_library.py --scan           # 只跑编译期扫描器（I3 / ID / 孤儿）
"""

