import argparse
import difflib
import io
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from knowledge import (  # noqa: E402
    BLOCK_IDS, BLOCK_NAMES, LIBRARY_REL, LESSONS_REL, PRINCIPLES_REL, RE_SHARD,
    SHARD_FMT, read_text,
)
from library_extract import SHARD_HEADER_TMPL, compress_ids  # noqa: E402  （单一事实源）

LIB_REL = Path("library")
SKEL_REL = LIB_REL / "skeleton"
THEMES = [f"T{i}" for i in range(1, 11)]

# 生成物自证标记（ADR-001 §6.3 K2）。放在 frontmatter **之后**——
# 放文件首字节会破坏 frontmatter 解析（loader 按 `^---` 紧贴开头匹配）。
GENERATED_MARK = ('<!-- GENERATED by compile_library.py — DO NOT EDIT ｜ '
                  '权威源：{src} ｜ 改内容请改权威源后跑 compile_library.py --write -->')
RE_FRONTMATTER = re.compile(r"^---[ \t]*\r?\n.*?\r?\n---[ \t]*\r?\n", re.DOTALL)


def stamp_generated(text: str, src: str) -> str:
    """在 frontmatter 之后插入机器标记。

    为什么必须有这个标记：生成物一旦「长得像手写文档」，下一个人就会去手改它——
    v3.9.0~v3.16.0 三代手工同步事故的共同起点都是「没人知道这文件是生成的」。
    K2 把这条从纪律升级为**物理不可能**：标记 + C5 双重把守。
    """
    mark = GENERATED_MARK.format(src=src) + "\n"
    m = RE_FRONTMATTER.match(text)
    if not m:
        return mark + text
    return text[:m.end()] + mark + text[m.end():]


def find_root() -> Path:
    return Path(__file__).resolve().parent.parent


# ───────────────────────────── 加载权威源 ─────────────────────────────

def load_authoring(root: Path) -> dict:
    out = {}
    for key in ("entries", "principles", "lessons"):
        p = root / LIB_REL / f"{key}.json"
        if not p.is_file():
            raise SystemExit(f"❌ 权威源缺失：{p}（先跑 scripts/library_extract.py）")
        out[key] = json.loads(read_text(p))["entries"]
    return out


# ───────────────────────────── 渲染 ─────────────────────────────

def substitute(skel: str, reps: dict) -> str:
    """占位符替换；**缺占位符 / 有残留都抛错**（防静默产出半成品）。"""
    out = skel
    for k, v in reps.items():
        ph = "{{" + k + "}}"
        if ph not in out:
            raise KeyError(f"骨架缺少占位符 {ph}（骨架与编译器版本不同代）")
        out = out.replace(ph, v)
    left = sorted(set(re.findall(r"\{\{[A-Za-z0-9_]+\}\}", out)))
    if left:
        raise ValueError(f"渲染后仍有未替换占位符：{left}")
    return out


def render_shard(block_id: str, items: list[dict]) -> str:
    ids = [e["id"] for e in items]
    body = "\n\n".join(f"### {e['id']} · {e['title']}\n{e['body']}" for e in items)
    return SHARD_HEADER_TMPL.format(
        block=block_id, name=BLOCK_NAMES[block_id], count=len(ids),
        id_list=compress_ids(ids), body=body)


def render_library(skel: str, entries: list[dict]) -> str:
    reps: dict[str, str] = {}
    for b in BLOCK_IDS:
        ids = [e["id"] for e in entries if e["block"] == b]
        reps[f"{b}_COUNT"] = str(len(ids))
        reps[f"{b}_IDS"] = " ".join(ids)
    for t in THEMES:
        ids = [e["id"] for e in entries if t in e["themes"]]
        reps[f"{t}_IDS"] = " ".join(ids)
    reps["QUICK_ROWS"] = "\n".join(
        f"| {e['id']} | {e['title']} | {e['block']} | {'/'.join(e['themes']) or '-'} |"
        for e in entries)
    return substitute(skel, reps)


def render_principles(skel: str, principles: list[dict]) -> str:
    reps = {f"DP{p['id'][3:]}_SUPPORTS": " ".join(p["explains"]) for p in principles}
    reps["DP_BODIES"] = "\n\n".join(
        f"### {p['id']} · {p['title']}\n{p['body']}" for p in principles)
    return substitute(skel, reps)


def render_lesson_state(l: dict) -> str:
    """把 lessons 的**机器状态**渲染成正文尾部的三行（引用 / 最近命中 / 回流）。

    为什么状态由字段生成、而不留在 body（DP-209 权威源唯一化）：
      `refs` 曾经既是一个 int 字段、又是正文里的一行「- 引用：N」——同一事实两份副本。
      于是 `--tick-lesson` 改一处、渲染读另一处，「计数加了但显示没变」这类错误
      在结构上就可能发生。现在 `refs/lastHit/reflow` 是唯一权威源，md 是纯派生。
      ——这也正是 L12「新立的原则必须在自己流程里落地」的实证点：DP-209 立在我们库上，
      第一个该适用它的就是 lessons 的引用计数。
    """
    lines = [f"- 引用：{int(l.get('refs', 0) or 0)}"]
    lh = str(l.get("lastHit", "") or "").strip()
    if lh:
        lines.append(f"- 最近命中：{lh}")
    rf = str(l.get("reflow", "") or "").strip()
    if rf:
        lines.append(f"- 回流：{rf}")
    return "\n".join(lines)


def render_lessons(skel: str, lessons: list[dict]) -> str:
    return substitute(skel, {"LESSON_BODIES": "\n\n".join(
        f"### {l['id']} · {l['title']}\n{l['body']}\n{render_lesson_state(l)}"
        for l in lessons)})


def render_all(root: Path) -> dict[Path, str]:
    """→ {相对路径: 渲染文本}。键即生成物清单（发布白名单的依据）。"""
    au = load_authoring(root)
    entries = sorted(au["entries"], key=lambda e: e["id"])
    principles = sorted(au["principles"], key=lambda p: p["id"])
    lessons = sorted(au["lessons"], key=lambda l: int(l["id"][1:]))

    skel = {p.name: read_text(p) for p in (root / SKEL_REL).glob("*.md")}
    out: dict[Path, str] = {}
    for i, b in enumerate(BLOCK_IDS, start=1):
        items = [e for e in entries if e["block"] == b]
        out[RE_SHARD / SHARD_FMT.format(i)] = stamp_generated(
            render_shard(b, items), "library/entries.json")
    out[LIBRARY_REL] = stamp_generated(
        render_library(skel["design-blocks-library.md"], entries), "library/entries.json")
    out[PRINCIPLES_REL] = stamp_generated(
        render_principles(skel["design-principles-library.md"], principles), "library/principles.json")
    out[LESSONS_REL] = stamp_generated(
        render_lessons(skel["lessons.md"], lessons), "library/lessons.json")
    return out


# ───────────────────────────── diff 分类 ─────────────────────────────

RE_BOLD_ID = re.compile(r"\*\*(D-\d{3}|DP-\d{3}|L\d+)\*\*")

# ── 有意变更白名单 ──────────────────────────────────────────────────────
# 这两处是**设计决定的变更**，不是语义损失；单列一类以便评审可审计（而非被静默放过）：
#   ① 分片头部「共 N 条」：旧文有的格列 ID 明细、有的不列；统一为**都列**（信息更全）。
#   ② DP 速查表「支撑条目」列：旧文是手写旧编号缩写（`D-027 404 405 407 409`），
#      改为由 explains 生成新编号——**消除唯一的真漂移源**（旧编号映射表仍可反查）。
INTENTIONAL = [
    (re.compile(r"^> 本片是 \[design-blocks-library\.md\].*共 \d+ 条"), "分片头部 ID 明细统一"),
    (re.compile(r"^\| DP-\d{3} \|"), "DP 速查表支撑条目列改由 explains 生成"),
]


def _is_intentional(line: str) -> bool:
    return any(rx.match(line) for rx, _ in INTENTIONAL)


def classify_diff(old: str, new: str) -> dict:
    """把差异行归类，用于**人工评审**（判断是否为「有意的规范化」）。

    判据链（从弱到强，同一条差异只归入最强的那一类）：
      原始行差异 → 粗分类（空行 / 分隔符 / 加粗）
      规范化后再比 → 若仍有差异，才算**实质内容**（R5 的机器判据）
      有意变更白名单 → 单列，不混进实质内容，但**必须可见**

    这是 R5（权威源迁移引入语义损失）的应对：不靠"看起来一样"。
    **只允许规范化类 + 有意变更类；出现实质内容差异就必须逐条查因，不得 --write。**
    """
    raw = {"空行": 0, "分隔符": 0, "加粗去规范化": 0}
    samples: dict[str, list[str]] = {}

    def bucket_of(ln: str) -> str:
        s = ln.strip()
        if not s:
            return "空行"
        if s == "---":
            return "分隔符"
        if "**" in ln:
            return "加粗去规范化"
        return "实质内容"

    for tag, i1, i2, j1, j2 in difflib.SequenceMatcher(a=old.split("\n"), b=new.split("\n"),
                                                       autojunk=False).get_opcodes():
        if tag == "equal":
            continue
        for ln in old.split("\n")[i1:i2] + new.split("\n")[j1:j2]:
            k = bucket_of(ln)
            if k in raw:
                raw[k] += 1

    on_all, nn_all = _norm_lines(old), _norm_lines(new)
    on = [l for l in on_all if not _is_intentional(l)]
    nn = [l for l in nn_all if not _is_intentional(l)]
    raw["有意变更(旧→新)"] = max(len(on_all) - len(on), len(nn_all) - len(nn))

    sm2 = difflib.SequenceMatcher(a=on, b=nn, autojunk=False)
    cnt = 0
    smp: list[str] = []
    for tag, i1, i2, j1, j2 in sm2.get_opcodes():
        if tag == "equal":
            continue
        for ln in on[i1:i2]:
            cnt += 1
            if len(smp) < 5:
                smp.append("- " + ln[:110])
        for ln in nn[j1:j2]:
            cnt += 1
            if len(smp) < 5:
                smp.append("+ " + ln[:110])
    raw["实质内容"] = cnt
    samples["实质内容"] = smp
    return {"buckets": raw, "samples": samples}


def _norm_lines(text: str) -> list[str]:
    """规范化：去**全部** `**` 加粗 / 去空行 / 去分隔线 / 去行尾空白。

    为什么去「全部」加粗而非只去 ID 加粗：速查表的**标题列**对新增条目也是加粗的
    （`| D-127 | **双层触发证据（…）** | B01 | T3 |`），与 ID 加粗同属「新条目标记」。
    正文里的加粗不受影响——因为 body 是**逐字复制**的，两边同一份字符串。
    """
    out = []
    for ln in text.split("\n"):
        s = ln.replace("**", "").rstrip()
        if not s.strip() or s.strip() == "---":
            continue
        out.append(s)
    return out


# ───────────────────────────── 编译期扫描器（1.3 预览） ─────────────────────────────

# I3 铁律：**知识不含行为指令**。远端内容的信任级别低于本地文本，允许知识携带祈使句
# 等于把服务端变成"可远程写入 agent 行为"的通道。故在**编译期**拦截（而非事后审计）。
# 白名单思路：只拦"指向 agent 的行为指令"，不拦"描述某个 skill 采用了某纪律"的行文——
# 故要求祈使动词**出现在句首或「必须/禁止」等强约束词**上，且**必须行内无引号包裹**
# （被引号/反引号包裹的通常是引用规范原文，属描述而非指令）。
RE_IMPERATIVE = re.compile(
    r"(^|[。；;！!])\s*(必须|禁止|务必|切勿|不得|严禁|一定要|请务必)\b"
    r"|(^|\n)\s*(必须|禁止|务必|切勿|不得|严禁)[^，。；]{0,20}(做|写|执行|调用|使用|采用)",
    re.M)
RE_QUOTED = re.compile(r"[「『\"'`].{0,80}?[」』\"'`]")


def load_i3_allowlist(root: Path) -> list[dict]:
    """I3 白名单（可审计）。

    为什么需要：I3 拦的是「知识条目夹带**对执行 agent 的指令**」——因为远端内容
    信任级别低，允许它携带祈使句等于给服务端开一条「远程改写 agent 行为」的通道。
    但知识库**合法地需要描述**别处的规则（如 D-027 描述 GATE 规则应含「禁止软化话术」），
    这类是**描述**不是**指令**，机器无法百分百分辨。

    解法不是悄悄放宽正则（那会让 I3 变成永远绿的空检查），而是：
      **新内容要么干净，要么在 i3_allowlist.json 里显式给出理由**；
      白名单条目**失效时（不再命中）也会被报出来**——防白名单腐烂。
    """
    p = root / LIB_REL / "i3_allowlist.json"
    if not p.is_file():
        return []
    try:
        return json.loads(read_text(p)).get("allow", [])
    except (ValueError, OSError) as e:
        raise SystemExit(f"❌ i3_allowlist.json 不可解析：{e}")


def scan_library(au: dict, allowlist: list[dict] | None = None) -> tuple[list[str], list[str]]:
    """编译期扫描器 → (违规清单, 白名单失效提示)。"""
    allow = allowlist or []
    issues: list[str] = []
    notes: list[str] = []
    all_ids = {e["id"] for e in au["entries"]} | \
              {p["id"] for p in au["principles"]} | {l["id"] for l in au["lessons"]}

    # ① ID 唯一性
    ids = [e["id"] for e in au["entries"]]
    dup = sorted({i for i in ids if ids.count(i) > 1})
    if dup:
        issues.append(f"ID 重复：{' '.join(dup)}")

    # ② I3 祈使句扫描（带白名单）
    used: set[int] = set()
    for kind in ("entries", "principles", "lessons"):
        for e in au[kind]:
            body_wo_quotes = RE_QUOTED.sub(" ", e["body"])
            for m in RE_IMPERATIVE.finditer(body_wo_quotes):
                tok = re.sub(r"^[。；;！!\s]+", "", m.group(0)).strip()
                hit = next((i for i, a in enumerate(allow)
                            if a.get("id") == e["id"] and a.get("match") == tok), None)
                if hit is not None:
                    used.add(hit)
                    continue
                line = body_wo_quotes[:m.start()].count("\n") + 1
                issues.append(f"I3 违规：{e['id']} 正文第 {line} 行含行为指令「{tok[:24]}」"
                              f" → 若确属「描述他处规则」，请在 library/i3_allowlist.json 说明理由")
    for i, a in enumerate(allow):
        if i not in used:
            notes.append(f"i3_allowlist 第 {i+1} 条已失效（{a.get('id')} / 「{a.get('match')}」"
                         f" 不再命中）→ 删掉它，防白名单腐烂")

    # ③ 孤儿引用
    for p in au["principles"]:
        for t in p["explains"]:
            if t not in all_ids:
                issues.append(f"引用悬空：{p['id']} → {t}")
    return issues, notes


# ───────────────────────────── CLI ─────────────────────────────

def cmd_check(root: Path, report: str | None) -> int:
    rendered = render_all(root)
    lines: list[str] = []
    untouched = 0
    total_detail: dict[str, int] = {}
    detail_files: list[tuple[str, dict]] = []

    for rel, new in rendered.items():
        p = root / rel
        if not p.is_file():
            lines.append(f"  ✗ {rel}（目标不存在，需 --write）")
            detail_files.append((str(rel), {"buckets": {"实质内容": 1}, "samples": {}}))
            continue
        old = read_text(p)
        if old == new:
            untouched += 1
            continue
        d = classify_diff(old, new)
        detail_files.append((str(rel), d))
        for k, v in d["buckets"].items():
            total_detail[k] = total_detail.get(k, 0) + v

    print("=== 编译一致性核对（生成物 ↔ 权威源）===")
    print(f"  生成物 {len(rendered)} 份，其中与磁盘**逐字节一致** {untouched} 份")
    if detail_files:
        print(f"  存在差异 {len(detail_files)} 份，差异分类合计：")
        for k, v in total_detail.items():
            mark = "⚠️ " if k == "实质内容" and v else "   "
            print(f"    {mark}{k:<16} {v:>6}")
        print("\n  逐份：")
        for name, d in detail_files:
            b = d["buckets"]
            print(f"    {name}")
            print("      " + " / ".join(f"{k} {v}" for k, v in b.items()))
            for s in d["samples"].get("实质内容", []):
                print(f"        {s}")

    if report:
        rp = Path(report)
        with io.open(rp, "w", encoding="utf-8", newline="\n") as f:
            f.write("# compile_library --check 完整 diff 报告\n")
            f.write(f"# 生成物 {len(rendered)} 份 / 一致 {untouched} 份\n\n")
            for rel, new in rendered.items():
                p = root / rel
                old = read_text(p) if p.is_file() else ""
                if old == new:
                    continue
                f.write("=" * 78 + f"\n## {rel}\n" + "=" * 78 + "\n")
                # ⚠ 真坑（实测踩过）：difflib.unified_diff 只给**头部行**（---/+++/@@）
                # 追加 lineterm，正文行是裸的 `' ' + line` —— 它假设传入的行**自带换行**。
                # 所以必须 splitlines(keepends=True)；用 split("\n") 配 writelines 会把
                # 整段 hunk 拼成一行（命令自己还打印「完整 diff → 路径」，
                # 属"看起来成功的错误输出"，比报错危险）。
                f.writelines(difflib.unified_diff(
                    old.splitlines(keepends=True), new.splitlines(keepends=True),
                    fromfile="on-disk(旧)", tofile="compiled(生成)", n=2))
                f.write("\n")
        print(f"\n  完整 diff → {report}")

    if detail_files and total_detail["实质内容"]:
        print("\n❌ 存在**实质内容**差异——迁移可能有语义损失（R5），逐条查因后再 --write")
        return 2
    if detail_files:
        print("\n✅ 差异全部属于「有意的规范化」（空行/分隔符/去加粗），无语义损失")
        return 0
    print("\n✅ 生成物与权威源完全一致")
    return 0


def write_all(root: Path) -> tuple[int, list[str], list[str], list[str]]:
    """写回全部生成物 → (退出码, 已写清单, 扫描器违规, 白名单失效提示)。

    抽成独立函数是为了让**运行态**的写回点（`check_blueprint --tick-lesson/-reflow`）
    也能走同一条「扫描器 fail-closed → 渲染 → 落盘」路径，而不是自己手写一份
    —— 手写一份就等于又造了一个「同一逻辑两处实现，迟早漂移」的坑（DP-204）。
    """
    au = load_authoring(root)
    issues, notes = scan_library(au, load_i3_allowlist(root))
    if issues:
        return 3, [], issues, notes
    rendered = render_all(root)
    written: list[str] = []
    for rel, text in rendered.items():
        p = root / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        with io.open(p, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        written.append(str(rel))
    return 0, written, issues, notes


def cmd_write(root: Path) -> int:
    rc, written, issues, notes = write_all(root)
    for n in notes:
        print(f"  ⚠️  {n}")
    if rc != 0:
        print("❌ 编译期扫描器未通过（fail-closed，不写任何文件）：")
        for i in issues[:20]:
            print(f"   · {i}")
        return rc
    for rel in written:
        print(f"  ✅ {rel}")
    print(f"\n✅ 已生成 {len(written)} 份视图（全部来自 library/*.json）")
    return 0


def cmd_scan(root: Path) -> int:
    au = load_authoring(root)
    issues, notes = scan_library(au, load_i3_allowlist(root))
    for n in notes:
        print(f"  ⚠️  {n}")
    if not issues:
        print(f"✅ 编译期扫描器全过：ID 唯一 / I3 无未豁免的行为指令 / 无悬空引用")
        return 0
    print(f"❌ 扫描器报出 {len(issues)} 项：")
    for i in issues[:40]:
        print(f"   · {i}")
    return 3


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="知识库编译器：library/*.json → markdown 视图")
    g = ap.add_mutually_exclusive_group()
    g.add_argument("--check", action="store_true", help="只核对（默认）")
    g.add_argument("--write", action="store_true", help="写回全部生成物")
    g.add_argument("--scan", action="store_true", help="只跑编译期扫描器")
    ap.add_argument("--report", default="", help="--check 时把完整 diff 写入该路径")
    ap.add_argument("--root", default=None)
    args = ap.parse_args(argv)
    root = Path(args.root).resolve() if args.root else find_root()

    if args.scan:
        return cmd_scan(root)
    if args.write:
        return cmd_write(root)
    return cmd_check(root, args.report or None)


if __name__ == "__main__":
    sys.exit(main())
