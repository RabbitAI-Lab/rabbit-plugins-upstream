@dataclass
class LawSuggestion:
    """法条建议"""
    law_name: str
    article_range: str = ""
    reason: str = ""
    priority: int = 0  # 越小越优先
    confidence: float = 0.0


def suggest_laws(cause: str, disputes: list = None, legal_issues: list = None) -> list:
    """
    根据案由 + 争议焦点，返回应引用的法条建议列表。
    
    Args:
        cause: 案由名称
        disputes: 争议焦点列表
        legal_issues: 法律争点列表
    
    Returns:
        list[LawSuggestion]: 按优先级排序的法条建议
    """
    suggestions = []
    
    # 1. 精确匹配案由
    if cause in CAUSE_LAW_MAP:
        for i, (law, articles, reason) in enumerate(CAUSE_LAW_MAP[cause]):
            suggestions.append(LawSuggestion(
                law_name=law,
                article_range=articles or "",
                reason=reason,
                priority=i,
                confidence=1.0,
            ))
    
    # 2. 模糊匹配（子串包含）
    if not suggestions:
        for cause_key, law_list in CAUSE_LAW_MAP.items():
            if cause_key in cause or cause in cause_key:
                for i, (law, articles, reason) in enumerate(law_list):
                    suggestions.append(LawSuggestion(
                        law_name=law,
                        article_range=articles or "",
                        reason=reason,
                        priority=i,
                        confidence=0.7,
                    ))
                break
    
    # 3. 关键词匹配（争议焦点→法条）
    if disputes or legal_issues:
        keywords = (disputes or []) + (legal_issues or [])
        keyword_law_hints = {
            "利率": [("民间借贷规定", "", "利率上限")],
            "利息": [("民间借贷规定", "", "利率"), ("民法典", "680", "禁止高利")],
            "交付": [("民法典", "595-646", "买卖合同"), ("民法典", "226-228", "交付")],
            "登记": [("民法典", "209-215", "不动产物权登记")],
            "抵押": [("民法典", "394-419", "抵押权")],
            "质押": [("民法典", "425-446", "质权")],
            "违约金": [("民法典", "585", "违约金")],
            "定金": [("民法典", "586-590", "定金")],
            "解除": [("民法典", "562-567", "合同解除")],
            "无效": [("民法典", "144-157", "民事法律行为效力")],
            "撤销": [("民法典", "147-151", "可撤销")],
            "赔偿": [("民法典", "1179-1187", "人身损害赔偿")],
            "精神损害": [("民法典", "1183", "精神损害赔偿")],
            "时效": [("民法典", "188-199", "诉讼时效")],
            "举证": [("民事诉讼法", "", "举证责任")],
            "鉴定": [("民事诉讼法", "", "鉴定")],
        }
        for kw in keywords:
            for pattern, laws in keyword_law_hints.items():
                if pattern in kw:
                    for law, articles, reason in laws:
                        # 避免重复
                        if not any(s.law_name == law for s in suggestions):
                            suggestions.append(LawSuggestion(
                                law_name=law,
                                article_range=articles,
                                reason=reason,
                                priority=100,
                                confidence=0.5,
                            ))
    
    # 4. 通用兜底（所有案件都可能用到的法条）
    universal_laws = [
        ("民事诉讼法", "", "程序法"),
    ]
    for law, articles, reason in universal_laws:
        if not any(s.law_name == law for s in suggestions):
            suggestions.append(LawSuggestion(
                law_name=law,
                article_range=articles,
                reason=reason,
                priority=200,
                confidence=0.3,
            ))
    
    # 按优先级排序
    suggestions.sort(key=lambda s: s.priority)
    return suggestions


def format_suggestions(suggestions: list) -> str:
    """格式化法条建议为可读文本"""
    if not suggestions:
        return "未找到匹配的法条建议"
    
    lines = ["📋 法条引用建议："]
    for i, s in enumerate(suggestions[:10], 1):  # 最多显示10条
        art = f"第{s.article_range}条" if s.article_range else ""
        conf = f"（置信度{s.confidence:.0%}）" if s.confidence < 1.0 else ""
        lines.append(f"  {i}. 《{s.law_name}》{art} — {s.reason}{conf}")
    
    if len(suggestions) > 10:
        lines.append(f"  ... 还有{len(suggestions) - 10}条建议")
    
    return "\n".join(lines)


