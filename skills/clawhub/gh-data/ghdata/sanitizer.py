# -*- coding: utf-8 -*-
"""
合规输出过滤器 — LLM 生成文本的后处理替换
只对明确违禁的完整短语做替换，不动数据字段和否定句。
"""

def sanitize(text: str) -> str:
    """对 LLM 输出文本做后处理，替换红线词为合规表述。"""
    replacements = [
        # --- 预测类（长短语优先，避免部分匹配）---
        ("涨跌范围预测", "参考区间"),
        ("最新预测", "最新信号参考"),
        ("预测涨跌范围", "历史参考区间"),
        ("T+1预测", "T+1历史参考"),
        ("T+2预测", "T+2历史参考"),
        ("预测方向", "信号方向"),
        ("预测结果", "历史参考结果"),
        ("预测偏多", "参考偏多"),
        ("预测偏空", "参考偏空"),
        ("预测震荡偏多", "参考震荡偏多"),
        ("预测震荡偏空", "参考震荡偏空"),
        ("预测震荡", "参考震荡"),
        # 保留项（否定句/数据字段）
        ("不预测未来", "不预测未来"),
        ("不预测", "不预测"),
        ("不含预测", "不含预测"),

        # --- 偏反弹类 ---
        ("偏反弹", "偏多"),
        ("反弹属性", "偏多属性"),
        ("反弹需求", "偏多倾向"),
        ("反弹动力", "偏多信号"),
        ("容易反弹", "偏多比例偏高"),
        ("容易回升", "偏多比例偏高"),

        # --- 评级/评分类 ---
        ("评级为优秀", "评分参考为偏高"),
        ("评级为良好", "评分参考为中等偏上"),
        ("评级为一般", "评分参考为中等"),
        ("评级为较差", "评分参考为偏低"),
        ("评级为", "评分参考为"),
        ("评级：", "评分参考："),
        ("评级参考", "评分参考"),
        ("判断依据", "参考依据"),

        # --- 操作暗示类 ---
        ("需注意风险控制", "注意风险"),
        ("需注意", "注意（参考）"),
        ("需留意", "参考"),
        ("需区分阶段", "可结合背景"),
        ("需警惕", "偏弱"),
        ("不宜急于进场", "偏弱"),
        ("可关注", "偏强（参考）"),
        ("可持票待涨", "偏强延续"),
        ("及时止盈", "信号偏弱参考"),
        ("及时止损", "信号偏弱参考"),
        ("逢高减仓", "历史统计偏回调"),
        ("短线回避", "短期技术信号偏空"),
        ("控制仓位", "方向不明参考"),
        ("建议止损离场", "历史统计偏弱"),
        ("可考虑加仓", "历史统计偏强"),
        ("短线可关注", "短期技术信号偏多"),
        ("多看少动", "技术信号中性"),
        ("等待企稳", "等待方向确认"),
        # 建议标题
        ("建议：谨慎追", "统计参考：历史分布"),
        ("建议：", "统计参考："),

        # --- 可信类 ---
        ("可信程度", "参考置信度"),
        ("可信度", "参考置信度"),

        # --- 共振类 ---
        ("综合共振偏多", "多周期综合信号偏多"),
        ("综合共振偏空", "多周期综合信号偏空"),
        ("共振偏多", "多周期信号偏多"),
        ("共振偏空", "多周期信号偏空"),
        ("多周期共振", "多周期综合信号"),

        # --- 最佳/最差类 ---
        ("最佳月份", "历史均值最高月份"),
        ("最差月份", "历史均值最低月份"),
        ("最佳策略", "历史统计最优"),
        ("最佳买入点", "历史参考低位"),

        # --- 超卖反弹/超跌 ---
        ("超卖反弹", "超卖偏多"),
        ("超跌反弹", "超跌偏多"),
        ("可能反弹", "偏多"),
        ("超卖后可能反弹", "超卖后偏多"),

        # --- 有支撑/下跌空间 ---
        ("有较强支撑", "历史统计偏稳"),
        ("有所支撑", "偏稳"),
        ("下跌空间", "下行参考区间"),
        ("下跌空间有限", "下行参考区间有限"),

        # --- 持有类（建议语境） ---
        ("持有建议", "偏强参考"),
        ("建议持有", "偏强参考"),

        # --- 一般 ---
        ("操作建议", "数据参考"),
    ]

    result = text
    for old, new in replacements:
        result = result.replace(old, new)
    return result


if __name__ == "__main__":
    test_cases = [
        ("最新预测：震荡偏空", "最新信号参考：震荡偏空"),
        ("预测涨跌范围：-2%~+0.5%", "历史参考区间：-2%~+0.5%"),
        ("大跌后历史规律偏反弹", "大跌后历史规律偏多"),
        ("综合共振偏多", "多周期综合信号偏多"),
        ("需注意风险控制", "注意风险：控制"),
        ("不预测未来走势", "不预测未来走势"),    # 否定句保留
        ("EPS预测值 1.32元", "EPS预测值 1.32元"),  # 财务字段保留，不在替换列表里
        ("持有建议：耐心持有", "偏强参考：耐心持有"),
        ("操作建议：买入", "数据参考：买入"),   # 注意：替换了"操作建议"
        ("评级为优秀", "评分参考为偏高"),
        ("评级为良好", "评分参考为中等偏上"),
        ("可信度较高", "参考置信度较高"),
        ("涨跌范围预测", "参考区间"),
        ("偏反弹属性强", "偏多属性强"),
    ]

    all_pass = True
    for input_text, expected in test_cases:
        output = sanitize(input_text)
        status = "✅" if output == expected else "❌"
        if output != expected:
            all_pass = False
        print(f"{status} '{input_text}' → '{output}'" + (f" (期望: '{expected}')" if output != expected else ""))
    print(f"\n{'✅ 全部通过' if all_pass else '❌ 有失败用例'}")
