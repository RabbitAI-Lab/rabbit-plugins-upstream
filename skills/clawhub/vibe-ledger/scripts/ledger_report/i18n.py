def probe_message(message: str, lang: str) -> str:
    """A probe finding's message in the page language (the probes write English)."""
    if lang != "zh":
        return message
    core, suffix = message, ""
    if message.endswith(_CREDENTIALS_EN):
        core, suffix = message[:-len(_CREDENTIALS_EN)], "，而且会带上访问者的 cookie 和登录凭据"
    for rx, template in PROBE_ZH:
        m = rx.match(core)
        if m:
            parts = m.groupdict()
            if "who" in parts:
                parts["who"], parts["perms"] = _WHO[parts["who"]], _PERMS[parts["perms"]]
            return template.format(**parts) + suffix
    return message
