SCENE_BY_QUARTER = {0: "S1", 1: "S2", 2: "S3", 3: "S4"}


def build(ep: int):
    spec = EPS[ep]
    raw = spec["lines"]
    n = len(raw)
    step = n / 4.0

    lines = []
    for i, (spk, text, emo, sfx) in enumerate(raw):
        lines.append(
            {
                "seq": i + 1,
                "speaker": spk,
                "type": "narration" if spk == "旁白" else "dialogue",
                "text": text,
                "emotion": emo,
                "sfx": sfx,
                "scene": SCENE_BY_QUARTER[min(3, int(i / step))],
            }
        )

    zooms = {"S1": 0.88, "S2": 0.98, "S3": 0.92, "S4": 0.95}
    titles = {"S1": "宣布规则", "S2": "开始执行", "S3": "升级", "S4": "反转"}
    scenes = []
    for sid in ("S1", "S2", "S3", "S4"):
        scenes.append(
            {
                "id": sid,
                "title": titles[sid],
                "background": "会议室",
                "actors": ["阿强", "老板"],
                "camera": {"x": 0.5, "y": 0.52, "zoom": zooms[sid]},
                "positions": {"阿强": 0.29, "老板": 0.70},
            }
        )

    script = {
        "title": spec["title"],
        "season": 1,
        "episode": ep,
        "durationTarget": spec["durationTarget"],
        "hook": spec["hook"],
        "reversal": spec["reversal"],
        "unsaid": spec["unsaid"],
        "characters": [
            {"name": "阿强", "persona": "认真的执行者", "voice": "云希-清亮少年", "gender": "male"},
            {"name": "老板", "persona": "一本正经定离谱规则", "voice": "云扬-沉稳男声", "gender": "male"},
        ],
        "scenes": scenes,
        "lines": lines,
    }

    md = [
        f"# 第0{ep}集：{spec['title']}",
        "",
        f"> 抖音 / 9:16 / 目标 {spec['durationTarget']}s / 2 角色 / 1 场景（会议室固定）",
        "",
        "## 一、本集目标",
        "",
        f"- 钩子：{spec['hook']}",
        f"- **说不出口的那句话：{spec['unsaid']}**",
        f"- 反转：{spec['reversal']}",
        "- 结尾：一句冷幽默 + 黑屏字幕",
        "",
        "## 二、四段式",
        "",
        "| 段 | 内容 |",
        "|---|---|",
        "| 钩子 | 老板宣布离谱规则 |",
        "| 执行 | 阿强一本正经照做，出现第一个离谱结果 |",
        "| 升级 | 结果失控，老板自己被卷进来 |",
        "| 反转 | 老板先翻车，阿强把那句话说出口 |",
        "",
        "## 三、角色表",
        "",
        "| 角色 | 干什么 | 音色 |",
        "|---|---|---|",
        "| 老板 | 一本正经定规则，真心觉得合理 | 云扬-沉稳男声 |",
        "| 阿强 | 一本正经执行，全程不吐槽 | 云希-清亮少年 |",
        "",
        "## 三点五、场景表",
        "",
        "| 场景 | 地点 | 出场角色 | 镜头 |",
        "|---|---|---|---|",
        "| S1 | 宣布规则 | 阿强、老板 | 双人全景 |",
        "| S2 | 开始执行 | 阿强、老板 | 双人中景 |",
        "| S3 | 升级 | 阿强、老板 | 双人中景 · 略推 |",
        "| S4 | 反转 | 阿强、老板 | 双人近景 |",
        "",
        "## 四、台词表",
        "",
        "| 序号 | 角色 | 台词 | 情绪 | 音效 | 场景 |",
        "|---|---|---|---|---|---|",
    ]
    for l in lines:
        md.append(f"| {l['seq']} | {l['speaker']} | {l['text']} | {l['emotion']} | {l['sfx']} | {l['scene']} |")

    (BASE / "剧本.json").write_text(json.dumps(script, ensure_ascii=False, indent=2), encoding="utf-8")
    (BASE / f"第0{ep}集.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    (BASE / f"第0{ep}集.json").write_text(json.dumps(script, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"✓ 第0{ep}集《{spec['title']}》 {len(lines)} 句 / 说不出口：{spec['unsaid']}")


if __name__ == "__main__":
    build(int(sys.argv[1]))
