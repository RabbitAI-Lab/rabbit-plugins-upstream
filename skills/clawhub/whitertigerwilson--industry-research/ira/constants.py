def find_commodity(commodity: str) -> list[tuple]:
    """
    按商品名称查找股票池。

    支持模糊匹配：
    - 完全匹配："铜"
    - 子串匹配："白" 可匹配 "白酒"
    """
    commodity = commodity.strip()
    # 1. 完全匹配
    if commodity in KNOWN_MAP:
        return KNOWN_MAP[commodity]
    # 2. 子串匹配
    matches = []
    for key, stocks in KNOWN_MAP.items():
        if commodity in key or key in commodity:
            matches.extend(stocks)
    return matches


