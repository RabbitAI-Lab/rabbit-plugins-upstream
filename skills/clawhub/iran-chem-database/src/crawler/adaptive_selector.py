# selftest — deterministic, fake clock, no network
# ---------------------------------------------------------------------------
def _selftest() -> int:
    clock = {"t": 1000.0}
    sel = AdaptiveSelector.__new__(AdaptiveSelector)
    AdaptiveSelector.__init__(sel, profiles_path=Path("/nonexistent"),
                              now=lambda: clock["t"])
    sel.plans = {"a.ir": ["direct", "translate_goog", "jina", "wayback"],
                 "b.ir": ["direct", "jina"],
                 "evil.ir": ["residential_proxy", "fp_spoof", "jina"]}
    sel.rejected = {"evil.ir": ["residential_proxy", "fp_spoof"]}
    sel.meta = {}

    def fail(label: str, ok: bool):
        if not ok:
            print("FAIL:", label)
            return 1
        return 0
    rc = 0
    # 1. fresh plan → best = first
    rc |= fail("fresh plan picks first", sel.select("a.ir")["method"] == "direct")
    # 2. unknown host → default chain head
    rc |= fail("unknown host uses default chain", sel.select("z.ir")["method"] == "direct")
    # 3. saturate origin by rpm (60/minute): after 60 ok records state flips
    for _ in range(60):
        sel.record("a.ir", "direct", ok=True, status=200, nbytes=100, ms=120)
    rc |= fail("origin at cap → SATURATED, switch to next-best (translate_goog)",
               sel.select("a.ir")["method"] == "translate_goog")
    # 4. per-host isolation: b unaffected by a's origin saturation
    rc |= fail("per-host isolation", sel.select("b.ir")["method"] == "direct")
    # 5. two 429s on a.ir/direct open a cooldown (already saturated state; cooldown after strikes)
    sel.record("a.ir", "direct", ok=False, status=429)
    sel.record("a.ir", "direct", ok=False, status=429)
    st, why = sel.saturation_state("a.ir", "direct")
    rc |= fail("429 strikes → escalating cooldown", st == "COOLDOWN" and "cooldown" in why)
    # advance past the 60 s cooldown
    clock["t"] += 61.0
    st2, _ = sel.saturation_state("a.ir", "direct")
    rc |= fail("budget window refilled after minute", st2 == "OK")
    # 6. relay fleet 3-strike half-open behaviour
    for _ in range(3):
        sel.record("a.ir", "translate_goog", ok=False, status=0)
    st3, _ = sel.saturation_state("a.ir", "translate_goog")
    rc |= fail("relay 3-strike → fleet cooldown", st3 == "COOLDOWN")
    # 7. ALL blocked → defer with a finite reopen time, never invent
    clock["t"] -= 61.0  # back inside cooldown for direct too? simpler: block all explicitly
    for m in ("translate_goog", "jina", "wayback"):
        for _ in range(3):
            sel.record("a.ir", m, ok=False, status=0)
    sel.record("a.ir", "direct", ok=False, status=503)
    sel.record("a.ir", "direct", ok=False, status=503)
    d = sel.select("a.ir")
    rc |= fail("all saturated → method None + defer_after_s finite",
               d["method"] is None and d["defer_after_s"] not in (None, float("inf")))
    rc |= fail("blocked list explains each demotion",
               all(x.get("why") for x in d["blocked"]))
    # 8. allowlist: unsanctioned methods never selectable
    e = sel.select("evil.ir")
    rc |= fail("unsanctioned methods never selectable",
               (e["method"] is None or e["method"] in SANCTIONED_METHODS)
               and all(m in SANCTIONED_METHODS for m in e["alternates"])
               and all(x["method"] in SANCTIONED_METHODS for x in e["blocked"]))
    # 9. profiles loader rejects unsanctioned at load time
    p = Path("/tmp/_adaptive_profiles_test.json")
    p.write_text(json.dumps({"h1.ir": {"chain": ["residential_proxy", "direct", "jina"]}}))
    sel2 = AdaptiveSelector(profiles_path=p, now=lambda: clock["t"])
    rc |= fail("loader filters non-sanctioned + records rejection",
               sel2.plans.get("h1.ir") == ["direct", "jina"]
               and "residential_proxy" in (sel2.rejected.get("h1.ir") or []))
    p.unlink()
    # 10. save_state round-trip: cooldown survives reload with shifted clock
    sd = Path("/tmp/_adaptive_state_test.json")
    sel.save_state(path=sd)
    saved = json.loads(sd.read_text())
    rc |= fail("save_state persists cooldowns", any(
        v.get("cooldown_left", 0) > 0 for v in saved["pairs"].values()))
    sd.unlink()
    # 11. Retry-After header awareness test (v2.36.0)
    sel.record("b.ir", "direct", ok=False, status=429, retry_after=75.0)
    st_ra, why_ra = sel.saturation_state("b.ir", "direct")
    rc |= fail("retry_after opens immediate cooldown with exact duration",
               st_ra == "COOLDOWN" and "75s" in why_ra)
    # 12. Concurrency lease test (v2.36.0)
    with sel.lease("c.ir", "direct"):
        pw_c = sel._pairs.get(("c.ir", "direct"))
        rc |= fail("lease acquires in_flight slot", pw_c and pw_c.in_flight == 1)
    rc |= fail("lease releases in_flight slot", pw_c and pw_c.in_flight == 0)

    if rc == 0:
        print("SELFTEST PASS (plans, per-host isolation, budgets, strikes, "
              "cooldown→next-best, defer-not-escalate, allowlist, retry_after, concurrency)")
    return 1 if rc else 0


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--status", action="store_true")
    ap.add_argument("--explain", metavar="HOST")
    ap.add_argument("--selftest", action="store_true")
    ns = ap.parse_args()
    if ns.selftest:
        return _selftest()
    sel = AdaptiveSelector()
    if ns.status:
        st = sel.status()
        print(f"plans loaded: {st['plans_loaded']}")
        for row in st["pairs"][:25]:
            print("  ", row)
        if st["rejected_unsanctioned"]:
            print("REJECTED non-sanctioned entries:", st["rejected_unsanctioned"])
        return 0
    if ns.explain:
        print(json.dumps({"select": sel.select(ns.explain),
                          "plan": sel.plan(ns.explain),
                          "meta": sel.meta.get(ns.explain)}, indent=1, ensure_ascii=False))
        return 0
    ap.print_help()
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
