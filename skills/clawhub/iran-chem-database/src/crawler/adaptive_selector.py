#!/usr/bin/env python3
"""Adaptive per-site method selector with saturation awareness — v2.36.1.

Contract, per the user's Round-12 requirement:

  1. EVERY host gets a PERSONAL method chain — the exact ordered techniques
     that empirically work on THAT site (from ``data/site_profiles.json``,
     generated by ``src/crawler/site_profiler.py`` against live seeds).
  2. When the technique currently being pushed on a host hits its capacity —
     rate-limited (429/503), timing out, Retry-After header signaled, or its
     measured bytes/rpm/concurrency budget is exhausted — the selector DEMOTES
     it for that host with an escalating cooldown (60→120→300 s, half-open
     probe after) and switches to the NEXT BEST sanctioned option for THAT
     SAME SITE. Per-host isolation: host A saturating translate_goog does not
     re-plan host B.
  3. When every option for a host is saturated, the crawl DEFERS that host to
     the earliest reopen time. It does NOT escalate. The method universe is a
     hard allowlist — anything not in it is refused at load time with a logged
     reason, so no future code path can "discover" WAF defeats, fingerprint
     spoofing, origin-IP exposure or residential relays through this selector.

Shared-relay fairness: relays (translate_goog, jina, …) are public services;
their saturation budget is tracked GLOBALLY per method (aggregate rpm & concurrency),
while origin-direct budgets are tracked per host (1 rps, size-capped). A relay
going fleet-wide saturated demotes it in every plan — which is exactly what
``tools/relay_liveness.py`` does between runs, at minute resolution.

    python3 -m src.crawler.adaptive_selector --status
    python3 -m src.crawler.adaptive_selector --explain kimyapardazan.com
    python3 -m src.crawler.adaptive_selector --selftest
"""
from __future__ import annotations

import argparse
import contextlib
import json
import threading
import time
from collections import deque
from pathlib import Path
from typing import Callable, Optional

ROOT = Path(__file__).resolve().parents[2]
PROFILES = ROOT / "data" / "site_profiles.json"
STATE = ROOT / "data" / "adaptive_state.json"

# Hard allowlist. This is POLICY, enforced in code (docs/RELAY_INTEGRITY_ROUND10.md
# §5). New relay classes only enter through a release that measures them first.
SANCTIONED_METHODS = frozenset({
    "direct",  # polite origin fetch (robots-aware), only when profile says reachable
    "translate_goog", "amp_cache", "microlink", "jina", "wayback", "spn2",
    "commoncrawl", "arquivo_pt", "cors_proxy", "cloud_egress", "translate",
    "archivetoday", "bing_cache", "yandex_cache",  # last two: measured dead, tail-only
})
RELAY_METHODS = SANCTIONED_METHODS - {"direct"}

DEFAULT_CHAIN = ["direct", "translate_goog", "amp_cache", "microlink", "jina",
                 "commoncrawl", "arquivo_pt", "cors_proxy", "wayback", "spn2",
                 "translate", "archivetoday"]

# budgets: (max requests/minute, max bytes/minute)
BUDGET_ORIGIN = (1 * 0 + 60, 600_000)   # 60 rpm would be rude; 1 rps cap → 60, bytes 600 kB/min
BUDGET_RELAY = (90, 3_000_000)          # per relay fleet, aggregate across hosts
COOLDOWNS = (60.0, 120.0, 300.0)        # escalating, per (host, method) pair
SOFT_FRAC = 0.8

# Concurrency limits per method
CONCURRENCY_CAPS = {
    "direct": 2,
    "translate_goog": 6,
    "jina": 3,
    "wayback": 5,
    "commoncrawl": 6,
    "amp_cache": 5,
    "cors_proxy": 5,
    "microlink": 3,
    "spn2": 2,
    "arquivo_pt": 4,
    "translate": 3,
}


def _now() -> float:
    return time.monotonic()


class PairWindow:
    __slots__ = ("reqs", "bytes", "fails", "strikes", "cooldown_until", "cool_idx",
                 "ewma_ms", "in_flight")

    def __init__(self):
        self.reqs: deque = deque()          # (t, bytes)
        self.bytes = 0
        self.fails: deque = deque()         # t of 429/503/timeout
        self.strikes = 0                    # consecutive hard failures
        self.cooldown_until = 0.0
        self.cool_idx = 0
        self.ewma_ms: Optional[float] = None
        self.in_flight = 0


class AdaptiveSelector:
    """Per-site chain + saturation-aware selection. Thread-safe."""

    def __init__(self, profiles_path: Path = PROFILES, now: Callable[[], float] = _now):
        self._now = now
        self._lock = threading.Lock()
        self._pairs: dict[tuple, PairWindow] = {}
        self.rejected: dict[str, list[str]] = {}
        self.plans: dict[str, list[str]] = {}
        self.meta: dict[str, dict] = {}
        self._load_profiles(profiles_path)
        self._load_state()

    # --- configuration ------------------------------------------------------
    def _load_profiles(self, path: Path) -> None:
        try:
            raw = json.loads(path.read_text())
        except (OSError, ValueError):
            return
        for host, prof in (raw.get("hosts", raw) or {}).items():
            if not isinstance(prof, dict):
                continue
            chain, bad = [], []
            for m in prof.get("chain", []):
                if m.startswith("entry:"):
                    chain.append(m)          # profile entry-points ride as-is
                elif m in SANCTIONED_METHODS:
                    chain.append(m)
                else:
                    bad.append(m)
            if bad:
                self.rejected.setdefault(host, []).extend(bad)
            if chain:
                self.plans[host] = chain
            self.meta[host] = {"family": prof.get("family"),
                               "pagination": prof.get("pagination", []),
                               "gated": prof.get("gated", False),
                               "profiled": prof.get("profiled")}

    def _load_state(self) -> None:
        try:
            data = json.loads(STATE.read_text())
        except (OSError, ValueError):
            return
        for key, s in (data.get("pairs") or {}).items():
            h, m = key.split("|", 1)
            pw = self._pairs.setdefault((h, m), PairWindow())
            pw.strikes = s.get("strikes", 0)
            pw.cool_idx = s.get("cool_idx", 0)
            pw.ewma_ms = s.get("ewma_ms")
            cd = s.get("cooldown_left")
            if cd:
                pw.cooldown_until = self._now() + float(cd)

    def save_state(self, path: Path = STATE) -> None:
        out = {}
        with self._lock:
            for (h, m), pw in self._pairs.items():
                left = max(0.0, pw.cooldown_until - self._now())
                if pw.strikes or left or pw.ewma_ms:
                    out[f"{h}|{m}"] = {"strikes": pw.strikes, "cool_idx": pw.cool_idx,
                                        "cooldown_left": round(left, 1),
                                        "ewma_ms": round(pw.ewma_ms, 1) if pw.ewma_ms else None}
        path.parent.mkdir(parents=True, exist_ok=True)
        tmp = str(path) + ".tmp"
        with open(tmp, "w") as fh:
            json.dump({"saved": time.time(), "pairs": out}, fh, indent=1)
        import os
        os.replace(tmp, path)

    # --- concurrency lease --------------------------------------------------
    @contextlib.contextmanager
    def lease(self, host: str, method: str):
        """Context manager to track active in-flight requests per method."""
        key = (host, method) if method == "direct" else ("*", method)
        with self._lock:
            pw = self._pairs.setdefault(key, PairWindow())
            pw.in_flight += 1
        try:
            yield
        finally:
            with self._lock:
                pw.in_flight = max(0, pw.in_flight - 1)

    # --- budgets / saturation ------------------------------------------------
    def _prune(self, pw: PairWindow) -> None:
        t = self._now()
        while pw.reqs and t - pw.reqs[0][0] > 60.0:
            _, b = pw.reqs.popleft()
            self._pair_bytes(pw, -b)
        while pw.fails and t - pw.fails[0] > 120.0:
            pw.fails.pop()

    def _pair_bytes(self, pw: PairWindow, delta: int) -> None:
        pw.bytes = max(0, pw.bytes + delta)

    def _budget_for(self, method: str) -> tuple[int, int]:
        return BUDGET_ORIGIN if method == "direct" else BUDGET_RELAY

    def saturation_state(self, host: str, method: str) -> tuple[str, str]:
        """→ (state, why) with state in OK | SOFT | COOLDOWN | SATURATED."""
        key = (host, method) if method == "direct" else ("*", method)
        with self._lock:
            pw = self._pairs.get(key)
            if pw is None:
                return "OK", ""
            self._prune(pw)
            t = self._now()
            if t < pw.cooldown_until:
                return "COOLDOWN", f"penalty cooldown {pw.cooldown_until - t:.0f}s left"
            if method in RELAY_METHODS and pw.strikes >= 3:
                # fleet-wide failure streak: open like the breaker, half-open after
                pw.cooldown_until = t + COOLDOWNS[min(pw.cool_idx, len(COOLDOWNS) - 1)]
                pw.cool_idx += 1
                pw.strikes = 0
                return "COOLDOWN", "relay fleet 3-strike open (half-open probe scheduled)"

            # Check in-flight concurrency slots
            cap = CONCURRENCY_CAPS.get(method, 4)
            if pw.in_flight >= cap:
                return "SATURATED", f"concurrency slot full ({pw.in_flight}/{cap})"

            rpm_cap, bps_cap = self._budget_for(method)
            rpm, bmin = len(pw.reqs), pw.bytes
            if rpm >= rpm_cap or bmin >= bps_cap:
                return "SATURATED", f"budget {rpm}/{rpm_cap} rpm, {bmin}/{bps_cap} B/min"
            if rpm >= SOFT_FRAC * rpm_cap or bmin >= SOFT_FRAC * bps_cap:
                return "SOFT", "≥80% budget — deprioritise"
            if pw.ewma_ms and pw.ewma_ms > 6000.0:
                return "SOFT", f"high latency {pw.ewma_ms:.0f}ms — consider alternates"
            return "OK", ""

    # --- planning --------------------------------------------------------------
    def plan(self, host: str) -> list[str]:
        """Runtime allowlist enforcement and multi-layer fallback preservation."""
        chain = list(self.plans.get(host, DEFAULT_CHAIN))
        # Ensure fallback coverage if host plan is minimal
        if len(chain) < 3:
            for fallback in ("translate_goog", "jina", "wayback", "commoncrawl", "spn2"):
                if fallback not in chain:
                    chain.append(fallback)
        return [m for m in chain if m in SANCTIONED_METHODS or m.startswith("entry:")]

    def select(self, host: str) -> dict:
        """Best currently-usable method for this host + alternates + defer time.

        Never invents a method: the candidate universe is this host's profiled
        chain (allowlist-verified at load). Saturation → demote for THIS host
        and move to the NEXT BEST — cooldowns are pauses, never escalations.
        """
        chain = self.plan(host)
        ok, soft, blocked = [], [], []
        reopen_at = float("inf")
        for m in chain:
            st, why = self.saturation_state(host, m)
            if st in ("OK",):
                ok.append((m, why))
            elif st == "SOFT":
                soft.append((m, why))
            else:
                blocked.append((m, st, why))
                if st == "COOLDOWN":
                    pw = self._pairs.get((host, m) if m == "direct" else ("*", m))
                    if pw:
                        reopen_at = min(reopen_at, pw.cooldown_until - self._now())
        order = [m for m, _ in ok] + [m for m, _ in soft]
        return {"host": host, "method": order[0] if order else None,
                "alternates": order[1:],
                "blocked": [{"method": m, "state": s, "why": w} for m, s, w in blocked],
                "defer_after_s": (round(max(0.0, reopen_at), 1)
                                  if not order else None)}

    # --- accounting -------------------------------------------------------------
    def record(self, host: str, method: str, *, ok: bool, status: int = 0,
               nbytes: int = 0, ms: Optional[float] = None,
               retry_after: Optional[float] = None) -> None:
        key = (host, method) if method == "direct" else ("*", method)
        t = self._now()
        with self._lock:
            pw = self._pairs.setdefault(key, PairWindow())
            if ms is not None:
                pw.ewma_ms = ms if pw.ewma_ms is None else 0.3 * ms + 0.7 * pw.ewma_ms
            if ok:
                pw.reqs.append((t, nbytes))
                pw.bytes += nbytes
                pw.strikes = 0
                pw.cool_idx = 0
            else:
                hard = status in (429, 503) or (status == 0 and nbytes == 0)
                if hard:
                    pw.fails.append(t)
                    pw.strikes += 1
                    cooldown = COOLDOWNS[min(pw.cool_idx, len(COOLDOWNS) - 1)]
                    if retry_after is not None and retry_after > 0:
                        cooldown = max(cooldown, retry_after)
                    if pw.strikes >= 2 or (retry_after is not None and retry_after > 0):
                        pw.cooldown_until = t + cooldown
                        pw.cool_idx += 1
                        pw.strikes = 0
            self._prune(pw)

    # --- introspection -----------------------------------------------------------
    def status(self) -> dict:
        rows = []
        with self._lock:
            for (h, m), pw in sorted(self._pairs.items()):
                self._prune(pw)
                rows.append({"host": h, "method": m, "rpm": len(pw.reqs),
                             "bytes_min": pw.bytes, "strikes": pw.strikes,
                             "in_flight": pw.in_flight,
                             "cooldown_left": round(max(0.0, pw.cooldown_until - self._now()), 1),
                             "ewma_ms": round(pw.ewma_ms, 1) if pw.ewma_ms else None})
        return {"pairs": rows, "plans_loaded": len(self.plans),
                "rejected_unsanctioned": self.rejected}


