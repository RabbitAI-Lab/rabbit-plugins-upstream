# 查询指定城市的实时油价
query_oil_price() {
    local city="$1"
    
    # 查找省份代码
    local province_name=""
    local province_code=""
    
    # 先查找城市到省份名的映射
    if [ -n "${CITY_PROVINCE_MAP[$city]+x}" ]; then
        province_name="${CITY_PROVINCE_MAP[$city]}"
    else
        # 直接查找省份名
        if [ -n "${PROVINCE_MAP[$city]+x}" ]; then
            province_name="$city"
        fi
    fi
    
    # 如果找到了省份名，再查找对应的省份代码
    if [ -n "$province_name" ]; then
        if [ -n "${PROVINCE_MAP[$province_name]+x}" ]; then
            province_code="${PROVINCE_MAP[$province_name]}"
        else
            # 如果省份名没找到，尝试直接匹配代码
            province_code="$province_name"
        fi
    fi
    
    if [ -z "$province_code" ]; then
        echo "❌ 错误：无法识别城市 '$city'，请检查输入。"
        exit 1
    fi
    
    echo "正在查询油价数据..."
    
    # 请求实时油价 API
    local response=$(curl -s "https://map.360.cn/app/qcms?req=oil_price&cityid=${province_code}" 2>/dev/null)
    
    if [ -z "$response" ] || [ "$response" = "[]" ]; then
        echo "❌ 错误：无法从 API 获取数据（省份代码：$province_code）。"
        exit 1
    fi
    
    # 保存到临时文件
    local tmpfile=$(mktemp)
    echo "$response" > "$tmpfile"
    
    # 调用 Python 脚本解析数据
    local timestamp=$(date '+%Y-%m-%d')
    local python_output=$(python3 "${SCRIPT_DIR}/oil_price.py" "$tmpfile" "$province_code" "$timestamp" 2>/dev/null)
    
    rm -f "$tmpfile"
    
    # 显示查询结果
    echo ""
    echo "============================================================"
    echo "  油价查询结果 ($timestamp)"
    echo "============================================================"
    echo ""
    echo "$python_output"
    echo ""
}

