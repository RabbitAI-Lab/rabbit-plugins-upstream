#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
clause_check.py — 条款四看核对清单（怎么买）

输入险种，输出一张能对着合同逐项勾的清单。
客户手上有合同 → 让他自己勾；客户还没买 → 用这份清单去问销售，写不进合同的就不算。

四看：保什么 / 不保什么 / 赔多少 / 怎么赔
专项：医疗险加看续保（到期接着买）条款；所有险种加看犹豫期（买完这段时间内退保全退）

用法：
    python3 clause_check.py --insurance-type 百万医疗
    python3 clause_check.py --insurance-type 重疾 --output clause_list.md

退出码：0 = 正常；1 = 险种不支持
"""

import argparse
import sys

FOOTER = (
    "> 本文为保险通识教育内容，不构成投保建议；"
    "一切以保险条款原文、保险公司核保理赔结论及监管规定为准。"
)

# 四看的通用项
COMMON_ITEMS = {
    "保什么": [
        ("保险责任那一节，列了哪些情况才给钱", "没列进去的一律不给"),
    ],
    "不保什么": [
        ("责任免除（免责条款，写了哪些情况不赔）那一节，一条条读", "这节最重要——它是保险公司真正保护自己的地方"),
        ("有没有医院范围限制（比如要求二级及以上公立医院）", "去错医院可能报不了"),
    ],
    "赔多少": [
        ("保额（出事了最多赔你多少）是多少", "给付型（符合条件直接给钱）直接看这个数"),
        ("赔付比例是不是 100%", "有些只报一定比例"),
        ("免赔额（这个数额以下不赔，你自己先出）是多少", "报销型（花多少报多少，不重复赔）必看"),
    ],
    "怎么赔": [
        ("要交哪些材料（病历、发票原件、费用清单、诊断证明）", "缺材料是最常见的卡点"),
        ("报案有没有时限要求", "超时限会给流程添麻烦，先记下报案电话"),
    ],
}

# 各险种专看项
BY_TYPE = {
    "百万医疗": {
        "专看": [
            ("合同里有没有**「保证续保」四个字**、最长保几年", "没有这四个字，到期要不要你取决于保险公司的审核；**口头承诺不算**"),
            ("续保（到期接着买）那一条写的是「保证续保」还是「可续保／续保时审核」", "这两个词的差别，是这份合同最值钱的一行"),
            ("停售了怎么办，条款里写了吗", "医疗险最现实的风险，是它自己停售"),
            ("免赔额（这个数额以下不赔，你自己先出）是多少、社保（医保）结算的部分算不算在内", "很多纠纷出在「医保报掉的那部分算不算免赔额」上"),
            ("外购药、特殊门诊、住院前后门急诊管不管", "住院不是只有住院那几天要花钱"),
        ],
    },
    "重疾": {
        "专看": [
            ("保的是哪些病、疾病定义是怎么样才算（不是病名一样就算）", "确诊标准写在条款里，不是写在常识里"),
            ("轻症（比重疾轻一级，赔付比例有上限）赔多少比例、中症赔多少", "比例有上限，看清楚是百分之几"),
            ("是赔付一次还是分组多次赔", "同组只能赔一次"),
            ("有没有身故责任（人不在了赔不赔）", "有身故责任的重疾通常贵不少"),
            ("等待期（买完这段时间内出事不赔）是多少天", "90 天和 180 天差别很大"),
        ],
    },
    "意外": {
        "专看": [
            ("意外身故、意外伤残分别赔多少", "伤残是按等级比例赔，不是全赔"),
            ("意外医疗管不管、免赔额（这个数额以下不赔，你自己先出）多少", "磕碰摔伤最常用到的其实是这一项"),
            ("有没有医院范围限制、有没有特定情形的免除（比如高风险运动）", "喜欢爬山潜水的要特别看免除那一条"),
            ("是保一年还是长期、到期要不要重新买", "意外险通常一年一买"),
        ],
    },
    "定寿": {
        "专看": [
            ("保到什么时候（保到 60 岁还是终身）", "保到 60 岁通常便宜很多，那时孩子大了、房贷还完了"),
            ("全残（完全丧失劳动能力）算不算", "有些只保身故，不保全残"),
            ("责任免除（免责条款，写了哪些情况不赔）有几条", "定寿的免除条款通常很短，短是好事"),
            ("受益人（拿赔款的人）写的是名字还是「法定」", "写名字；只写法定，将来按遗产处理，手续更麻烦"),
        ],
    },
}

ALIASES = {
    "医疗": "百万医疗", "百万医疗险": "百万医疗", "医疗险": "百万医疗",
    "重疾险": "重疾", "重大疾病": "重疾", "重大疾病险": "重疾",
    "意外险": "意外", "意外伤害": "意外",
    "定期寿险": "定寿", "寿险": "定寿", "定寿": "定寿",
}

COMMON_END = [
    "犹豫期（买完这段时间内退保全退）有几天",
    "宽限期（忘交保费后的补救时间）有几天、忘交了怎么补",
    "缴费日是哪天、一年交几次",
    "报案电话是哪个（抄合同封面上的官方客服号，不存销售的手机号）",
]


def normalize(t):
    return ALIASES.get((t or "").strip(), (t or "").strip())


def build(t):
    key = normalize(t)
    if key not in BY_TYPE:
        return None
    lines = []
    lines.append("# 条款四看核对清单（{}）".format(key))
    lines.append("")
    lines.append("> 用法：手上有合同就自己逐项勾；还没买就拿这张单子去问销售，**写不进合同的就不算**。")
    lines.append("")
    lines.append("先认识几个词：")
    lines.append("")
    for word in [
        "保额（出事了最多赔你多少）",
        "免赔额（这个数额以下不赔，你自己先出）",
        "保证续保（写进合同、年限内必须让你续）",
        "免责条款（写了哪些情况不赔）",
        "犹豫期（买完这段时间内退保全退）",
        "宽限期（忘交保费后的补救时间）",
        "轻症（比重疾轻一级，赔付比例有上限）",
        "重疾（重大疾病险）",
        "保费（你交的钱）",
        "受益人（拿赔款的人）",
    ]:
        lines.append("- {}".format(word))
    lines.append("")

    order = ["保什么", "不保什么", "赔多少", "怎么赔"]
    for i, sec in enumerate(order, 1):
        lines.append("## 第 {} 看 · {}".format(i, sec))
        lines.append("")
        lines.append("| 核对项 | 为什么看这条 | 合同上写的 |")
        lines.append("|---|---|---|")
        for item, why in COMMON_ITEMS[sec]:
            lines.append("| {} | {} | ____________ |".format(item, why))
        lines.append("")

    lines.append("## 第 5 看 · {}专看".format(key))
    lines.append("")
    lines.append("| 核对项 | 为什么看这条 | 合同上写的 |")
    lines.append("|---|---|---|")
    for item, why in BY_TYPE[key]["专看"]:
        lines.append("| {} | {} | ____________ |".format(item, why))
    lines.append("")

    lines.append("## 通用四项（不看完别签字）")
    lines.append("")
    for c in COMMON_END:
        lines.append("- [ ] {}".format(c))
    lines.append("")

    lines.append("## 你现在可以做的一步")
    lines.append("")
    lines.append(
        "打开合同，先跳到**责任免除（免责条款，写了哪些情况不赔）**那一节——"
        "这节读完，你对这份合同的判断就有了八成。"
    )
    lines.append("")
    lines.append("---")
    lines.append("")
    lines.append(FOOTER)
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description="条款四看核对清单")
    ap.add_argument("--insurance-type", required=True,
                    help="险种：百万医疗 / 重疾 / 意外 / 定寿")
    ap.add_argument("--output", help="输出到文件（默认打印到屏幕）")
    args = ap.parse_args()

    body = build(args.insurance_type)
    if body is None:
        print("[没认出来] 险种「{}」我这边没对上。\n"
              "  能处理这四类（说简称也行）：\n"
              "    百万医疗   也可以说：医疗 / 医疗险 / 百万医疗险\n"
              "    重疾       也可以说：重疾险 / 大病险\n"
              "    意外       也可以说：意外险 / 意外伤害\n"
              "    定寿       也可以说：寿险 / 定期寿险 / 身故险\n"
              "  例：--insurance-type 重疾".format(args.insurance_type),
              file=sys.stderr)
        return 1

    if args.output:
        with open(args.output, "w", encoding="utf-8") as f:
            f.write(body + "\n")
        print("[完成] 核对清单已写入 {}".format(args.output))
    else:
        print(body)
    return 0


if __name__ == "__main__":
    sys.exit(main())
