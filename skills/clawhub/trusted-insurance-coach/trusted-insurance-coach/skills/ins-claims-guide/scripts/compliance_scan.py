def selftest():
    print("运行内置正反测试用例：\n")
    failed = 0
    for i, (text, should_block) in enumerate(SELFTEST, 1):
        findings, _cited, term_hits = scan(text)
        blocked = bool(findings or term_hits)
        status_ok = (blocked == should_block)
        if not status_ok:
            failed += 1
        flag = "✅" if status_ok else "❌"
        print(f"{flag} 用例 {i}：期望{'拦下' if should_block else '放行'}，实际{'拦下' if blocked else '放行'}")
        if not status_ok:
            print(f"    文本：{text}")
            for cat, hit, _ in findings:
                print(f"    命中：{cat} → {hit}")
            for sent, terms in term_hits:
                print(f"    术语：{sent} → {'、'.join(terms)}")
    print("-" * 60)
    if failed:
        print(f"自检失败：{failed}/{len(SELFTEST)} 个用例不符合预期")
        return 2
    print(f"自检通过：{len(SELFTEST)}/{len(SELFTEST)} 个用例符合预期")
    return 0


def main():
    parser = argparse.ArgumentParser(
        description="保险专家包统一输出自检（八类黑名单 + 术语项）")
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--text", help="待检查的文本")
    group.add_argument("--file", help="待检查的文件路径")
    group.add_argument("--selftest", action="store_true", help="跑内置正反测试用例")
    parser.add_argument("--ignore-terms", action="store_true",
                        help="跳过术语项——扫描 SKILL.md / references 等内部文件时使用"
                             "（术语规范只在**输出阶段**生效）")
    args = parser.parse_args()

    if args.selftest:
        return selftest()

    if args.file:
        with open(args.file, encoding="utf-8") as fp:
            text = fp.read()
    else:
        text = args.text

    findings, cited, term_hits = scan(text)
    if args.ignore_terms:
        term_hits = []
    return print_report(findings, cited, term_hits, len(text))


