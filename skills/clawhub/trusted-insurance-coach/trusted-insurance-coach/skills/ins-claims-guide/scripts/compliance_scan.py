SENTENCE_SPLIT = re.compile(r"[。！？!?；;\n]+")

# 长术语优先："预核保"优先于"核保"，避免子串重复计数
TERMS_SORTED = sorted(set(TERMS), key=len, reverse=True)


def _find_explained_terms(text: str) -> set:
    """
    全文范围内已给出人话解释的术语（五铁律：首现必翻）。四种"已翻译"写法都认：
      ① 术语 + 括号人话：保额（最多赔你多少）
      ② 括号人话 + 术语：重度疾病（重疾）
      ③ 术语 = 人话：重疾保额 = 治疗费用 + 5 年收入
      ④ 术语对照表整行：| 保额 | 出事了最多赔你多少 |
    只要在同一份文件里讲清过一次，后续再出现就不再重复要求（避免同一文件反复告警）。
    """
    explained = set()
    for term in TERMS_SORTED:
        t = re.escape(term)
        if (re.search(t + r"\s*[（(][^）)]{2,}[）)]", text)
                or re.search(r"[（(][^）)]{2,}\s*" + t + r"[）)]", text)
                or re.search(r"\*\*?" + t + r"\*\*?\s*[=＝]", text)
                or re.search(r"\|[^|\n]*" + t + r"[^|\n]*\|[^|\n]{2,}\|", text)):
            explained.add(term)
    return explained


def _explained_here(sent: str, start: int, end: int) -> bool:
    """
    判断"这个术语在这一处算不算已经翻译成人话"。四种即时写法都算：
      ① 术语 + 括号人话 —— 保额（最多赔你多少）
      ② 术语后直接是/为 + 数字或人话 —— 宽限期是 60 天 / 标准体是正常保
      ③ 术语后接转述词 —— 保额就是…/ 免赔额即…
      ④ 术语自带口语后缀 —— 宽限期内 / 保额够 / 保费超
    """
    tail = sent[end:end + 12]
    if re.match(r"\s*[（(]", tail):
        return True
    if re.search(r"(?:就是|即|便是|指的是|的意思是)", tail):
        return True
    if re.match(r"\s*[是为]\s*(?:[\d一二三四五六七八九十百千万几]|\D{2,})", tail):
        return True
    if sent[end:end + 1] in "内够超剩还已不倒挂":
        return True
    return False


def scan_terms(text: str):
    """
    同一句内 ≥2 个未解释术语 → 告警。
    三条容错：① 长术语优先匹配，子串（如"预核保"里的"核保"）不重复计数；
              ② 该术语在全文任何位置已被人话解释过（首现已翻），后续不再要求重复翻译；
              ③ 句内同一术语已有一处解释过，别处的复述不再计入。
    """
    explained_global = _find_explained_terms(text)
    hits = []
    for sent in SENTENCE_SPLIT.split(text):
        if not sent.strip():
            continue
        unexplained = []
        occupied = []   # 已被更长术语占用的区间（防子串重复计数）
        done = set()    # 本句已判定为"已解释"的术语
        for term in TERMS_SORTED:
            if term in explained_global or term in done:
                continue
            for m in re.finditer(re.escape(term), sent):
                if any(s <= m.start() < e for s, e in occupied):
                    continue
                occupied.append((m.start(), m.end()))
                if _explained_here(sent, m.start(), m.end()):
                    done.add(term)
                elif term not in unexplained:
                    unexplained.append(term)
                break
        if len(unexplained) >= 2:
            hits.append((sent.strip()[:80], unexplained))
    return hits


# 引用豁免：指令文档/示例里常把禁用语当作"禁令引用"（如 不说"保险公司耍赖"），
# 这类命中不拦截，但单列出来供人工复核。
QUOTE_PAIRS = [("“", "”"), ("\"", "\""), ("'", "'"), ("「", "」"), ("《", "》")]
NEGATION_CUES = ["不", "禁", "别", "勿", "避免", "拒绝", "杜绝", "严禁", "防止", "≠", "不等于", "并非", "不会"]


def _is_citation(text: str, start: int, end: int, window: int = 12, quote_window: int = 40) -> bool:
    pre = text[max(0, start - window):start]
    if any(cue in pre for cue in NEGATION_CUES):
        return True
    pre_wide = text[max(0, start - quote_window):start]
    if any(a in pre_wide for a in CITATION_ANCHORS):
        # 锚点之后若已经出现一个完整的"「…」"，说明锚点在管别的东西，不是管这一处
        inner = pre_wide[pre_wide.rfind("「") + 1:] if "「" in pre_wide else ""
        if "」" in inner:
            pass  # 锚点在管前面那段，继续看引号配对
        else:
            return True
    # 引号包裹：整句可能是很长的引用（如拒答清单里的用户原话），窗口放宽
    # 只比较「开引号之后」的那一小段：引用通常很短（「都填否就行」），
    # 不能拿 40 字的窗口去找闭引号，否则隔壁句子的引号会被借来配对。
    pre_q = text[max(0, start - 30):start]
    post_q = text[end:end + 8]
    # 左右引号必须配对：取匹配点之前**最后一个**开引号，和之后**最近**的闭引号，
    # 否则「A」／「B」这种并列引用会被误判（A 的开引号 + B 的闭引号也算一对）。
    for l, r in QUOTE_PAIRS:
        li = pre_q.rfind(l)
        if li == -1:
            continue
        # 开引号到匹配点之间若已有闭引号，说明匹配点根本不在引号里（是后面的「B」）
        inner = pre_q[li + 1:]
        if r in inner or l in inner:
            continue
        ri = post_q.find(r)
        if ri != -1 and l not in post_q[:ri]:
            return True
    return False


# 引用豁免只给"禁令式引用"用：把禁语括起来是为了告诉客户"这句话别说"。
# 如果括起来是为了"给我写一段这样的话""用这个说法去讲"，那就是在要话术，必须拦。
ORDER_CUES = [
    "帮我写", "帮我编", "给我写", "编一段", "写一段", "写一句", "编一组", "来一段",
    "这样说", "就这么讲", "这么讲", "怎么讲", "跟客户讲", "跟客户说", "对客户说",
    "照着说", "这样说对吗", "教我说",
]

# 引用豁免的额外闸门：禁令引用通常紧挨"不说/别说/拒答/不为"这类词。
# 只靠"引号 + 不"太松——"推荐一个"「胜算多大」里隔着十几字也能蹭到"不"字。
CITATION_ANCHORS = ["不说", "不要说", "别说", "别用", "禁用", "拒答", "不为", "严禁", "避免",
                    "不做", "不写", "不给", "别信", "一律拒", "红线", "禁语", "拒绝"]


def _is_order_to_repeat(text: str, start: int, end: int, window: int = 30) -> bool:
    """
    括号里的禁语，是"被要求照着说"还是"被要求别说"？
    只看同一行内、并且没有被换行/句子边界隔开的那一小段——
    上一行另一条禁令里的"帮我写"不能拿来给这一行定罪。
    """
    ls = text.rfind("\n", 0, start) + 1
    le = text.find("\n", end)
    le = len(text) if le == -1 else le
    seg = text[max(ls, start - window):min(le, end + window)]
    return any(c in seg for c in ORDER_CUES)


def _mask_quoted(text: str) -> str:
    """把「」里引述的内容替换成等长占位符：引述 ≠ 主张，不该按字面命中。
    保留长度，便于报告上下文仍指向原文位置。"""
    out = list(text)
    i = 0
    while i < len(text):
        if text[i] == "「":
            j = text.find("」", i + 1)
            if j == -1:
                break
            for k in range(i, j + 1):
                if out[k] != "\n":
                    out[k] = "·"
            i = j + 1
        else:
            i += 1
    return "".join(out)


# 代理人识别：必须"两边都占"才判——
#   ① 有卖方视角的标记（我客户 / 我们产品 / 同业 / 我这个客户…）
#   ② 有索取动作（帮我 / 怎么写 / 促成 / 算算…）
# 单纯"我们公司给员工买了团体险"这种员工视角不算，不误伤。
# ---- 代理人识别（闸门）----
# 判定原则：「同句之内」卖方视角 + 向 AI 索要，两者必须落在同一句里。
# 用整段文本做模糊匹配会疯狂误伤——"客户要"「他说」「怎么」这些词在文档正文里到处都是。
# 先切句（。！？\n 分号），再在句内判断。
_SEP = re.compile(r"[。！？!?\n]+")

# 卖方视角强标记：客户绝不会这样称呼自己，出现即判（但仍要看否定语境）
AGENT_ONLY = ["我客户", "我的客户", "我这有个客户", "我这个客户", "我这边有客户",
              "我手上这个客户", "我名下客户", "我手上这个", "我们产品", "我们的产品",
              "我们这款", "我这款", "我们保司", "我保司", "我们团队", "我团队",
              "同业对比", "同业产品", "客户名单", "客户画像", "客户分层", "名单分层"]

# 卖方视角弱标记：配索取动作才算
AGENT_SELF = ["我客户", "我的客户", "我这有个客户", "我这个客户", "我这边有客户",
              "我们产品", "我们的产品", "我们这款", "我这款", "我们团队", "我团队",
              "我们保司", "我保司", "签单", "出单", "转介绍", "客户资料",
              "客户问我要", "客户跟我说", "我给他发", "我给他讲", "我跟他讲"]

# 向 AI 索取的动作（要"对我说话"的语气，不要"描述某个动作"的动词）
ASK_ACTS = ["帮我", "给我", "怎么", "如何", "你说", "写一份", "做一份", "整理一份",
            "算算", "列出", "介绍一下", "教教", "能不能", "可否", "发我", "发什么",
            "说轻", "说得", "解释才", "看起来专业", "显得专业", "说服他", "劝他",
            "拿去跟客户", "能促成", "要能", "突出我们"]

# 更稳的结构信号：把"客户"当第三方对象（我要给他 / 他问我 / 我这个客户）+ 索取动作。
# 这两组词只在"同一句内"才配对，避免文档里"客户要…"和别处的"怎么…"串味。
THIRD_PERSON = ["给他", "跟他说", "他问", "劝他", "说服他", "让他签",
                "我这个客户", "这个客户", "客户问我", "客户嫌", "客户拒绝",
                "客户说要", "客户想", "客户觉得"]
REQUEST = ["怎么", "帮我", "给我", "发什么", "能促成", "解释", "说服", "说服他",
           "写得", "说得", "算算", "整理", "对比", "要能", "拿去", "教教", "回他"]

# 非保险从业者（银行柜员、HR 等）替客户/同事问，不属于保险销售场景，放行
# 注意：这里必须是"自称"句式。光写 "HR" 会命中任何提到 HR 的句子
# （"回头你问一下 HR" 是正常给客户的建议），只能写"我是 HR"这类。
OTHER_ROLE = ["银行客户经理", "银行柜员", "我是银行的", "我是HR", "我是 HR", "我是人事",
              "公司行政", "我是客户", "作为客户", "我是投保人", "我是被保险人"]

# 否定语境：禁令 / 角色声明 / 拒绝声明里出现的"客户怎么…"不是代理人在提问。
# 例："不服务保险代理人""不推销加保""不接代理人代客户提问""我不卖保险、不拿佣金"。
NEG_CONTEXT = ["不服务", "不接", "不做", "不代理", "不代办", "不代写", "不代填",
               "不推销", "不劝", "不给", "不提供", "不支持", "不针对", "不面向",
               "不卖", "不拿", "不收", "禁止", "严禁", "红线", "拒答", "拒绝",
               "只服务", "仅服务", "本人", "本 skill", "本专家", "专家包",
               "不评价", "不预测", "不承诺", "不保证", "不谈"]


def _sentences(text: str):
    """按句切分并保留偏移量，便于在句内做共现判断。"""
    out, pos = [], 0
    for m in _SEP.finditer(text):
        if m.start() > pos:
            out.append((pos, text[pos:m.start()]))
        pos = m.end()
    if pos < len(text):
        out.append((pos, text[pos:]))
    return out


# "我是客户"这类自我声明，如果是代理人借客户身份替第三方问，仍然要拦：
#   我是客户，我朋友是代理人，他想知道…… 
# 所以"自称客户"只在"没有替第三方索取"时才算豁免。
_THIRD_PARTY = ["我朋友", "我朋友是", "我哥", "我姐", "我同学", "我同事", "我亲戚",
                "他想知道", "他想问", "他要问", "他问", "帮他想", "替他问",
                "他想让我", "他要我", "让我帮他", "帮朋友", "帮亲戚", "帮同事"]


def _sent_start(text: str, sent: str) -> int:
    i = text.find(sent)
    return 0 if i < 0 else i


def _is_agent_request(text: str) -> bool:
    # 先看"自称客户"出现在哪：如果只出现在清单项里（"- 我是客户经理..."），
    # 那是文档举例，不是用户在说话，不能据此判身份。
    for w in OTHER_ROLE:
        if w not in text:
            continue
        p = text.find(w)
        if _is_bullet_line(text, p) or _under_ban_heading(text, p):
            continue                      # 这处是清单举例，跳过
        # 真正自称：再看有没有替第三方索取
        if not any(t in text for t in _THIRD_PARTY):
            return False
        return True
    # 表格形态的"客户场景 → 我该怎么回"对应表：话术列和客户列必须在同一行。
    # 只看全篇有没有"话术"和"客户"两个词太松——任何讲销售套路的文档都会同时出现。
    lines = text.splitlines()
    table_has_script = False
    for line in lines:
        st = line.lstrip()
        if not st.startswith("|"):
            table_has_script = False      # 离开表格就重置
            continue
        cells = [c.strip() for c in st.strip("|").split("|")]
        if any(re.search(r"话术|说辞|开场白|怎么回|应对", c) for c in cells):
            table_has_script = True
            continue
        if table_has_script and re.search(r"客户|异议|拒绝|嫌贵|再想想", line) \
                and re.search(r"帮我|给我|写一|编一|来一", line):
            return True

    for _, sent in _sentences(text):
        s = sent.strip()
        if not s:
            continue
        # 否定/角色声明语境整句放行（"不推销加保""不拿佣金""本 skill 只服务本人"）
        if any(n in s for n in NEG_CONTEXT):
            continue
        # 列举行（"- 客户画像 / 名单分层"）是清单项，不是自称；
        # 禁令标题下的条目同理。这两类都不该判成代理人在提问。
        _pos = _sent_start(text, s)
        if any(w in s for w in AGENT_ONLY) and not _is_bullet_line(text, _pos) \
                and not _under_ban_heading(text, _pos):
            return True
        # 所有分支共用一个前提：这不是一句"清单举例"，也不是禁令标题下的条目。
        # 否则文档里写 "- 我们这款跟 X 比怎么说" 这种禁项举例会被当成真请求。
        _pos = _sent_start(text, s)
        _in_list = _is_bullet_line(text, _pos) or _under_ban_heading(text, _pos)
        if any(a in s for a in AGENT_SELF) and any(b in s for b in ASK_ACTS) and not _in_list:
            return True
        if any(t in s for t in THIRD_PERSON) and any(r in s for r in REQUEST) and not _in_list:
            return True
        # "这个产品 / 这款产品" + 索取动作：卖方才会称"这个产品"
        if re.search(r"(?:这个|这款|该|我们)产品", s) and any(b in s for b in ("帮我", "给我", "怎么", "如何", "写", "说说")):
            return True
        # "拿去跟客户讲 / 跟客户说"：说话人自己不是客户
        if re.search(r"(?:拿去|用来|好)(?:跟|和|对)客户(?:讲|说|沟通|解释|谈)", s):
            return True
    return False


def _line_of(text: str, start: int) -> str:
    ls = text.rfind("\n", 0, start) + 1
    le = text.find("\n", start)
    le = len(text) if le == -1 else le
    return text[ls:le]


# 硬索取：第一人称直接要 AI 干活。这类句式不存在"列举禁项"的可能，
# 所有豁免（引号、列表、禁令标题）一律不适用。
HARD_ASK = re.compile(r"(?:帮我|给我|帮我写|替我写|替我|来一段|来几句|编一段|编几句|写一段|"
                      r"写几句|出一套|整一套|教我说|教我写|照着说|这么说行吗|这样讲行吗)")


def _is_hard_ask(text: str, start: int, end: int) -> bool:
    """命中位置所在那一句里有没有第一人称索取。"""
    ls = text.rfind("\n", 0, start)
    ls = 0 if ls == -1 else ls
    le = text.find("\n", end)
    le = len(text) if le == -1 else le
    seg = text[ls:le]
    # 引号内的内容不算（「」里是引述）
    return bool(HARD_ASK.search(_mask_quoted(seg)))


# "要拒的 / 不能做 / 红线 / 禁止"这类小标题下面，整段列表都是在列举禁项。
_LIST_HEAD = re.compile(r"(?:要拒|拒答|不能做|不要做|不做|禁止|严禁|红线|禁语|不给|底线|"
                        r"不接受|不服务|该拒|必须拒|违规|别做|避坑|"
                        r"不拒|不该拦|例外|放行|不误伤|看着像)")


def _under_ban_heading(text: str, start: int, lookback: int = 600) -> bool:
    """往上找最近的标题行（# 或 **…**：），看是不是"禁项清单"的标题。"""
    ls = text.rfind("\n", 0, start)
    pos = ls
    seen = 0
    while pos > 0 and seen < lookback:
        prev = text.rfind("\n", 0, pos)
        line = text[prev + 1:pos].strip()
        if line.startswith("#") or (line.startswith("**") and line.endswith(("**", "**：", "**:"))):
            return bool(_LIST_HEAD.search(line))
        seen += len(line) + 1
        pos = prev
    return False


def _is_bullet_line(text: str, start: int) -> bool:
    """这一行是不是项目符号 / 表格行 / 编号项？
    文档里「要拒的」清单是"列举禁项"，和"向我索取"是两回事——
    `- 客户画像 / 名单分层 / 转介绍 / 拓客` 这一行没有任何指令意图。"""
    ls = text.rfind("\n", 0, start) + 1
    line = text[ls:ls + 40].lstrip()
    # 表格行也算：文档里"| 客户原话示例 | 路由 |"整张表都是在举例
    return line.startswith(("-", "*", "·", "|")) or bool(re.match(r"^\d+[.、]", line))


def scan(text: str):
    blocked, cited = [], []
    masked = _mask_quoted(text)
    for category, cfg in RULES.items():
        for pat in cfg["patterns"]:
            for m in re.finditer(pat, masked):
                start = max(0, m.start() - 20)
                end = min(len(text), m.end() + 20)
                item = (category, m.group(0), text[start:end].replace("\n", " "))
                if _is_citation(text, m.start(), m.end()) and not _is_order_to_repeat(text, m.start(), m.end()) \
                        and not _is_hard_ask(text, m.start(), m.end()):
                    cited.append(item)
                elif _is_hard_ask(text, m.start(), m.end()):
                    # 第一人称索取：豁免全部失效，直接拦
                    blocked.append(item)
                elif _under_ban_heading(text, m.start()) and not _is_hard_ask(text, m.start(), m.end()):
                    # 「要拒的」清单下的条目，即使写着"怎么拖理赔""怎么写拒赔说明"，
                    # 也是在列举禁项，不是向我索取。
                    cited.append(item)
                elif _is_bullet_line(text, m.start()) and not _is_order_to_repeat(text, m.start(), m.end()) \
                        and not any(a in _line_of(text, m.start()) for a in ASK_ACTS):
                    # 清单式列举（- 拓客 / - 转介绍）不是在向我下指令；
                    # 但 "- 帮我写一套促成话术" 这种列表里的请求，照样要拦。
                    cited.append(item)
                else:
                    blocked.append(item)
    # 身份闸门：整段话出现"我客户/我们产品/我公司/我这边"等代理人自称，
    # 且夹带"帮我/怎么/你说/给我"等索取动作 → 整段判为代理场景。
    if _is_agent_request(text):
        cat = "代理话术请求"
        start = 0
        end = min(len(text), 40)
        item = (cat, "代理人身份征询", text[start:end].replace("\n", " "))
        if item not in blocked:
            blocked.insert(0, item)

    # 第二遍：被「」遮住的引述内容，如果整段是"帮我写…「禁语」…话"这种要话术的句式，
    # 遮罩会把它漏掉——这里对原文再扫一次，只保留"指令语境"里的命中。
    for category, cfg in RULES.items():
        for pat in cfg["patterns"]:
            for m in re.finditer(pat, text):
                if re.match(r"^[·]+$", masked[m.start():m.end()]) and _is_order_to_repeat(text, m.start(), m.end()):
                    start = max(0, m.start() - 20)
                    end = min(len(text), m.end() + 20)
                    item = (category, m.group(0), text[start:end].replace("\n", " "))
                    if item not in blocked:
                        blocked.append(item)
    return blocked, cited, scan_terms(text)


