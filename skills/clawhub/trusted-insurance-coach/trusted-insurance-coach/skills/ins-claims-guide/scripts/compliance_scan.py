    ok = True
    if cited:
        print(f"⚠️  引用豁免 {len(cited)} 处（禁用语出现在禁令/引号语境，不计入拦截，供人工复核）：")
        for cat, hit, ctx in cited[:10]:
            print(f"      · [{cat}] {hit}  ← …{ctx}…")
        print()
    if findings:
        ok = False
        print(f"❌ 命中黑名单 {len(findings)} 处：\n")
        by_cat = {}
        for cat, hit, ctx in findings:
            by_cat.setdefault(cat, []).append((hit, ctx))
        for cat, items in by_cat.items():
            print(f"  【{cat}】命中 {len(items)} 处 —— {RULES[cat]['hint']}")
            for hit, ctx in items[:8]:
                print(f"      · 命中词：{hit}")
                print(f"        上下文：…{ctx}…")
            print()
    else:
        print("✅ 八类黑名单：无命中")

    if term_hits:
        ok = False
        print(f"❌ 术语未翻译（五铁律）：{len(term_hits)} 句\n")
        for sent, terms in term_hits[:8]:
            print(f"      · 句：{sent}")
            print(f"        未解释术语：{'、'.join(terms)}（首次出现需带括号人话）")
        print()
    else:
        print("✅ 术语未翻译：无命中")

    print("-" * 60)
    if ok:
        print("结论：通过，可以输出。")
    else:
        print("结论：不通过，请修改后重新扫描再输出。")
    return 0 if ok else 1


