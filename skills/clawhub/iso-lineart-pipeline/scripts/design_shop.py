#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""
design_shop.py —— 单层单坡「废土杂货铺」体块设计（Lv.3 成品态）

设计原则（这一版最重要的改动）：
  所有装饰件（封檐板 / 窗台 / 招牌 / 门框）一律做「薄板」，
  ⛔ 不做厚盒子。厚盒子的三个可见面都是纸白色，堆在一起会变成一堆木块。
  构件尺寸下限 0.03（≈30px），低于这个尺寸在 1920 画布里只是噪点。
"""
import numpy as np
import line3d as L
from line3d import box, slab, wquad, beam, prism

# ── 主要尺寸：宽而低 ──────────────────────────────────────────
A0, A1 = -0.24, 0.26      # 进深。A0 是前脸（屏幕左）
B0, B1 = -0.26, 0.30      # 面宽。B0 是右脸（屏幕右）
EAVE, RIDGE = -0.290, 0.285
TA = 0.280
HT = 0.470
H_LOW = HT - (A0 - EAVE) * TA


def rh(a):
    return H_LOW + (a - EAVE) * TA


def build():
    F = []
    # ── 地台 ──────────────────────────────────────────────
    F += box(-0.318, 0.318, -0.326, 0.326, -0.024, 0.0, 'sil')

    # ── 墙：顶跟着屋面斜 ───────────────────────────────────
    F += box(A1 - 0.018, A1, B0, B1, 0.0, rh(A1) - 0.018, 'str')
    F += wquad(A0, A1, B1 - 0.024, B1, 0.0, lambda a: rh(a) - 0.016, 'str')

    # 右脸 b=B0：切真门洞
    DA0, DA1, DH = 0.010, 0.118, 0.300
    F += wquad(A0, DA0, B0, B0 + 0.022, 0.0, lambda a: rh(a) - 0.004, 'str')
    F += wquad(DA1, A1, B0, B0 + 0.022, 0.0, lambda a: rh(a) - 0.004, 'str')
    F += wquad(DA0, DA1, B0, B0 + 0.022, DH, lambda a: rh(a) - 0.004, 'str')
    # 门框：薄板，只做两条立框
    F += box(DA0 - 0.014, DA0, B0 - 0.010, B0 + 0.004, 0.0, DH + 0.014, 'str')
    F += box(DA1, DA1 + 0.014, B0 - 0.010, B0 + 0.004, 0.0, DH + 0.014, 'str')
    F += box(DA0 - 0.014, DA1 + 0.014, B0 - 0.010, B0 + 0.004, DH, DH + 0.014, 'str')
    # 内退门扇
    F += box(DA0 + 0.020, DA1 - 0.020, B0 + 0.070, B0 + 0.082, 0.0, DH - 0.016, 'det')

    # 前脸 a=A0：柜台口
    HTL = rh(A0) - 0.004
    OB0, OB1 = B0 + 0.028, 0.100
    F += box(A0, A0 + 0.022, OB1, B1, 0.0, HTL, 'str')
    # 窗：只留一块内退矩形板
    F += box(A0 - 0.006, A0 + 0.014, 0.152, 0.246, 0.168, 0.310, 'str')
    F += box(A0 - 0.002, A0 + 0.004, 0.166, 0.232, 0.182, 0.296, 'det')
    # 柜台口：过梁 + 内壁 + 地面
    F += box(A0, A0 + 0.022, OB0, OB1, 0.320, HTL, 'str')
    F += box(A0 + 0.022, A0 + 0.050, OB0, OB1, 0.316, 0.344, 'str')
    F += box(A0 + 0.190, A0 + 0.210, OB0, OB1, 0.0, 0.500, 'str')
    F += box(A0, A0 + 0.190, OB1 - 0.022, OB1, 0.0, 0.500, 'str')
    F += box(A0 + 0.022, A0 + 0.190, OB0, OB1, 0.0, 0.006, 'det')
    # 角柱：细，只比墙略突
    F += box(A0 - 0.006, A0 + 0.036, OB1 - 0.016, OB1 + 0.036, 0.0, HTL - 0.002, 'sil')

    # ── 挑出墙外的售卖台：两根立柱撑住檐口 ────────────────────
    SA = A0 - 0.046
    F += box(SA, A0 + 0.070, -0.246, 0.022, 0.104, 0.122, 'sil')          # 台面
    F += box(SA, SA + 0.022, -0.246, 0.022, 0.0, 0.104, 'str')            # 台面前板
    F += box(SA + 0.024, A0 + 0.070, -0.246, -0.214, 0.0, 0.104, 'str')   # 台侧封板
    F += box(A0 + 0.020, A0 + 0.070, -0.246, -0.214, 0.0, 0.104, 'str')
    for bb2 in (-0.242, 0.012):                                            # 檐口立柱
        F += box(SA - 0.008, SA + 0.030, bb2, bb2 + 0.036, 0.0, 0.446, 'sil')
    F += box(A0 + 0.070, A0 + 0.140, -0.196, -0.150, 0.122, 0.170, 'det')  # 台上小柜

    # ── 屋面：不等宽长条，檐口逐条错台 ─────────────────────
    bw = [0.095, 0.130, 0.115, 0.145, 0.125]
    eave = [-0.302, -0.278, -0.322, -0.286, -0.308]
    cuts = [
        [-0.100],
        [-0.185],
        [0.015],
        [-0.145],
        [0.055],
    ]
    offs = [0.007, -0.004, 0.003, 0.009, -0.006]
    bb = -0.300
    for i in range(5):
        b0, b1 = bb, bb + bw[i]
        bb = b1
        seq = [eave[i]] + cuts[i] + [RIDGE]
        for k in range(len(seq) - 1):
            a0, a1 = seq[k], seq[k + 1]
            off = offs[(i + k * 2) % 5]
            e = 0.0022
            quad = [(a0 + e, b0 + e, rh(a0 + e) + off),
                    (a1 - e, b0 + e, rh(a1 - e) + off),
                    (a1 - e, b1 - e, rh(a1 - e) + off),
                    (a0 + e, b1 - e, rh(a0 + e) + off)]
            F += slab(quad, 0.008, 'str')
        # 封檐板：薄板。之前做成 0.08 高，在 1:1 下就是一根白梁
        F += box(eave[i] - 0.010, eave[i] + 0.004, b0 + 0.002, b1 - 0.002,
                 rh(eave[i]) - 0.036, rh(eave[i]) + 0.004, 'sil')

    # 屋脊压条
    F += box(RIDGE - 0.008, RIDGE + 0.024, -0.302, 0.322,
             rh(RIDGE) + 0.001, rh(RIDGE) + 0.019, 'sil')

    # ── 补丁压条：横跨横缝的窄铁条 ──────────────────────────
    straps = [(-0.100, 0.020, 0.100), (-0.145, 0.150, 0.100), (0.055, 0.060, 0.095)]
    for ac, bs, bwid in straps:
        F += slab([(ac - 0.024, bs, rh(ac - 0.024) + 0.010),
                   (ac + 0.024, bs, rh(ac + 0.024) + 0.010),
                   (ac + 0.024, bs + bwid, rh(ac + 0.024) + 0.010),
                   (ac - 0.024, bs + bwid, rh(ac - 0.024) + 0.010)],
                  0.005, 'det')

    # ── 地台上的杂物 ──────────────────────────────────────
    F += prism(0.020, -0.296, 0.0, 0.042, 0.090, 12, 0.3, 'str', rim=0.013)
    F += prism(0.108, -0.304, 0.0, 0.036, 0.080, 12, 0.9, 'str', rim=0.011)
    F += prism(-0.070, -0.294, 0.0, 0.034, 0.074, 10, 0.2, 'str', rim=0.010)
    F += box(0.178, 0.252, -0.300, -0.232, 0.0, 0.058, 'str')
    F += box(0.184, 0.246, -0.294, -0.238, 0.058, 0.104, 'str')
    return F


if __name__ == '__main__':
    import sys
    out = sys.argv[1] if len(sys.argv) > 1 else 'shop_lineart.png'
    L.render(build(), out)
    print(f'-> {out}')
