#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
生成《小红书赛道深度分析主表》骨架（Markdown）。
用法:
  python3 scaffold_table.py "<品类名>" [输出路径]
若不指定输出路径，则直接打印到标准输出。
"""
import sys
import datetime
import os


def build(category: str) -> str:
    today = datetime.date.today().isoformat()
    return f"""# 小红书赛道深度分析主表 · {category}
生成日期: {today}
> 采集时间距本表生成 > 90 天的内容须标"需复核"；重投放品类须标注商业化浓度并打折解读。

## 一、研究任务与三问
- 这次最想看懂什么:
- 品牌最后要做出什么选择:
- 结论交给谁使用:
- 采集时间窗口（起止，> 90 天须标"需复核"）:

## 二、关键词四分组
| 分组 | 关键词 | 对应问题 |
| --- | --- | --- |
| 人群与阶段 |  | 谁有需求 |
| 问题与效果 |  | 哪里不满意 |
| 产品与选择 |  | 在找什么 |
| 达人关联 |  | 达人能否自然参与 |

## 三、采集记录（每轮一行）
| 轮次 | 关键词 | 排序角度 | 展示位置 | 去重后笔记 | 来源(搜索/达人主页) | 采集时间 | 备注 |
| --- | --- | --- | --- | --- | --- | --- | --- |

## 四、重点笔记与达人（合并去重，保留出处）
| 笔记/达人 | 出现关键词(保留全部) | 来源(本人/第三方) | 商业化浓度(自然/疑似投放/合作) | 正文要点 | 素材 | 评论要点 | 关键判断 |
| --- | --- | --- | --- | --- | --- | --- | --- |

## 五、评论行为归类
| 内容 | 向往状态 | 追问选择 | 确认效果/风险 | 比较产品 | 说明 |
| --- | --- | --- | --- | --- | --- | --- |

## 六、关键判断与下一步
- 用户在问什么:
- 平台内容怎样回答:
- 谁来讲 / 谁最可信:
- 下一步建议:

## 七、证据边界（必填）
- 样本量 / 覆盖:
- 不能下结论的部分:
- 需品牌自有数据验证的:

## 八、决策结论（必填，分析须收敛到投决）
- 投决建议: GO / NO-GO / 条件GO（附条件）:
- 找谁讲: 推荐达人类型与各自信问题边界（状态/成分/测评/官方）:
- 讲什么角度: 状态/成分/实测/怎么选/值不值/进入日常生活:
- 证据边界内置信度: 高/中/低:

---

> 由 擎漫网络 | Qomob.AI 提供支持
"""


def main():
    category = sys.argv[1] if len(sys.argv) > 1 else "{{品类}}"
    out_path = sys.argv[2] if len(sys.argv) > 2 else None
    md = build(category)
    if out_path:
        # 若为目录则自动补文件名
        if os.path.isdir(out_path):
            out_path = os.path.join(out_path, "赛道分析主表.md")
        with open(out_path, "w", encoding="utf-8") as f:
            f.write(md)
        print("written:", out_path)
    else:
        sys.stdout.write(md)


if __name__ == "__main__":
    main()
