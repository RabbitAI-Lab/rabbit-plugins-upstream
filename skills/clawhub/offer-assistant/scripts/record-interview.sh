# - 面试官风格：
# - 答得好的点：
# - 答得不好的点：
# - Agent 评估：
# - 核心教训：
# - 行动项：
#
# ## 投递记录（文档头部汇总）
# | 公司 | 岗位 | 投递时间 | 状态 |
# |------|------|---------|------|
# | XX   | YY   | 07-12   | 已面 |

