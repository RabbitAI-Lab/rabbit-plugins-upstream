def focus_ids(primary: str, secondary: str | None) -> dict:
    out = {fid: txt for fid, txt in _sector(primary)["focus"]}
    if secondary:
        out.update({"S" + fid[1:]: txt for fid, txt in _sector(secondary)["focus"]})
    return out


