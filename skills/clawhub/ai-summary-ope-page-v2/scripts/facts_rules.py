def cmd_detect(args) -> None:
    """Отдать модели первые DETECT_PAGES страниц и каталог секторов: сектор решает модель."""
    jdir = core.job_dir(args.job)
    meta = core.read_json(jdir / "meta.json", {})
    total = int(meta.get("pages_total", 0) or 0)
    upto = min(DETECT_PAGES, total) if total else DETECT_PAGES
    pages, empty = [], []
    for n in range(1, upto + 1):
        txt = core.page_text(jdir, n).strip()
        if not txt:
            empty.append(n)
        pages.append({"page": n, "text": txt})
    if empty and len(empty) == len(pages):
        core.fail("На первых %d страницах нет текстового слоя — сектор определять не по чему." % upto,
                  "Сначала распознайте страницы: pdf.py ocr %s, затем повторите detect." % args.job,
                  pages_without_text=empty)
    catalogue = [{"id": k, "name": v["name"], "ru": v["ru"], "scope": v["scope"]} for k, v in SECTORS.items()]
    catalogue.append({"id": "general", "name": GENERAL["name"], "ru": GENERAL["ru"], "scope": GENERAL["scope"]})
    resp = {"ok": True, "job": args.job,
            "pdf_title": meta.get("pdf_title", ""), "pdf_author": meta.get("pdf_author", ""),
            "pages_total": total, "doc_language": meta.get("doc_language", ""),
            "first_pages": pages,
            "catalogue": catalogue,
            "boundaries": BOUNDARIES,
            "how_to_choose": ("Прочитай первые страницы и реши как ведущий аналитик: о какой отрасли документ и "
                              "чьи показатели в нём главные. Выбери один id из catalogue; если документ о двух "
                              "отраслях — основной сектор и --secondary. Пограничные случаи — в boundaries. Если "
                              "документ межотраслевой или подходящего сектора нет — general. В --why одной фразой "
                              "напиши, на чём основан выбор (о чём документ, чьи показатели)."),
            "next": "facts_rules.py set %s --sector <id> [--secondary <id>] --why '<одной фразой>'" % args.job}
    if empty:
        resp["pages_without_text"] = empty
        resp["note"] = ("Страницы %s без текста (скан или картинки): если по остальным сектор неясен — сначала "
                        "pdf.py ocr %s." % (empty, args.job))
    cur = load(jdir)
    if cur:
        resp["current"] = cur
    core.out(resp)


def cmd_set(args) -> None:
    jdir = core.job_dir(args.job)
    primary = _resolve(args.sector)
    if not primary:
        core.fail("Неизвестный сектор: %r." % args.sector,
                  "Возьмите id из facts_rules.py list (например semi_memory, fig, datacenters) или general.")
    secondary = _resolve(args.secondary) if args.secondary else None
    if args.secondary and not secondary:
        core.fail("Неизвестный второй сектор: %r." % args.secondary, "id — из facts_rules.py list.")
    if secondary == primary:
        secondary = None
    data = {"sector": primary, "name": _sector(primary)["name"], "secondary": secondary,
            "secondary_name": _sector(secondary)["name"] if secondary else None,
            "why": core.as_text(args.why)[:300]}
    prev = load(jdir)
    core.write_json(jdir / "sector.json", data)
    extra = {}
    n_facts = len(core.read_json(jdir / "facts.json", {"facts": []}).get("facts", []))
    if prev and prev.get("sector") != primary and n_facts:
        extra["warning"] = ("Сектор сменён с %s на %s, а в реестре уже %d фактов: их поля focus относятся к прежним правилам. "
                            "Проверьте реестр (facts.py list) и при необходимости пересдайте ключевые факты." % (prev.get("sector"), primary, n_facts))
    core.out({"ok": True, "job": args.job, **data, **extra,
              "focus": focus_ids(primary, secondary),
              "rules": render_rules(primary, secondary),
              "next": ("Держи эти правила перед глазами при чтении: pdf.py pages %s --pages 1-8, затем facts.py add. "
                       "В конце facts.py stats покажет, по каким пунктам focus фактов нет." % args.job)})


def cmd_show(args) -> None:
    if args.job:
        jdir = core.job_dir(args.job)
        cur = load(jdir)
        if not cur:
            core.fail("Сектор для задания не выбран.", "facts_rules.py detect %s, затем set." % args.job)
        primary, secondary = cur["sector"], cur.get("secondary")
    else:
        primary = _resolve(args.sector)
        secondary = _resolve(args.secondary) if args.secondary else None
        if not primary:
            core.fail("Укажите <job> или --sector <id>.")
    core.out({"ok": True, "sector": primary, "secondary": secondary, "rules": render_rules(primary, secondary)})


def main() -> None:
    core.setup_stdio()
    ap = core.JsonArgumentParser(prog="facts_rules.py", description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd")
    p = sub.add_parser("list"); p.set_defaults(fn=cmd_list)
    p = sub.add_parser("detect"); p.add_argument("job"); p.set_defaults(fn=cmd_detect)
    p = sub.add_parser("set"); p.add_argument("job"); p.add_argument("--sector", required=True)
    p.add_argument("--secondary"); p.add_argument("--why"); p.set_defaults(fn=cmd_set)
    p = sub.add_parser("show"); p.add_argument("job", nargs="?"); p.add_argument("--sector"); p.add_argument("--secondary")
    p.set_defaults(fn=cmd_show)
    args = ap.parse_args()
    if not getattr(args, "fn", None):
        core.fail("Не указана команда.", "Доступно: list, detect, set, show.")
    args.fn(args)


if __name__ == "__main__":
    try:
        main()
    except SystemExit:
        raise
    except Exception as e:
        core.fail("Внутренняя ошибка facts_rules.py: %s: %s" % (type(e).__name__, e))
