def _sentences(text: str) -> list[str]:
    keep = "\x01"   # временная склейка: инициалы и сокращения не делят предложение
    t = re.sub(r"(?<![\w-])([А-ЯЁA-Z]\.)[\s\u00a0]+(?=[А-ЯЁA-Z])", r"\1" + keep, text)
    t = re.sub(r"\b(г|гг|млн|млрд|трлн|тыс|долл|руб|т\.\s?е|т\.\s?д|др|пр)\.[\s\u00a0]+(?=[а-яёa-z0-9(«])", r"\1." + keep, t)
    parts = re.split(r"(?<=[.!?…])\s+(?=[«\"(]?[А-ЯЁA-Z0-9])", t.strip())
    return [p.replace(keep, " ") for p in parts if p.strip()]


def _words(s: str) -> list[str]:
    return re.findall(r"[A-Za-zА-Яа-яЁё0-9%]+(?:[-\u2011–][A-Za-zА-Яа-яЁё0-9%]+)*", s)


def _stems(s: str) -> set[str]:
    out = set()
    for w in re.findall(r"[а-яё]{4,}|[a-z]{3,}", s.lower()):
        st = w[:5]
        if st not in STOP_STEMS:
            out.add(st)
    return out


def _has_number(s: str) -> bool:
    return bool(re.search(r"\d", s))


def check(data: dict) -> tuple[list[dict], list[dict], dict]:
    errors: list[dict] = []
    warnings: list[dict] = []

    def add(bucket, where, cat, problem, fix):
        bucket.append({"where": where, "category": cat, "problem": problem, "fix": fix})

    def E(where, problem, fix, cat="естественность"):
        add(errors, where, cat, problem, fix)

    def W(where, problem, fix, cat="естественность"):
        add(warnings, where, cat, problem, fix)

    findings = [f for f in (data.get("findings") or []) if isinstance(f, dict)]
    questions = [q for q in (data.get("questions") or []) if isinstance(q, dict)]

    # Куски текста: (где, роль, текст)
    blocks: list[tuple[str, str, str]] = [("title", "title", str(data.get("title") or "")),
                                          ("lede", "lede", str(data.get("lede") or ""))]
    for i, f in enumerate(findings, 1):
        blocks.append(("вывод %d.lead" % i, "lead", str(f.get("lead") or "")))
        blocks.append(("вывод %d.body" % i, "fbody", str(f.get("body") or "")))
    for i, q in enumerate(questions, 1):
        blocks.append(("вопрос %d.q" % i, "q", str(q.get("q") or "")))
        blocks.append(("вопрос %d.body" % i, "qbody", str(q.get("body") or "")))
        blocks.append(("вопрос %d.ask" % i, "ask", str(q.get("ask") or "")))

    soft_parallel: list[str] = []
    triads: list[str] = []
    body_sents: list[str] = []
    dash_total = 0

    for where, role, text in blocks:
        if not text.strip():
            continue
        low = text.lower()
        # ---------- лексика (везде)
        for rx, problem, fix in STAMPS + CONNECTORS:
            m = re.search(rx, low)
            if m:
                E(where, "%s: «%s»" % (problem, m.group(0).strip(" .,")), fix)
        m = re.search(VAGUE_ATTR, low)
        if m:
            E(where, "размытая атрибуция «%s»" % m.group(0), "назовите источник из документа: «по оценке авторов», «по данным опроса 1 200 банков»")
        m = re.search(CHATBOT, low)
        if m:
            E(where, "реплика чат-бота «%s»" % m.group(0), "уберите: резюме обращается к читателю, а не к заказчику")
        for rx, problem in ARTIFACTS:
            m = re.search(rx, text)
            if m:
                E(where, "%s: «%s»" % (problem, m.group(0).strip()), "обычный текст без разметки и служебных символов")
        if role in ("title", "lede"):
            continue

        # ---------- синтаксис (выводы и вопросы)
        sents = _sentences(text)
        m = re.search(NEG_PARALLEL_HARD, low)
        if m:
            E(where, "шаблон «не только…, но и / не просто…, а»: «%s»" % m.group(0)[:60],
              "скажите одно утверждение прямо: «Банки теряют и комиссию, и клиентов»")
        m = re.search(NEG_PARALLEL_SOFT, low)
        if m:
            soft_parallel.append("%s: «%s»" % (where, m.group(0)[:50]))
        if re.search(BOTH_SIDES, low):
            E(where, "уклончивое «с одной стороны… с другой»", "займите позицию документа: что перевешивает и почему")
        m = re.search(REVEAL, low)
        if m:
            E(where, "драматическое «%s:» перед ответом" % m.group(0).strip(" .:"), "сразу назовите причину: «Причина в том, что…» или без вступления")
        m = re.search(PARTICIPLE_TAIL, low)
        if m:
            E(where, "хвост значимости «%s…»" % m.group(0).strip(", "),
              "уберите деепричастный хвост; если следствие важно — отдельное предложение с фактом")
        m = re.search(WHAT_TAIL, low)
        if m:
            E(where, "хвост-оценка «%s…»" % m.group(0).strip(", "), "оценку уберите; оставьте факт или скажите следствие с числом")
        m = re.search(FALSE_RANGE, low)
        if m and not re.search(r"\d", m.group(0)):
            E(where, "ложный диапазон «%s»" % m.group(0), "назовите, кого именно это касается, без «от … до …»")
        m = re.search(NOUN_CHAIN, low)
        if m:
            E(where, "цепочка отглагольных существительных «%s»" % m.group(0), "перестройте через глагол: «чтобы платежи проходили быстрее»")
        m = re.search(PASSIVE, low)
        if m:
            W(where, "канцелярский пассив «%s»" % m.group(0), "назовите, кто действует: «банки проводят…»")
        if role in ("lead", "fbody", "qbody") and "?" in text:
            E(where, "риторический вопрос в утверждении", "вопросы — только в блоке «Вопросы для обсуждения»")
        if role == "lead" and re.search(r"[а-яё]+, [а-яё]+ и [а-яё]+", low):
            E(where, "перечисление-тройка в тезисе", "тезис — одно утверждение, без списка")
        for s in sents:
            sl = s.lower().strip()
            dashes = s.count(DASH) + len(re.findall(r"\s[-–]\s", s))
            dash_total += dashes
            if dashes >= 2:
                E(where, "два тире в одном предложении: «%s…»" % s[:50], "оставьте одно тире; второе — точка или запятая")
            if s.count(":") >= 2:
                E(where, "два двоеточия в одном предложении", "разбейте на два предложения")
            mt = re.search(r"([а-яё]+(?:\s[а-яё]+)?), ([а-яё]+(?:\s[а-яё]+)?),? и ([а-яё]+(?:\s[а-яё]+)?)", sl)
            if mt and not re.search(r"\d", mt.group(0)):
                triads.append("%s: «%s»" % (where, mt.group(0)[:50]))
            if re.match(VAGUE_THIS, sl):
                E(where, "предложение начинается с «%s» — непонятно, к чему оно относится" % sl.split()[0],
                  "назовите предмет: «Такой разрыв…», «Рост мошенничества…»", "ясность")
            if role in ("fbody", "qbody"):
                mi = re.search(INTENSIFIERS, sl)
                if mi and not _has_number(s):
                    E(where, "усилитель без числа «%s»: «%s…»" % (mi.group(0), s[:50]),
                      "замените на число из документа или уберите усилитель", "ясность")
                elif mi:
                    W(where, "лишний усилитель «%s» рядом с числом" % mi.group(0), "число говорит само; уберите усилитель")
                mq = re.search(VAGUE_QTY, sl)
                if mq and not _has_number(s):
                    W(where, "неопределённое количество «%s»" % mq.group(0), "дайте число из документа: сколько именно", "ясность")
                mc = re.search(COMPARATIVE_BARE, sl)
                if mc:
                    W(where, "сравнение без второй стороны: «%s…»" % s[:60], "добавьте, с чем сравнивают: «…выше, чем у банков без проверки»", "ясность")
                if re.search(TIMES_NO_BASE, sl) and not re.search(r"\bчем\b|против|по сравнению|относительно|\bс \w+", sl):
                    W(where, "«в N раз» без базы: «%s…»" % s[:60], "чем что: «в 3 раза больше, чем в 2022 г.»", "ясность")
                if re.search(CHANGE, sl) and re.search(r"на \d", sl) and not re.search(PERIOD, sl):
                    W(where, "изменение без периода или базы: «%s…»" % s[:60], "за какой период или по сравнению с кем: «на 27% за 2025 г.», «на 12%, а у опоздавших — минус 4%»; "
                      "если периода в документе нет — дайте вторую сторону сравнения", "ясность")
                nums = re.findall(r"\d+(?:[.,]\d+)?%?", s)
                if len(nums) > 4:
                    W(where, "в одном предложении %d чисел" % len(nums), "оставьте одно сравнение: два числа на предложение", "ясность")
                body_sents.append(s)
        if role in ("fbody", "qbody") and sents:
            first = sents[0].lower().strip()
            if re.match(PRONOUN_START, first):
                E(where, "пункт начинается с местоимения «%s» — неясно, о ком речь" % first.split()[0],
                  "назовите участника прямо: «Банки…», «Клиенты…»", "ясность")
            # связность соседних предложений
            for a, b in zip(sents, sents[1:]):
                if not (_stems(a) & _stems(b)) and not re.search(LINKS, b.lower()[:80]):
                    W(where, "не видна связь между предложениями: «%s…» → «%s…»" % (a[:35], b[:35]),
                      "второе предложение должно продолжать первое: общий предмет, «поэтому», «при этом», «у них»", "ясность")
        if role == "fbody" and re.search(r"\b(мы|нас|нам|наш\w*)\b", low):
            W(where, "«мы» в выводе: неясно — авторы отчёта или наша компания", "в выводах — «авторы», «банки»; «мы» — только в вопросах", "ясность")

    # ---------- связь тезиса и тела
    for i, f in enumerate(findings, 1):
        lead, body = str(f.get("lead") or ""), str(f.get("body") or "")
        if lead and body and not (_stems(lead) & _stems(body)):
            W("вывод %d" % i, "тело не подхватывает слова тезиса — читатель не увидит, что оно его доказывает",
              "первое предложение тела должно говорить о том же предмете, что и тезис", "ясность")

    # ---------- по всему резюме
    if len(soft_parallel) > 1:
        E("резюме", "противопоставление «не X, а Y» / «X, а не Y» повторяется %d раз: %s" % (len(soft_parallel), "; ".join(soft_parallel[:3])),
          "оставьте не больше одного на всё резюме; остальные — прямые утверждения")
    if len(triads) >= 3:
        E("резюме", "перечисления-тройки повторяются %d раз: %s" % (len(triads), "; ".join(triads[:3])),
          "оставьте одну тройку; в остальных — два пункта или одно обобщение")
    items = len(findings) + len(questions)
    if items and dash_total > max(3, items // 2 + 1):
        E("резюме", "длинное тире %d раз на %d пунктов" % (dash_total, items),
          "не больше одного тире на два пункта: замените на глагол, запятую или точку")

    def same_start(texts: list[str], label: str, n_words: int = 1, limit: int = 3) -> None:
        heads = [" ".join(t.lower().split()[:n_words]) for t in texts if t.strip()]
        for h in set(heads):
            if heads.count(h) >= limit:
                E("резюме", "%s начинаются одинаково («%s…») — %d раз" % (label, h, heads.count(h)),
                  "начните по-разному: с участника, с числа, с причины")

    same_start([str(f.get("lead") or "") for f in findings], "тезисы")
    same_start([str(f.get("body") or "") for f in findings], "тела выводов", 2, 3)
    same_start([str(q.get("q") or "") for q in questions], "вопросы", 1, 3)
    same_start([str(q.get("ask") or "") for q in questions], "замыкающие вопросы", 2, 3)
    year_starts = sum(1 for s in body_sents if re.match(r"\s*в 20\d\d", s.lower()))
    if year_starts >= 4:
        W("резюме", "%d предложений начинаются с «В 20XX г.»" % year_starts, "чередуйте: начните с участника или с причины")
    lead_lens = [len(str(f.get("lead") or "")) for f in findings]
    if len(lead_lens) >= 5 and statistics.pstdev(lead_lens) < 4:
        W("резюме", "все тезисы одной длины — механический ритм", "сделайте один-два тезиса заметно короче")

    lengths = [len(_words(s)) for s in body_sents]
    cv = round(statistics.pstdev(lengths) / statistics.mean(lengths), 2) if len(lengths) >= 2 and statistics.mean(lengths) else None
    if cv is not None and len(lengths) >= 6 and cv < 0.25:
        W("резюме", "предложения почти одной длины (разброс %.2f при норме от 0,3)" % cv,
          "чередуйте: короткое предложение на 5–8 слов после длинного")
    concrete = round(sum(1 for s in body_sents if _has_number(s) or re.search(r"\b[A-ZА-ЯЁ][a-zа-яё]+\s[A-ZА-ЯЁ]|[A-Z]{2,}", s[1:]))
                     / len(body_sents), 2) if body_sents else None
    if concrete is not None and concrete < 0.5:
        W("резюме", "конкретики мало: число или название есть в %d%% предложений" % round(concrete * 100),
          "в каждом пункте — минимум одно число из документа", "ясность")
    metrics = {
        "sentences": len(body_sents),
        "avg_words": round(statistics.mean(lengths), 1) if lengths else None,
        "length_spread_cv": cv,
        "concrete_share": concrete,
        "dashes": dash_total,
        "triads": len(triads),
        "contrast_not_x_but_y": len(soft_parallel),
        "_": ("разброс длины (cv) у живого текста обычно от 0,3; доля конкретики — доля предложений с числом или названием"),
    }
    return errors, warnings, metrics
