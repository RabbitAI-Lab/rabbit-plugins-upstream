def render_policy_csv() -> str:
    """渲染政策工具箱 CSV。按 行情阶段 → 政策层级 → tool_id 排序，保证确定性。"""
    order = {s: i for i, s in enumerate(ENUM_MARKET_STAGE)}
    level = {s: i for i, s in enumerate(ENUM_POLICY_LEVEL)}
    return csvio.render_csv(
        POLICY_RECORDS,
        POLICY_FIELDS,
        sort_key=lambda r: (order.get(r["market_stage"], 99), level.get(r["level"], 99), r["tool_id"]),
    )


