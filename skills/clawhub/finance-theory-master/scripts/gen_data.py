def render_case_csv() -> str:
    """渲染投资案例 CSV。按 case_id 排序，保证确定性。"""
    return csvio.render_csv(CASE_RECORDS, CASE_FIELDS, sort_key=lambda r: r["case_id"])


def main() -> int:
    ap = argparse.ArgumentParser(description="生成或校验全部数据集")
    ap.add_argument("--check", action="store_true", help="只比对，不写入")
    ap.add_argument("--out", default=None, help="理论索引输出路径（覆盖默认）")
    args = ap.parse_args()

    targets = [
        (Path(args.out) if args.out else OUT, render_csv(), len(RECORDS), "理论索引"),
        (TIMELINE_OUT, render_timeline_csv(), len(TIMELINE_RECORDS), "金融史时间线"),
        (POLICY_OUT, render_policy_csv(), len(POLICY_RECORDS), "政策工具箱"),
        (CASE_OUT, render_case_csv(), len(CASE_RECORDS), "投资案例"),
    ]

    if args.check:
        failed = False
        for path, text, n, label in targets:
            if not path.exists():
                print(f"[FAIL] {label}：目标文件不存在 {path}")
                failed = True
            elif path.read_text(encoding="utf-8") != text:
                print(f"[FAIL] {label}：磁盘内容与生成结果不一致，请重新生成")
                failed = True
            else:
                print(f"[OK] {label}：与磁盘一致，{n} 条记录")
        return 1 if failed else 0

    for path, text, n, label in targets:
        if csvio.write_if_changed(path, text):
            print(f"[OK] 已写入 {path}（{label}，{n} 条记录）")
        else:
            print(f"[--] 未变化 {path}（{label}，{n} 条记录）")
    return 0


if __name__ == "__main__":
    sys.exit(main())
