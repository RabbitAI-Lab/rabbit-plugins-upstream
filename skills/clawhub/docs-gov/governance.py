def _skill_home() -> Path:
    """Where the skill source is installed: the common skill install directories under the home directory.
    The source path must not be hard-coded to one machine's directory — anyone installed elsewhere would never find the source,
    and the template fallback would fail silently.
    DOC_GOVERNANCE_HOME is deliberately NOT consulted here: this location supplies code that init installs and that then runs
    on every commit, and an inherited environment variable is not something to trust with that. The variable only tells
    pre-commit where to find the source for its read-only drift comparison."""
    for base in SKILL_INSTALL_DIRS:
        cand = Path.home() / base / "docs-gov"
        if (cand / "governance.py").is_file():
            return cand
    return SKILL_DIR


SKILL_HOME = _skill_home()
PROVENANCE = ("# This is a copy of governance.py from the docs-gov skill (installed into the project for CI and pre-commit).\n"
              "# After the source is upgraded, cp it again (source: where the skill is installed, e.g. ~/.claude|.cursor|.codex/skills/docs-gov);\n"
              "# don't edit it here on its own — two diverging copies are exactly the disease this script guards against.\n")


def _templates_dir() -> Path:
    """The templates directory. Once installed, this script is a copy under scripts/, and templates/ isn't next to it —
    that's exactly how the first init on a real repo crashed (FileNotFoundError, propagated to the top of the stack).
    Unit tests run inside the skill source directory and never hit this path."""
    for d in (SKILL_DIR / "templates", SKILL_HOME / "templates"):
        if d.is_dir():
            return d
    raise SelfCheckFailure(
        f"Can't find the templates directory (looked in {SKILL_DIR / 'templates'} and {SKILL_HOME / 'templates'})."
        "\n  Run init from the skill source directory, or put templates/ next to the script.")


def _checker_path() -> Path:
    """The file init copies: always the governance.py that is actually running — the code you invoked and can inspect —
    never a file some other directory or variable points at."""
    return Path(__file__).resolve()


def _checker_source() -> str:
    """The script body to copy into the project. A copy can itself serve as the source — strip any existing provenance note first,
    so installing again doesn't stack another layer."""
    text = _checker_path().read_text(encoding="utf-8")
    return text.replace(PROVENANCE, "", 1)


def plan_init(root: Path, cfg: dict | None, comps: list[Component] | None) -> list[tuple[str, str]]:
    """Return [(action, description)] without executing anything. Install what's missing; leave what exists alone."""
    actions: list[tuple[str, str]] = []
    if not (root / CONFIG_NAME).exists():
        actions.append(("config", f"create {CONFIG_NAME} (this skill's config; checks can't run without it)"))
    if not (root / "scripts" / "governance.py").exists():
        src = _checker_path()
        digest = hashlib.sha256(src.read_bytes()).hexdigest()[:12]
        actions.append(("script", f"copy governance.py into scripts/ (CI can't reach the skill directory on this machine) — from {src}, sha256 {digest}"))
    if not (root / ".githooks" / "pre-commit").exists() and is_git_repo(root):
        actions.append(("hook", "install .githooks/pre-commit and link it into .git/hooks (closes the path where direct pushes bypass CI)"))
    if not all((root / ".claude" / "hooks" / n).exists() for n in CLAUDE_HOOKS):
        desc = ("install two Claude Code hooks and register them in .claude/settings.json"
                " (hard gate before writing a new plan / cascade check right after editing a decision)")
        for n in CLAUDE_HOOKS:
            dest = root / ".claude" / "hooks" / n
            if dest.is_file():
                src = _templates_dir() / n.replace("doc-governance-", "claude-hook-")
                same = dest.read_bytes() == src.read_bytes()
                desc += (f"; existing .claude/hooks/{n} "
                         + ("matches the bundled hook" if same else "differs from the bundled hook — kept, and neither hook will be registered"))
        actions.append(("claude-hooks", desc))
    for c in comps or []:
        if c.verdict == "missing" and c.installable and c.key == "G2":
            actions.append(("adr", f"create {cfg['adr_dir'] if cfg else 'docs/adr'}/README.md and a decision template"))
        if c.verdict == "missing" and c.installable and c.key == "G4":
            actions.append(("plan", f"create {cfg['plan_dir'] if cfg else 'docs/planning'}/README.md and a plan template"))
    return actions


def do_init(root: Path, actions: list[tuple[str, str]], cfg: dict | None) -> list[str]:
    done: list[str] = []

    # Every directory created and every file written is checked on its own, right before it happens.
    # A symlinked directory or file would otherwise carry the write out of the repository. The first version of this guard
    # checked one representative path per action and missed the .git/hooks shim and .claude/settings.json.
    def outside(path: Path) -> bool:
        if _inside(root, path):
            return False
        done.append(f"⚠️ skipped {path.relative_to(root)}: it resolves outside the repository (a symlink?) — nothing written there")
        return True

    # "Existing files are left alone" is enforced here, not only by plan_init's filtering: a security audit found that
    # with one Claude hook present and the other missing, the combined action rewrote both. Only settings.json, which is
    # merged rather than replaced, passes replace=True.
    def write(path: Path, text: str, executable: bool = False, replace: bool = False) -> bool:
        if outside(path.parent) or outside(path):
            return False
        if not replace and (path.exists() or path.is_symlink()):
            done.append(f"⚠️ preserved existing {path.relative_to(root)} — not overwritten")
            return False
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        if executable:
            path.chmod(0o755)
        return True

    for kind, _ in actions:
        if kind == "config":
            _found = discover_layout(root) or {}
            if write(root / CONFIG_NAME, json.dumps({
                "docs_root": "docs",
                "adr_dir": _found.get("adr_dir", "docs/adr"),
                "plan_dir": _found.get("plan_dir", "docs/planning"),
                "exclude": [], "pending_exclude": [],
                "pending_max_days": 30, "stale_plan_days": 45,
                # Allowed domain values for this project; empty = not checked. Fill it in to block typos
                "adr_domains": [],
            }, ensure_ascii=False, indent=2) + "\n"):
                done.append(CONFIG_NAME)
        elif kind == "script":
            head, rest = _checker_source().split("\n", 1)
            if write(root / "scripts" / "governance.py", head + "\n" + PROVENANCE + rest):
                done.append("scripts/governance.py")
        elif kind == "hook":
            hook = (_templates_dir() / "pre-commit").read_text(encoding="utf-8")
            if write(root / ".githooks" / "pre-commit", hook, executable=True):
                done.append(".githooks/pre-commit")
            live = root / ".git" / "hooks" / "pre-commit"
            if live.parent.is_dir() and not live.exists() and \
                    write(live, "#!/bin/sh\nset -eu\nexec sh \"$(git rev-parse --show-toplevel)/.githooks/pre-commit\" \"$@\"\n", executable=True):
                done.append(".git/hooks/pre-commit (forwarding shim)")
        elif kind == "claude-hooks":
            # Installed at project level and committed to git — same reason as .githooks/: under ~/.claude it would be private to this machine,
            # absent from fresh clones, invisible to other sessions, and changes wouldn't show up in git status.
            hooks_dir = root / ".claude" / "hooks"
            installed = True
            for name in CLAUDE_HOOKS:
                dest = hooks_dir / name
                src = _templates_dir() / name.replace("doc-governance-", "claude-hook-")
                if dest.is_file() and _inside(root, dest):
                    # Keep an existing file as is, but only register what is provably ours: a file planted under this name
                    # would otherwise become a hook Claude Code runs on every write (security audit finding). Registration is
                    # all or nothing, so one unverified hook blocks both.
                    have, want = hashlib.sha256(dest.read_bytes()).hexdigest(), hashlib.sha256(src.read_bytes()).hexdigest()
                    if have == want:
                        done.append(f"⚠️ preserved existing .claude/hooks/{name} — identical to the bundled hook")
                    else:
                        done.append(f"⚠️ preserved existing .claude/hooks/{name} — not overwritten, and not registered: its sha256 {have[:12]}"
                                    f" differs from the bundled hook's {want[:12]}. Review it; if you trust it, register the hooks manually")
                        installed = False
                    continue
                if write(dest, src.read_text(encoding="utf-8"), executable=True):
                    done.append(f".claude/hooks/{name}")
                else:
                    installed = False
            if not installed:
                continue  # don't register hooks that weren't installed
            settings = root / ".claude" / "settings.json"
            if outside(settings):
                continue
            data = {}
            if settings.is_file():
                try:
                    data = json.loads(settings.read_text(encoding="utf-8"))
                except json.JSONDecodeError:
                    done.append("⚠️ .claude/settings.json is not valid JSON, so it was left untouched — register the two hooks manually")
                    continue
                if not isinstance(data, dict) or not isinstance(data.get("hooks", {}), dict):
                    done.append("⚠️ .claude/settings.json doesn't have the expected object shape, so it was left untouched — register the two hooks manually")
                    continue
            hooks = data.setdefault("hooks", {})
            for name, (event, matcher, _) in CLAUDE_HOOKS.items():
                cmd = f'sh "$CLAUDE_PROJECT_DIR/.claude/hooks/{name}"'
                entries = hooks.setdefault(event, [])
                if any(h.get("command") == cmd for e in entries for h in e.get("hooks", [])):
                    continue
                slot = next((e for e in entries if e.get("matcher") == matcher), None)
                if slot is None:
                    slot = {"matcher": matcher, "hooks": []}
                    entries.append(slot)
                slot.setdefault("hooks", []).append({"type": "command", "command": cmd})
            if write(settings, json.dumps(data, ensure_ascii=False, indent=2) + "\n", replace=True):
                done.append(".claude/settings.json (registered two hooks)")
        elif kind in ("adr", "plan"):
            key = "adr_dir" if kind == "adr" else "plan_dir"
            d = root / ((cfg or {}).get(key) or f"docs/{'adr' if kind=='adr' else 'planning'}")
            tpl = _templates_dir() / f"{kind}-README.md"
            if tpl.is_file() and not (d / "README.md").exists() and write(d / "README.md", tpl.read_text(encoding="utf-8")):
                done.append(f"{d.relative_to(root)}/README.md")
    return done


# ───────────────────────── Checks (check) ─────────────────────────


def run(root: Path, modes: tuple[str, ...] = ALL_MODES, today: date | None = None) -> tuple[list[Finding], dict[str, int]]:
    """Return (findings, files scanned per mode). Raises SelfCheckFailure when a self-check fails."""
    today = today or date.today()
    cfg = load_config(root)
    counts: dict[str, int] = {}
    findings: list[Finding] = []

    for key in REQUIRED_KEYS:
        if len(md_files(root, cfg, cfg[key])) == 0:
            raise SelfCheckFailure(f"{key}={cfg[key]!r} contains no .md files. Either the config points at the wrong place or the directory was emptied — both must be red.")

    for mode in modes:
        if mode == "pending":
            findings += check_pending(root, cfg, today); counts[mode] = len(md_files(root, cfg))
        elif mode == "cascade":
            findings += check_cascade(root, cfg); counts[mode] = len(md_files(root, cfg, cfg["adr_dir"]))
        elif mode == "status":
            findings += check_status(root, cfg, today); counts[mode] = len(md_files(root, cfg, cfg["plan_dir"]))
        elif mode == "refs":
            findings += check_refs(root, cfg); counts[mode] = len(md_files(root, cfg, cfg["adr_dir"]))
        elif mode == "links":
            findings += check_links(root, cfg); counts[mode] = len(md_files(root, cfg))
        elif mode == "sections":
            findings += check_sections(root, cfg); counts[mode] = len(md_files(root, cfg))
        elif mode == "index":
            findings += check_index(root, cfg); counts[mode] = len(md_files(root, cfg, cfg["adr_dir"]))
        elif mode == "tables":
            findings += check_tables(root, cfg); counts[mode] = len(md_files(root, cfg))
        elif mode == "contract":
            findings += check_contract(root, cfg); counts[mode] = len(cfg.get("contract_checks") or [])
        else:
            raise SelfCheckFailure(f"unknown mode {mode!r}. Available: {', '.join(ALL_MODES)}")
    return findings, counts


# ───────────────────────── CLI ─────────────────────────


MARK = {"ok": "✅", "partial": "⚠️ ", "missing": "❌"}


def main(argv: list[str]) -> int:
    root = Path(".")
    action = ""
    modes: list[str] = []
    assume_yes = False
    it = iter(argv)
    for arg in it:
        if arg == "--root":
            root = Path(next(it, "."))
        elif arg in ("-h", "--help"):
            print(__doc__); return 0
        elif arg == "--yes":
            assume_yes = True
        elif arg in ("audit", "init", "check") and not action:
            action = arg
        else:
            modes.append(arg)
    root = root.resolve()
    action = action or ("check" if modes else "audit")

    if action == "audit":
        try:
            cfg = load_config(root)
        except SelfCheckFailure:
            cfg = None
        if cfg is None:
            cfg, _note = fallback_cfg(root)
            print(_note + "\n")
        comps = audit(root, cfg, date.today())
        print("Documentation governance architecture audit (criteria in framework.md)\n")
        for c in comps:
            print(f"  {MARK[c.verdict]} {c.key} {c.title}")
            print(f"       {c.detail}")
            if c.verdict != "ok":
                print(f"       What goes wrong without it: {c.consequence}")
            print()
        bad = [c for c in comps if c.verdict != "ok"]
        actions = plan_init(root, cfg, comps)
        print(f"Result: {len(comps) - len(bad)}/{len(comps)} components complete.")
        if actions:
            print("\nCan be installed automatically:")
            for _, why in actions:
                print(f"  · {why}")
            print(f"\n  Run `python3 {Path(__file__).name} init --root {root}` to install (it lists the changes first and asks).")
        manual = [c for c in bad if not c.installable]
        if manual:
            print("\nCan't be installed — only filled in while writing docs:")
            for c in manual:
                print(f"  · {c.key} {c.title}")
        return 0 if not bad else 1

    if action == "init":
        try:
            cfg = load_config(root)
        except SelfCheckFailure:
            cfg = None
        eff = cfg
        if eff is None:
            eff, _note = fallback_cfg(root)
            print(_note + "\n")
        comps = audit(root, eff, date.today())
        actions = plan_init(root, eff, comps)
        if not actions:
            print("Nothing to install — everything that should be there is there."); return 0
        print("Planned changes:\n")
        for _, why in actions:
            print(f"  · {why}")
        if not assume_yes:
            print("\nListed only, nothing installed. Re-run with --yes to confirm.")
            return 0
        done = do_init(root, actions, cfg)
        print("\nInstalled:")
        for d in done:
            print(f"  {d}" if d.startswith("⚠️") else f"  ✓ {d}")
        print("\n⚠️ One manual step left: hook `python3 scripts/governance.py check --root .` into this project's "
              "existing verify/CI chain — don't build a new mechanism, attach to the existing one.")
        return 0

    # check
    try:
        findings, counts = run(root, tuple(modes) or ALL_MODES)
    except SelfCheckFailure as error:
        print(f"⛔ Self-check failed — the check mechanism itself doesn't hold; this is not “no problem”:\n  {error}")
        return 1
    for mode, n in counts.items():
        if mode == "contract":
            print(f"  [contract] checked {n} contracts against the code" if n else
                  "  [contract] ⚠️ contract_checks not configured — whether the contracts the docs declare match the code is unchecked")
        else:
            print(f"  [{mode}] scanned {n} file{'' if n == 1 else 's'}")
    if not findings:
        print("Passed: no visible drift between the docs and reality.")
        return 0
    print(f"\nFound {len(findings)} drifts:\n")
    for f in findings:
        print(f"  {f}")
    print("\nThe incident behind each mode is in incidents.md — read that first, then the line numbers above.")
    return 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
