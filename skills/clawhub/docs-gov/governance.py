#!/usr/bin/env python3
"""docs-gov — install a documentation governance architecture in a project, and diagnose what it's missing.

Three actions:
    audit   diagnose this project's documentation governance architecture (seven components G1–G7; criteria in framework.md)
    init    install the missing components (config / script copy / pre-commit gate /
            two Claude Code hooks / decision and plan templates)
    check   continuous checks: do the documents' claims about reality still hold (nine modes, below)

Distilled from the documentation system of a large protocol project — twenty-plus doc directories, hundreds of ADRs,
dozens of rules, iterated for most of a year without falling apart.

The master principle in one sentence (the core diagnosis from a real project postmortem):
    what the system actually does and what the team believes have drifted apart, and no measurement anywhere makes the drift visible; the fix is always to make it visible first.

The nine modes, each backed by at least one real incident (see incidents.md in this directory):
    pending   a "change it after X" promise left hanging too long, with nobody coming back
    cascade   ADR cascade memo: ✅ items must really have landed, ⏸ items must give a reason
    status    a plan says in progress, but the file hasn't been touched in ages
    refs      ADR references point to ADRs that don't exist; supersede relations form a cycle
    links     broken links
    sections  cross-file §X.Y references point to sections the target file doesn't have
    index     the ADR directory and the index don't fully cover each other
    tables    Markdown tables with misaligned columns / a missing separator row (rendering breaks, silently)
    contract  endpoints / fields the docs declare no longer exist in the code

Self-check principle: missing config, a nonexistent directory, zero files scanned — always red, never silently treated as "no problem".
(Source: a sync job failed yet was marked success; an alert webhook that silently returns when unconfigured is a bell with no wire.)

Usage:
    python3 governance.py audit --root <repo root>
    python3 governance.py init  --root <repo root> [--yes]
    python3 governance.py check --root <repo root> [pending|cascade|status|refs|links|sections|index|tables|contract ...]
    No action = audit. check with no mode given = run all. Exit code 1 = findings or a self-check failure.
"""

from __future__ import annotations

import hashlib
import json
import os
import re
import subprocess
import sys
from dataclasses import dataclass
from datetime import date, datetime, timedelta
from pathlib import Path

CONFIG_NAME = ".doc-governance.json"
ALL_MODES = ("pending", "cascade", "status", "refs", "links", "sections", "index", "tables", "contract")
REQUIRED_KEYS = ("docs_root", "adr_dir", "plan_dir")
DEFAULTS = {"exclude": [], "pending_exclude": [], "pending_max_days": 30, "stale_plan_days": 45,
            "adr_domains": [], "contract_checks": [], "public_content_scan": {},
            # Scaffold ledgers: status files generated by AI-collaboration scaffolds
            # that claim "what is being worked on now". By default only the two with measured data —
            # other scaffolds add themselves in config; don't presume names for things we haven't seen.
            "scaffold_ledgers": [".autopilot", "PROGRESS_SNAPSHOT.md"],
            "scaffold_stale_days": 30}

DATE_RE = re.compile(r"20\d{2}-\d{2}-\d{2}")
# "Pending X, then change" phrasing: 待 (pending) / 等 (waiting for) + a condition + a completion verb. Only this one form — narrow over broad:
# everyday words like 待办队列 ("to-do queue") or 等一下 ("wait a moment") must not be reported.
# Negative lookahead: in 待确认卡片 ("pending-confirmation card") or 待落地清单 ("to-land list"), 待 is directly followed by a
# completion verb — a noun compound (pending-X), not a "pending X, then change" promise. Common in collaboration-board docs.
# 等 is ambiguous: 等负责人拍板后 means "wait for the owner's call, then", but 产品等 stakeholder 的确认 means "product etc. stakeholders' confirmation".
# So 等 only counts as a promise with a suffix 后/再/才 ("after / then"); 待 has no such ambiguity, so the suffix is optional.
# Cost: suffix-less 等负责人确认 ("waiting for the owner to confirm") is missed — accepted, since "A 等 B's confirmation" false positives are more common.
_VERBS = r"确认|落地|完成|上线|拍板|批准|定稿|回复|答复"
PENDING_RE = re.compile(
    rf"(?:待(?!{_VERBS})[^。\n，,；;「」]{{1,30}}?(?:{_VERBS})(?:后|之后|再|才)?"
    rf"|等(?!{_VERBS})[^。\n，,；;「」]{{1,30}}?(?:{_VERBS})(?:后|之后|再|才))"
)
# Text wrapped in 「」, like 「待您确认」 ("awaiting your confirmation"), is UI copy / a card name, not a promise
QUOTED_LABEL_RE = re.compile(r"「[^」]*(?:待|等)[^」]*」")
# English: a deferred promise with a condition. Base-form verb + once/after/when/until + a completion word,
# a TODO/TBD tied to a condition, or "pending/awaiting … approval". Base form on purpose:
# "the index is updated after each merge" describes behavior; "update after X is merged" is a promise.
_EN_DONE = r"confirmed|approved|decided|finali[sz]ed|signed[ -]off|merged|shipped|released|landed|done|completed|agreed"
PENDING_EN_RE = re.compile(
    rf"\b(?:rewrite|revise|update|revisit|change|fix|redo|recheck|re-check|clean up|remove)\b[^.;\n]{{0,40}}?"
    rf"\b(?:once|after|when|until)\b[^.;\n]{{1,50}}?\b(?:{_EN_DONE})\b"
    rf"|\b(?:TODO|TBD|FIXME)\b[^.;\n]{{0,40}}?\b(?:once|after|when|until)\b"
    rf"|\b(?:pending|awaiting|waiting (?:for|on|until))\s+[^.;\n]{{0,40}}?\b(?:confirmation|approval|decision|sign-?off|review|{_EN_DONE})\b",
    re.I)
# Quoted UI labels ("Waiting for approval" tab) are copy, not promises.
QUOTED_EN_RE = re.compile(r"\u201c[^\u201d]*\u201d|\"[^\"\n]*\"")
PENDING_DONE_EN_RE = re.compile(r"\b(?:done|resolved|completed)\s*[:\u2014-]|\boriginal(?:ly| wording)\b|^\s*[-*]\s*\[x\]", re.I)
# These marks mean the pending item was already handled and is no longer left hanging (✅, strikethrough, 已完成 "done", 已于 "on <date>", 原文 "original wording", …)
PENDING_DONE_MARKS = ("✅", "~~", "已完成", "已于", "已落地", "已处理", "原表述", "原文", "原提示", "原写", "原为")
ADR_REF_RE = re.compile(r"ADR-(\d{3,4})")
# File names may carry an `ADR-` prefix: one repository named all 17 decisions `ADR-0017-xxx.md`, and with only bare
# numbers recognised none of them were read by refs/index/cascade and nothing was reported — output identical to
# "checked, no problems". The prefix is surface spelling; the frontmatter standard stays the same.
ADR_FILE_RE = re.compile(r"^(?:ADR-)?(\d{3,4})-.*\.md$")
# Plan files: `PLAN-` and `TASK-` mean the same thing (same repository: `docs/tasks/TASK-0008-xxx.md`).
# The matching "D-tier = finished" check has to recognise both too — widening recognition without widening the
# check leaves the newly recognised files with one layer less protection.
PLAN_FILE_RE = re.compile(r"^(?:PLAN|TASK)-")
PLAN_DONE_TIER_RE = re.compile(r"^(?:PLAN|TASK)-D\d")
SUPERSEDED_RE = re.compile(r"(?:被\s*ADR-(\d{3,4})\s*取代|superseded\s+by\s+ADR-(\d{3,4}))", re.I)
# ── Decision record frontmatter (field set and schema validator from the source project's hundreds of ADRs) ──
FM_REQUIRED = ("id", "title", "domain", "visibility", "status", "date")
FM_STATUS = {"draft", "accepted", "deprecated", "superseded"}
FM_VISIBILITY = {"public", "internal", "confidential"}
FM_TYPE = {"decision", "memo", "postmortem", "contrastive-analysis"}
# Relation fields: the value may be several comma-separated ADRs
FM_REL = ("supersedes", "superseded_by", "supersedes_partially", "derives_from", "extends", "related")
# A misspelled relation key is silently ignored — the key doesn't match, so the program treats it as absent,
# and "declared a supersede relation" looks exactly like "declared nothing" to the machine.
# Generalized from the source project's "forbidden keys" list: only near-misspellings that can never be legal, so zero false positives.
FM_FORBIDDEN = {
    "derives": "derives_from", "derive_from": "derives_from",
    "supersede": "supersedes", "supercedes": "supersedes",
    "superceded_by": "superseded_by", "superseeded_by": "superseded_by",
    "supersedes_by": "superseded_by",
    "extend": "extends", "relates": "related", "related_to": "related",
}
# The first body heading must state its own number — mirrors the "first non-empty line" check in the source project's schema validator.
ADR_H1_RE = re.compile(r"^#\s+ADR-(\d{3,4})(?![0-9])")
# In YAML plain scalars, "space + #" starts a comment. When the template's `status: accepted   # draft | accepted | …`
# is copied wholesale into a real ADR, the value becomes "accepted   # draft | …" and the enum check emits a message nobody can read.
FM_COMMENT_RE = re.compile(r"\s+#.*$")
FM_LINE_RE = re.compile(r"^([A-Za-z_][A-Za-z0-9_]*):\s*(.*)$")
MD_LINK_RE = re.compile(r"\[[^\]]*\]\(([^)\s]+)(?:\s+\"[^\"]*\")?\)")
# §X.Y cross-file references: either "[…§N](path)" or "[…](path) §N".
# Grab the whole link text first, then look for § inside it — a non-greedy [^\]]*? runs all the way to ], so a middle group would never match.
SECTION_LINK_RE = re.compile(r"\[([^\]]*)\]\(([^)\s#]+\.md)(?:#[^)]*)?\)\s*(?:§\s*(\d+(?:\.\d+)*))?")
SECTION_IN_TEXT_RE = re.compile(r"§\s*(\d+(?:\.\d+)*)")
# Section numbers come in two styles and both must be recognized, or a reference to an inline subsection gets misreported as wrong:
#   ① heading lines: "## 5. Title", "### 6.4 Title", "## §5 Title"
#   ② bold inline subsections: "**9.1 Home page goes minimal.**" — real projects write decision-record subsections this way
SECTION_HEAD_RE = re.compile(r"^#{1,6}\s+(?:§\s*)?(\d+(?:\.\d+)*)[.、）)\s]")
SECTION_BOLD_RE = re.compile(r"^\s*\*\*(?:§\s*)?(\d+(?:\.\d+)+)[.、）)\s]")
ESCAPED_PIPE_RE = re.compile(r"\\\|")
INLINE_CODE_RE = re.compile(r"`[^`]*`")
TABLE_SEP_RE = re.compile(r"^\s*\|[\s:|\-]+\|\s*$")
PATH_IN_ITEM_RE = re.compile(r"\[[^\]]*\]\(([^)\s#]+)|`([^`\s]+\.md)`")
# Recognize both status styles: a "Status: xxx" line, or a table row "| 状态 | xxx |" (状态 = Status).
# Measured: recognizing only the former judged three table-style plans as "missing a status field" —
# a style the checker can't read gets treated as "the document is missing something", which is a false positive.
STATUS_LINE_RE = re.compile(r"^(?:Status:\s*(.+)|\|\s*(?:状态|Status)\s*\|\s*(.+?)\s*\|)\s*$", re.M)
STATUS_LIVE_RE = re.compile(r"in_progress|active|planned|partially|pending|blocked|🚧|📋", re.I)


@dataclass(frozen=True)
class Finding:
    mode: str
    path: str
    line: int
    message: str

    def __str__(self) -> str:
        loc = f"{self.path}:{self.line}" if self.line else self.path
        return f"[{self.mode}] {loc} — {self.message}"


class SelfCheckFailure(RuntimeError):
    """The check mechanism itself doesn't hold. Must be red, never treated as "no problem"."""


# ───────────────────────── Config and file enumeration ─────────────────────────


def _inside(root: Path, path: Path) -> bool:
    """Does path, after following symlinks, still sit inside root? A textual check alone misses a symlink pointing elsewhere."""
    try:
        path.resolve().relative_to(root.resolve())
        return True
    except ValueError:
        return False


def _require_repo_relative(value: object, label: str) -> None:
    """Every path in the config is joined onto the repo root. An absolute path or a .. component
    would make check read (and init write) outside the repo — refuse it instead of following it."""
    if not isinstance(value, str) or not value.strip():
        raise SelfCheckFailure(f"{CONFIG_NAME}: {label}={value!r} must be a non-empty path relative to the repo root.")
    if Path(value).is_absolute() or ".." in Path(value).parts:
        raise SelfCheckFailure(
            f"{CONFIG_NAME}: {label}={value!r} must be a path relative to the repo root (no absolute paths, no ..)."
            " This skill only reads and writes inside the repository it was pointed at.")


def load_config(root: Path) -> dict:
    path = root / CONFIG_NAME
    if not path.exists():
        raise SelfCheckFailure(
            f"Missing {CONFIG_NAME}. Without config there's no way to know what to check — that isn't “no problem”, it's “not checked”."
            f"\n  Create one at the repo root: {{\"docs_root\":\"docs\",\"adr_dir\":\"docs/adr\",\"plan_dir\":\"docs/planning\"}}"
        )
    if not _inside(root, path):
        raise SelfCheckFailure(f"{CONFIG_NAME} resolves outside the repository (a symlink?) — refusing to read it.")
    try:
        cfg = json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as error:
        raise SelfCheckFailure(f"{CONFIG_NAME} is not valid JSON: {error}") from error
    for key in REQUIRED_KEYS:
        if key not in cfg:
            raise SelfCheckFailure(f"{CONFIG_NAME} is missing required key {key!r}")
    for key, value in DEFAULTS.items():
        cfg.setdefault(key, value)
    for key in REQUIRED_KEYS:
        _require_repo_relative(cfg[key], key)
        if not (root / cfg[key]).is_dir():
            raise SelfCheckFailure(f"{CONFIG_NAME}: {key}={cfg[key]!r} is not a directory. Config pointing at the wrong place means nothing gets checked.")
        if not _inside(root, root / cfg[key]):
            raise SelfCheckFailure(f"{CONFIG_NAME}: {key}={cfg[key]!r} resolves outside the repository (a symlink?). Refusing to scan it.")
    for i, rel in enumerate(cfg.get("scaffold_ledgers") or []):
        _require_repo_relative(rel, f"scaffold_ledgers[{i}]")
    for spec in cfg.get("contract_checks") or []:
        if not isinstance(spec, dict):
            continue
        name = spec.get("name", "contract")
        docs = spec.get("doc")
        for item in (docs if isinstance(docs, list) else [docs] if docs is not None else []):
            _require_repo_relative(item, f"contract_checks[{name}].doc")
        for pattern in spec.get("code_glob") or []:
            _require_repo_relative(pattern, f"contract_checks[{name}].code_glob")
    return cfg


def _excluded(path: Path, root: Path, cfg: dict) -> bool:
    rel = path.relative_to(root).as_posix()
    return any(rel == ex or rel.startswith(ex.rstrip("/") + "/") for ex in cfg["exclude"])


def md_files(root: Path, cfg: dict, sub: str | None = None) -> list[Path]:
    base = root / (sub or cfg["docs_root"])
    # A symlinked .md inside the docs tree can point anywhere; only files that really live in the repo are read
    files = [p for p in sorted(base.rglob("*.md")) if not _excluded(p, root, cfg) and _inside(root, p)]
    return files


def _rel(root: Path, path: Path) -> str:
    return path.relative_to(root).as_posix()


def _read_lines(path: Path) -> list[str]:
    return path.read_text(encoding="utf-8", errors="replace").split("\n")


def _first_date_in(lines: list[str]) -> date | None:
    for line in lines:
        m = DATE_RE.search(line)
        if m:
            try:
                return date.fromisoformat(m.group(0))
            except ValueError:
                continue
    return None


def _strip_code_blocks(lines: list[str]) -> list[tuple[int, str]]:
    """Return (line number, content), skipping content inside ``` fences — a "pending X" phrase in a code block is not a pending item."""
    out: list[tuple[int, str]] = []
    in_code = False
    for i, line in enumerate(lines, start=1):
        if line.lstrip().startswith("```"):
            in_code = not in_code
            continue
        if not in_code:
            out.append((i, line))
    return out


# ───────────────────────── Mode: pending ─────────────────────────


def _pending_search(line: str):
    """Chinese pattern first, then English. Either language counts."""
    return PENDING_RE.search(line) or PENDING_EN_RE.search(line)


def check_pending(root: Path, cfg: dict, today: date) -> list[Finding]:
    """How long a "pending X, then change" promise has been left hanging.
    Incident: in one PRD, "rewrite once Plan B is confirmed" hung across 8 rows; the condition was met and nobody touched it for six weeks."""
    findings: list[Finding] = []
    max_days = int(cfg["pending_max_days"])
    frozen = [ex.rstrip("/") for ex in cfg["pending_exclude"]]
    for path in md_files(root, cfg):
        rel = _rel(root, path)
        # Snapshot docs (one-off evidence, handover archives) are frozen in time — their "pending confirmation" is history, not a hanging promise.
        # Only pending is exempt; links and the other modes still check them.
        if any(rel == ex or rel.startswith(ex + "/") for ex in frozen):
            continue
        lines = _read_lines(path)
        header_date = _first_date_in(lines[:15])
        body = _strip_code_blocks(lines)
        for idx, (lineno, line) in enumerate(body):
            m0 = _pending_search(line)
            if not m0:
                continue
            if any(mark in line for mark in PENDING_DONE_MARKS) or PENDING_DONE_EN_RE.search(line):
                continue
            # A heading line describes a section, not a promise — the items under "## Pending owner confirmation" are the pending ones
            if re.match(r"^\s{0,3}#{1,6}\s", line):
                continue
            # If the matched fragment sits inside corner brackets or quotes, it's UI copy / a card name
            quotes = list(QUOTED_LABEL_RE.finditer(line)) + list(QUOTED_EN_RE.finditer(line))
            if any(q.start() <= m0.start() and m0.end() <= q.end() for q in quotes):
                continue
            # Date: this line → up to 3 lines above → file header
            when = _first_date_in([line]) or _first_date_in([b[1] for b in body[max(0, idx - 3) : idx]])
            estimated = False
            if when is None and header_date is not None:
                when, estimated = header_date, True
            snippet = m0.group(0)
            if when is None:
                findings.append(Finding("pending", _rel(root, path), lineno, f"“{snippet}” has no date, so there's no telling how long it has been hanging — add a date or resolve it"))
                continue
            age = (today - when).days
            if age > max_days:
                basis = f"estimated from the file-header date {when}" if estimated else f"since {when}"
                findings.append(Finding("pending", _rel(root, path), lineno, f"“{snippet}” — {basis}, left hanging for {age} days (limit {max_days}) — the condition arrived and nobody made the change, or should it be dropped?{' (no date on this line, so the estimate may run high — add a date to this line)' if estimated else ''}"))
    return findings


# ───────────────────────── Mode: cascade ─────────────────────────


def _cascade_items(lines: list[str]) -> list[tuple[int, str]]:
    """Extract the items in the "## Cascade memo" section, including continuation lines."""
    items: list[tuple[int, str]] = []
    in_section = False
    current: list[str] = []
    current_line = 0
    for i, line in enumerate(lines, start=1):
        if line.startswith("## "):
            if in_section and current:
                items.append((current_line, "\n".join(current)))
                current = []
            in_section = bool(CASCADE_SECTION_RE.match(line))
            continue
        if not in_section:
            continue
        if re.match(r"^- ", line):
            if current:
                items.append((current_line, "\n".join(current)))
            current = [line]
            current_line = i
        elif current and (line.startswith("  ") or line.strip() == ""):
            current.append(line)
    if in_section and current:
        items.append((current_line, "\n".join(current)))
    return items


def check_cascade(root: Path, cfg: dict) -> list[Finding]:
    """ADR cascade memo: ✅ items must really have landed, ⏸ items must give a reason.
    Incident: the first drafts of ADR-0007/0008 had no cascade memo, and a PRD conflict sat for a day; once one was added, PLAN.md and SPEC were still missed."""
    findings: list[Finding] = []
    adr_dir = root / cfg["adr_dir"]
    for path in md_files(root, cfg, cfg["adr_dir"]):
        m = ADR_FILE_RE.match(path.name)
        if not m:
            continue
        adr_num = m.group(1)
        lines = _read_lines(path)
        for lineno, item in _cascade_items(lines):
            head = item.split("\n", 1)[0]
            if "✅" in head or "[x]" in head:
                pm = PATH_IN_ITEM_RE.search(item)
                if not pm:
                    findings.append(Finding("cascade", _rel(root, path), lineno, "✅ marked “landed” but doesn't say which file it landed in — can't be verified"))
                    continue
                target_rel = (pm.group(1) or pm.group(2)).split("#")[0]
                candidates = (path.parent / target_rel, root / cfg["docs_root"] / target_rel, root / target_rel)
                target = next((c.resolve() for c in candidates if c.exists()), candidates[0].resolve())
                if not _inside(root, target):
                    findings.append(Finding("cascade", _rel(root, path), lineno,
                        f"✅ points to {target_rel}, which is outside the repository — not read, so it can't be verified from here; point it at a file in this repo"))
                    continue
                if not target.exists():
                    findings.append(Finding("cascade", _rel(root, path), lineno, f"✅ points to {target_rel}, but that file does not exist"))
                    continue
                # A directory target can't be read_text'd — this really happened: an item
                # "✅ content moved into [archive/old/](…)" crashed the whole check,
                # and none of the nine modes produced a single result. A crash is worse than a false positive: a false positive can at least be read.
                if target.is_dir():
                    findings.append(Finding("cascade", _rel(root, path), lineno,
                        f"✅ points to the directory {target_rel}, not a specific file — can't verify whether it mentions ADR-{adr_num}; point it at the specific file"))
                    continue
                text = target.read_text(encoding="utf-8", errors="replace")
                if adr_num not in text and f"ADR-{adr_num}" not in text:
                    findings.append(Finding("cascade", _rel(root, path), lineno, f"✅ says it landed in {target_rel}, but that file never mentions ADR-{adr_num} — did it really land?"))
            elif "⏸" in head or "[ ]" in head:
                reason = re.sub(r"^- \S+\s*", "", head).strip()
                body = item.split("\n", 1)[1] if "\n" in item else ""
                if len(reason) + len(body.strip()) < 20:
                    findings.append(Finding("cascade", _rel(root, path), lineno, "⏸ marked “deferred” but doesn't say why — “deliberately deferred” and “forgotten” must be told apart"))
    return findings


# ───────────────────────── Mode: status ─────────────────────────


def _last_touched(path: Path, root: Path) -> date:
    try:
        out = subprocess.run(
            ["git", "log", "-1", "--format=%cs", "--", str(path)],
            cwd=root, capture_output=True, text=True, timeout=10,
        )
        if out.returncode == 0 and out.stdout.strip():
            return date.fromisoformat(out.stdout.strip())
    except (OSError, ValueError, subprocess.SubprocessError):
        pass
    return datetime.fromtimestamp(path.stat().st_mtime).date()


def check_status(root: Path, cfg: dict, today: date) -> list[Finding]:
    """A plan says in progress but the file hasn't been touched in ages — one of the two is false.
    Incident: a product repo's plan files all stopped updating for half a month while trunk got hundreds of commits; three statuses were badly stale."""
    findings: list[Finding] = []
    stale_days = int(cfg["stale_plan_days"])
    for path in md_files(root, cfg, cfg["plan_dir"]):
        if not PLAN_FILE_RE.match(path.name):
            continue
        text = path.read_text(encoding="utf-8", errors="replace")
        sm = STATUS_LINE_RE.search(text)
        if not sm:
            continue
        status = sm.group(1) or sm.group(2) or ""
        # The status value = the part before a dash / parenthesis. Explanatory prose usually follows,
        # and it may contain words like "originally `in_progress`" — judging the whole sentence misfires (measured).
        status_value = re.split(r"[—–\-(（]", status, maxsplit=1)[0].strip().strip("`").strip()
        if not STATUS_LIVE_RE.search(status_value):
            continue
        # Number contradicts status: a D-tier (finished) plan that still says in progress / pending.
        # Real case: PLAN-D02 said in_progress and D03 said accepted, both contradicting "finished".
        # "How long untouched" can't catch it — those files aren't supposed to change anymore.
        if PLAN_DONE_TIER_RE.match(path.name) and STATUS_LIVE_RE.search(status_value):
            findings.append(Finding("status", _rel(root, path), text[: sm.start()].count("\n") + 1,
                f"the file name is D-tier (finished), but the status says “{status.strip()[:36]}” — number and status contradict each other"))
            continue

        touched = _last_touched(path, root)
        age = (today - touched).days
        if age > stale_days:
            lineno = text[: sm.start()].count("\n") + 1
            findings.append(Finding("status", _rel(root, path), lineno, f"Status says “{status[:40]}”, but the file hasn't been touched in {age} days (limit {stale_days}) — is it really in progress, or finished with nobody coming back to update it?"))
    return findings


# ───────────────────────── Frontmatter parsing (decision records) ─────────────────────────


def parse_frontmatter(path: Path) -> tuple[dict[str, str], list[str]]:
    """Return (fields, structural errors). With no frontmatter, returns ({}, [a hint])."""
    lines = _read_lines(path)
    if not lines or lines[0].strip() != "---":
        return {}, ["line 1 has no frontmatter opening ---"]
    end = next((i for i in range(1, len(lines)) if lines[i].strip() == "---"), None)
    if end is None:
        return {}, ["frontmatter has no closing ---"]
    data: dict[str, str] = {}
    errs: list[str] = []
    for n, line in enumerate(lines[1:end], start=2):
        if not line.strip():
            continue
        m = FM_LINE_RE.match(line)
        if not m:
            errs.append(f"line {n} is not `key: value`: {line[:40]}")
            continue
        data[m.group(1)] = m.group(2).strip()
    for key in ("domain", "visibility", "status", "type", *FM_REL):
        if key in data:
            data[key] = FM_COMMENT_RE.sub("", data[key]).strip()
    return data, errs


def _first_body_line(path: Path) -> str | None:
    """The first non-empty line after the frontmatter. Returns None if there is no frontmatter or it isn't closed."""
    lines = _read_lines(path)
    if not lines or lines[0].strip() != "---":
        return None
    end = next((i for i in range(1, len(lines)) if lines[i].strip() == "---"), None)
    if end is None:
        return None
    for line in lines[end + 1:]:
        if line.strip():
            return line.strip()
    return None


def _rel_targets(value: str | None) -> list[str]:
    return ADR_REF_RE.findall(value or "")


# ───────────────────────── Mode: refs ─────────────────────────


def check_refs(root: Path, cfg: dict) -> list[Finding]:
    """Schema and cross-validation for decision records. Ported from the source project's ADR schema validator:

    - frontmatter requires id/title/domain/visibility/status/date, with values in the allowed sets
    - domain is checked against the adr_domains whitelist in .doc-governance.json (only when configured — whitelists vary by project)
    - relation keys may not use near-misspellings (a misspelled key is silently ignored, as if never declared)
    - status: superseded must state superseded_by
    - the first body heading must be `# ADR-NNNN`, with the number matching the file name
    - id matches the number in the file name
    - relation fields (supersedes / superseded_by / derives_from / extends) must point to decisions that exist
    - back-links: if A declares superseded_by B, B must declare supersedes A
    - supersede cycles: A and B each declare being superseded by the other

    ADR-NNNN references in body prose are checked for existence too — prose references can point at nonexistent decisions just the same.
    """
    findings: list[Finding] = []
    domains = cfg.get("adr_domains") or []
    files = [p for p in md_files(root, cfg, cfg["adr_dir"]) if ADR_FILE_RE.match(p.name)]
    corpus: dict[str, dict[str, str]] = {}
    for path in files:
        num = ADR_FILE_RE.match(path.name).group(1)
        data, errs = parse_frontmatter(path)
        for e in errs:
            findings.append(Finding("refs", _rel(root, path), 1, f"frontmatter problem: {e}"))
        if not data:
            continue
        corpus[num] = data
        for key in FM_REQUIRED:
            if key not in data:
                findings.append(Finding("refs", _rel(root, path), 1, f"frontmatter is missing required field {key!r}"))
        want_id = f"ADR-{num}"
        if data.get("id") and data["id"] != want_id:
            findings.append(Finding("refs", _rel(root, path), 1, f"id is {data['id']}, but going by the file name it should be {want_id}"))
        for key, allowed in (("status", FM_STATUS), ("visibility", FM_VISIBILITY), ("type", FM_TYPE)):
            v = data.get(key)
            if v and v not in allowed:
                findings.append(Finding("refs", _rel(root, path), 1,
                    f"{key} is {v!r}; allowed values are only {', '.join(sorted(allowed))}"))
        if domains and data.get("domain") and data["domain"] not in domains:
            findings.append(Finding("refs", _rel(root, path), 1,
                f"domain is {data['domain']!r}, but adr_domains in {CONFIG_NAME} only allows "
                f"{', '.join(domains)} — a typo'd domain stays silent all the way down, and this record vanishes when decisions are filtered by domain"))
        for bad, right in FM_FORBIDDEN.items():
            if bad in data:
                findings.append(Finding("refs", _rel(root, path), 1,
                    f"frontmatter uses {bad!r}; the standard key is {right!r} — "
                    f"a misspelled key is silently ignored, so this relation is effectively undeclared"))
        if data.get("status") == "superseded" and not data.get("superseded_by"):
            findings.append(Finding("refs", _rel(root, path), 1,
                "status is superseded but superseded_by is missing — it says the record is void without saying what replaced it, so readers have nowhere to go"))
        head = _first_body_line(path)
        if head is None:
            findings.append(Finding("refs", _rel(root, path), 1, "no body after the frontmatter"))
        else:
            hm = ADR_H1_RE.match(head)
            if hm is None:
                findings.append(Finding("refs", _rel(root, path), 1,
                    f"the first body line is {head[:30]!r}; it should start with `# ADR-{num}` — "
                    f"if the heading doesn't state its number, nobody can tell which record a copied or renamed file is"))
            elif hm.group(1) != num:
                findings.append(Finding("refs", _rel(root, path), 1,
                    f"the body heading says ADR-{hm.group(1)}, but the file name says {num} — most likely copied from a template without updating it"))

    ids = set(corpus)
    for num, data in corpus.items():
        path = next(p for p in files if ADR_FILE_RE.match(p.name).group(1) == num)
        for key in FM_REL:
            for ref in _rel_targets(data.get(key)):
                if ref not in ids:
                    findings.append(Finding("refs", _rel(root, path), 1,
                        f"{key} points to ADR-{ref}, but {cfg['adr_dir']} has no such record"))
        # Back-links
        for target in _rel_targets(data.get("superseded_by")):
            back = _rel_targets(corpus.get(target, {}).get("supersedes")) + \
                   _rel_targets(corpus.get(target, {}).get("supersedes_partially"))
            if target in ids and num not in back:
                findings.append(Finding("refs", _rel(root, path), 1,
                    f"declares being superseded by ADR-{target}, but ADR-{target} doesn't point back with supersedes ADR-{num} — a one-way declaration makes people think this one is still in force"))
            if num in _rel_targets(corpus.get(target, {}).get("superseded_by")):
                findings.append(Finding("refs", _rel(root, path), 1, f"this record and ADR-{target} each declare being superseded by the other — a cycle"))

    findings += _check_public_exposure(root, cfg, files, corpus)

    # References in body prose
    for path in files:
        for lineno, line in _strip_code_blocks(_read_lines(path)):
            for m in ADR_REF_RE.finditer(line):
                if m.group(1) not in ids and ids:
                    findings.append(Finding("refs", _rel(root, path), lineno,
                        f"references ADR-{m.group(1)}, but {cfg['adr_dir']} has no such record"))
    return findings


# ───────────────────────── Mode: links ─────────────────────────


def _check_public_exposure(root: Path, cfg: dict, files: list[Path],
                           corpus: dict[str, dict[str, str]]) -> list[Finding]:
    """Once a decision record is marked visibility: public, redaction goes from "not needed" to "mandatory".

    This is the one item on the "deliberately not ported" list that comes with a precondition: the second stage of
    the source project's pre-publication script scans ADRs about to go public for internal names, client names, internal addresses and credential fragments.
    A small project with nothing published genuinely doesn't need it — but that is a **precondition**, not a forever.
    Reviewing a private product repo confirmed the precondition held (private repo, all ADRs internal,
    no doc publishing pipeline), and also found that this trigger line lived only in the docs with no device behind it — a sticky note.
    This function is that device: **zero cost while there are no public ADRs, red the moment the first one appears.**

    A hit reports only "which rule / which category" and the line number, **never the matched content** —
    otherwise the sensitive value gets copied a second time into CI logs.
    """
    public = [(p, n) for p in files
              if (n := ADR_FILE_RE.match(p.name).group(1)) in corpus
              and corpus[n].get("visibility") == "public"]
    if not public:
        return []
    rules = (cfg.get("public_content_scan") or {}).get("forbid") or []
    findings: list[Finding] = []
    if not rules:
        for path, num in public:
            findings.append(Finding("refs", _rel(root, path), 1,
                f"ADR-{num} is marked visibility: public, but this project has no public_content_scan configured. "
                f"Before publishing an internal decision, spell out what must not go out with it "
                f"(internal names, client names, internal addresses, credential fragments…). "
                f"Configure public_content_scan.forbid in {CONFIG_NAME}, or change this record back to internal"))
        return findings
    compiled = []
    for i, rule in enumerate(rules, start=1):
        if isinstance(rule, dict):
            compiled.append((rule.get("name") or f"rule {i}", re.compile(rule["pattern"])))
        else:
            compiled.append((f"rule {i}", re.compile(rule)))
    for path, num in public:
        for lineno, line in _strip_code_blocks(_read_lines(path)):
            for label, rx in compiled:
                if rx.search(line):
                    findings.append(Finding("refs", _rel(root, path), lineno,
                        f"ADR-{num} is public, and this line matches redaction rule “{label}” — "
                        f"the matched content is not printed here, so it doesn't leak again into CI logs. Look at the line yourself"))
    return findings


def check_links(root: Path, cfg: dict) -> list[Finding]:
    """Broken links. Incident: after a batch migration was "declared fixed", 34 broken links sat for two days before a human noticed."""
    findings: list[Finding] = []
    for path in md_files(root, cfg):
        for lineno, line in _strip_code_blocks(_read_lines(path)):
            for m in MD_LINK_RE.finditer(line):
                raw = m.group(1)
                if re.match(r"^[a-z][a-z0-9+.-]*:", raw, re.I) or raw.startswith("#"):
                    continue
                target = raw.split("#")[0]
                if not target:
                    continue
                if not (path.parent / target).exists():
                    findings.append(Finding("links", _rel(root, path), lineno, f"link {raw} points to a file that does not exist"))
    return findings


# ───────────────────────── Mode: sections ─────────────────────────


def _section_numbers(path: Path) -> set[str]:
    """Numbers from heading lines + bold inline subsections. Missing the latter misreports real references as wrong."""
    out: set[str] = set()
    for line in _read_lines(path):
        for pattern in (SECTION_HEAD_RE, SECTION_BOLD_RE):
            m = pattern.match(line)
            if m:
                out.add(m.group(1))
                break
    return out


def check_sections(root: Path, cfg: dict) -> list[Finding]:
    """A cross-file §X.Y reference must point to a section number that really exists in the target file.

    Incident: an audit found a v1.0 Plan citing §9.1/§9.3/§9.4, all pointing at the wrong sections.
    Root cause: "writing references from semantic memory" — after the spec's sections were renumbered the references didn't error, they silently pointed at the wrong place
    (so the source project made a rule: every §X.Y must be verified with grep, never assumed from memory).
    """
    findings: list[Finding] = []
    cache: dict[Path, set[str]] = {}
    for path in md_files(root, cfg):
        for lineno, line in _strip_code_blocks(_read_lines(path)):
            for m in SECTION_LINK_RE.finditer(line):
                in_text = SECTION_IN_TEXT_RE.search(m.group(1))
                sec = (in_text.group(1) if in_text else None) or m.group(3)
                if not sec:
                    continue
                target = (path.parent / m.group(2)).resolve()
                if not target.exists() or not _inside(root, target):
                    continue  # broken links belong to the links mode; files outside the repo are never read
                if target not in cache:
                    cache[target] = _section_numbers(target)
                have = cache[target]
                # The target file has no numbered sections at all → it doesn't use a numbering style, so the reference isn't wrong
                if have and sec not in have:
                    sample = ", ".join("§" + s for s in sorted(have)[:6])
                    findings.append(Finding("sections", _rel(root, path), lineno,
                        f"§{sec} points to {m.group(2)}, but that file has no such section (it has {sample}) — references silently go wrong after sections are renumbered"))
    return findings


# ───────────────────────── Mode: index ─────────────────────────


def check_index(root: Path, cfg: dict) -> list[Finding]:
    """The ADR directory and the ADR index (README) must fully cover each other.

    Incident: the "Recent ADRs" row in the ADR index was missed by all three authors; an ADR that is written but not indexed
    can't be found from the index, so it might as well not exist. (Step 2 of the source project's four cascade steps.)
    """
    findings: list[Finding] = []
    adr_dir = root / cfg["adr_dir"]
    readme = adr_dir / "README.md"
    files = {m.group(1) for p in md_files(root, cfg, cfg["adr_dir"])
             if (m := ADR_FILE_RE.match(p.name))}
    if not files:
        return findings
    if not readme.exists():
        return [Finding("index", _rel(root, adr_dir), 0,
                        f"{len(files)} ADRs but no README.md index — a decision nobody can find from the index might as well not exist")]
    if not _inside(root, readme):
        return [Finding("index", _rel(root, readme), 0, "the index resolves outside the repository (a symlink?) — not read")]
    text = readme.read_text(encoding="utf-8", errors="replace")
    # Only count "links to a decision file in this directory" — an ADR-NNN mentioned in prose (e.g. citing another
    # project's lesson number) is not an index entry. Hit on a fresh-project demo: the template body mentioned
    # "another project's ADR-178", and it was treated as an index row pointing at a nonexistent decision.
    listed = {m.group(1) for m in re.finditer(r"\]\((?:ADR-)?(\d{3,4})-[^)]*\.md[^)]*\)", text)}
    for missing in sorted(files - listed):
        findings.append(Finding("index", _rel(root, readme), 0,
            f"ADR-{missing} has a file but isn't in the index — written, and nobody can find it"))
    for ghost in sorted(listed - files):
        findings.append(Finding("index", _rel(root, readme), 0,
            f"ADR-{ghost} in the index has no matching file — it points at a nonexistent decision"))
    return findings


# ───────────────────────── Mode: tables ─────────────────────────


def _logical_pipes(line: str) -> int:
    r"""Count only GFM-effective |: an escaped \| and a | inside inline code don't count.
    (Counting any other way floods the screen with false positives — an imprecise checker produces noise nobody reads.)"""
    cleaned = ESCAPED_PIPE_RE.sub("", line)
    cleaned = INLINE_CODE_RE.sub("", cleaned)
    return cleaned.count("|")


def check_tables(root: Path, cfg: dict) -> list[Finding]:
    """Markdown table integrity: every row's column count must match the header; each contiguous table block needs a separator row.

    Incident: a roadmap's table broke — a blank line cut the table, the second half became
    an orphaned fragment, and GFM rendering broke silently, with nothing visible when reading the source.
    """
    findings: list[Finding] = []
    for path in md_files(root, cfg):
        lines = _read_lines(path)
        in_code = False
        segs: list[list[tuple[int, str]]] = []
        cur: list[tuple[int, str]] = []
        for i, line in enumerate(lines, start=1):
            if line.lstrip().startswith("```"):
                in_code = not in_code
                continue
            if not in_code and line.strip().startswith("|"):
                cur.append((i, line))
            elif cur:
                segs.append(cur); cur = []
        if cur:
            segs.append(cur)
        for seg in segs:
            if len(seg) < 2:
                continue
            (h_no, header), (s_no, sep) = seg[0], seg[1]
            if not TABLE_SEP_RE.match(sep):
                findings.append(Finding("tables", _rel(root, path), h_no,
                    f"table fragment has no |---|---| separator row (line {s_no} isn't one) — most likely a blank line above cut the table; GFM renders it broken without any error"))
                continue
            want = _logical_pipes(header)
            for line_no, row in seg[2:]:
                got = _logical_pipes(row)
                if got != want:
                    findings.append(Finding("tables", _rel(root, path), line_no,
                        f"column count doesn't match the header (header has {want} pipes, this row {got}) — rendering will be misaligned"))
                    break
    return findings


# ───────────────────────── Mode: contract ─────────────────────────


# Skip a doc line marked with an implementation status — exactly the annotation the doc rule "architecture tables must mark implementation status" asks for.
# Markers include 已过时 (obsolete), 已下线 (retired), 未实现 (not implemented), 规划中 (planned), 待建 (to be built), and English equivalents.
# An annotated "not built yet" is honest; an unannotated "it exists" that doesn't is the disease.
CONTRACT_STATUS_RE = re.compile(
    r"已过时|已下线|已撤销|已移除|已废弃|不再维护|未实现|尚未实现|规划中|计划中|待建|待实现|📋|🚧|⏸"
    r"|\b(?:deprecated|retired|removed|obsolete|no longer (?:maintained|supported)|not (?:yet )?implemented"
    r"|unimplemented|planned|to be (?:built|implemented)|coming soon|TBD)\b", re.I)


def _first_group(m: re.Match) -> str:
    """Take the first non-empty capture group. When a regex has alternatives (one contract written several ways),
    use whichever branch matched; with no groups, use the whole match."""
    for g in m.groups():
        if g:
            return g
    return m.group(0)


def _norm_path(value: str) -> str:
    """Flatten path parameters into a placeholder so the two sides can be compared:
    docs writing /reports/:tradeDate and code writing /reports/:date mean the same endpoint."""
    segs = []
    for seg in value.rstrip("/").split("/"):
        segs.append(":P" if (seg.startswith(":") or (seg.startswith("{") and seg.endswith("}"))) else seg)
    return "/".join(segs)


def check_contract(root: Path, cfg: dict) -> list[Finding]:
    """Are the contracts the docs declare still present in the code.

    Guards against this: an architecture table lists endpoints / fields without marking implementation status, so readers assume they exist when they don't.
    A manual comparison on a real product repo hit two on the spot —
    the spec declared `/api/v1/help/ask` (the real endpoint is called chat), and
    `/api/admin/items/:id` (removed together with a retired feature; the spec didn't follow).

    Only one direction is checked: **the docs say it exists, the code doesn't have it**. The reverse (code has it, docs don't mention it) is normal and not reported.
    A doc line marked with an implementation status is skipped — turning the prose rule "mark implementation status" into a machine check that rewards following it.

    Every project's framework differs, so how each side is read has to be configured. Misconfiguration must be red:
    if the code side extracts nothing, report a self-check failure — at that point "no problems found" is false.

    Regexes may have alternatives (the first non-empty capture group is used) — real code often writes one contract several ways.
    Measured while configuring object-storage keys: keys were spelled three ways (`key(prefix,"X",…)`, a literal
    `"X/….json"`, a default `?? "X"`); recognizing only one misses a whole class and reports keys that exist as "missing".
    `doc_exclude` drops look-alikes in the docs that don't belong to this contract (a source-tree path like `backend/tsconfig.json`
    gets caught by the object-key regex). Both exist to suppress false positives — an imprecise checker is worse than none.
    """
    findings: list[Finding] = []
    for spec in cfg.get("contract_checks") or []:
        name = spec.get("name", "contract")
        # doc can be a single file or a list / glob — the same contract often gets written into several documents,
        # and watching only one lets the rest keep drifting quietly.
        wanted = spec["doc"] if isinstance(spec["doc"], list) else [spec["doc"]]
        docs: list[Path] = []
        for item in wanted:
            hit = sorted(q for q in root.glob(item) if q.is_file()) if any(c in item for c in "*?[") \
                else ([root / item] if (root / item).is_file() else [])
            hit = [q for q in hit if _inside(root, q)]
            if not hit:
                raise SelfCheckFailure(f"contract_checks[{name}]: doc={item!r} matched no files. Config pointing at the wrong place means nothing gets checked.")
            docs += hit
        claim_re = re.compile(spec["doc_claim"])
        code_re = re.compile(spec["code_claim"])
        excludes = [re.compile(x) for x in (spec.get("doc_exclude") or [])]
        prefixes = spec.get("code_prefix") or {}
        real: set[str] = set()
        for pattern in spec["code_glob"]:
            prefix = prefixes.get(pattern, "")
            for f in sorted(root.glob(pattern)):
                if not f.is_file() or not _inside(root, f):
                    continue
                for m in code_re.finditer(f.read_text(encoding="utf-8", errors="replace")):
                    real.add(_norm_path(prefix + _first_group(m)))
        if not real:
            raise SelfCheckFailure(
                f"contract_checks[{name}]: the code side extracted nothing (code_glob={spec['code_glob']})."
                "\n  The regex or path is misconfigured — at this point “no problems found” is false.")
        for doc in docs:
          for lineno, line in _strip_code_blocks(_read_lines(doc)):
            if CONTRACT_STATUS_RE.search(line):
                continue
            for m in claim_re.finditer(line):
                claim = _first_group(m)
                if any(x.search(claim) for x in excludes):
                    continue
                norm = _norm_path(claim)
                if norm in real:
                    continue
                if norm.endswith("/*") and any(r.startswith(norm[:-1]) for r in real):
                    continue
                findings.append(Finding("contract", _rel(root, doc), lineno,
                    f"{name}: the docs declare {claim}, but it can't be found in the code. "
                    f"⚠️ Before marking it “retired”, grep for it yourself — this really happened: "
                    f"code_claim missed an HTTP method, a real endpoint was judged “missing”, "
                    f"and a false annotation nearly went into the spec — and a false annotation silences this very check. "
                    f"Confirm the code really lacks it, then decide whether to fix the docs or mark the implementation status"))
    return findings


