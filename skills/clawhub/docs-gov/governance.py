def _abandoned_scaffold_ledgers(root: Path, cfg: dict) -> list[str]:
    """Find "abandoned scaffold ledgers" — ones still claiming what is being worked on, but not updated in ages.

    The criterion is **relative**: how long the ledger itself has gone untouched means little (the whole project may be paused);
    what matters is **the project still moving while the ledger hasn't kept up**. The gap between the two is the drift.

    Real case: in a product repo the scaffold ledger lagged by more than a month, while "status follows it"
    was still written in the rules — following that rule would revert the correct table to the wrong one. Three other projects on the same machine
    were in the same state at the same time (lagging one to two months), and nothing made it visible.

    Repo activity uses the last git commit first; if it isn't a git repo (or git is unavailable),
    fall back to "the mtime of the newest document in the repo". If neither is available, skip —
    better not to report than to report a number that couldn't be computed.
    """
    # A missing key falls back to the default list — projects installed before this feature won't have the key in their config,
    # yet they are exactly the ones most in need of checking (measured: every scaffolded project on one machine was like this).
    # Only an explicit [] turns it off.
    ledgers = cfg.get("scaffold_ledgers", DEFAULTS["scaffold_ledgers"])
    if not ledgers:
        return []
    max_gap = int(cfg.get("scaffold_stale_days", DEFAULTS["scaffold_stale_days"]))

    repo_ts = None
    try:
        out = subprocess.run(["git", "-C", str(root), "log", "-1", "--format=%ct"],
                             capture_output=True, text=True, timeout=5)
        if out.returncode == 0 and out.stdout.strip():
            repo_ts = float(out.stdout.strip())
    except Exception:
        repo_ts = None
    if repo_ts is None:
        mtimes = [p.stat().st_mtime for p in md_files(root, cfg)]
        repo_ts = max(mtimes) if mtimes else None
    if repo_ts is None:
        return []

    stale: list[str] = []
    for rel in ledgers:
        target = root / rel
        if not target.exists() or not _inside(root, target):
            continue
        # For a directory, take the newest file inside, not the directory's own mtime — that doesn't change when the contents do
        if target.is_dir():
            inner = [f.stat().st_mtime for f in target.rglob("*") if f.is_file() and _inside(root, f)]
            ts = max(inner) if inner else target.stat().st_mtime
        else:
            ts = target.stat().st_mtime
        gap = int((repo_ts - ts) / 86400)
        if gap > max_gap:
            stale.append(f"{rel} lags the repo by {gap} days")
    return stale


def audit(root: Path, cfg: dict, today: date) -> list[Component]:
    docs_root = root / cfg["docs_root"]
    adr_dir = root / cfg["adr_dir"]
    plan_dir = root / cfg["plan_dir"]
    comps: list[Component] = []

    # ── G1 Source-of-truth layering ──
    entry_text = "\n".join(p.read_text(encoding="utf-8", errors="replace")
                           for p in _root_docs(root) + [docs_root / "README.md"] if p.is_file() and _inside(root, p))
    hits = len(TRUTH_SOURCE_RE.findall(entry_text))
    contracts = len(cfg.get("contract_checks") or [])
    sub1 = [f"{hits} “source of truth / takes precedence” declarations in entry docs"]
    # Declaring "the code is the technical source of truth" with nothing checking docs against code makes the declaration empty talk
    sub1.append(f"{contracts} contracts checked against the code" if contracts else
                "⚠️ nothing checks the docs against the code — “the code takes precedence” is only a declaration so far")
    comps.append(Component(
        "G1", "Source-of-truth layering (who is authoritative for what)",
        "ok" if (hits >= 2 and contracts) else ("partial" if (hits or contracts) else "missing"),
        "; ".join(sub1),
        "Real case: the PRD never cited the SPEC (2 references the other way — one-directional), "
        "and the PRD went 34 days untouched, because “which document wins on technical matters” was never written down; "
        "later measurement also found two endpoints declared in the spec that didn't exist in the code",
        installable=True))

    # ── G2 Decision record system (four sub-items) ──
    adr_files = [p for p in md_files(root, cfg, cfg["adr_dir"]) if ADR_FILE_RE.match(p.name)] if adr_dir.is_dir() else []
    nums = sorted(ADR_FILE_RE.match(p.name).group(1) for p in adr_files)
    gaps = []
    if nums:
        ints = [int(n) for n in nums]
        gaps = [f"{i:0{len(nums[0])}d}" for i in range(min(ints), max(ints) + 1) if i not in set(ints)]
    has_index = (adr_dir / "README.md").is_file()
    schema_keys, schema_ok = _adr_metadata_shape(adr_files)
    sub = []
    if not adr_files:
        verdict, sub = "missing", ["no decision-record directory, or no files numbered NNNN-slug.md (an ADR- prefix is fine)"]
    else:
        sub.append(f"{len(adr_files)} decisions")
        if gaps:
            sub.append(f"⚠️ missing numbers {', '.join(gaps)}")
        sub.append("has an index" if has_index else "⚠️ no index README")
        sub.append(f"standard frontmatter ({', '.join(schema_keys)})" if schema_ok
                   else "⚠️ not using standard frontmatter, or required fields missing — schema validation can't run")
        # Legal domain values vary by project, so they have to be configured; unconfigured means this cell isn't checked
        used = sorted({d for d in (parse_frontmatter(p)[0].get("domain") for p in adr_files) if d})
        domains_set = bool(cfg.get("adr_domains"))
        sub.append("domain whitelist configured" if domains_set else
                   f"⚠️ adr_domains not configured (currently used: {', '.join(used) or 'none'}) — configure it to block typos")
        verdict = "ok" if (not gaps and has_index and schema_ok and domains_set) else "partial"
    comps.append(Component(
        "G2", "Decision record system (ADR)", verdict, "; ".join(sub),
        "status fields are free-form, so nobody knows which decisions are still in force; a decision written but not indexed = nobody can find it",
        installable=True))

    # ── G3 Cascade discipline ──
    with_cascade = [p for p in adr_files if CASCADE_SECTION_RE.search(p.read_text(encoding="utf-8", errors="replace"))]
    if not adr_files:
        verdict, detail = "missing", "no decision records, so there's nothing to cascade"
    elif not with_cascade:
        verdict, detail = "missing", f"none of the {len(adr_files)} decisions has a cascade memo section"
    elif len(with_cascade) < len(adr_files):
        verdict = "partial"
        detail = f"{len(with_cascade)}/{len(adr_files)} have a cascade memo section"
    else:
        verdict, detail = "ok", f"all {len(with_cascade)} have a cascade memo section"
    comps.append(Component(
        "G3", "Cascade discipline (which documents a decision lands in)", verdict, detail,
        "The same lesson was repeated three times, each found only when the user pressed on it and routing turned out not to have landed; "
        "in another repo, two ADRs' first drafts missed this section and three PRD conflicts sat for a day",
        installable=False))  # can only be filled in while writing ADRs; can't be installed

    # ── G4 Planning system ──
    plans = [p for p in md_files(root, cfg, cfg["plan_dir"]) if p.name.upper().startswith(("PLAN", "TASK"))] if plan_dir.is_dir() else []
    with_status = [p for p in plans if STATUS_LINE_RE.search(p.read_text(encoding="utf-8", errors="replace"))]
    plan_index = (plan_dir / "README.md").is_file()
    if not plans:
        verdict, detail = "missing", "no plan directory, or no PLAN-/TASK- plan files"
    else:
        detail = f"{len(plans)} plans; {len(with_status)} have a status field; {'has an' if plan_index else '⚠️ no'} index"
        verdict = "ok" if (len(with_status) == len(plans) and plan_index) else "partial"
    # A second answer to "what is being worked on now", and it has gone stale — also a G4 disease.
    stale_ledgers = _abandoned_scaffold_ledgers(root, cfg)
    if stale_ledgers:
        detail += "; ⚠️ scaffold ledger abandoned: " + ", ".join(stale_ledgers)
        verdict = "partial" if verdict == "ok" else verdict
    comps.append(Component(
        "G4", "Planning system (what is being done now, how far along)", verdict, detail,
        "Real case: the plan layer wasn't missing, it had stalled — the plan directory and even its index had long existed, "
        "but plan files went 15 days without an update while trunk got 366 commits. "
        "The same repo later turned up a second answer: a scaffold ledger lagging by more than a month, "
        "while “status follows it” was still written in the rules — following that would revert the correct table to the wrong one",
        installable=True))

    # ── G5 Checkpoints bound to actions (two sub-items: written down + bound to a device) ──
    # Criterion revised: it used to check only "is a checkpoint written in the docs" — checking the sticky note, not the device.
    # "A trigger line written only in docs, waiting for someone to remember it, is as good as unset" — this criterion broke that very rule.
    cp_hits = len(CHECKPOINT_RE.findall(entry_text))
    devices = _checkpoint_devices(root)
    sub5 = [f"{cp_hits} “before X, run Y” checkpoints written in entry docs"]
    sub5.append("devices: " + ", ".join(devices) if devices
                else "⚠️ no device found — checkpoints are only written in docs, waiting for someone to remember")
    # State the ledger before reporting an absence: the search scope is itself a blind spot
    sub5.append("(searched in-repo only: pre-commit / CI / Claude hook / Cursor rules. "
                "A device outside the repository — a scheduled task, a machine-level hook — is invisible here "
                "and must be judged by hand; this tool deliberately reads nothing outside the repository)")
    if not any("before writing a new plan" in d for d in devices):
        sub5.append("⚠️ no device for “before writing a new plan” — and that is exactly the moment CI can't catch")
    comps.append(Component(
        "G5", "Checkpoints bound to actions (when checks are mandatory)",
        "ok" if (cp_hits >= 2 and any("before writing a new plan" in d for d in devices)) else
        ("partial" if (cp_hits or devices) else "missing"),
        "; ".join(sub5),
        "CI can't catch “a new plan written against a stale spec” — the new plan is itself compliant; "
        "only a reverse audit before starting can catch it, and a reverse audit not bound to a device is just a sticky note",
        installable=True))

    # ── G6 Gates ──
    # Symlinks skipped, not followed: a workflows/ or scripts/ directory pointing outside the repo must not have
    # its contents read into the audit — read access, not only write access, stays inside `root` (security audit).
    ci_files = [p for p in list((root / ".github" / "workflows").glob("*.yml")) + list((root / ".github" / "workflows").glob("*.yaml"))
                if p.is_file() and _inside(root, p)]
    ci_text = "\n".join(p.read_text(encoding="utf-8", errors="replace") for p in ci_files)
    ci_has = "governance.py" in ci_text or "doc-truth" in ci_text
    hook_src = root / ".githooks" / "pre-commit"
    hook_live = root / ".git" / "hooks" / "pre-commit"
    hook_has = hook_src.is_file() and hook_live.is_file()
    direct = _direct_push_ratio(root)
    if ci_has and hook_has:
        verdict, detail = "ok", "CI has a docs gate; the pre-commit hook is installed and version-controlled"
    elif ci_has:
        verdict = "partial"
        detail = f"CI has a docs gate, but there is no pre-commit hook" + (
            f" — of the last {direct[1]} commits, {direct[0]} were direct pushes that CI never ran on" if direct else "")
    elif hook_has:
        verdict, detail = "partial", "has a pre-commit hook, but CI has no docs gate"
    elif not is_git_repo(root):
        # Cannot-install is not not-installed. An unfillable prescription is worse than none.
        verdict, detail = "missing", "not a git repository — a commit gate cannot be installed here; `git init` first"
    else:
        verdict, detail = "missing", "no docs gate in CI or on local commits"
    comps.append(Component(
        "G6", "Gates (not relying on people remembering)", verdict, detail,
        "Real case: of a product repo's last 80 commits, 36 were direct pushes to main, and CI never ran on any of them — "
        "whether “CI is enough” depends on whether the team uses PRs. Note this is a sliding-window number: "
        "the same repo measured between 33 and 44 at different times, so cite it with the measurement date",
        installable=True))

    # ── G7 Incident traceability ──
    gate_text = ci_text + "\n" + "\n".join(
        p.read_text(encoding="utf-8", errors="replace")
        for p in list((root / "scripts").glob("*"))
        if p.is_file() and p.suffix in (".py", ".mjs", ".js", ".sh") and _inside(root, p))
    dated = len(set(DATE_RE.findall(gate_text)))
    comps.append(Component(
        "G7", "Incident traceability (every gate states the failure it guards against)",
        "ok" if dated >= 3 else ("partial" if dated >= 1 else "missing"),
        f"{dated} distinct incident dates cited in gate scripts / CI",
        "Rules get bypassed as bureaucracy; incidents don't — nobody turns off a check that says “the table-corruption incident of such-and-such date”",
        installable=False))

    return comps


def _adr_metadata_shape(adr_files: list[Path]) -> tuple[list[str], bool]:
    """Do all decision records use standard frontmatter, with required fields present and values legal.

    The standard follows the field set battle-tested across the source project's hundreds of ADRs (id/title/domain/visibility/status/date
    + type + relation fields). The settled principle: every project uses this one set —
    for a solo developer running several projects, the cost of non-standardization is "one mental model per project",
    and that is what really eats attention.
    """
    if not adr_files:
        return [], False
    ok = True
    seen: set[str] = set()
    for p in adr_files:
        data, errs = parse_frontmatter(p)
        if errs or not data:
            ok = False
            continue
        seen |= set(data)
        if any(k not in data for k in FM_REQUIRED):
            ok = False
        if data.get("status") not in FM_STATUS or data.get("visibility") not in FM_VISIBILITY:
            ok = False
    return sorted(k for k in FM_REQUIRED if k in seen), ok


CLAUDE_HOOKS = {
    "doc-governance-plan-gate.sh": ("PreToolUse", "Write", "before writing a new plan"),
    "doc-governance-adr-cascade.sh": ("PostToolUse", "Write|Edit", "after editing a decision"),
}


def discover_layout(root: Path) -> dict[str, str] | None:
    """With no config present, find the decision and plan directories by **content** instead of assuming default paths.

    A real run reported "no decision-record directory" for a project whose records lived in `docs/decisions/`.
    They were three well-formed records: numbering continuous, H1 matching the filename, filenames matching
    the very regex used here. The only thing wrong was that nobody looked there.

    Worse is the second half: `init` would then create a *second* decision directory at the default path,
    so this tool would **manufacture the very "second answer" it exists to detect** (the G4 failure mode).

    Only used when there is no config: an explicitly written path always wins over a guess.
    Returns None when nothing is found; the caller falls back to the defaults — but must say the path was a guess.

    Every returned path is produced by walking inside `root`, so it is repo-relative by construction
    (see _require_repo_relative for why that matters).
    """
    skip = {".git", "node_modules", ".venv", "venv", "__pycache__", ".pytest_cache",
            "dist", "build", ".next", "target"}
    adr_hits: dict[Path, int] = {}
    plan_hits: dict[Path, int] = {}
    for path in root.rglob("*.md"):
        if any(part in skip for part in path.relative_to(root).parts[:-1]):
            continue
        if ADR_FILE_RE.match(path.name):
            adr_hits[path.parent] = adr_hits.get(path.parent, 0) + 1
        if path.name.upper().startswith(("PLAN", "TASK")):
            plan_hits[path.parent] = plan_hits.get(path.parent, 0) + 1
    if not adr_hits and not plan_hits:
        return None
    out: dict[str, str] = {}
    if adr_hits:
        out["adr_dir"] = max(adr_hits, key=lambda d: adr_hits[d]).relative_to(root).as_posix()
    if plan_hits:
        out["plan_dir"] = max(plan_hits, key=lambda d: plan_hits[d]).relative_to(root).as_posix()
    return out or None


def fallback_cfg(root: Path) -> tuple[dict, str]:
    """The stand-in config used when none exists, plus one line stating whether the paths were discovered or guessed."""
    cfg = {"docs_root": "docs", "adr_dir": "docs/adr", "plan_dir": "docs/planning",
           "exclude": [], "pending_exclude": [], "pending_max_days": 30, "stale_plan_days": 45}
    found = discover_layout(root)
    if not found:
        return cfg, (f"⚠️  No {CONFIG_NAME} yet, and no decision or plan files found in the repo — "
                     "auditing against the default layout (docs/ · docs/adr · docs/planning).")
    cfg.update(found)
    where = ", ".join(f"{k.replace('_dir', '')}={v}" for k, v in sorted(found.items()))
    return cfg, (f"⚠️  No {CONFIG_NAME} yet. Layout discovered from **file content**: {where} "
                 "(not the default path; write it into the config to make this stable).")


def is_git_repo(root: Path) -> bool:
    """Every G6 gate depends on git. Where there is no repository, "no gate installed" means it **cannot be** installed.

    A real run reported "no docs gate in CI or on local commits" for a directory that was not a git repository
    at all, and offered to install a pre-commit hook there — a prescription that could not be filled.
    Cannot-install is not the same as not-installed, and an unfillable prescription is worse than none:
    it is how people start distrusting the output.
    """
    return (root / ".git").exists()


def _checkpoint_devices(root: Path) -> list[str]:
    """Which checkpoints are really bound to a device. Written only in docs doesn't count — that's a sticky note."""
    found: list[str] = []
    if (root / ".githooks" / "pre-commit").is_file() and (root / ".git" / "hooks" / "pre-commit").is_file():
        found.append("pre-commit (every commit)")
    wf = (root / ".github" / "workflows")
    if wf.is_dir() and any("governance.py" in f.read_text(encoding="utf-8", errors="replace")
                           for f in list(wf.glob("*.yml")) + list(wf.glob("*.yaml"))
                           if f.is_file() and _inside(root, f)):
        found.append("CI (every PR)")
    settings = root / ".claude" / "settings.json"
    if settings.is_file() and _inside(root, settings):
        text = settings.read_text(encoding="utf-8", errors="replace")
        for name, (_, _, when) in CLAUDE_HOOKS.items():
            if name in text and (root / ".claude" / "hooks" / name).is_file():
                found.append(f"Claude Code hook ({when})")
    if any((root / ".cursor" / "rules").glob("*doc-governance*.mdc")) if (root / ".cursor" / "rules").is_dir() else False:
        found.append("Cursor rule")
    return found


def _direct_push_ratio(root: Path) -> tuple[int, int] | None:
    """How many of the last 80 trunk commits skipped PRs. Whether PRs are used decides whether CI covers them."""
    try:
        out = subprocess.run(["git", "log", "--oneline", "-80"], cwd=root,
                             capture_output=True, text=True, timeout=10)
        if out.returncode != 0 or not out.stdout.strip():
            return None
        lines = out.stdout.strip().split("\n")
        pr = sum(1 for l in lines if re.search(r"\(#\d+\)|Merge pull request", l))
        return len(lines) - pr, len(lines)
    except (OSError, subprocess.SubprocessError):
        return None


