TRUTH_SOURCE_RE = re.compile(r"真相源|source of truth|以.{0,12}为准|权威(?:出处|在)|\bauthoritative\b|\btakes precedence\b", re.I)
CASCADE_SECTION_RE = re.compile(r"##\s*(?:级联备忘|备忘路由|路由级联|Cascade(?:\s+(?:memo|notes|updates|log))?\b|Propagation\b|Downstream updates\b)", re.I)
# "Before / after doing X, run Y". Both styles must be recognized:
#   prose: 写新计划前先跑 npm run … ("before writing a new plan, run npm run …")
#   table: | **写新计划前** | `npm run …` | — the action and the command are split into two columns by |
# The first version required a verb like 跑/执行 ("run / execute") in the same sentence as the action, and missed every table;
# relaxed to: within 60 chars after "action + 前/后 (before/after)", something command-like (backticked, or starting with npm/python) or a run-type verb.
CHECKPOINT_RE = re.compile(
    r"(?:开工|写(?:新)?计划|改完|写完|发版|改名|迁移|移动|提交|部署|上生产|开始)[^。\n]{0,24}(?:前|后)"
    r"[^。\n]{0,60}?(?:先跑|必须跑|自动跑|执行|运行|跑一遍|照\s*\[|`[^`]+`|npm run|python3?\s)"
    r"|\b(?:before|after)\s+(?:starting|writing|drafting|editing|merging|releasing|renaming|moving|committing|deploying|shipping)\b"
    r"[^.\n]{0,60}?(?:\brun\b|\bexecute\b|`[^`]+`|npm run|python3?\s)", re.I)


def _all_docs_text(root: Path, cfg: dict) -> str:
    return "\n".join(p.read_text(encoding="utf-8", errors="replace") for p in md_files(root, cfg))


