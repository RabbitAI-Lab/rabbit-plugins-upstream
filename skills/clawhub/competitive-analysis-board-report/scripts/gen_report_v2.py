def shade(cell, hexcolor):
    tcPr = cell._tc.get_or_add_tcPr()
    sh = OxmlElement("w:shd")
    sh.set(qn("w:val"), "clear")
    sh.set(qn("w:color"), "auto")
    sh.set(qn("w:fill"), hexcolor)
    tcPr.append(sh)


def set_cell(cell, text, bold=False, color=None, size=9.5, align="left"):
    cell.text = ""
    p = cell.paragraphs[0]
    p.alignment = {"left": WD_ALIGN_PARAGRAPH.LEFT, "center": WD_ALIGN_PARAGRAPH.CENTER,
                   "right": WD_ALIGN_PARAGRAPH.RIGHT}[align]
    for li, line in enumerate(str(text).split("\n")):
        if li > 0:
            p = cell.add_paragraph()
            p.alignment = {"left": WD_ALIGN_PARAGRAPH.LEFT, "center": WD_ALIGN_PARAGRAPH.CENTER,
                           "right": WD_ALIGN_PARAGRAPH.RIGHT}[align]
        r = p.add_run(line)
        r.font.name = F
        r.element.rPr.rFonts.set(qn("w:eastAsia"), F)
        r.font.size = Pt(size)
        r.font.bold = bold
        r.font.color.rgb = color or C_TXT


def add_table(headers, rows, widths=None, head_fill="1F3B63", font=9.5, head_font=9.5, zebra="E6F1FB"):
    t = doc.add_table(rows=1, cols=len(headers))
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.style = "Table Grid"
    for i, h in enumerate(headers):
        set_cell(t.rows[0].cells[i], h, bold=True, color=RGBColor(0xFF, 0xFF, 0xFF), size=head_font, align="center")
        shade(t.rows[0].cells[i], head_fill)
    for ri, row in enumerate(rows):
        cells = t.add_row().cells
        for ci, v in enumerate(row):
            set_cell(cells[ci], v, size=font)
            if ri % 2 == 1:
                shade(cells[ci], zebra)
    if widths:
        for row in t.rows:
            for i, w in enumerate(widths):
                row.cells[i].width = Cm(w)
    doc.add_paragraph()
    return t


def chart(name, width=Cm(16.2), cap=None):
    p = os.path.join(CHART, name)
    if os.path.exists(p):
        doc.add_picture(p, width=width)
        doc.paragraphs[-1].alignment = WD_ALIGN_PARAGRAPH.CENTER
    if cap:
        c = doc.add_paragraph()
        c.alignment = WD_ALIGN_PARAGRAPH.CENTER
        r = c.add_run(cap)
        r.font.size = Pt(8.5)
        r.font.color.rgb = C_GRAY
        r.italic = True


def para(text, size=10.5, bold=False, color=None, gap_after=6, align="left"):
    p = doc.add_paragraph()
    p.alignment = {"left": WD_ALIGN_PARAGRAPH.LEFT, "center": WD_ALIGN_PARAGRAPH.CENTER,
                   "justify": WD_ALIGN_PARAGRAPH.JUSTIFY}[align]
    p.paragraph_format.space_after = Pt(gap_after)
    r = p.add_run(text)
    r.font.name = F
    r.element.rPr.rFonts.set(qn("w:eastAsia"), F)
    r.font.size = Pt(size)
    r.font.bold = bold
    r.font.color.rgb = color or C_TXT
    return p


