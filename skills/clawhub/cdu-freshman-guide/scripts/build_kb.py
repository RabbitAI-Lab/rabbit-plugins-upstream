# ---------- 校验 ----------

RE_PHONE = re.compile(r'(?<!\d)1[3-9]\d{9}(?!\d)')
RE_ID = re.compile(r'(?<!\d)\d{17}[\dXx](?!\d)')
RE_EMAIL = re.compile(r'[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}')
RE_QQ = re.compile(r'(?<!\d)[1-9]\d{4,11}(?!\d)')
RE_STUDENT = re.compile(r'(?<!\d)\d{10,12}(?!\d)')
# 座机号码（区号-号码，如 028-84616550），非个人 PII
RE_LANDLINE = re.compile(r'0\d{2,3}-\d{7,8}')

GRAY_KEYWORDS = ('代课', '代签', '代考', '代写', '代做', '代取', '代跑', '代测',
                 '代看', '代听', '代买', '代充', '挂证', '挂名', '代发', '代拉',
                 '代刷', '代充', '买证', '卖证', '论文代', '代过', '包过')


def collect_text() -> list[str]:
    """收集所有知识条目文本，用于校验。"""
    texts = []
    for cat in FAQ['categories']:
        for item in cat['items']:
            texts.extend([item['q'], item['a'], item['source']])
    for p in PROCESS['processes']:
        texts.extend([p['name'], p['summary'], p['location'], p['time'], p['source']])
        texts.extend(p['materials'])
        texts.extend(p['steps'])
        texts.extend(p['tips'])
    for pl in PLACES['places']:
        texts.extend([pl['name'], pl['location'], pl['info'], pl['source']])
        texts.extend(pl.get('tips', []))
    for n in NOTICES['notices']:
        texts.extend([n['title'], n['content'], n['source']])
    for ch in OFFICIAL['channels']:
        texts.extend([ch['name'], ch['url'], ch['info'], ch['source']])
        texts.extend(ch.get('tips', []))
    return texts


def validate() -> list[str]:
    """校验知识库：schema 完整 + 无 PII + 无灰色交易。返回问题列表。"""
    problems = []

    # PII 校验
    for t in collect_text():
        # 座机号码（官方热线）不属于个人 PII，先剔除再校验
        t_clean = RE_LANDLINE.sub('', t)
        for label, pat in (('手机号', RE_PHONE), ('身份证', RE_ID), ('邮箱', RE_EMAIL),
                           ('QQ号', RE_QQ), ('学号', RE_STUDENT)):
            if pat.search(t_clean):
                problems.append(f'PII 残留 [{label}]: {t[:40]}...')

    # 灰色交易校验
    for t in collect_text():
        for kw in GRAY_KEYWORDS:
            if kw in t:
                problems.append(f'灰色交易关键词 [{kw}]: {t[:40]}...')

    # schema 校验
    for cat in FAQ['categories']:
        for item in cat['items']:
            for field in ('q', 'a', 'source'):
                if not item.get(field):
                    problems.append(f'FAQ 缺字段 {field}: {item}')
    for p in PROCESS['processes']:
        for field in ('id', 'name', 'summary', 'materials', 'steps', 'location', 'time', 'source'):
            if field not in p:
                problems.append(f'流程缺字段 {field}: {p.get("id")}')
    for pl in PLACES['places']:
        for field in ('id', 'name', 'location', 'info', 'source'):
            if not pl.get(field):
                problems.append(f'地点缺字段 {field}: {pl}')
    for n in NOTICES['notices']:
        for field in ('id', 'title', 'content', 'date', 'source'):
            if not n.get(field):
                problems.append(f'通知缺字段 {field}: {n}')
    for ch in OFFICIAL['channels']:
        for field in ('id', 'name', 'type', 'url', 'info', 'source'):
            if not ch.get(field):
                problems.append(f'官方渠道缺字段 {field}: {ch}')

    return problems


def main() -> int:
    problems = validate()
    if problems:
        print('❌ 知识库校验失败：')
        for p in problems:
            print('  -', p)
        return 1

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    outputs = {
        'kb_faq.json': {'meta': META, **FAQ},
        'kb_process.json': {'meta': META, **PROCESS},
        'kb_places.json': {'meta': META, **PLACES},
        'kb_notices.json': {'meta': META, **NOTICES},
        'kb_official.json': {'meta': META, **OFFICIAL},
    }
    for name, data in outputs.items():
        path = OUT_DIR / name
        with open(path, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print(f'✅ 已生成 {path}')

    n_faq = sum(len(c['items']) for c in FAQ['categories'])
    print(f'\n知识库统计：FAQ {n_faq} 条 / 流程 {len(PROCESS["processes"])} 个 / '
          f'地点 {len(PLACES["places"])} 个 / 通知 {len(NOTICES["notices"])} 条 / '
          f'官方渠道 {len(OFFICIAL["channels"])} 个')
    return 0


if __name__ == '__main__':
    sys.exit(main())
