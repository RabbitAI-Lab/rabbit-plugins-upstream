# 半角标点 -> 全角(中文字幕里半角逗号/问号很显眼)
PUNCT = [(",", "，"), ("?", "？"), ("!", "！"), (";", "；"), (":", "：")]


def fix_text(s):
    for half, full in PUNCT:
        s = s.replace(half, full)
    for wrong, right in TERMS:
        if wrong in s:
            s = s.replace(wrong, right)
    return s


def fix_srt(path):
    with open(path, encoding="utf-8") as f:
        content = f.read()
    # 只替换文本行: 按空行切块, 跳过序号行与时间轴行
    blocks = content.split("\n\n")
    out = []
    for b in blocks:
        lines = b.split("\n")
        if len(lines) >= 3 and "-->" in lines[1]:
            lines[2:] = [fix_text(l) for l in lines[2:]]
        out.append("\n".join(lines))
    new = "\n\n".join(out)
    with open(path, "w", encoding="utf-8") as f:
        f.write(new)
    return content != new


