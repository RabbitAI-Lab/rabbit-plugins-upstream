#!/usr/bin/env python3
"""
Bills Watcher
Fetches utility/subscription bill emails from Gmail with dedup + auth-error
handling. Where the biller attaches a statement, the PDF text is extracted via
pypdf (core.pdf_attachments — a generic Gmail-attachment helper). Where it does not, the
email body is returned instead: plenty of billers only ever send "your bill is
ready, log in to view", and those are bills too.

Doctrine (see skills/homebase/CLAUDE.md):
- Python returns data. Agent decides + delivers. No summarization or "tips"
  generation here — that's LLM reasoning and belongs to the agent.
- Every state write goes through utils.write_json_atomic.
"""

from __future__ import annotations

import base64
import html as _htmllib
import json
import os
import re
import sys
from datetime import datetime
from typing import Dict, List, Optional

from utils import (write_json_atomic, append_capped_id, locked_file,
                   read_id_list, AuthErrorFlag)
from core.pdf_attachments import extract_pdf_attachments


def _collapse_ws(text: str) -> str:
    """Squeeze runs of whitespace without joining separate lines.

    Bill mail is generated by templating engines and arrives padded with
    hundreds of consecutive CRLFs. That padding is not free: `body` is capped
    before it reaches the model, and a cap spent on blank lines is a cap not
    spent on the amount due.
    """
    text = text.replace("\r\n", "\n").replace("\r", "\n")
    text = text.replace("\u00a0", " ").replace("\ufeff", "")
    text = re.sub(r"[ \t]{2,}", " ", text)
    text = re.sub(r"[ \t]*\n[ \t]*", "\n", text)
    return re.sub(r"\n{3,}", "\n\n", text).strip()


def _html_to_text(markup: str) -> str:
    """Crude tag strip, good enough to hand to a model.

    Billers that attach no PDF put the amount and due date in the HTML body
    itself, so "no attachment" must not mean "no content" - that assumption is
    what made this watcher blind to two of its three billers until 2026-08-22.
    Not a parser and not trying to be: scripts and styles out, block ends to
    newlines, tags to spaces, entities decoded.
    """
    text = re.sub(r"(?is)<(script|style)\b.*?</\1>", " ", markup)
    text = re.sub(r"(?i)<br\s*/?>|</p>|</tr>|</div>|</h[1-6]>", "\n", text)
    text = re.sub(r"<[^>]+>", " ", text)
    return _collapse_ws(_htmllib.unescape(text))


def _has_pdf_part(payload: Dict) -> bool:
    """True if the message carries an application/pdf part, read or not."""
    if payload.get("mimeType") == "application/pdf":
        return True
    return any(_has_pdf_part(p) for p in (payload.get("parts") or []))


def _signal(text: str) -> int:
    """How much of this is actually content: non-whitespace characters."""
    return len(re.sub(r"\s+", "", text))


def _extract_body(payload: Dict) -> str:
    """Recursive multipart walk, returning whichever alternative actually
    carries the bill.

    Preferring `text/plain` outright is the obvious rule and it is wrong here.
    SCE's "Bill is Ready" ships a text/plain part that is 96 bytes of CRLF
    scaffolding around the customer's first name, with the amount and due date
    present only in the HTML. Choosing by content rather than by MIME type
    keeps the clean plain-text body when a biller sends a real one, and falls
    through to the markup when the plain part is decorative.
    """
    plain: List[str] = []
    markup: List[str] = []

    def walk(part: Dict) -> None:
        mime = part.get("mimeType", "")
        data = part.get("body", {}).get("data", "")
        if data:
            try:
                decoded = base64.urlsafe_b64decode(data).decode("utf-8", errors="replace")
            except Exception:
                decoded = ""
            if mime == "text/plain":
                plain.append(decoded)
            elif mime == "text/html":
                markup.append(decoded)
        for sub in part.get("parts", []) or []:
            walk(sub)

    walk(payload)
    plain_text = _collapse_ws("\n".join(plain)) if plain else ""
    html_text = _html_to_text("\n".join(markup)) if markup else ""
    # Ties go to plain text: when both say the same thing, it says it cleaner.
    return plain_text if _signal(plain_text) >= _signal(html_text) else html_text


class BillsWatcher:
    """Gmail poll + dedup for bill emails. Returns raw extracted PDF text;
    the agent summarizes consumption and pulls genuine tips from it.
    """

    def __init__(self, base_path: str = "."):
        self.base_path = base_path
        self.config_file = os.path.join(base_path, "config.json")
        self.processed_ids_file = os.path.join(
            base_path, "household", "bills_processed.json"
        )
        self.auth_error_state_file = os.path.join(
            base_path, "household", "bills_auth_error_state.json"
        )
        os.makedirs(os.path.dirname(self.processed_ids_file), exist_ok=True)
        self.load_config()
        self.processed_ids = self._load_processed_ids()
        # Why the last get_gmail_service() returned None, in the same
        # three-way vocabulary the school monitor uses.
        self.auth_status = None
        self.auth_detail = None

    # ─── Config & state ──────────────────────────────────────────────────────

    def load_config(self) -> None:
        if os.path.exists(self.config_file):
            with open(self.config_file, "r") as f:
                self.config = json.load(f)
        else:
            self.config = {}

    @property
    def enabled(self) -> bool:
        return bool(self.config.get("bills", {}).get("enabled", False))

    @property
    def billers(self) -> List[Dict]:
        return self.config.get("bills", {}).get("billers", [])

    @property
    def lookback_days(self) -> int:
        return int(self.config.get("bills", {}).get("lookback_days", 3))

    @property
    def owner_phone(self) -> str:
        return self.config.get("app", {}).get("owner_phone", "")

    @property
    def family_group(self) -> Optional[Dict[str, str]]:
        """Return {jid, name} for the primary family WhatsApp group, or None
        if unconfigured. Mirrors ClubStudioWatcher.notify_targets()'s legacy
        scalar / groups[] handling and placeholder-JID skip."""
        wa = self.config.get("whatsapp", {})
        groups = wa.get("groups")
        if isinstance(groups, list) and groups:
            g = groups[0] or {}
            jid = g.get("id", "").strip()
            if jid and "YOUR" not in jid:
                return {"jid": jid, "name": g.get("name", jid)}
        legacy_id = wa.get("group_id", "").strip()
        if legacy_id and "YOUR" not in legacy_id:
            return {"jid": legacy_id, "name": wa.get("group_name", legacy_id)}
        return None

    def _load_processed_ids(self) -> set:
        # The file is the ordered record; the set is a membership index over
        # it. See utils.append_capped_id — capping the set instead dropped
        # arbitrary IDs, and a dropped ID means a bill posted to the group twice.
        self._processed_order = read_id_list(self.processed_ids_file)
        return set(self._processed_order)

    def _save_processed_ids(self) -> None:
        write_json_atomic(self.processed_ids_file, self._processed_order)

    def mark_processed(self, msg_id: str) -> None:
        """Record a bill as handled so it is never fetched again.

        Public and separate from `fetch_emails` on purpose: this is a
        one-way ledger, so it must not advance until whoever fetched the
        bill has actually delivered it. Marking at fetch time — which is
        what this class did until 2026-08-17 — meant any later failure
        (compose, send, a crashed run) destroyed that bill permanently,
        because the next poll skipped it. Callers now fetch, deliver, and
        only then mark. Mirrors `mark_email_synced` on the school side.
        """
        # Locked across read -> append -> write, re-reading inside the lock.
        # A lost id here means the bill posts to the family group a second
        # time, which is the outcome utils.append_capped_id's own comment
        # names. Mirrors SchoolEmailMonitor._mark_processed.
        with locked_file(self.processed_ids_file):
            self._processed_order = append_capped_id(
                read_id_list(self.processed_ids_file), msg_id)
            self.processed_ids = set(self._processed_order)
            self._save_processed_ids()

    # ─── Auth-error dedup ────────────────────────────────────────────────────

    # One implementation, in utils.AuthErrorFlag. This was a near-verbatim
    # copy of the school monitor's, differing only in a log prefix.
    def _auth_flag(self) -> AuthErrorFlag:
        return AuthErrorFlag(self.auth_error_state_file, "bills")

    def _is_auth_error_notified(self) -> bool:
        return self._auth_flag().notified()

    def _set_auth_error_notified(self, notified: bool) -> None:
        self._auth_flag().set(notified)

    # ─── Gmail auth ──────────────────────────────────────────────────────────

    # ─── Query building ──────────────────────────────────────────────────────

    def build_query(self) -> str:
        """OR across every configured biller's sender address, within the
        configured lookback.

        `sender` holds a full mailbox address (e.g. "billing@electricco.example.com"),
        not just a domain — some billers send through a shared billing
        platform (e.g. a water district's e-bills arriving via a
        third-party biller-payment domain used by many other senders too),
        so matching on domain alone would over-match unrelated mail from
        the same platform.

        There is deliberately **no** `has:attachment` clause. One was here
        until 2026-08-22, and it quietly reduced this watcher to a single
        biller: only the water district attaches a PDF. The electricity and
        waste companies send a link-only "your bill is ready" notice, so not
        one of their bills was ever seen — every run logged `no_new_emails`
        and the ledger held nothing but water bills for two months.

        The cost of dropping it is that non-bill mail from a biller's address
        (outage alerts, marketing, payment receipts) now matches too. That is
        handled where the judgement belongs — the composing model returns
        NOT_A_BILL and the runner stays quiet — rather than by a Gmail
        operator guessing from the presence of an attachment.
        """
        senders = [b["sender"] for b in self.billers if b.get("sender")]
        if not senders:
            return ""
        from_clause = " OR ".join(f"from:{s}" for s in senders)
        return f"({from_clause}) newer_than:{self.lookback_days}d"

    def _match_biller(self, sender: str) -> Optional[str]:
        """Return the configured biller name whose sender address appears in
        the From: header, or None if nothing matches (defensive — the Gmail
        query already filters by sender, but a biller could be removed from
        config between the query and this call)."""
        sender_lower = sender.lower()
        for b in self.billers:
            addr = b.get("sender", "")
            if addr and addr.lower() in sender_lower:
                return b.get("name", addr)
        return None

    # ─── Fetch matching emails ───────────────────────────────────────────────

    def fetch_emails(
        self,
        skip_processed: bool = True,
        max_results: int = 10,
        take: Optional[int] = 1,
    ) -> List[Dict]:
        """Return list of {id, subject, sender, date, biller_name, pdf_text}
        for unprocessed bill emails, OLDEST FIRST.

        **Marks nothing.** Reading a bill is not the same as having
        delivered it, so the ledger is the caller's to advance via
        `mark_processed()` once the summary is actually sent. Calling this
        twice without marking returns the same bill twice, by design — that
        is what makes a failed run retryable.

        Args:
          skip_processed: honor the dedup file (default True)
          max_results: how many candidates to pull from Gmail (search page size)
          take: how many to return (default 1 — mirrors the club_studio/school
            hard cap that works around gemma4:26b's silent-stop-after-first-item
            failure mode). The unpicked remainder stays available either way.
        """
        query = self.build_query()
        if not query:
            return []

        from core import gmail

        try:
            message_ids = gmail.search(query, max_results=max_results)
        except Exception as e:
            print(f"[bills] Gmail search failed: {e}", file=sys.stderr)
            return []

        candidates: List[Dict] = []
        for msg_id in message_ids:
            if skip_processed and msg_id in self.processed_ids:
                continue

            try:
                full = gmail.get_message(msg_id)
            except Exception as e:
                print(f"[bills] Gmail get failed for {msg_id}: {e}", file=sys.stderr)
                continue

            headers = full.get("payload", {}).get("headers", [])
            subject = next(
                (h["value"] for h in headers if h["name"].lower() == "subject"), ""
            )
            sender = next(
                (h["value"] for h in headers if h["name"].lower() == "from"), ""
            )
            date_str = next(
                (h["value"] for h in headers if h["name"].lower() == "date"), ""
            )

            candidates.append(
                {
                    "id": msg_id,
                    "subject": subject,
                    "sender": sender,
                    "date": date_str,
                    "biller_name": self._match_biller(sender) or "Unknown",
                    "_ts": int(full.get("internalDate", 0)),
                    "_payload": full.get("payload", {}),
                }
            )

        candidates.sort(key=lambda e: e["_ts"])
        picked = candidates if take is None else candidates[:take]

        out: List[Dict] = []
        for e in picked:
            pdf_texts = extract_pdf_attachments(e["id"], e["_payload"])
            # Whether a PDF is ATTACHED, independent of whether pypdf could
            # read it. `bool(pdf_texts)` conflated the two, so a scanned or
            # malformed statement came back looking like a notice-only bill and
            # the composer summarized a full statement as "your bill is ready".
            has_attachment = _has_pdf_part(e["_payload"])
            out.append(
                {
                    "id": e["id"],
                    "subject": e["subject"],
                    "sender": e["sender"],
                    "date": e["date"],
                    "biller_name": e["biller_name"],
                    # The email's own text. For a biller that attaches a PDF
                    # this is boilerplate, but for one that only ever says
                    # "your bill is ready, log in" it is the entire bill —
                    # amount and due date included.
                    "body": _extract_body(e["_payload"])[:8000],
                    # Lets the caller tell a notice-only bill from a full
                    # statement without inferring it from an empty string.
                    "has_pdf": has_attachment,
                    # True when a PDF was attached but yielded no text — a
                    # scan, or a reader failure. The caller should treat the
                    # bill as notice-only rather than claim usage detail it
                    # does not have.
                    "pdf_unreadable": has_attachment and not pdf_texts,
                    # 20000, not 8000: a real multi-page bill's actual billing
                    # details (tiered usage/rate breakdown) often lands on
                    # page 2-3, after a page of pure legal boilerplate. An
                    # 8000-char cap cut off before that page ever arrived,
                    # leaving only promotional callouts from page 1 visible.
                    "pdf_text": "\n\n".join(pdf_texts)[:20000],
                }
            )

        return out


# ─── Direct debug entry point ────────────────────────────────────────────────
#
# Production goes through `bin/homebase fetch_bill_emails` (a thin wrapper on
# this module), driven by the scheduled bills runner outside this skill. This
# __main__ block exists for manual debugging / smoke tests:
#
#   python3 -m features.bills.watcher              # print raw bill emails (pdf_text truncated)
#   python3 -m features.bills.watcher --full        # print with full pdf_text
#
# Safe to run repeatedly: since 2026-08-17 fetching marks nothing, so
# inspecting a bill here no longer consumes it. Emits JSON on stdout so it
# stays parseable for scripting.


def _cli_main() -> int:
    import traceback

    try:
        # The keyring-importability probe that stood here until 2026-09-07 is
        # gone with the credentials it guarded. It existed because this
        # interpreter used to read GOOGLE_* out of the Keychain itself, and a
        # python without `keyring` reported "no credentials" when the real
        # problem was the interpreter. gog holds the token now and reports its
        # own state via `gog auth status`, so there is nothing here to probe.
        from core.config_loader import SKILL_DIR

        watcher = BillsWatcher(base_path=SKILL_DIR)

        if not watcher.enabled:
            print(json.dumps({"status": "disabled"}))
            return 0

        try:
            emails = watcher.fetch_emails()
        except Exception as e:
            # gog reports its own auth state; there is no credential probe here
            # to distinguish "no secret" from "unreadable keyring" any more.
            # `gog auth status` answers that, and answers it about the thing
            # actually doing the authenticating.
            print(json.dumps({"status": "auth_failed", "error": str(e)[:200]}))
            return 0

        if not emails:
            print(json.dumps({"status": "no_new_emails"}))
            return 0

        # pdf_text can contain real account/usage numbers — truncate by
        # default so a casual debug run doesn't dump full bills into
        # terminal scrollback/logs. Pass --full to see complete content.
        show_full = "--full" in sys.argv
        debug_emails = emails if show_full else [
            {**e,
             # For a notice-only biller the BODY is the entire bill — amount
             # and due date included — so truncating only pdf_text left real
             # account numbers in terminal scrollback and any redirected log.
             "body": (e.get("body", "")[:150] + "... [truncated, use --full]"),
             "pdf_text": (e.get("pdf_text", "")[:150] + "... [truncated, use --full to see complete text]")
                              if len(e.get("pdf_text", "")) > 150 else e.get("pdf_text", "")}
            for e in emails
        ]

        print(
            json.dumps(
                {
                    "status": "emails_found",
                    "count": len(emails),
                    "emails": debug_emails,
                },
                indent=2,
            )
        )
        return 0
    except Exception as e:
        print(
            json.dumps(
                {
                    "status": "crashed",
                    "error": str(e),
                    "traceback": traceback.format_exc(),
                }
            )
        )
        return 1


if __name__ == "__main__":
    sys.exit(_cli_main())
