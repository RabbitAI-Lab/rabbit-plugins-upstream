def record_correction(
    original: str,
    corrected: str,
    source: str,
    confidence: float,
    bvid: str,
    problem_type: str = "",
    solution: str = "",
    example: str = "",
):
    """
    记录一次修正到错题库（题型模式）。
    
    v3 从"词对"存储升级为"题型+解题思路+示例"。
    同一题型的问题归类在一起，便于后续统计和学习。
    
    Args:
        original: 原始低置信词
        corrected: 修正后的词
        source: 修正来源 (L1~L5)
        confidence: 修正置信度
        bvid: 视频ID
        problem_type: 题型分类（同音/语义/术语/上下文/填充词/其他）
        solution: 解题思路（为什么这样修）
        example: 示例句子
    """
    correction_dict = load_correction_dict()
    
    if "patterns" not in correction_dict:
        correction_dict["patterns"] = []
    if "stats" not in correction_dict:
        correction_dict["stats"] = {"total": 0, "by_type": {}}
    
    entry = {
        "original": original,
        "corrected": corrected,
        "source": source,
        "confidence": confidence,
        "bvid": bvid,
        "problem_type": problem_type,
        "solution": solution,
        "example": example,
        "timestamp": time.strftime("%Y-%m-%d %H:%M:%S"),
    }
    correction_dict["patterns"].append(entry)
    correction_dict["stats"]["total"] += 1
    if problem_type:
        correction_dict["stats"]["by_type"][problem_type] = \
            correction_dict["stats"]["by_type"].get(problem_type, 0) + 1
    
    save_correction_dict(correction_dict)


def load_correction_stats() -> Dict:
    """加载修正统计"""
