def save_correction_stats(stats: Dict):
    """保存修正统计"""
    try:
        os.makedirs(os.path.dirname(CORRECTION_STATS_FILE), exist_ok=True)
        with open(CORRECTION_STATS_FILE, "w") as f:
            json.dump(stats, f, ensure_ascii=False, indent=2)
    except OSError:
        pass


def update_stats(bvid: str, corrected: str, original: str, source: str, confidence: float):
    """更新单条修正统计"""
    stats = load_correction_stats()
    key = f"{original}→{corrected}"
    if key not in stats:
        stats[key] = {"count": 0, "sources": [], "last_bvid": "", "last_confidence": 0.0}
    stats[key]["count"] += 1
    if source not in stats[key]["sources"]:
        stats[key]["sources"].append(source)
    stats[key]["last_bvid"] = bvid
    stats[key]["last_confidence"] = max(stats[key]["last_confidence"], confidence)
    save_correction_stats(stats)


def get_problem_type(word: str) -> str:
    """根据词特征推断题型（供record_correction自动分类）"""
    if any(c in word for c in "*#@！￥"):
        return "消音标记"
    if len(word) <= 1:
        return "单字误识"
    if word in SPEECH_FILLERS:
        return "口语填充"
    # 检查是否包含交易术语关键词中的字
    for term in TRADING_TERMS:
        if any(c in word for c in term if len(c) >= 2):
            return "交易术语同音"
    return "一般同音/语义"
