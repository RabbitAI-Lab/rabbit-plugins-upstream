def check_bleep(word: str) -> Optional[Tuple[str, float, str]]:
    """检查是否是BLEEP/消音标记"""
    for marker, desc in BEEP_TERMS.items():
        if marker in word or word == marker:
            return (f"[{desc}]", 1.0, f"明确消音标记'{marker}'")
    if '*' in word and len(word) >= 2:
        return ("[消音]", 0.9, f"含星号: whisper可能误消音为词")
    return None


def check_multi_word_pattern(words: List[str], text: str) -> List[Dict]:
    """多词模式检测 — 多个低置信词是否构成同音错误模式"""
    patterns = []
    from collections import Counter
    
    for anchor in TRADING_TERMS:
        matching = [w for w in words if any(c in w for c in anchor if len(c) >= 2)]
        if len(matching) >= 2:
            patterns.append({
                "words": matching,
                "common": anchor[:4],
                "count": len(matching),
            })
    
    word_counts = Counter(words)
    for w, cnt in word_counts.most_common():
        if cnt >= 2 and len(w) >= 2:
            patterns.append({
                "words": [w] * cnt,
                "common": w,
                "count": cnt,
                "duplicate": True,
            })
    
    return patterns


