def fast_domain_correct(text: str) -> str:
    """快速的领域确定性纠错 — 只做0歧义的替换"""
    corrected = text
    for wrong, correct in DOMAIN_CORRECTIONS.items():
        if wrong in corrected:
            corrected = corrected.replace(wrong, correct)
    return corrected


