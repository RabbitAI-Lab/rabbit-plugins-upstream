#!/usr/bin/env python3
"""Write curated aliases into `props.aliases` and re-embed just those nodes.

An alias is new vocabulary for a node whose real name uses your jargon while the
question uses the asker's words. It is picked up free by three channels: FTS (the
`props` column is already indexed), the vector index (embeddings.py::_node_text
appends aliases), and the name channel (an aliased node is pin-eligible whatever
its type). One line per node, auditable, reversible — delete `props.aliases`.

Rule of thumb: no alias repeats a word the node's name already has. That would be
a ranking hack, not a vocabulary fix.

usage: engram-aliases.py <db> [--spec aliases.json] [--apply]

Spec format (keys are node ids; `name` is checked against the DB as a safety net,
keys starting with `_` are ignored so the file can carry its own notes):

  {
    "_rule": "free-text note, ignored",
    "18": {"name": "Jane Doe", "aliases": ["owner", "founder"]}
  }
"""

