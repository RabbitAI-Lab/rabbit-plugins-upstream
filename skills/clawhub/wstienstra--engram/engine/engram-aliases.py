import argparse, json, os, sqlite3, sys

HERE = os.path.dirname(os.path.abspath(__file__))

ap = argparse.ArgumentParser()
ap.add_argument('db')
ap.add_argument('--spec', default=os.path.join(HERE, 'aliases.json'),
                help='alias spec JSON (default: aliases.json next to this script)')
ap.add_argument('--apply', action='store_true', help='write; without it, preview only')
args = ap.parse_args()

if not os.path.exists(args.spec):
    print(f"no alias spec at {args.spec} — nothing to do")
    sys.exit(0)

spec = json.load(open(args.spec))
db = sqlite3.connect(args.db)
db.row_factory = sqlite3.Row
touched = []
for nid, info in spec.items():
    if nid.startswith('_'):
        continue
    row = db.execute("SELECT id,name,props FROM nodes WHERE id=?", (int(nid),)).fetchone()
    if not row:
        print(f"  MISSING #{nid} ({info['name']}) — skipped"); continue
    # The id is the key, but a spec written against another database would silently
    # alias the wrong node. Require the names to agree before writing.
    if row['name'].split(':')[0].strip()[:20] not in info['name'][:40] and \
       info['name'][:20] not in row['name']:
        print(f"  MISMATCH #{nid}: db has {row['name'][:50]!r} — skipped"); continue
    try: props = json.loads(row['props']) if row['props'] else {}
    except Exception: props = {}
    props['aliases'] = info['aliases']
    print(f"  #{nid} {row['name'][:44]:44s} <- {info['aliases']}")
    if args.apply:
        db.execute("UPDATE nodes SET props=? WHERE id=?", (json.dumps(props), int(nid)))
    touched.append(int(nid))
if args.apply:
    db.commit()
    # Aliases only reach the semantic channel after the node is re-embedded.
    os.environ['ENGRAM_DB'] = args.db
    sys.path.insert(0, HERE)
    from embeddings import SemanticEngine
    eng = SemanticEngine(args.db)
    n = 0
    for nid in touched:
        row = db.execute("SELECT * FROM nodes WHERE id=?", (nid,)).fetchone()
        eng.index_node(nid, eng._node_text(row)); n += 1
    print(f"re-embedded {n} nodes")
else:
    print(f"(preview: {len(touched)} node(s) would change — pass --apply to write)")
db.close()
