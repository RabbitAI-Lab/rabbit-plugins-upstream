# ── SUPERSEDE (truth maintenance) ───────────────────────
# Timestamps make superseded chains a progression of insight, not silent
# overwrites. Superseding sets old.props.superseded_by = new.id and records
# a 'supersedes' association (source=new, target=old) so recall can hide
# stale nodes by default while preserving the full chain via --history.

def _resolve_node_ref(db, ref):
    """Resolve a node by numeric id or by name (case-insensitive, exact)."""
    ref = (ref or "").strip()
    if ref.isdigit():
        row = db.execute("SELECT * FROM nodes WHERE id = ?", (int(ref),)).fetchone()
        if row:
            return row
    return db.execute("SELECT * FROM nodes WHERE name = ? COLLATE NOCASE", (ref,)).fetchone()


def _supersedes_closure(db, node_id):
    """Return the set of node ids transitively superseded BY node_id
    (i.e. walking outgoing 'supersedes' associations from node_id)."""
    seen = set()
    frontier = [node_id]
    while frontier:
        cur = frontier.pop()
        rows = db.execute(
            "SELECT target_id FROM associations WHERE source_id = ? AND relation = 'supersedes'",
            (cur,)
        ).fetchall()
        for r in rows:
            tid = r["target_id"]
            if tid not in seen:
                seen.add(tid)
                frontier.append(tid)
    return seen


def _create_supersede_link(db, new_node, old_node):
    """Create a supersedes link: new_node supersedes old_node.
    Raises ValueError if this would create a cycle in the supersedes chain.
    """
    new_id, old_id = new_node["id"], old_node["id"]
    if new_id == old_id:
        raise ValueError("A node cannot supersede itself.")

    # Cycle check: walk the supersedes chain from old (what old already
    # supersedes); if new appears in it, this would close a loop.
    if new_id in _supersedes_closure(db, old_id):
        raise ValueError(
            f"Cycle: '{old_node['name']}' already (directly or transitively) supersedes '{new_node['name']}'"
        )

    ensure_weights(db)
    ts = now()
    try:
        db.execute(
            "INSERT INTO associations (source_id, target_id, relation, weight, created_at) VALUES (?, ?, ?, ?, ?)",
            (new_id, old_id, "supersedes", 1, ts)
        )
    except sqlite3.IntegrityError:
        pass  # link already exists

    try:
        old_props = json.loads(old_node["props"]) if old_node["props"] else {}
    except Exception:
        old_props = {}
    prev_superseded_by = old_props.get("superseded_by")
    old_props["superseded_by"] = new_id
    old_props["superseded_at"] = ts
    db.execute("UPDATE nodes SET props = ? WHERE id = ?", (json.dumps(old_props), old_id))

    # Phase 4d bi-temporal: superseding closes the old fact's validity window
    # (valid_to = supersede date) so an as-of recall after this date prefers
    # the new fact, while recall before it still surfaces the old one. Only
    # set when unbounded — never stomp an explicit expiry the user chose.
    try:
        ensure_temporal_columns(db)
        if not (_as_date(_node_field(old_node, "valid_to", "")) or ""):
            db.execute("UPDATE nodes SET valid_to = ? WHERE id = ?", (ts[:10], old_id))
    except Exception:
        pass

    ensure_history_table(db)
    record_history(db, old_id, "props.superseded_by", prev_superseded_by, new_id)
    db.commit()


def cmd_supersede(args):
    """Mark an old node as superseded by a new one.
    Usage: engram supersede "<old name or id>" "<new name or id>"
    """
    db = get_db()
    old_node = _resolve_node_ref(db, args.old)
    new_node = _resolve_node_ref(db, args.new)
    if not old_node:
        print(f"❌ Node '{args.old}' not found.")
        sys.exit(1)
    if not new_node:
        print(f"❌ Node '{args.new}' not found.")
        sys.exit(1)

    try:
        _create_supersede_link(db, new_node, old_node)
    except ValueError as e:
        print(f"❌ {e}")
        sys.exit(1)

    print(f"⏭️  '{new_node['name']}' supersedes '{old_node['name']}'")


