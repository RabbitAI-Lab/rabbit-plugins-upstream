def cmd_context_recall(args):
    """Context-aware recall: pass conversation context to weight results by relevance to current work."""
    db = get_db()
    context = args.context
    query = args.query or ""
    
    # Extract key terms from context
    import re
    # Filter out common English stop words that pollute results
    stop_words = {
        "the", "and", "for", "are", "but", "not", "you", "all", "can", "her",
        "was", "one", "our", "out", "has", "have", "had", "been", "from",
        "this", "that", "with", "they", "will", "each", "make", "like",
        "just", "use", "used", "using", "how", "what", "when", "where",
        "which", "who", "why", "some", "any", "also", "about", "into",
        "more", "other", "than", "then", "them", "these", "would", "could",
        "should", "does", "did", "get", "got", "here", "there", "very",
        "after", "before", "being", "both", "between", "still", "over",
    }
    words = [w for w in re.findall(r'[a-z]{3,}', context.lower()) if w not in stop_words]
    
    # Get top 5 most specific words (least common in DB)
    word_freq = {}
    for w in set(words):
        count = db.execute("SELECT COUNT(*) FROM nodes WHERE lower(name) LIKE ? OR lower(content) LIKE ?",
                          (f"%{w}%", f"%{w}%")).fetchone()[0]
        if count > 0:
            word_freq[w] = count
    
    # Most specific = lowest frequency but > 0
    specific = sorted(word_freq.items(), key=lambda x: x[1])[:5]
    context_terms = [w for w, c in specific]
    
    # Relevance threshold: if no context terms match anything in the DB, bail
    if not context_terms:
        print(f"🎯 No relevant context terms found in: {context[:80]}")
        print("🔍 No results for context query")
        return
    
    if not query:
        query = " ".join(context_terms[:3])
    
    # Verify FTS5 actually matches before running full recall
    fts_check = db.execute(
        "SELECT COUNT(*) FROM nodes_fts WHERE nodes_fts MATCH ?",
        (f'"{query}"',)
    ).fetchone()[0]
    
    # Also check individual terms
    if fts_check == 0:
        for term in context_terms[:3]:
            fts_check += db.execute(
                "SELECT COUNT(*) FROM nodes_fts WHERE nodes_fts MATCH ?",
                (term,)
            ).fetchone()[0]
    
    if fts_check == 0:
        print(f"🎯 Context terms: {', '.join(context_terms)}")
        print(f"🔍 No results for context query: {query}")
        return
    
    print(f"🎯 Context terms: {', '.join(context_terms)} (matched {fts_check} nodes)")
    print(f"   Expanded query: {query}\n")
    
    # Reuse recall with the expanded query
    args.query = query
    args.mode = "solve"  # Context recall = broad
    cmd_recall(args)


# ── HOP PATHS (pre-computed multi-hop traversal) ──────────────────────

def ensure_hop_table(db):
    """Create hop_paths table for pre-computed multi-hop association paths."""
    db.execute("""CREATE TABLE IF NOT EXISTS hop_paths (
        source_id INTEGER,
        target_id INTEGER,
        distance INTEGER,
        via_ids TEXT DEFAULT '[]',
        max_weight INTEGER DEFAULT 3,
        computed_at TEXT,
        PRIMARY KEY (source_id, target_id)
    )""")
    db.execute("CREATE INDEX IF NOT EXISTS idx_hop_source ON hop_paths(source_id)")
    db.execute("CREATE INDEX IF NOT EXISTS idx_hop_target ON hop_paths(target_id)")
    db.execute("CREATE INDEX IF NOT EXISTS idx_hop_dist ON hop_paths(distance)")


# Node types excluded from the hop graph: high-volume time-series/log nodes
# that would blow up path counts without adding recall value.
HOP_SKIP_TYPES = ('message_sent', 'message_received', 'heartbeat_log',
                  'project_action', 'extract', 'session_summary')
# Nodes with more edges than this are hubs (e.g. the owner's contact node);
# paths *through* them are low-information, so BFS never expands past them.
HOP_DEGREE_CAP = 150


def build_hop_paths(db, max_depth=3):
    """BFS from every node to pre-compute reachable paths up to max_depth hops."""
    ensure_hop_table(db)

    # Load adjacency list into memory, excluding log/message-type endpoints
    skip_marks = ",".join("?" for _ in HOP_SKIP_TYPES)
    adj = {}  # node_id -> [(neighbor_id, weight)]
    rows = db.execute(f"""
        SELECT a.source_id, a.target_id, COALESCE(a.weight, 3) as w
        FROM associations a
        JOIN nodes ns ON ns.id = a.source_id
        JOIN nodes nt ON nt.id = a.target_id
        WHERE ns.type NOT IN ({skip_marks}) AND nt.type NOT IN ({skip_marks})
    """, (*HOP_SKIP_TYPES, *HOP_SKIP_TYPES)).fetchall()
    for r in rows:
        adj.setdefault(r["source_id"], []).append((r["target_id"], r["w"]))
        adj.setdefault(r["target_id"], []).append((r["source_id"], r["w"]))

    hubs = {n for n, nb in adj.items() if len(nb) > HOP_DEGREE_CAP}
    all_nodes = [r["id"] for r in db.execute("SELECT id FROM nodes").fetchall()]
    ts = now()

    db.execute("DELETE FROM hop_paths")

    batch = []
    for start in all_nodes:
        if start not in adj or start in hubs:
            continue
        # BFS from this node
        visited = {start: (0, [], 0)}  # node -> (distance, via_ids, max_weight_on_path)
        queue = [(start, 0, [], 0)]  # (node, dist, path, max_weight)
        
        while queue:
            current, dist, path, mw = queue.pop(0)
            if dist >= max_depth:
                continue
            if current != start and current in hubs:
                continue  # hubs are reachable but never traversed through
            for neighbor, weight in adj.get(current, []):
                new_dist = dist + 1
                new_mw = max(mw, weight)
                new_path = path + [current] if current != start else []
                
                if neighbor not in visited or visited[neighbor][0] > new_dist or \
                   (visited[neighbor][0] == new_dist and visited[neighbor][2] > new_mw):
                    visited[neighbor] = (new_dist, new_path, new_mw)
                    queue.append((neighbor, new_dist, new_path, new_mw))
        
        # Store paths (skip self and direct neighbors which are already in associations)
        for target, (dist, via, mw) in visited.items():
            if target == start:
                continue
            if dist >= 2:  # Only store multi-hop (depth 1 is already in associations)
                batch.append((start, target, dist, json.dumps(via), mw, ts))
        
        # Batch insert every 500 paths
        if len(batch) >= 500:
            db.executemany("INSERT OR REPLACE INTO hop_paths VALUES (?,?,?,?,?,?)", batch)
            batch = []
    
    if batch:
        db.executemany("INSERT OR REPLACE INTO hop_paths VALUES (?,?,?,?,?,?)", batch)
    
    db.commit()
    
    total = db.execute("SELECT COUNT(*) FROM hop_paths").fetchone()[0]
    return total


def cmd_hop_build(args):
    """Build or rebuild pre-computed hop paths."""
    db = get_db()
    depth = getattr(args, 'depth', 3) or 3
    print(f"🔗 Building hop paths (max depth={depth})...")
    total = build_hop_paths(db, max_depth=depth)
