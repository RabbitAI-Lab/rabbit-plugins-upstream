_HUB_SHAPE_TYPE_CAP = 6      # max candidates of any one node type in the reranker pool
_HUB_SHAPE_SIM_THRESHOLD = 0.90  # cosine above which two candidates count as near-dupes
_HUB_SHAPE_POOL_SIZE = 30    # candidates handed to the reranker


def _shape_candidate_pool(scored, node_vecs, pool_size=_HUB_SHAPE_POOL_SIZE,
                           type_cap=_HUB_SHAPE_TYPE_CAP, pinned_ids=None):
    """Anti-hub candidate shaping (Package 4): walk `scored` (already RRF-fused
    and sorted, highest first) and build a diverse pool of up to `pool_size`
    candidates for the reranker, so one node TYPE flooding the fused ranking
    (e.g. 20 outreach_prospect rows sharing a hub word) can't crowd out a
    small, genuinely-relevant node before the cross-encoder ever sees it.

    Per-type cap: at most `type_cap` candidates of any single node type make
    the pool (uncapped once fewer than pool_size/2 slots remain, so the cap
    only bites early, before it can starve the pool itself).

    An embedding-cosine MMR dedup was tried here too (skip a candidate whose
    vector is a near-duplicate of one already selected) and reused the same
    0.90 threshold _cosine_sim/output_node use to fold near-identical nodes
    at display time. It was removed: on real data, genuinely-redundant
    near-dupes (repeated EMAIL templates differing only by timestamp) and
    merely topic-related-but-distinct nodes (two different outreach prospects
    in the same niche) both land at ~0.90-0.94 cosine with this embedding
    model — there's no threshold that separates them, and it demonstrably
    discarded the one node that actually answered a battery query in favor
    of an unrelated node that happened to be selected first by RRF luck.
    Display-time folding (same threshold) is unaffected by this and still
    runs — there, picking the "wrong" representative just costs a line of
    text, not a wrong or missing answer.

    `pinned_ids` (from _pin_hub_entities) always makes the pool regardless of
    the type cap — a hub-entity pin is a high-precision signal that a small
    node genuinely IS the query's subject, and losing it to a type cap would
    defeat the whole point of pinning it in the first place."""
    pinned_ids = set(pinned_ids or ())
    type_counts = {}
    selected = []       # [(match_type, node, score)]

    def _nid_of(node):
        return node["id"] if not isinstance(node, dict) else node.get("id")

    def _type_of(node):
        return (node["type"] if not isinstance(node, dict) else node.get("type")) or ""

    # Pass 1: always include pinned hub entities first, in their given order.
    remaining = []
    for match_type, node, score in scored:
        nid = _nid_of(node)
        if nid in pinned_ids:
            selected.append((match_type, node, score))
            type_counts[_type_of(node)] = type_counts.get(_type_of(node), 0) + 1
        else:
            remaining.append((match_type, node, score))

    # Pass 2: fill the rest in fused-score order, subject to the type cap.
    for match_type, node, score in remaining:
        if len(selected) >= pool_size:
            break
        ntype = _type_of(node)

        # Per-type cap only bites while there's still real competition for
        # slots — once the pool is more than half-empty, let anything in
        # rather than leave slots unfilled.
        slots_left = pool_size - len(selected)
        if slots_left <= pool_size // 2 and type_counts.get(ntype, 0) >= type_cap:
            continue

        selected.append((match_type, node, score))
        type_counts[ntype] = type_counts.get(ntype, 0) + 1

    return selected


_RERANKER_STATE = {}  # process-wide cache: {"ranker": Ranker|None}
FLASHRANK_MODEL_NAME = "ms-marco-TinyBERT-L-2-v2"
# Engram: flashrank model cache lives in the install dir from engram.json.
try:
    FLASHRANK_CACHE_DIR = os.path.join(bpconfig.engram_dir(), "models", "flashrank-tinybert-l2")
except Exception:
    FLASHRANK_CACHE_DIR = os.path.join(
        os.path.dirname(os.path.abspath(__file__)), "models", "flashrank-tinybert-l2")
RERANK_PASSAGE_CHARS = 500   # truncation keeps CPU cost <100ms for 30 candidates


def _get_reranker():
    """Lazy-load the cross-encoder reranker once per process and cache it in
    a module-level dict, so the warm daemon (which keeps this module resident
    between calls) pays the ~150-250ms ONNX load cost exactly once, not per
    request. Returns None (never raises) if flashrank isn't installed or the
    model fails to load — callers must degrade to pure RRF order on None."""
    if "ranker" in _RERANKER_STATE:
        return _RERANKER_STATE["ranker"]
    try:
        from flashrank import Ranker
        ranker = Ranker(model_name=FLASHRANK_MODEL_NAME, cache_dir=FLASHRANK_CACHE_DIR)
    except Exception:
        ranker = None
    _RERANKER_STATE["ranker"] = ranker
    return ranker


def _rerank_pool(query, pool):
    """Stage-2 cross-encoder rerank over `pool` (list of (match_type, node,
    score)). Returns {node_id: sigmoid_score} on success, or None if the
    reranker is unavailable or errors — callers must fall back to pure RRF
    order on None, never raise or crash recall. flashrank's own pairwise CE
    forward pass already applies sigmoid/softmax, so the scores returned are
    directly usable as calibrated confidence, no extra transform needed."""
    ranker = _get_reranker()
    if ranker is None or not pool:
        return None
    try:
        from flashrank import RerankRequest
        passages = []
        for _, node, _ in pool:
            nid = node["id"] if not isinstance(node, dict) else node.get("id")
            name = (node["name"] if not isinstance(node, dict) else node.get("name")) or ""
            ntype = (node["type"] if not isinstance(node, dict) else node.get("type")) or ""
            content = (node["content"] if not isinstance(node, dict) else node.get("content")) or ""
            text = f"{name} ({ntype}): {content}"[:RERANK_PASSAGE_CHARS]
            passages.append({"id": nid, "text": text})
        results = ranker.rerank(RerankRequest(query=query, passages=passages))
        return {r["id"]: float(r["score"]) for r in results}
    except Exception:
        return None


# Calibrated on the 2026-07-05 battery: flashrank top1 sigmoid scores for the
# 3 negative-control queries (things NOT in the engram) topped out at 0.006,
# while every genuine match sampled (including a fuzzy-typo adversarial hit)
# scored >= 0.18 — a ~30x gap. RERANK_ABSTAIN_FLOOR sits an order of
# magnitude above the negative-control ceiling and well below the lowest
# real hit observed, so it separates the two without being tuned to any one
# query. RERANK_MARGIN_ZONE_MAX + RERANK_MARGIN_MIN add a secondary check
# only in the ambiguous band just above the floor (real confident hits are
# usually >>0.3 and don't need it).
RERANK_ABSTAIN_FLOOR = 0.08
RERANK_MARGIN_ZONE_MAX = 0.30
RERANK_MARGIN_MIN = 0.02


# ── Lexical-evidence bypass for the abstention gate (2026-09-18) ──
# _rerank_confidence tests flashrank's ABSOLUTE score. Measured on 74 real mined queries
#: that score is ~0.000 for almost
# every genuine paraphrase AND for almost every unanswerable question, so it cannot
# separate them — six of the eight false abstentions had the right answer already ranked
# in the reranker's own top 7, four of them in its top 3, and the gate threw the result
# away anyway. Retuning the constants provably changes nothing (§1.4, run 05).
#
# So the gate keeps its reranker test and gains a second, independent way to be satisfied:
# does a top-ranked candidate show real LEXICAL evidence for this query? Two ways to
# qualify, both about rarity rather than volume — matching many common words is what makes
# a coincidence look confident:
#   * it contains the query's rarest distinctive term, and that term is rare enough that
#     containing it is evidence (document frequency <= GATE_EVIDENCE_DF_MAX), or
#   * the query terms it does contain carry at least GATE_EVIDENCE_IDF_MASS of IDF.
# Both thresholds sit on a wide plateau (df 350-1000, mass 10-12 all score identically);
# they are not knife-edge fits. Runs at mass 9 leak negatives, at mass 15 lose paraphrases.
GATE_EVIDENCE_DF_MAX = 500      # a term in more than this many nodes is not evidence
GATE_EVIDENCE_IDF_MASS = 11.0   # ~ two moderately rare terms, or one very rare one
GATE_EVIDENCE_TOP_N = 3         # only the candidates we would actually show first


def _lexical_evidence(db, query, nodes):
    """Second, independent grounding signal for the abstention gate. True when the
    best-covering candidate among `nodes` carries genuine lexical evidence for `query`.

    Deliberately narrow: `nodes` is the reranker's top few, not its whole pool. The same
    test over a 30-candidate pool collapses the negative class from 85% to 31% (§1.4,
    run 03) because with enough candidates something matches most of the query by
    coincidence — which is also why _lexical_grounding is not reused here."""
    if not query or not nodes:
        return False
    import math as _math
    import re as _re
    generic = set(get_config(db, "generic_words"))
    terms = [w.lower() for w in _re.findall(r"[A-Za-z][A-Za-z0-9_-]{2,}", query)
             if w.lower() not in generic and len(w) >= 4]
    terms = list(dict.fromkeys(terms))
    if not terms:
        return False

    total = db.execute("SELECT COUNT(*) FROM nodes").fetchone()[0] or 1
    dfs = {}
    for t in terms:
        try:
            dfs[t] = db.execute(
                "SELECT COUNT(*) FROM nodes_fts WHERE nodes_fts MATCH ?", (f'"{t}"',)
            ).fetchone()[0]
        except sqlite3.OperationalError:
            dfs[t] = total

    # Best-covering candidate only: one node must account for the evidence, so two
    # different nodes each matching half the query cannot add up to false confidence.
    best = set()
    for node in nodes:
        if isinstance(node, dict):
            get = node.get
        else:
            keys = node.keys()
            get = lambda k, d=None, _n=node, _k=keys: _n[k] if k in _k else d
        blob = " ".join(str(get(k, "") or "") for k in ("name", "content", "props")).lower()
        hit = {t for t in terms if t in blob}
        if len(hit) > len(best):
            best = hit
    if not best:
        return False

    rare_term = min(dfs, key=lambda t: dfs[t])
    if dfs[rare_term] <= GATE_EVIDENCE_DF_MAX and rare_term in best:
        return True
    mass = sum(_math.log(total / max(dfs[t], 1)) for t in best)
    return mass >= _idf_bar(GATE_EVIDENCE_IDF_MASS, total)


def _rerank_confidence(rerank_scores, candidate_ids):
    """Given {node_id: score} from _rerank_pool and the ids to consider (in
    fused-score order), return (confident: bool, top1, margin)."""
    scores = [rerank_scores[nid] for nid in candidate_ids if nid in rerank_scores]
    if not scores:
        return False, 0.0, 0.0
    scores.sort(reverse=True)
    top1 = scores[0]
    top2 = scores[1] if len(scores) > 1 else 0.0
    margin = top1 - top2
    if top1 < RERANK_ABSTAIN_FLOOR:
        return False, top1, margin
    if top1 < RERANK_MARGIN_ZONE_MAX and margin < RERANK_MARGIN_MIN:
        return False, top1, margin
    return True, top1, margin


def _batch_tag_idf(db, node_ids, total_nodes):
    """Batch tag-IDF for ALL candidates in one query, instead of the old
    per-candidate tags-JOIN-node_tags join (~27ms x N candidates)."""
    import math
    if not node_ids:
        return {}
    placeholders = ",".join("?" * len(node_ids))
    rows = db.execute(f"""
        SELECT nt.node_id AS nid, t.id AS tag_id, COUNT(nt2.node_id) AS doc_freq
        FROM node_tags nt
        JOIN tags t ON t.id = nt.tag_id
        LEFT JOIN node_tags nt2 ON t.id = nt2.tag_id
        WHERE nt.node_id IN ({placeholders})
        GROUP BY nt.node_id, t.id
    """, node_ids).fetchall()
    idf_sum = {}
    for r in rows:
        idf = math.log(total_nodes / max(r["doc_freq"], 1))
        idf_sum[r["nid"]] = idf_sum.get(r["nid"], 0.0) + idf
    return idf_sum


