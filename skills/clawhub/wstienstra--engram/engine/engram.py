# Structural words that say nothing about whether two names mean the same thing.
# Deliberately grammatical: domain-generic words live in the tunable `generic_words`
# config, this list is the glue English puts between them, plus the type words that
# a migrated name carries as a prefix ("RULE: ", "FACT: ").
#
# Screen by this list and NOT by word length. Short words are the most distinctive
# ones there are — an acronym, a tax id, a port name, a three-letter product. A
# `len >= 4` filter dropped "nif" from "any news from the nif lawyer" and lost the
# case outright, which is the opposite of the problem this screen exists to solve.
_FUZZY_STOP = {
    "a", "an", "the", "and", "or", "of", "to", "in", "on", "at", "by", "for",
    "from", "with", "without", "as", "is", "it", "be", "was", "were", "are", "am",
    "do", "does", "did", "doing", "done", "have", "has", "had", "been", "being",
    "not", "no", "if", "so", "we", "i", "you", "your", "my", "our", "us", "me",
    "he", "she", "him", "her", "they", "them", "their", "its", "ours", "mine",
    "this", "that", "these", "those", "same", "here", "there", "then", "than",
    "when", "while", "which", "what", "who", "whom", "whose", "why", "how",
    "will", "would", "shall", "should", "can", "could", "may", "might", "must",
    "cannot", "into", "onto", "over", "under", "about", "after", "before",
    "only", "also", "just", "very", "more", "most", "less", "some", "such",
    "each", "every", "both", "any", "all", "up", "out", "off", "per", "via",
    "rule", "fact", "note", "lesson", "decision", "method", "policy", "project",
}


def fuzzy_find_node(db, query, limit=5, threshold=0.55):
    """Fuzzy match node names using SequenceMatcher.
    Falls back from exact LIKE → trigram-ish substring → fuzzy ratio.
    Returns list of (node_row, score) tuples sorted by score desc.
    threshold: minimum similarity ratio (0.0-1.0) to include.
    """
    from difflib import SequenceMatcher
    query_lower = query.lower().strip()

    # Phase 1: exact LIKE match (fast path)
    exact = db.execute(
        "SELECT * FROM nodes WHERE name LIKE ? COLLATE NOCASE LIMIT ?",
        (f"%{query}%", limit)
    ).fetchall()
    if exact:
        return [(row, 1.0) for row in exact]

    # Phase 2: fuzzy match against all node names
    # Load candidate names (exclude internal types for speed). ORDER BY id DESC
    # so the LIMIT cap (needed on large DBs) prefers recently-created nodes
    # over an arbitrary table-scan order.
    candidates = db.execute(
        "SELECT id, name FROM nodes WHERE type NOT IN ('config') ORDER BY id DESC LIMIT 5000"
    ).fetchall()

    scored = []
    query_words = set(query_lower.split())
    # Overlap is counted on DISTINCTIVE words only. Counting every shared token
    # made two unrelated rules look identical: "RULE: Always write the changelog
    # entry in the same commit as the version bump" and "RULE: Every promise
    # becomes a ticket in the same turn it is made" share `rule:`, `the`, `in` and
    # `same` — four tokens, which the old formula scored 1.1, above every threshold
    # in the file including auto-supersede's 0.85. The first rule was silently
    # marked superseded by the second and vanished from recall. Anything that
    # prefixes names with its type ("RULE: ", "FACT: ") hits this, which is every
    # workspace built by the markdown migration.
    _generic = set(get_config(db, "generic_words"))

    def _signif(words):
        out = set()
        for w in words:
            w = w.strip(".,;:!?()[]\"'").lower()
            # The leading TYPE: prefix is compared separately, as a type, and a
            # structural word is not evidence that two names mean the same thing.
            # Length is deliberately not a criterion — see _FUZZY_STOP.
            if not w or w in _generic or w in _FUZZY_STOP:
                continue
            out.add(w)
        return out

    query_signif = _signif(query_words)

    for cand in candidates:
        cand_lower = cand["name"].lower()
        cand_words = set(cand_lower.split())

        # SequenceMatcher ratio on full name
        ratio = SequenceMatcher(None, query_lower, cand_lower).ratio()

        # Bonus: word-level overlap (handles reordered/partial names). Capped at
        # 1.0 — a similarity above 1.0 was the tell that the formula was wrong.
        word_overlap = len(query_signif & _signif(cand_words))
        if word_overlap:
            ratio = max(ratio, min(1.0, 0.3 + 0.2 * word_overlap))

        # Bonus: each word fuzzy matched individually
        if len(query_words) > 1:
            best_word_scores = []
            for qw in query_words:
                best = max(
                    (SequenceMatcher(None, qw, cw).ratio() for cw in cand_words),
                    default=0
                )
                best_word_scores.append(best)
            avg_word_score = sum(best_word_scores) / len(best_word_scores)
            ratio = max(ratio, avg_word_score * 0.9)

        if ratio >= threshold:
            scored.append((cand["id"], cand["name"], ratio))

    # Sort by score, fetch full rows for top matches
    scored.sort(key=lambda x: -x[2])
    results = []
    for node_id, name, score in scored[:limit]:
        row = db.execute("SELECT * FROM nodes WHERE id = ?", (node_id,)).fetchone()
        if row:
            results.append((row, round(score, 3)))

    return results


