    conflicts = check_contradictions(db, args.name, args.content, args.props)
    for c in conflicts:
        print(c)

    node_type = (args.type or "concept").lower()

    # Auto-supersede: for truth-maintained types, a fuzzy-similar node of the
    # same type is an outdated peer, not a coincidence — store the new node,
    # then link it as superseding the old one instead of silently coexisting.
    auto_supersede_target = None
    if node_type in _SUPERSEDE_ELIGIBLE_TYPES:
        for cand_row, _score in fuzzy_find_node(db, args.name, limit=5, threshold=0.85):
            if (cand_row["type"] or "").lower() == node_type and cand_row["name"].lower() != args.name.lower():
                auto_supersede_target = cand_row
                break

    props = args.props or "{}"
    if isinstance(props, str):
        try:
            json.loads(props)  # validate
        except json.JSONDecodeError:
            print(f"❌ Invalid JSON in --props: {props}")
            sys.exit(1)

    # Bi-temporal validity window (Phase 4d) — both optional, ISO dates.
    _vf = _as_date(getattr(args, 'valid_from', '') or '') or ''
    _vt = _as_date(getattr(args, 'valid_to', '') or '') or ''
    cur = db.execute(
        "INSERT INTO nodes (name, type, content, props, created_at, updated_at, valid_from, valid_to) VALUES (?, ?, ?, ?, ?, ?, ?, ?)",
        (args.name, node_type, args.content or "", props, ts, ts, _vf, _vt)
    )
    node_id = cur.lastrowid

    # Handle tags
    tag_ids = []
    if args.tags:
        for tag_name in args.tags.split(","):
            tag_id = ensure_tag(db, tag_name)
            tag_ids.append(tag_id)
            db.execute("INSERT OR IGNORE INTO node_tags (node_id, tag_id) VALUES (?, ?)", (node_id, tag_id))

    # Auto-associate co-occurring tags
    if len(tag_ids) > 1:
        auto_associate_tags(db, tag_ids)

    db.commit()

    if auto_supersede_target:
        new_node = db.execute("SELECT * FROM nodes WHERE id = ?", (node_id,)).fetchone()
        try:
            _create_supersede_link(db, new_node, auto_supersede_target)
            print(f"⏭️  Auto-superseded '{auto_supersede_target['name']}' (id={auto_supersede_target['id']}) — similar {node_type} detected")
        except ValueError as e:
            print(f"⚠️  Auto-supersede skipped: {e}")

    # Auto-index embedding (background-safe)
    try:
        from embeddings import SemanticEngine
        engine = SemanticEngine(DB_PATH)
        node = db.execute("SELECT * FROM nodes WHERE id = ?", (node_id,)).fetchone()
        engine.index_node(node_id, engine._node_text(node))
    except Exception:
        pass

    print(f"✅ Stored '{args.name}' (id={node_id}, type={args.type or 'concept'}, tags={args.tags or 'none'})")


