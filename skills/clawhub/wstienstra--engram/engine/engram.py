# ── PROCEDURAL MEMORY ("method") ────────────────────────
# Trauma-tier node type storing proven task methodologies so the FIRST
# attempt at a previously-solved kind of task is the working way, not the
# Nth. Content template: TASK PATTERN / WORKS / PITFALLS / VERIFY.
# props: task_signature, success_count, fail_count, consecutive_fails,
# last_used, derived_from, needs_revision.

_METHOD_STOP_WORDS = {"the","and","for","are","but","not","you","all","can","her","was","one","our",
              "out","has","have","had","been","from","this","that","with","they","will","each",
              "make","like","just","use","used","using","how","what","when","where","which",
              "who","why","some","any","also","about","into","more","other","than","then",
              "them","these","would","could","should","does","did","get","got","here","there",
              "very","after","before","being","both","still","over","want","need","check","look"}


def _tokenize_method_query(text):
    words = [w for w in re.findall(r'[a-z]{3,}', (text or '').lower()) if w not in _METHOD_STOP_WORDS]
    return words


def _method_candidates_fts(db, words, limit=10):
    """FTS channel restricted to type='method'. AND first, OR fallback."""
    if not words:
        return []
    fts_words = words[:4]
    and_query = ' '.join(f'"{w}"*' for w in fts_words)
    try:
        rows = db.execute("""
            SELECT n.* FROM nodes n JOIN nodes_fts f ON f.rowid = n.id
            WHERE nodes_fts MATCH ? AND n.type = 'method' ORDER BY rank LIMIT ?
        """, (and_query, limit)).fetchall()
    except sqlite3.OperationalError:
        rows = []
    if rows:
        return rows
    or_query = ' OR '.join(f'"{w}"*' for w in fts_words)
    try:
        rows = db.execute("""
            SELECT n.* FROM nodes n JOIN nodes_fts f ON f.rowid = n.id
            WHERE nodes_fts MATCH ? AND n.type = 'method' ORDER BY rank LIMIT ?
        """, (or_query, limit)).fetchall()
    except sqlite3.OperationalError:
        rows = []
    return rows


def _method_candidates_signature(db, words, limit=10):
    """task_signature overlap channel — cheap full scan, method table is small."""
    if not words:
        return []
    wset = set(words)
    rows = db.execute("SELECT * FROM nodes WHERE type = 'method'").fetchall()
    scored = []
    for r in rows:
        try:
            props = json.loads(r["props"] or "{}")
        except (json.JSONDecodeError, TypeError):
            props = {}
        sig = {w.lower() for w in (props.get("task_signature") or [])}
        overlap = len(wset & sig)
        if overlap:
            scored.append((overlap, r))
    scored.sort(key=lambda x: -x[0])
    return [r for _, r in scored[:limit]]


def _method_candidates_semantic(db, query, limit=8):
    """Semantic channel — only used by the standalone `method match` command,
    never by msgctx (too slow for the hot path)."""
    try:
        from embeddings import SemanticEngine
        engine = SemanticEngine(DB_PATH)
        results = engine.search(query, top_k=limit * 3, min_score=0.30)
    except Exception:
        return []
    rows = []
    for nid, _score in results:
        row = db.execute("SELECT * FROM nodes WHERE id = ? AND type = 'method'", (nid,)).fetchone()
        if row:
            rows.append(row)
        if len(rows) >= limit:
            break
    return rows


def find_matching_methods(db, query_text, limit=2, use_semantic=True):
    """Hybrid FTS + task_signature (+ optional semantic) match against method
    nodes, RRF-fused, gated by the shared lexical-grounding confidence floor
    so an unrelated message honestly returns nothing instead of a coincidence.
    """
    words = _tokenize_method_query(query_text)
    if not words:
        return []

    fts_rows = _method_candidates_fts(db, words, limit=10)
    sig_rows = _method_candidates_signature(db, words, limit=10)
    sem_rows = _method_candidates_semantic(db, query_text, limit=8) if use_semantic else []

    channels = {
        "fts": [r["id"] for r in fts_rows],
        "sig": [r["id"] for r in sig_rows],
    }
    if sem_rows:
        channels["sem"] = [r["id"] for r in sem_rows]

    fused = _rrf_fuse(channels)
    if not fused:
        return []

    all_rows = {}
    for r in list(fts_rows) + list(sig_rows) + list(sem_rows):
        all_rows[r["id"]] = r

    ranked_ids = sorted(fused.keys(), key=lambda nid: -fused[nid])

    grounded = []
    for nid in ranked_ids:
        row = all_rows.get(nid)
        if not row:
            continue
        if _lexical_grounding(db, query_text, [row]):
            grounded.append(row)
        if len(grounded) >= limit:
            break
    return grounded


def _method_sections(content):
    """Pull WORKS/PITFALLS bodies out of the TASK PATTERN/WORKS/PITFALLS/VERIFY template."""
    works_m = re.search(r'WORKS:\s*\n(.*?)(?:\nPITFALLS:|\nVERIFY:|\Z)', content or '', re.S)
    pitfalls_m = re.search(r'PITFALLS:\s*\n(.*?)(?:\nVERIFY:|\Z)', content or '', re.S)
    works = works_m.group(1).strip() if works_m else ""
    pitfalls = pitfalls_m.group(1).strip() if pitfalls_m else ""
    return works, pitfalls


def _method_compact_block(row, prefix="📋", max_chars=1000):
    """Compact name + WORKS + PITFALLS block, budget-capped (~250 tokens)."""
    props = json.loads(row["props"] or "{}") if row["props"] else {}
    works, pitfalls = _method_sections(row["content"] or "")
    lines = [f"{prefix} {row['name']} (id={row['id']})"]
    if works:
        lines.append("WORKS:")
        lines.append(works)
    if pitfalls:
        lines.append("PITFALLS:")
        lines.append(pitfalls)
    if props.get("needs_revision"):
        lines.append("⚠️  flagged needs_revision — 2+ consecutive failures, treat with caution")
    text = "\n".join(lines)
    if len(text) > max_chars:
        text = text[:max_chars - 3] + "..."
    return text


def cmd_method_save(args):
    db = get_db()
    name = (args.arg or "").strip()
    if not name:
        print("❌ Usage: engram method save \"<name>\" --pattern ... --works ... --pitfalls ... --verify ...")
        sys.exit(1)

    pattern = (args.pattern or "").strip()
    verify = (args.verify or "").strip()

    def _split_items(raw):
        raw = (raw or "").strip()
        if not raw:
            return []
        return [p.strip() for p in re.split(r'\n|;', raw) if p.strip()]

    works_items = _split_items(args.works)
    pitfalls_items = _split_items(args.pitfalls)

    lines = [f"TASK PATTERN: {pattern}", "WORKS:"]
    for i, step in enumerate(works_items, 1):
        lines.append(f"{i}. {step}")
    lines.append("PITFALLS:")
    for p in pitfalls_items:
        lines.append(f"- {p}")
    lines.append(f"VERIFY: {verify}")
    content = "\n".join(lines)

    generic = set(get_config(db, "generic_words"))
    sig_source = f"{name} {pattern}"
    signature = sorted({
        w.lower() for w in re.findall(r"[A-Za-z][A-Za-z0-9_-]{2,}", sig_source)
        if w.lower() not in generic and len(w) >= 3
    })

    derived_from = []
    for tok in (args.derived_from or "").split(","):
        tok = tok.strip()
        if tok.isdigit():
            derived_from.append(int(tok))

    props = {
        "task_signature": signature,
        "success_count": 0,
        "fail_count": 0,
        "consecutive_fails": 0,
        "last_used": None,
        "derived_from": derived_from,
        "needs_revision": False,
    }

    store_args = argparse.Namespace(
        name=name, type="method", content=content,
        props=json.dumps(props), tags=args.tags or ""
    )
    cmd_store(store_args)


