def _fetch_embedding_vectors(db_path, node_ids):
    """Fetch L2-normalized embedding vectors for near-duplicate suppression.
    Returns {} if embeddings/numpy are unavailable — dedup is skipped, not fatal."""
    if not node_ids:
        return {}
    try:
        import numpy as np
        import struct
        conn = sqlite3.connect(db_path)
        conn.row_factory = sqlite3.Row
        placeholders = ",".join("?" * len(node_ids))
        rows = conn.execute(
            f"SELECT node_id, embedding FROM embeddings WHERE node_id IN ({placeholders})",
            node_ids
        ).fetchall()
        conn.close()
        vecs = {}
        for r in rows:
            blob = r["embedding"]
            n = len(blob) // 4
            vecs[r["node_id"]] = np.array(struct.unpack(f"{n}f", blob), dtype=np.float32)
        return vecs
    except Exception:
        return {}


def _cosine_sim(a, b):
    import numpy as np
    na = float(np.linalg.norm(a))
    nb = float(np.linalg.norm(b))
    if na == 0 or nb == 0:
        return 0.0
    return float(np.dot(a, b) / (na * nb))


def score_node(node, db, query_lower="", total_nodes=1, tag_idf=None):
    """Score a node by relevance: TF-IDF tag weight + recency + query match.
    Used by cmd_fast_recall. cmd_recall's deep path uses RRF fusion instead."""
    import math
    score = 0.0

    # Tag specificity score (IDF: rare tags = higher score).
    # Pass a precomputed tag_idf dict (see _batch_tag_idf) to avoid the
    # per-candidate join below — that join used to cost ~27ms x N candidates.
    if tag_idf is not None:
        nid = node["id"] if not isinstance(node, dict) else node.get("id")
        score += tag_idf.get(nid, 0.0)
    else:
        tags = db.execute("""
            SELECT t.name, COUNT(nt2.node_id) as doc_freq
            FROM tags t
            JOIN node_tags nt ON t.id = nt.tag_id
            LEFT JOIN node_tags nt2 ON t.id = nt2.tag_id
            WHERE nt.node_id = ?
            GROUP BY t.id
        """, (node["id"],)).fetchall()

        for tag in tags:
            idf = math.log(total_nodes / max(tag["doc_freq"], 1))
            score += idf
    
    # Relevance decay: last_relevant drives recency, not just updated_at
    try:
        lr = node["last_relevant"] if node["last_relevant"] else node["updated_at"]
        relevant_dt = datetime.fromisoformat(lr)
        age_days = (datetime.now(timezone.utc) - relevant_dt).days
        if age_days < 3:
            score += 8 - (age_days * 2)      # Very fresh: +2 to +8
        elif age_days < 7:
            score += 3 - (age_days - 3) * 0.5  # Recent: +1 to +3
        elif age_days < 30:
            pass                               # Neutral: no boost, no penalty
        else:
            score -= min(age_days / 30, 5)     # Stale: up to -5 penalty
    except:
        pass
    
    # Type priority: knowledge-rich types rank higher than raw data
    type_priority = {
        'rule': 20, 'policy': 20, 'workflow': 18, 'knowledge': 15,
        'person': 12, 'organization': 10, 'project': 10,
        'credential': 12, 'decision': 10, 'concept': 8,
        'task': 5, 'lesson': 5,
        'reddit_thread': -5, 'extract': -10, 'session_summary': -15
    }
    node_type = node['type'] if 'type' in node.keys() else ''
    score += type_priority.get(node_type, 0)
    
    # Direct name/content match boost
    if query_lower:
        name_lower = node["name"].lower()
        # Full query in name
        if query_lower in name_lower:
            score += 50
        # Individual query words in name (strongest signal)
        for word in query_lower.split():
            if word in name_lower:
                if name_lower == word:
                    score += 50  # EXACT name match (e.g. "alice" = "Alice")
                elif name_lower.split()[0] == word and len(name_lower.split()) <= 3:
                    score += 30  # Short name starts with word (e.g. "Alice Johnson")
                elif name_lower.startswith(word):
                    score += 10  # Name starts with word but is long compound name
                else:
                    score += 5   # Name contains the word somewhere
        # Content match
        if query_lower in node["content"].lower():
            score += 3
        props = node["props"].lower()
        if query_lower in props:
            score += 2
        # Prop key/value match (pricing→pricing, email→email)
        prop_hits = 0
        for word in query_lower.split():
            if f'"{word}' in props or f'{word}":' in props:
                prop_hits += 1
                score += 8
        # If node has BOTH name match AND prop match, it's almost certainly the right node
        name_hit = any(w in name_lower for w in query_lower.split())
        if name_hit and prop_hits > 0:
            score += 15  # Double-match bonus: entity + attribute
    
    return score


_TERMINAL_PROJECT_STATUSES = {"shelved", "done", "shipped", "completed", "cancelled", "canceled"}


def _find_stop_hits(nodes):
    """Detect PROJECT nodes with terminal status among candidate nodes/rows.
    Checks props.status AND name-suffix patterns like "— shelved". Returns a
    deduped list of (final_status, name, props) tuples."""
    def _node_field(_n, _k):
        try:
            return _n[_k] if not isinstance(_n, dict) else _n.get(_k)
        except (KeyError, IndexError):
            return None
    _stop_hits = []
    _seen_stop = set()
    for _node in nodes:
        if _node_field(_node, "type") != "project":
            continue
        _raw = _node_field(_node, "props")
        try:
            _props = json.loads(_raw) if isinstance(_raw, str) and _raw else (_raw if isinstance(_raw, dict) else {})
        except Exception:
            _props = {}
        _status = (_props.get("status") or "").lower()
        _name = _node_field(_node, "name") or ""
        _name_l = _name.lower()
        _name_status = next((s for s in _TERMINAL_PROJECT_STATUSES if f"— {s}" in _name_l or f"- {s}" in _name_l or _name_l.endswith(s)), None)
        _final = _status if _status in _TERMINAL_PROJECT_STATUSES else _name_status
        _nid = _node_field(_node, "id")
        if _final and _nid not in _seen_stop:
            _seen_stop.add(_nid)
            _stop_hits.append((_final, _name, _props))
    return _stop_hits


def _print_stop_banner(stop_hits):
    """Print the STOP banner for closed/shelved PROJECT nodes (mirrors both recall paths)."""
    if not stop_hits:
        return
    print("🛑 " + "═" * 70)
    for _final, _name, _props in stop_hits:
        _verb = {"shelved": "SHELVED", "done": "DONE", "shipped": "SHIPPED",
                 "completed": "COMPLETED", "cancelled": "CANCELLED", "canceled": "CANCELLED"}[_final]
        print(f"🛑 PROJECT {_verb}: {_name}")
        _when = _props.get("shelved_at") or _props.get("completed_at") or _props.get("done_at")
        _reason = _props.get("reason")
        if _when:
            print(f"   when: {_when}")
        if _reason:
            print(f"   reason: {_reason}")
        print(f"   → Do NOT draft, evaluate, or rework. Only act if the owner explicitly reopens.")
    print("🛑 " + "═" * 70)


def cmd_fast_recall(args):
    """Fast recall: FTS + scoring only, no semantic search or tag expansion.
    ~50ms instead of ~3s. Use for real-time context lookups."""
    db = get_db()
    query = args.query
    budget = getattr(args, 'budget', 0) or 400
    query_lower = query.lower()
    
    # FTS search — quote each token so punctuation ("nicolas's", "<", ".")
    # can't be parsed as FTS5 syntax and crash the fast path (msgctx runs
    # this on every message).
    _fts_tokens = re.findall(r'\w+', query, re.UNICODE)
    _fts_query = ' '.join(f'"{t}"' for t in _fts_tokens)
    rows = []
    if _fts_query:
        try:
            rows = db.execute('''
                SELECT n.id, n.name, n.type, n.props, n.content, n.created_at, n.updated_at, n.last_touched
                FROM nodes n
                JOIN nodes_fts fts ON fts.rowid = n.id
                WHERE nodes_fts MATCH ?
                ORDER BY rank
                LIMIT 30
            ''', (_fts_query,)).fetchall()
        except sqlite3.OperationalError:
            rows = []

    # Episodic filter: exclude conversational/log node types unless requested
    if not _should_include_episodic(args, db):
        rows = [r for r in rows if (r["type"] or "").lower() not in EPISODIC_NODE_TYPES]

    # Truth maintenance: hide superseded nodes unless --history requested
    history_mode = getattr(args, 'history', False)
    def _row_props(r):
        try:
            return json.loads(r["props"]) if r["props"] else {}
        except Exception:
            return {}
    if not history_mode:
        rows = [r for r in rows if not _row_props(r).get("superseded_by")]

    # Fast scoring — batch tag-IDF once for all candidates instead of a
    # per-candidate join (was ~27ms x N candidates).
    _total_nodes = db.execute("SELECT COUNT(*) FROM nodes").fetchone()[0]
    _tag_idf = _batch_tag_idf(db, [r["id"] for r in rows], _total_nodes)
    scored = [(score_node(r, db, query_lower, _total_nodes, tag_idf=_tag_idf), r) for r in rows]
    if history_mode:
        # Progression of insight: oldest -> newest (when authored) instead of by relevance score
        scored.sort(key=lambda x: x[1]["created_at"] or x[1]["updated_at"] or "")
    else:
        scored.sort(key=lambda x: -x[0])
    
    # Output
    tokens_used = 0
    print(f"\U0001f9e0 RECALL (fast): {query}")
    print(f"   Found {len(rows)} node(s) | mode: fast | budget: {budget} tokens")

    # STOP banner for shelved/done projects (mirrors full recall path)
    _stop_hits = _find_stop_hits(_row for _s, _row in scored[:10])
    if _stop_hits:
        print()
        _print_stop_banner(_stop_hits)
    print(f"\n== FAST ==")
    
    for s, row in scored[:5]:
        content_preview = (row['content'] or '')[:200].replace('\n', ' ')
        status = ''
        try:
            p = json.loads(row['props'] or '{}')
            status = p.get('status', '')
        except:
            pass
        marker = f" [{status}]" if status else ""
        print(f"\n{row['name']} [{row['type'].upper()}]{marker}")
        print(f"  {content_preview[:120]}")
        tokens_used += len(content_preview) // 4
        if tokens_used >= budget:
            break
    
    db.close()


def cmd_recall(args):
    # Fast path: skip semantic search, tag expansion, co-recall
    if getattr(args, 'fast', False):
        cmd_fast_recall(args)
        return
    
    db = get_db()
    depth = args.depth or 1
    limit = args.limit or 20
    budget = getattr(args, 'budget', 0) or 0
    # Bi-temporal as-of date (Phase 4d): default = today, so recall prefers
    # currently-valid facts; `asof` sets it to a past date to recall facts as
    # they were valid then. Ranking penalty only — never exclusion.
    asof_date = _as_date(getattr(args, 'asof', '') or '') or _today_date()

    seen_ids = set()
    results = []
    total_nodes = db.execute("SELECT COUNT(*) FROM nodes").fetchone()[0]

    # ── L3 hygiene: archived nodes do not compete for candidate slots ──
    # Applied inside the SQL rather than as a post-filter, because a pool is
    # LIMIT-bounded: 60 FTS rows spent on a July file dump are 60 rows the real
    # answer never gets to occupy. `--all` restores the whole graph.
    include_archived = bool(getattr(args, 'all', False))
    _tier_sql = "" if include_archived else " AND n.tier != 'archive'"
    _tier_sql_bare = "" if include_archived else " AND tier != 'archive'"

    # ── Phase 1: Direct match via FTS or tag ──
    if args.tag:
        # Tag-based query
        tag_name = args.tag.strip().lower()
        direct = db.execute("""
            SELECT n.* FROM nodes n
            JOIN node_tags nt ON n.id = nt.node_id
            JOIN tags t ON t.id = nt.tag_id
            WHERE t.name = ?
            ORDER BY n.updated_at DESC
            LIMIT ?
        """, (tag_name, limit)).fetchall()
    else:
        # FTS query
        query = args.query
        # Try exact name match first
        direct = db.execute(
            "SELECT * FROM nodes WHERE name = ? COLLATE NOCASE", (query,)
        ).fetchall()
        
        # Entity-first name channel: nodes whose NAME contains a distinctive query word.
        #
        # This used to count matching words and then throw the whole thing away unless it
        # produced 10 candidates or fewer ("too many = generic query, let FTS handle it").
        # Measured on 74 real queries (the measurement log): that discard fires on almost every
        # natural-language question, because the generic-word list does not cover "you",
        # "have", "are", "has", "still", so a query like "do you still have the openrouter
        # api key" produced 655 candidates and the exact name match on *openrouter* was
        # dropped along with the noise. Three of the nine paraphrase misses — including two
        # where the answer had the query's rarest word in its NAME — never reached the
        # reranker's candidate pool because of this one branch.
        #
        # Now: score by IDF instead of by count (a name matching a rare word is evidence, a
        # name matching "have" is not), skip words too common to be entity names at all,
        # keep the best few, and MERGE them with FTS instead of replacing it.
        name_hits = []
        if not direct:
            words = query.split()
            generic_words = set(get_config(db, "generic_words"))
            entity_words = [w for w in words if w.lower() not in generic_words and len(w) >= 3]

            if entity_words:
                import math as _math
                candidate_scores = {}
                for word in entity_words:
                    # Genericness is judged on the whole corpus, not on a hand-kept word
                    # list: "still", "have" and "you" are not in `generic_words` but appear
                    # in 750-1300 nodes, so matching them says nothing. This also skips the
                    # expensive LIKE scan for hub words.
                    try:
                        corpus_df = db.execute(
                            "SELECT COUNT(*) FROM nodes_fts WHERE nodes_fts MATCH ?",
                            (f'"{word}"',)).fetchone()[0]
                    except sqlite3.OperationalError:
                        corpus_df = 0
                    if corpus_df > NAME_MATCH_MAX_CORPUS_DF:
                        continue
                    name_matches = db.execute(
                        "SELECT * FROM nodes WHERE name LIKE ? COLLATE NOCASE",
                        (f"%{word}%",)
                    ).fetchall()
                    # A word in more node names than this is a hub word, not an entity name.
                    if not name_matches or len(name_matches) > NAME_MATCH_MAX_DF:
                        continue
                    w_idf = _math.log(max(total_nodes, 1) / len(name_matches))
                    for nm in name_matches:
                        nid = nm["id"]
                        if nid not in candidate_scores:
                            candidate_scores[nid] = [nm, 0.0, 0.0]
                        candidate_scores[nid][1] = max(candidate_scores[nid][1], w_idf)
                        candidate_scores[nid][2] += w_idf
                if candidate_scores:
                    # Rank on the RAREST word matched, then on total evidence. Summing
                    # alone lets two mid-frequency words ("api" + "key", idf 6.0 + 6.1)
                    # outrank the one node whose name carries the query's actual subject
                    # ("openrouter", idf 9.9) — measured, that is exactly how p03 failed.
                    ranked = sorted(candidate_scores.values(), key=lambda x: (-x[1], -x[2]))
                    # A name hit still has to clear an evidence bar. One mid-frequency word
                    # is not enough: "Workstation Sudo Password" matches *password* (idf
                    # 8.1) for a kubernetes question, looks like a name hit, and was enough
                    # to talk the abstention gate into answering (the measurement log).
                    _min_evidence = _idf_bar(NAME_MATCH_MIN_EVIDENCE, total_nodes)
                    name_hits = [row[0] for row in ranked[:NAME_MATCH_KEEP]
                                 if row[2] >= _min_evidence]

        if not direct:
            words = query.split()
            
            # ── Search-level expansion (clusters + manual synonyms) ──
            _search_synonyms = expand_query_with_clusters(db, query)
            
            # Build expanded word groups: each original word + its synonyms
            expanded_groups = []
            for w in words:
                group = [w]
                syns = _search_synonyms.get(w.lower(), [])
                group.extend(syns)
                expanded_groups.append(group)
            
            # AND query: each group is OR'd internally, groups AND'd together
            # e.g. "shampoo cost" → ("shampoo") AND ("cost" OR "pricing" OR "price")
            fts_and_parts = []
            for group in expanded_groups:
                if len(group) == 1:
                    fts_and_parts.append(f'"{group[0]}"*')
                else:
                    inner = " OR ".join(f'"{g}"*' for g in group)
                    fts_and_parts.append(f'({inner})')
            fts_and = " AND ".join(fts_and_parts)
            
            # Simple OR fallback (all words + all synonyms)
            all_terms = []
            for group in expanded_groups:
                all_terms.extend(group)
            fts_or = " OR ".join(f'"{t}"*' for t in all_terms)
            
            # Widen the ranking pool beyond the display limit — a node that's
            # relevant but not top-20 by raw BM25 (e.g. a small entity node
            # competing with many bigger documents) still deserves a shot at
            # RRF fusion instead of being truncated away before it's even a
            # candidate. Display-time truncation is handled later by budget.
            fts_pool_limit = max(limit, 60)
            for fts_query in [fts_and, fts_or]:
                try:
                    direct = db.execute(f"""
                        SELECT n.* FROM nodes n
                        JOIN nodes_fts f ON n.id = f.rowid
                        WHERE nodes_fts MATCH ?{_tier_sql}
                        ORDER BY rank
                        LIMIT ?
                    """, (fts_query, fts_pool_limit)).fetchall()
                except sqlite3.OperationalError:
                    direct = []
                if direct:
                    break

            # Merge the name channel ahead of FTS rank order: an exact rare-word hit in a
            # node's NAME outranks a body-text BM25 hit, but FTS is kept, not replaced.
            if name_hits:
                _seen_nm = set()
                _merged = []
                for n in list(name_hits) + list(direct):
                    if n["id"] not in _seen_nm:
                        _seen_nm.add(n["id"])
                        _merged.append(n)
                direct = _merged

        # Always search props too (credentials, tokens etc. live in properties)
        props_words = query.split() if query else []
        for word in props_words:
            if len(word) >= 3:
                props_results = db.execute(f"""
                    SELECT * FROM nodes WHERE props LIKE ? COLLATE NOCASE{_tier_sql_bare}
                    ORDER BY updated_at DESC LIMIT ?
                """, (f"%{word}%", min(5, limit))).fetchall()
                for node in props_results:
                    if node["id"] not in seen_ids:
                        direct = list(direct) if not isinstance(direct, list) else direct
                        direct.append(node)

    # Hub-entity pin (see _pin_hub_entities): runs independently of the
    # LIMIT-bounded FTS search above so a tiny person/contact/org node isn't
    # drowned out — or truncated away entirely — before RRF ever sees it.
    _hub_pin_fired = False
    _hub_pins = []
    if not args.tag and args.query:
        _generic_words = set(get_config(db, "generic_words"))
        _named_pins, _tag_pins = _pin_hub_entities_split(db, args.query, _generic_words)
        _hub_pins = _named_pins + _tag_pins
        # Only a NAME or alias pin counts as grounding for the abstention gate. A rare tag
        # is good enough to put a node in the pool, and not good enough to prove the engram
        # knows the answer: measured, letting tag pins set this flag dropped the negative
        # class from 85% to 46% — "wedding planning for cousin marta" finds *a* rarely
        # tagged node and stops abstaining. Pool membership and confidence are different
        # claims, and this is the line between them.
        if _named_pins:
            _hub_pin_fired = True
        if _hub_pins:
            # Measured (run 06): demoting tag pins to the back of the pool costs more than
            # it saves — negatives 77% -> 69%, name_lookup 93% -> 87%. What a tag pin needs
            # is a higher bar to fire at all (TAG_PIN_MIN_QUERY_COVER), not a worse seat.
            direct = list(direct)
            for _row in reversed(_hub_pins):
                direct = [_row] + [n for n in direct if n["id"] != _row["id"]]

    # RRF channel 1 (FTS/exact match): rank order = discovery order above
    # (hub-entity pins first, then exact name match, entity-word matches,
    # then FTS rank).
    channel_fts = [n["id"] for n in direct]

    for node in direct:
        if node["id"] not in seen_ids:
            seen_ids.add(node["id"])
            results.append(("direct", node))

    # ── Phase 1b: Semantic search (embedding-based) ──
    # RRF channel 2 (semantic): co-equal with FTS, not a bonus signal.
    channel_semantic = []
    if args.query and not args.tag:
        try:
            from embeddings import SemanticEngine
            sem_engine = SemanticEngine(DB_PATH)
            sem_results = sem_engine.search(args.query, top_k=15, min_score=0.30)
            channel_semantic = [nid for nid, _ in sem_results]
            for node_id, sem_score in sem_results:
                if node_id not in seen_ids:
                    node = db.execute("SELECT * FROM nodes WHERE id = ?", (node_id,)).fetchone()
                    if node:
                        seen_ids.add(node_id)
                        node_dict = dict(node)
                        node_dict['_sem_score'] = sem_score
                        results.append(("semantic", node_dict))
        except Exception:
            pass  # embeddings not available — skip silently
    
    # ── Phase 2: Tag expansion with relevance scoring ──
    channel_tag = []
    if results and depth >= 1:
        # Get all tags from matched nodes
        matched_ids = [n["id"] for _, n in results]
        placeholders = ",".join("?" * len(matched_ids))
        
        # Get tags from matched nodes, excluding ultra-common ones for scoring
        matched_tags = db.execute(f"""
            SELECT t.id, t.name, COUNT(nt2.node_id) as global_count
            FROM tags t
            JOIN node_tags nt ON t.id = nt.tag_id
            LEFT JOIN node_tags nt2 ON t.id = nt2.tag_id
            WHERE nt.node_id IN ({placeholders})
            GROUP BY t.id
        """, matched_ids).fetchall()
        
        tag_ids = [r["id"] for r in matched_tags]
        # Tags used by >50% of nodes are too common for relevance (e.g., 'company', 'outreach')
        total_nodes = db.execute("SELECT COUNT(*) FROM nodes").fetchone()[0]
        specific_tag_ids = [r["id"] for r in matched_tags if r["global_count"] < total_nodes * 0.3]
        broad_tag_ids = [r["id"] for r in matched_tags if r["global_count"] >= total_nodes * 0.3]
        
        if tag_ids and depth >= 2:
            tag_placeholders = ",".join("?" * len(tag_ids))
            assoc_tags = db.execute(f"""
                SELECT DISTINCT tag2_id as id FROM tag_associations
                WHERE tag1_id IN ({tag_placeholders})
                UNION
                SELECT DISTINCT tag1_id as id FROM tag_associations
                WHERE tag2_id IN ({tag_placeholders})
            """, tag_ids + tag_ids).fetchall()
            tag_ids.extend([r["id"] for r in assoc_tags])
            tag_ids = list(set(tag_ids))
        
        # Find nodes sharing tags — score by number of SPECIFIC tag overlaps
        # RRF channel 3 (tag-IDF expansion): rank order = overlap_score DESC.
        if tag_ids:
            scoring_tags = specific_tag_ids if specific_tag_ids else tag_ids
            scoring_placeholders = ",".join("?" * len(scoring_tags))
            related = db.execute(f"""
                SELECT n.*, COUNT(DISTINCT nt.tag_id) as overlap_score
                FROM nodes n
                JOIN node_tags nt ON n.id = nt.node_id
                WHERE nt.tag_id IN ({scoring_placeholders})
                GROUP BY n.id
                HAVING overlap_score >= 2
                ORDER BY overlap_score DESC, n.updated_at DESC
                LIMIT ?
            """, scoring_tags + [limit]).fetchall()
            channel_tag = [r["id"] for r in related]

            for node in related:
                if node["id"] not in seen_ids:
                    seen_ids.add(node["id"])
                    results.append(("tag_related", node))
    
    # ── Auto-rebuild clusters if stale (>24h since last build) ──
    ensure_cluster_table(db)
    try:
        last_cluster = db.execute("SELECT MAX(rowid) FROM word_clusters").fetchone()[0]
        if last_cluster is None:
            build_clusters(db)
    except:
        pass
    
    # ── Phase 3: Weight-aware association traversal (no hard cutoff) ──
    ensure_weights(db)
    mode_override = getattr(args, 'mode', '') or ''
    query_type = mode_override if mode_override in ('fact', 'solve', 'report') else classify_query(args.query or "", db)

    # RRF channel 4 (association/graph traversal, incl. hop paths): rank
    # order = direct associations (by weight) then multi-hop (by distance,
    # then weight) — mirrors hop_recall's own ORDER BY.
    channel_graph = []
    if results and ASSOC_CHANNEL_ENABLED:
        # Expanding from ALL candidates found so far, ordered by association weight, is
        # the shipped behaviour and two attempts to "focus" it both measured worse
        # (the measurement log): seeding from only the top 5 hits cost 8 points of paraphrase
        # recall, and ordering by Hebbian `strength` instead of `weight` cost 16 points of
        # the negative class. The breadth is the point — this channel earns its +6 by
        # feeding RRF a wider candidate set, not by being precise.
        direct_ids = [n["id"] for _, n in results]
        placeholders = ",".join("?" * len(direct_ids))

        # `l3-auto` edges are excluded here on purpose. They are INFERRED — an orphan
        # wired to its nearest embedding neighbour — not observed, and the battery says so:
        # with them in this channel the negative class falls 85% -> 77% (runs 13/14) while
        # nothing else improves. They end orphanhood and make the node reachable by graph
        # browsing; until they earn a measurement, they do not vote on what recall answers.
        # Direct associations (depth 1 — always from live table)
        assoc_nodes = db.execute(f"""
            SELECT DISTINCT n.*, a.relation, COALESCE(a.weight, 3) as assoc_weight,
                   COALESCE(a.strength, 1.0) as assoc_strength
            FROM associations a
            JOIN nodes n ON (n.id = a.target_id OR n.id = a.source_id)
            WHERE (a.source_id IN ({placeholders}) OR a.target_id IN ({placeholders}))
            AND n.id NOT IN ({placeholders})
            AND a.relation != 'l3-auto'
            ORDER BY COALESCE(a.weight, 3) ASC
            LIMIT ?
        """, direct_ids + direct_ids + direct_ids + [limit]).fetchall()
        channel_graph.extend(n["id"] for n in assoc_nodes)

        for node in assoc_nodes:
            if node["id"] not in seen_ids:
                seen_ids.add(node["id"])
                node_dict = dict(node)
                node_dict['_assoc_weight'] = node['assoc_weight']
                node_dict['_assoc_strength'] = node['assoc_strength'] if 'assoc_strength' in node.keys() else 1.0
                results.append(("associated", node_dict))

        # Multi-hop via pre-computed paths (depth >= 2)
        if depth >= 2:
            hop_nodes = hop_recall(db, direct_ids, max_depth=depth, limit=limit)
            channel_graph.extend(row["id"] for row in hop_nodes if row["id"] not in channel_graph)
            for row in hop_nodes:
                nid = row["id"]
                if nid not in seen_ids:
                    seen_ids.add(nid)
                    node_dict = dict(row)
                    node_dict['_assoc_weight'] = row['max_weight']
                    node_dict['_assoc_strength'] = 1.0
                    node_dict['_hop_distance'] = row['distance']
                    results.append(("hop", node_dict))

    # ── Reflective retrieval: auto-reformulate on poor results ──
    channel_reformulated = []
    direct_count = sum(1 for t, _ in results if t == "direct")
    if direct_count == 0 and args.query and not args.tag:
        reformulated = reflective_reformulate(db, args.query, results, seen_ids)
        if reformulated:
            channel_reformulated = [n["id"] for _, n in reformulated]
            results.extend(reformulated)
    
    # ── Post-filters ──
    exclude_statuses = set(s.strip() for s in (getattr(args, 'exclude', '') or '').split(',') if s.strip())
    filter_type = (getattr(args, 'type', '') or '').strip().lower()
    filter_status = (getattr(args, 'status', '') or '').strip().lower()
    due_filter = (getattr(args, 'due', '') or '').strip().lower()
    since_filter = (getattr(args, 'since', '') or '').strip()
    include_episodic = _should_include_episodic(args, db)
    history_mode = getattr(args, 'history', False)

    filtered = []
    for match_type, node in results:
        props = json.loads(node["props"])
        node_status = props.get("status", "").lower()

        # Episodic filter: exclude conversational/log node types unless requested
        if not include_episodic and (node["type"] or "").lower() in EPISODIC_NODE_TYPES:
            continue

        # Tier filter: the SQL above keeps archived nodes out of the FTS/props pools,
        # but the semantic, hop and tag channels reach nodes by id, so the gate is
        # repeated here — this is the one place every channel funnels through.
        if not include_archived and (node.get("tier") if isinstance(node, dict)
                                     else node["tier"]) == 'archive':
            continue

        # Truth maintenance: hide superseded nodes unless --history requested
        if not history_mode and props.get("superseded_by"):
            continue

        # Exclude filter
        if exclude_statuses and node_status in exclude_statuses:
            continue

        # Type filter
        if filter_type and node["type"].lower() != filter_type:
            continue
        
        # Status filter
        if filter_status and node_status != filter_status:
            continue
        
        # Since filter (days)
        if since_filter:
            try:
                max_age = int(since_filter.rstrip('d'))
                from datetime import timedelta
                cutoff = (datetime.now(timezone.utc) - timedelta(days=max_age)).isoformat()
                if node["updated_at"] < cutoff:
                    continue
            except ValueError:
                pass
        
        # Due filter (temporal)
        if due_filter:
            date_fields = [props.get(k, "") for k in ("date", "deadline", "follow_up", "call_date", "send_after")]
            dates = [d for d in date_fields if d]
            if not dates:
                continue
            
            from datetime import timedelta
            today = datetime.now(timezone.utc).strftime("%Y-%m-%d")
            tomorrow = (datetime.now(timezone.utc) + timedelta(days=1)).strftime("%Y-%m-%d")
            week_end = (datetime.now(timezone.utc) + timedelta(days=7)).strftime("%Y-%m-%d")
            
            match = False
            for d in dates:
                d_date = d[:10]
                if due_filter == "today" and d_date == today:
                    match = True
                elif due_filter == "tomorrow" and d_date == tomorrow:
                    match = True
                elif due_filter == "week" and today <= d_date <= week_end:
                    match = True
                elif due_filter == "overdue" and d_date < today:
                    match = True
            if not match:
                continue
        
        # Episodic filter (--when): filter by time of last touch or update
        when_filter = (getattr(args, 'when', '') or '').strip()
        if when_filter:
            from datetime import timedelta
            today = datetime.now(timezone.utc).strftime("%Y-%m-%d")
            yesterday = (datetime.now(timezone.utc) - timedelta(days=1)).strftime("%Y-%m-%d")
            week_start = (datetime.now(timezone.utc) - timedelta(days=datetime.now(timezone.utc).weekday())).strftime("%Y-%m-%d")
            last_week_start = (datetime.now(timezone.utc) - timedelta(days=datetime.now(timezone.utc).weekday() + 7)).strftime("%Y-%m-%d")
            
            # Use last_touched if available, fall back to updated_at
            try:
                lt = node["last_touched"] if "last_touched" in node.keys() else ""
            except:
                lt = ""
            node_date = (lt or node["updated_at"] or "")[:10]
            
            if when_filter == "today" and node_date != today:
                continue
            elif when_filter == "yesterday" and node_date != yesterday:
                continue
            elif when_filter == "this-week" and node_date < week_start:
                continue
            elif when_filter == "last-week" and (node_date < last_week_start or node_date >= week_start):
                continue
            elif when_filter not in ("today", "yesterday", "this-week", "last-week"):
                # Treat as YYYY-MM-DD
                if node_date != when_filter[:10]:
                    continue
        
        filtered.append((match_type, node))
    
    results = filtered
    
    # ── RRF fusion: merge the 4 independent channels ──
    # score(node) = sum over channels of 1/(60 + rank). Post-fusion, only
    # tiny adjustments are applied: type priors, recency tiebreak, and the
    # usefulness feedback boost/decay (Package D) — the old hand-tuned
    # additive constants (+20 direct, +5 associated, weight_penalty, etc.)
    # are gone; channel rank + channel agreement carries the signal now.
    import math
    query_lower = (args.query or "").lower()
    try:
        ensure_dynamics_columns(db)
    except:
        pass

    _rrf_weights = get_config(db, "rrf_weights")
    try:
        _rrf_k = int(get_config(db, "rrf_k") or 60)
    except (TypeError, ValueError):
        _rrf_k = 60
    fused_scores = _rrf_fuse({
        "fts": channel_fts,
        "semantic": channel_semantic,
        "tag": channel_tag,
        "graph": channel_graph,
        "reformulated": channel_reformulated,
    }, k=_rrf_k, weights=_rrf_weights)

    surviving_ids = []
    for _, node in results:
        nid = node["id"] if not isinstance(node, dict) else node.get("id")
        if nid is not None:
            surviving_ids.append(nid)
    useful_stats = _batch_useful_stats(db, surviving_ids)

    scored = []
    for match_type, node in results:
        nid = node["id"] if not isinstance(node, dict) else node.get("id")
        s = fused_scores.get(nid, 0.0)

        node_type = node["type"] if not isinstance(node, dict) else node.get("type")
        s += _type_prior(node_type)
        s += _recency_tiebreak(node)
        s += _temporal_penalty(node, asof_date)  # Phase 4d: demote out-of-window facts

        uc, ec = useful_stats.get(nid, (0, 0))
        if uc:
            s += min(USEFUL_BOOST_CAP, math.log1p(uc) * USEFUL_BOOST_UNIT)
        elif ec >= 5:
            s -= USEFUL_DECAY  # emitted often, never confirmed useful

        if match_type == "direct":
            # Passive touch tracking (no scoring effect) — also feeds the
            # usefulness loop if this node was emitted by an earlier recall.
            if nid:
                try:
                    touch_node(db, nid)
                except:
                    pass
        scored.append((match_type, node, s))

    scored.sort(key=lambda x: -x[2])

    # ── Phase 4d: optional graph-walk expansion (deep recall only) ──
    # Expand ONE hop from the top hits through their associations (weight-
    # decayed) and merge the neighbours into the candidate pool BEFORE the
    # reranker sees it: a genuinely-related node that only rode in on a weak
    # graph-channel RRF rank (or was truncated away) gets lifted by its
    # strong parent so the cross-encoder actually gets to judge it. Opt-in
    # via --walk; never runs on fast/msgctx (those never reach this function).
    if getattr(args, 'walk', False) and scored and args.query:
        scored = _graph_walk_expand(db, scored, seen_ids, asof_date)
        scored.sort(key=lambda x: -x[2])

    # ── Fetch embedding vectors up front — used for anti-hub MMR shaping now
    # and near-duplicate folding at display time later (one query, reused).
    _all_candidate_ids = []
    for _, _node, _ in scored:
        _nid = _node["id"] if not isinstance(_node, dict) else _node.get("id")
        if _nid is not None:
            _all_candidate_ids.append(_nid)
    node_vecs = _fetch_embedding_vectors(DB_PATH, _all_candidate_ids)

    # ── Stage 2: anti-hub candidate shaping + CPU cross-encoder rerank ──
    # Only for real deep-recall queries (not tag browsing). Never applied to
    # quick/fast/msgctx paths — those call cmd_fast_recall or their own
    # lighter logic, not this function. Degrades to pure RRF order (and the
    # old lexical-grounding abstention check) if flashrank is unavailable or
    # errors, so this can never crash or block recall.
    _rerank_scores = None
    _gate_top_nodes = []
    if args.query and not args.tag:
        import time as _rr_time
        # Pool protection follows the pins themselves, not the grounding flag: a tag pin
        # still deserves its slot against the per-type cap, it just does not vouch for
        # the answer.
        _pinned_ids = {r["id"] for r in _hub_pins} if _hub_pins else set()
        _pool_source = scored[:60]
        if not _episodic_pool_eligible(args, args.query, db):
            _pool_source = [(t, n, s) for t, n, s in _pool_source
                            if ((n["type"] if not isinstance(n, dict) else n.get("type")) or "").lower()
                            not in EPISODIC_NODE_TYPES]
        _pool = _shape_candidate_pool(_pool_source, node_vecs, pinned_ids=_pinned_ids)
        _rr_t0 = _rr_time.time()
        _rerank_scores = _rerank_pool(args.query, _pool)
        _rerank_elapsed_ms = (_rr_time.time() - _rr_t0) * 1000
        if _rerank_scores:
            def _sc_nid(_n):
                return _n["id"] if not isinstance(_n, dict) else _n.get("id")
            # Re-apply the temporal penalty on top of the cross-encoder score
            # so an out-of-window fact stays demoted even when the reranker
            # judged it textually relevant (penalty is 0 for in-window facts,
            # so in-window ordering from the reranker is preserved exactly).
            _reranked_part = [(t, n, _rerank_scores[_sc_nid(n)] + _temporal_penalty(n, asof_date))
                               for t, n, s in scored if _sc_nid(n) in _rerank_scores]
            _rest_part = [(t, n, s) for t, n, s in scored if _sc_nid(n) not in _rerank_scores]
            _reranked_part.sort(key=lambda x: -x[2])
            scored = _reranked_part + _rest_part
            # Candidates the abstention gate is allowed to read lexical evidence from:
            # the reranker's own top few, in pure reranker order (see _lexical_evidence).
            _gate_top_nodes = [n for _t, n, _s in sorted(
                ((t, n, _rerank_scores[_sc_nid(n)]) for t, n, s in scored
                 if _sc_nid(n) in _rerank_scores), key=lambda x: -x[2])][:GATE_EVIDENCE_TOP_N]

    # ── Hebbian: record co-activation of top results ──
    top_ids = []
    for match_type, node, score in scored[:10]:
        nid = node["id"] if not isinstance(node, dict) else node.get("id")
        if nid:
            top_ids.append(nid)
    if len(top_ids) >= 2:
        try:
            record_co_activation(db, top_ids[:5])  # Top 5 co-activate
        except:
            pass
    
    # ── Output with optional token budget ──
    if not scored:
        print(f"🔍 No results for '{args.query or args.tag}'")
        return
    
    compact = getattr(args, 'compact', False)
    
    header = f"🧠 RECALL: {args.query or f'tag:{args.tag}'}\n   Found {len(scored)} node(s) (depth={depth})"
    penalties = get_config(db, "weight_penalties")
    penalty_mult = penalties.get(query_type, 8)
    header += f" | mode: {query_type}(penalty: ×{penalty_mult})"
    if budget:
        header += f" | budget: {budget} tokens"
    print(header + "\n")

    # ── STOP banner: surface closed/shelved projects loudly ──
    # If any direct or semantic hit is a PROJECT node with terminal status
    # (shelved / done / shipped / completed / cancelled), print a banner
    # BEFORE the result body so it can't be missed.
    _stop_hits = _find_stop_hits(_node for _mt, _node, _ in scored if _mt in ("direct", "semantic"))
    if _stop_hits:
        _print_stop_banner(_stop_hits)
        print()

    # Group by match type (preserving score order within groups)
    direct_results = [(t, n, s) for t, n, s in scored if t == "direct"]
    semantic_results = [(t, n, s) for t, n, s in scored if t == "semantic"]
    reformulated_results = [(t, n, s) for t, n, s in scored if t.startswith("reformulated")]
    tag_results = [(t, n, s) for t, n, s in scored if t == "tag_related"]
    assoc_results = [(t, n, s) for t, n, s in scored if t == "associated"]
    hop_results = [(t, n, s) for t, n, s in scored if t == "hop"]

    # ── Calibrated abstention (any budget, incl. --history) ──
    # A query the engram has nothing on (a negative, an out-of-domain ask)
    # can still produce a "confident-looking" DIRECT section: RRF still
    # ranks *something* from generic-word FTS overlap, and this embedding
    # model returns 0.8+ cosine for nearly everything so a high semantic
    # score alone isn't proof of relevance. Primary signal: the reranker's
    # own calibrated top-score + top1-top2 margin (see _rerank_confidence)
    # when the cross-encoder ran; falls back to the older lexical-grounding
    # heuristic only when the reranker is unavailable (flashrank not
    # installed, or it errored) — never both at once, so the reranker is
    # actually authoritative when present, not just an extra OR clause.
    if not history_mode:
        _floor_candidates = [n for _, n, _ in direct_results[:10]] + [n for _, n, _ in semantic_results[:10]]
        if _rerank_scores:
            # Use the WHOLE reranked pool, not just direct+semantic — the
            # cross-encoder already judged genuine relevance across every
            # channel in the shaped pool (tag/graph included), and a
            # confident hit that only a non-direct/semantic channel
            # surfaced (e.g. it rides in via near-dup folding under an
            # unrelated direct hit at display time) is still real evidence
            # the engram has something on this query.
            _confident, _rr_top1, _rr_margin = _rerank_confidence(_rerank_scores, list(_rerank_scores.keys()))
            # Second, independent grounding signal — the reranker's absolute score is not
            # a usable relevance test on real queries (see _lexical_evidence).
            _grounded = (_confident or _hub_pin_fired
                         or _lexical_evidence(db, args.query or "", _gate_top_nodes))
        else:
            _grounded = _lexical_grounding(db, args.query or "", _floor_candidates, trusted=_hub_pin_fired)
        _strong_semantic = any(
            (n.get('_sem_score', 0) if isinstance(n, dict) else 0) >= 0.90
            for _, n, _ in semantic_results[:5]
        )
        if not _grounded and not _strong_semantic:
            weak = direct_results[:1] + semantic_results[:1]
            print(f"🔍 no confident match for '{args.query or args.tag}' — no candidate has genuine "
                  f"lexical or strong semantic grounding; not confabulating a listing.")
            if weak:
                print("\n== LOW-CONFIDENCE (unverified, likely irrelevant) ==")
                for _, node, _ in weak:
                    print(format_node(node, db, indent=1, compact=True,
                                       lean=getattr(args, 'lean', False), query_context=query_lower,
                                       full=getattr(args, 'full', False)))
            db.close()
            return

    # ── Confidence floor: tiny budgets get only high-confidence hits ──
    # Below 500 tokens there's no room to pad with weak matches — drop the
    # RELATED/weak-match sections entirely (tag, reformulated, associated,
    # hop) and keep only DIRECT + SEMANTIC (RRF's two co-equal, high-recall
    # channels — see Package A). If even those are empty, say so instead of
    # padding the answer with weak hits.
    low_budget_mode = bool(budget) and budget < 500
    if low_budget_mode:
        tag_results = []
        reformulated_results = []
        assoc_results = []
        hop_results = []
        if not direct_results and not semantic_results:
            print(f"🔍 no confident match for '{args.query or args.tag}' (budget too small for weak matches)")
            db.close()
            return

    # --history: order direct hits oldest -> newest (by when each version was
    # authored) so a supersede chain reads as a progression of insight.
    if history_mode and direct_results:
        def _chain_ts(node):
            return node["created_at"] or node["updated_at"] or ""
        direct_results = sorted(direct_results, key=lambda tns: _chain_ts(tns[1]))

    # Supersede breadcrumbs for direct-section hits only (one batched query).
    _supersede_breadcrumbs = {}
    if direct_results:
        _direct_ids = [n["id"] if not isinstance(n, dict) else n.get("id") for _, n, _ in direct_results]
        _direct_ids = [i for i in _direct_ids if i]
        if _direct_ids:
            _ph = ",".join("?" * len(_direct_ids))
            for r in db.execute(f"""
                SELECT a.source_id, n2.name AS old_name, n2.props AS old_props
                FROM associations a JOIN nodes n2 ON n2.id = a.target_id
                WHERE a.relation = 'supersedes' AND a.source_id IN ({_ph})
            """, _direct_ids).fetchall():
                try:
                    old_props = json.loads(r["old_props"]) if r["old_props"] else {}
                except Exception:
                    old_props = {}
                when = (old_props.get("superseded_at") or "")[:10]
                _supersede_breadcrumbs.setdefault(r["source_id"], []).append((r["old_name"], when))

    tokens_used = 0

    lean = getattr(args, 'lean', False)
    full = getattr(args, 'full', False)

    # ── Near-duplicate suppression (token economy) ──
    # node_vecs was already fetched for every candidate up front (see the
    # anti-hub shaping stage above) — reused here so near-identical nodes
    # fold into "≈ also: <id>" instead of repeating their full body.
    # Gracefully degrades to no-op if embeddings/numpy aren't available.
    emitted_vecs = []       # [(node_id, vector)] for nodes already given a body
    from collections import defaultdict as _defaultdict
    fold_counts = _defaultdict(int)  # node_id -> how many "≈ also:" lines it already carries
    out_lines = []          # buffered print() lines — lets us append "≈ also:"
    id_to_line_idx = {}     # node_id -> index into out_lines (its body line)
    emitted_ids = []        # node ids that actually got a body (Package D)

    def emit(text):
        out_lines.append(text)

    _history_mode = getattr(args, 'history', False)

    def output_node(node, compact_mode, indent=0, force=False):
        nonlocal tokens_used
        nid = node["id"] if not isinstance(node, dict) else node.get("id")

        # --history exists to show the full supersede chain as a progression;
        # folding near-identical chain members would hide exactly that.
        if nid in node_vecs and not _history_mode:
            vec = node_vecs[nid]
            for other_id, other_vec in emitted_vecs:
                if _cosine_sim(vec, other_vec) > 0.9:
                    idx = id_to_line_idx.get(other_id)
                    if idx is not None and fold_counts[other_id] >= FOLD_MAX_PER_NODE:
                        # Already shown enough near-identical siblings for this hit. The
                        # node is still suppressed (that is the token saving); it just does
                        # not get another "≈ also:" line of its own.
                        return True
                    if idx is not None:
                        fold_counts[other_id] += 1
                        # Show the folded node's own name, not just its bare id —
                        # a numeric id tells a reader (and the battery's regex
                        # matcher) nothing about what was actually found.
                        fold_name = node["name"] if not isinstance(node, dict) else node.get("name")
                        fold_name = (fold_name or "")[:70]
                        out_lines[idx] = out_lines[idx].rstrip() + f"\n  ≈ also: {fold_name} (id={nid})"
                    return True  # folded into the near-duplicate, not a failure

        text = format_node(node, db, indent=indent, compact=compact_mode, lean=lean, query_context=query_lower, full=full)
        node_tokens = len(text) // 4
        if budget and tokens_used + node_tokens > budget:
            if force and tokens_used == 0:
                # First direct hit: always show but budget is advisory
                pass
            else:
                return False
        out_lines.append(text)
        id_to_line_idx[nid] = len(out_lines) - 1
        if nid is not None:
            emitted_ids.append(nid)
            if nid in node_vecs:
                emitted_vecs.append((nid, node_vecs[nid]))
        tokens_used += node_tokens
        return True

    if direct_results:
        emit("== DIRECT ==")
        for _, node, s in direct_results:
            # Direct hits always shown (force=True), respect compact flag
            if not output_node(node, compact, force=True):
                break
            nid = node["id"] if not isinstance(node, dict) else node.get("id")
            for _old_name, _when in _supersede_breadcrumbs.get(nid, []):
                emit(f"  ↳ supersedes: {_old_name} ({_when})" if _when else f"  ↳ supersedes: {_old_name}")

    if semantic_results and (not budget or tokens_used < budget):
        emit(f"\n== SEMANTIC ({len(semantic_results)}) ==")
        for _, node, s in semantic_results:
            if not output_node(node, True, indent=1):
                break

    if tag_results and (not budget or tokens_used < budget):
        emit(f"\n== RELATED ({len(tag_results)}) ==")
        for _, node, s in tag_results:
            if not output_node(node, True, indent=1):
                remaining = sum(1 for _, n, _ in tag_results if n["id"] not in seen_ids)
                emit(f"  ...+{remaining} more")
                break

    if reformulated_results and (not budget or tokens_used < budget):
        emit(f"\n== REFORMULATED ({len(reformulated_results)}) ==")
        for _, node, s in reformulated_results:
            if not output_node(node, True, indent=1):
                break

    if assoc_results and (not budget or tokens_used < budget):
        emit(f"\n== ASSOCIATED ({len(assoc_results)}) ==")
        for _, node, s in assoc_results:
            if not output_node(node, True, indent=1):
                break

    if hop_results and (not budget or tokens_used < budget):
        emit(f"\n== HOP ({len(hop_results)}) ==")
        for _, node, s in hop_results:
            if not output_node(node, True, indent=1):
                break

    if budget:
        emit(f"\n📊 Used ~{tokens_used} of {budget} token budget")

    print("\n".join(out_lines))

    # Package D: record what was actually shown, for the usefulness loop.
    try:
        record_recall_emissions(db, emitted_ids)
    except Exception:
        pass

    # Auto-touch: bump last_relevant for all nodes that appeared in results
    touched_ids = set()
    for _, node, _ in scored:
        if node["id"] not in touched_ids:
            try:
                db.execute("UPDATE nodes SET last_relevant = ? WHERE id = ?", (now(), node["id"]))
                touched_ids.add(node["id"])
            except:
                pass
    if touched_ids:
        db.commit()

    print()


# ── ASOF (bi-temporal recall) ──────────────────────────

def cmd_asof(args):
    """Recall facts as they were valid at a given date (Phase 4d).

    Thin wrapper over cmd_recall: sets the as-of date so nodes valid at that
    date rank ahead of ones expired-before or not-yet-valid-at it. Ranking
    only — nothing is hidden, so a superseded fact still surfaces (demoted)."""
    args.asof = args.date
    args.fast = False  # bi-temporal ranking lives in the deep-recall path only
    cmd_recall(args)


# ── LINK ───────────────────────────────────────────────

def cmd_link(args):
    db = get_db()
    
    source = db.execute("SELECT id FROM nodes WHERE name = ? COLLATE NOCASE", (args.source,)).fetchone()
    target = db.execute("SELECT id FROM nodes WHERE name = ? COLLATE NOCASE", (args.target,)).fetchone()
    
    if not source:
        print(f"❌ Source node '{args.source}' not found.")
