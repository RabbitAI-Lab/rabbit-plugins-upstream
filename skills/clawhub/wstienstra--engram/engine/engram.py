def cmd_dupes(args):
    """Find potential duplicate nodes by fuzzy name/email matching."""
    db = get_db()
    
    nodes = db.execute("SELECT id, name, type, props FROM nodes ORDER BY name").fetchall()
    
    # Group by normalized name prefix (first 2 words, lowercase)
    from collections import defaultdict
    groups = defaultdict(list)
    for n in nodes:
        words = n["name"].lower().split()[:2]
        key = " ".join(words)
        if len(key) >= 4:
            groups[key].append(n)
    
    # Also group by email
    email_groups = defaultdict(list)
    for n in nodes:
        try:
            props = json.loads(n["props"]) if n["props"] else {}
            email = props.get("email", "").lower()
            if email and len(email) > 5:
                email_groups[email].append(n)
        except:
            pass
    
    print("🔍 Potential duplicates:\n")
    found = 0
    
    # Name-based dupes
    for key, group in sorted(groups.items()):
        if len(group) > 1:
            print(f"  📛 Name match '{key}':")
            for n in group:
                props = json.loads(n["props"]) if n["props"] else {}
                email = props.get("email", "")
                print(f"     {n['name']} [{n['type']}] {email}")
            found += 1
    
    # Email-based dupes
    for email, group in sorted(email_groups.items()):
        if len(group) > 1:
            names_shown = set()
            unique = [n for n in group if n["name"] not in names_shown and not names_shown.add(n["name"])]
            if len(unique) > 1:
                print(f"  📧 Email match '{email}':")
                for n in unique:
                    print(f"     {n['name']} [{n['type']}]")
                found += 1
    
    if found == 0:
        print("  ✅ No duplicates found!")
    else:
        print(f"\n  Found {found} potential duplicate groups. Merge with `engram update` + `engram delete`.")


