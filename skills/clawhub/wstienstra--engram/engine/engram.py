# ── PROSPECTIVE MEMORY (intentions) ────────────────────
# An 'intention' node is an armed "when X happens → do Y" trigger. On every
# incoming message msgctx text-matches the message against armed triggers
# (FTS-style keyword overlap only — NO model load on this hot path) and, on a
# match, surfaces a ⏰ INTENTION line FIRST. It never auto-fires: the agent
# decides and calls `intention-fire`. All matching is deterministic SQL + Python
# per the phase-4 RUNTIME COST POLICY (no LLM anywhere in runtime).

_INTENTION_STOP = {"the","and","for","are","but","not","you","all","can","her","was","one","our",
                   "out","has","have","had","been","from","this","that","with","they","will","each",
                   "make","like","just","use","used","using","how","what","when","where","which",
                   "who","why","some","any","also","about","into","more","other","than","then",
                   "them","these","would","could","should","does","did","get","got","here","there",
                   "very","after","before","being","both","still","over","want","need","check","look"}


def _intention_tokens(text):
    """Lowercase meaningful tokens (>=3 alpha chars, minus stop words), deduped
    order-preserving. Same tokenizer msgctx uses so trigger + message align."""
    toks = [w for w in re.findall(r'[a-z]{3,}', (text or '').lower())
            if w not in _INTENTION_STOP]
    seen = set()
    out = []
    for w in toks:
        if w not in seen:
            seen.add(w)
            out.append(w)
    return out


def _intention_proper_nouns(text):
    """Capitalized words in the raw trigger (names / proper nouns), lowercased.
    A single proper-noun hit is enough to fire (a name is a strong trigger)."""
    out = set()
    for w in re.findall(r'\b([A-Z][a-zA-Z]{2,})\b', text or ''):
        lw = w.lower()
        if lw not in _INTENTION_STOP:
            out.add(lw)
    return sorted(out)


def _fmt_trigger(trigger):
    """'when X' phrasing without doubling a leading 'when'."""
    t = (trigger or "").strip()
    if t.lower().startswith("when "):
        return t
    return f"when {t}"


def _intention_kw_hit(keyword, msg_tokens):
    """True if a trigger keyword occurs in the message: exact, or sharing a
    >=4-char prefix within 3 chars of length (covers plural/tense: replies↔replied)."""
    if keyword in msg_tokens:
        return True
    for t in msg_tokens:
        n = min(len(keyword), len(t))
        if n >= 4 and keyword[:n] == t[:n] and abs(len(keyword) - len(t)) <= 3:
            return True
    return False


def _armed_intentions(db):
    """Armed, non-expired intention nodes: [(id, name, props_dict), ...]."""
    try:
        rows = db.execute(
            "SELECT id, name, props FROM nodes WHERE type = 'intention' ORDER BY id DESC LIMIT 200"
        ).fetchall()
    except Exception:
        return []
    now_iso = now()
    out = []
    for r in rows:
        try:
            p = json.loads(r["props"] or "{}")
        except Exception:
            continue
        if p.get("status") != "armed":
            continue
        exp = p.get("expires_at")
        if exp and str(exp) <= now_iso:
            continue
        out.append((r["id"], r["name"], p))
    return out


def _score_intention(msg_tokens, props):
    """Return (matched, keyword_hits, proper_hits) for a message against a trigger.
    Fires when >=2 trigger keywords hit, or any proper-noun trigger word hits."""
    kws = props.get("trigger_keywords") or []
    proper = set(props.get("trigger_proper") or [])
    hits = [k for k in kws if _intention_kw_hit(k, msg_tokens)]
    proper_hits = [k for k in hits if k in proper]
    matched = (len(hits) >= 2) or (len(proper_hits) >= 1)
    return matched, len(hits), len(proper_hits)


def _emit_intention_matches(db, message):
    """Print ⏰ INTENTION lines for armed triggers this message matches. Hot path:
    FTS-style keyword overlap only, no semantic engine load. Best-effort DB write
    of last_matched (never blocks msgctx on a lock)."""
    armed = _armed_intentions(db)
    if not armed:
        return
    msg_tokens = set(_intention_tokens(message))
    if not msg_tokens:
        return
    fired = []
    for nid, _name, props in armed:
        matched, nhits, nproper = _score_intention(msg_tokens, props)
        if matched:
            fired.append((nproper * 10 + nhits, nid, props))
    if not fired:
        return
    fired.sort(key=lambda x: x[0], reverse=True)
    for _score, nid, props in fired[:3]:
        trig = props.get("trigger_desc", "")
        act = props.get("action_desc", "")
        print(f"⏰ INTENTION: {_fmt_trigger(trig)} → {act}")
        try:
            props["last_matched"] = now()
            db.execute("UPDATE nodes SET props = ?, updated_at = ? WHERE id = ?",
                       (json.dumps(props), now(), nid))
            db.commit()
        except Exception:
            pass


def cmd_intend(args):
    """Arm a prospective-memory intention: when <trigger> → do <action>."""
    db = get_db()
    trigger = (getattr(args, "trigger", "") or "").strip()
    action = (getattr(args, "action", "") or "").strip()
    if not trigger or not action:
        print('❌ Usage: engram intend "when X happens" "do Y" [--expires ISO]')
        sys.exit(1)

    keywords = _intention_tokens(trigger)
    proper = _intention_proper_nouns(trigger)
    expires = (getattr(args, "expires", "") or "").strip() or None

    props = {
        "trigger_desc": trigger,
        "trigger_keywords": keywords,
        "trigger_proper": proper,
        "action_desc": action,
        "expires_at": expires,
        "status": "armed",
        "created_from": (getattr(args, "source", "") or "cli"),
        "last_matched": None,
    }

    base = f"intention: {trigger}"
    name = base[:120]
    if db.execute("SELECT 1 FROM nodes WHERE LOWER(name) = LOWER(?)", (name,)).fetchone():
        stamp = datetime.now(timezone.utc).strftime("%y%m%d-%H%M%S")
        name = f"{base[:100]} [{stamp}]"

    content = f"WHEN: {trigger}\nDO: {action}"
    store_args = argparse.Namespace(
        name=name, type="intention", content=content,
        props=json.dumps(props), tags="intention,prospective",
    )
    cmd_store(store_args)
    if expires:
        print(f"⏰ Armed — expires {expires}")
    else:
        print("⏰ Armed (no expiry)")


