MSGCTX_MIN_WORDS = 3           # a one- or two-word message is chat, not a question
MSGCTX_RARE_FRACTION = 0.005   # same "distinctive term" test strategy 2 already uses
MSGCTX_RARE_FLOOR = 50
MSGCTX_TRUSTED_WEIGHT = 4      # strategy 0, the entity-NAME match
MSGCTX_MIN_RARE_HITS = 1       # distinctive query words an OR hit must contain
MSGCTX_MIN_RARE_HITS_AND = 1   # ...and an AND-FTS hit
MSGCTX_RARE_IN_NAME = True     # require them in the NAME rather than anywhere in the node
MSGCTX_RARE_IN_NAME_MAX_WEIGHT = 1   # ...for hits at or below this strategy weight
# Types msgctx will not inject. The first three were always excluded; the episodic ones are
# transcript exhaust (an EMAIL body contains almost any phrase) and were measured, in §4.3,
# to produce more noise than hits on this path.
# Excluding episodic types here was measured and REJECTED: it left the negative class at
# 38% and cost 8 points of paraphrase recall (§4.3).
MSGCTX_EXCLUDED_TYPES = ('session_summary', 'extract', 'method')
MSGCTX_EXCLUDED_SQL = "(" + ",".join(f"'{t}'" for t in MSGCTX_EXCLUDED_TYPES) + ")"
# msgctx runs on every message, so its candidate pools are the smallest in the system
# (LIMIT 2-5). Archived exhaust that reaches them costs a real hit, not just tokens.
MSGCTX_SCOPE_SQL = f"n.type NOT IN {MSGCTX_EXCLUDED_SQL} AND n.tier != 'archive'"


def _msgctx_filter(db, words, ranked):
    """Drop msgctx hits that are FTS coincidences, and return what survives.

    msgctx runs on EVERY user message, and its three strategies always find *something*:
    measured on 74 real mined queries it answered 85% of the questions the engram has
    nothing on, ~115 tokens each (the measurement log). Measuring precision per strategy showed
    where the noise is:

        strategy 0, entity-NAME match  (weight 4):  33 hits / 42 shown   negatives: 2
        strategy 1, AND-FTS            (weight 3):   1 hit  /  7 shown   negatives: 6
        strategy 2, IDF-gated OR       (weight 1):   3 hits / 10 shown   negatives: 3

    So a name match is trusted as-is, and the weaker two must earn their place: the node
    has to contain one of the query's DISTINCTIVE words (document frequency <= the same
    RARE_MAX strategy 2 already uses). Filtering per result rather than abstaining
    wholesale keeps the good name hits in queries that also drew noise.

    An IDF-mass floor over the whole result was tried first and traded much worse —
    reaching 60% on the negative class cost 20 points of paraphrase recall (§4.2).
    """
    if not ranked:
        return []
    uniq = list(dict.fromkeys(words))
    if len(uniq) < MSGCTX_MIN_WORDS:
        return []
    try:
        total = db.execute("SELECT COUNT(*) FROM nodes").fetchone()[0] or 1
    except Exception:
        return ranked
    rare_max = max(MSGCTX_RARE_FLOOR, int(total * MSGCTX_RARE_FRACTION))
    rare = []
    for w in uniq:
        try:
            dfv = db.execute("SELECT COUNT(*) FROM nodes_fts WHERE nodes_fts MATCH ?",
                             (f'"{w}"',)).fetchone()[0]
        except sqlite3.OperationalError:
            continue
        if 0 < dfv <= rare_max:
            rare.append(w)
    kept = []
    for r, weight in ranked:
        if weight >= MSGCTX_TRUSTED_WEIGHT:
            kept.append((r, weight))
            continue
        if not rare:
            continue
        name = str(r["name"] or "").lower() if "name" in r.keys() else ""
        blob = " ".join(str(r[k] or "") for k in ("name", "content") if k in r.keys()).lower()
        need = MSGCTX_MIN_RARE_HITS if weight <= 1 else MSGCTX_MIN_RARE_HITS_AND
        in_name = MSGCTX_RARE_IN_NAME and weight <= MSGCTX_RARE_IN_NAME_MAX_WEIGHT
        field = name if in_name else blob
        ok = sum(1 for w in rare if w in field) >= need
        if ok:
            kept.append((r, weight))
    return kept


def cmd_msgctx(args):
    """Message context: given a user message, return the 3 most relevant Engram nodes.
    Ultra-fast (<200ms). Used to pre-select context before responding.
    
    Usage: engram msgctx "user message text"
    Returns: compact list of relevant nodes
    """
    message = getattr(args, 'message', '') or ''
    if not message:
        return
    
    db = get_db()

    # Prospective memory: armed intentions this message matches fire FIRST,
    # before methods or any other context. Text-only match (no model load).
    try:
        _emit_intention_matches(db, message)
    except Exception:
        pass

    # Method channel: proven-approach recall runs FIRST, printed before any
    # other context — this is what makes "the first try is the working
    # methodology" automatic instead of relying on discipline. FTS + signature
    # only (no semantic engine load) since msgctx is a hot path (~70ms warm).
    try:
        method_hits = find_matching_methods(db, message, limit=1, use_semantic=False)
    except Exception:
        method_hits = []
    if method_hits:
        print(_method_compact_block(method_hits[0], prefix="📋 METHOD (proven approach):", max_chars=600))

    # Extract meaningful words (skip common stop words)
    stop_words = {"the","and","for","are","but","not","you","all","can","her","was","one","our",
                  "out","has","have","had","been","from","this","that","with","they","will","each",
                  "make","like","just","use","used","using","how","what","when","where","which",
                  "who","why","some","any","also","about","into","more","other","than","then",
                  "them","these","would","could","should","does","did","get","got","here","there",
                  "very","after","before","being","both","still","over","want","need","check","look"}

    import re as _re
    words = [w for w in _re.findall(r'[a-z]{3,}', message.lower()) if w not in stop_words]
    if not words:
        return
    
    # Build FTS query — AND logic: all words must appear
    fts_words = words[:4]
    
    results = []
    seen = set()

    # Strategy 0: Entity name match — highest priority. Prefers a node whose
    # NAME matches consecutive query words (handles particles like "van de"
    # that get stripped by the word filter). Beats body-text FTS hits.
    for n_len in range(min(len(fts_words), 4), 1, -1):
        name_hits = []
        for i in range(len(fts_words) - n_len + 1):
            like_pattern = '%' + '%'.join(fts_words[i:i + n_len]) + '%'
            try:
                rows = db.execute(f"""
                    SELECT n.id, n.name, n.type, n.props, n.content
                    FROM nodes n
                    WHERE LOWER(n.name) LIKE ?
                    AND {MSGCTX_SCOPE_SQL}
                    LIMIT 3
                """, (like_pattern,)).fetchall()
                for r in rows:
                    if r['id'] not in seen:
                        seen.add(r['id'])
                        name_hits.append((r, 4))
            except Exception:
                pass
        if name_hits:
            results.extend(name_hits)
            break

    # Strategy 1: AND search (all words must match) — highest relevance
    and_query = ' '.join(f'"{w}"*' for w in fts_words)
    try:
        and_rows = db.execute(f"""
            SELECT n.id, n.name, n.type, n.props, n.content
            FROM nodes n
            JOIN nodes_fts fts ON fts.rowid = n.id
            WHERE nodes_fts MATCH ?
            AND {MSGCTX_SCOPE_SQL}
            ORDER BY rank
            LIMIT 5
        """, (and_query,)).fetchall()
        for r in and_rows:
            if r['id'] not in seen:
                seen.add(r['id'])
                results.append((r, 3))  # weight 3: AND match = best
    except Exception:
        pass
    
    # Strategy 2: OR search (any word matches) — fill remaining slots.
    # IDF gate (2026-07-19, owner: "brown alone should not be a positive for
    # biefeld brown"): a single common word is not evidence. Compute each word's
    # document frequency; iterate rarest-first and skip words that match more
    # than RARE_MAX nodes — only distinctive terms may pull in OR hits alone.
    if len(results) < 3:
        try:
            n_total = db.execute("SELECT COUNT(*) FROM nodes").fetchone()[0] or 1
        except Exception:
            n_total = 20000
        RARE_MAX = max(50, int(n_total * 0.005))
        word_df = []
        for word in fts_words:
            try:
                df = db.execute("SELECT COUNT(*) FROM nodes_fts WHERE nodes_fts MATCH ?",
                                (f'"{word}"*',)).fetchone()[0]
            except Exception:
                df = n_total
            word_df.append((df, word))
        or_words = [w for df, w in sorted(word_df) if df <= RARE_MAX]
        for word in or_words:
            try:
                rows = db.execute(f"""
                    SELECT n.id, n.name, n.type, n.props, n.content
                    FROM nodes n
                    JOIN nodes_fts fts ON fts.rowid = n.id
                    WHERE nodes_fts MATCH ?
                    AND {MSGCTX_SCOPE_SQL}
                    AND n.id NOT IN ({','.join('?' * len(seen)) or '0'})
                    ORDER BY rank
                    LIMIT 2
                """, (word, *list(seen))).fetchall()
                for r in rows:
                    if r['id'] not in seen:
                        seen.add(r['id'])
                        results.append((r, 1))  # weight 1: OR match = lower
            except Exception:
                pass
            if len(results) >= 3:
                break
    
    if not results:
        return
    
    # Rank by weight (AND > OR). (The old second sort key read props['touch_count'], but
    # touch_count is a COLUMN and never appears in props, so it was always 0 — a dead
    # tiebreak. Dropped rather than left in place pretending to do something.)
    ranked = sorted(results, key=lambda x: x[1], reverse=True)[:3]

    # ── Abstention floor (L2) ──
    # msgctx runs on EVERY user message. Measured on 74 real mined queries, it answered 85%
    # of the questions the engram has nothing on, at ~115 tokens each
    # (the measurement log). Strategy 0's name LIKE and strategy 1's AND-FTS will always find
    # *something* for a conversational message. Require the best hit to actually cover some
    # rare query words before spending the reader's context on it — same rarity test the
    # deep-recall gate uses, so the two paths cannot disagree about what counts as evidence.
    ranked = _msgctx_filter(db, words, ranked)
    if not ranked:
        return

    for r, weight in ranked:
        p = json.loads(r['props']) if r['props'] else {}
        status = p.get('status', '')
        content_preview = (r['content'] or '')[:80].replace('\n', ' ')
        print(f"→ [{r['type']}] {r['name']}" + (f" [{status}]" if status else ""))
        if content_preview:
            print(f"  {content_preview}")



