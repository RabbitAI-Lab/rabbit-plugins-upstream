    cols = [r[1] for r in db.execute("PRAGMA table_info(nodes)").fetchall()]
    if "tier" not in cols:
        db.execute("ALTER TABLE nodes ADD COLUMN tier TEXT DEFAULT 'active'")
        db.execute("CREATE INDEX IF NOT EXISTS idx_node_tier ON nodes(tier)")
        db.commit()


