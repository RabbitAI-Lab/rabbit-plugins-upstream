_dendrite_cache = None

def _find_dendrites(node, db):
    """Find implicit references to other nodes in this node's content and props.
    Like neural dendrites — connections that emerge from the data itself."""
    global _dendrite_cache
    if _dendrite_cache is None:
        _dendrite_cache = {}
        for row in db.execute("SELECT id, name FROM nodes WHERE length(name) >= 3"):
            _dendrite_cache[row["id"]] = row["name"]
    
    text = (node["content"] + " " + node["props"]).lower()
    my_id = node["id"]
    my_name = node["name"].lower()
    
    # Get existing explicit associations to exclude
    existing = set()
    for row in db.execute("""
        SELECT target_id FROM associations WHERE source_id = ?
        UNION SELECT source_id FROM associations WHERE target_id = ?
    """, (my_id, my_id)):
        existing.add(row[0])
    
    found = []
    for nid, name in _dendrite_cache.items():
        if nid == my_id:
            continue
        if nid in existing:
            continue  # already an explicit link, skip
        # Skip very short or generic names
        if len(name) < 4:
            continue
        name_lower = name.lower()
        # Skip if it's a substring of our own name
        if name_lower in my_name or my_name in name_lower:
            continue
        # Check: full name match
        if name_lower in text:
            found.append(name)
            continue
        # Check: first significant word match (for multi-word names like "Acme Corporation")
        # Use first 2 words if name has 3+ words, or first word if 2 words
        words = name.split()
        if len(words) >= 2:
            # Try "Acme Corp", "Maria del", etc.
            partial = " ".join(words[:2]).lower()
            if len(partial) >= 6 and partial in text:
                found.append(name)
                continue
    
    # Limit to most relevant (max 8)
    return found[:8]


def format_node(node, db, indent=0, compact=False, lean=False, query_context="", full=False):
    """Format a node for output.
    compact: one-line summary (preferred for token efficiency)
    lean: DEPRECATED — use compact instead. Kept for backward compat, redirects to compact.
    query_context: only show props relevant to query
    full: bypass tier compression, show full content even for mid/long tier
    """
    if lean:
        compact = True  # lean → compact redirect
    prefix = "  " * indent
    lines = []
    
    node_type = node["type"].upper()
    props = json.loads(node["props"])
    memory_tier = node["memory_tier"] if "memory_tier" in node.keys() else "short"
    summary = node["summary"] if "summary" in node.keys() else ""
    
    if compact:
        status = props.get("status", "")
        status_str = f"|{status}" if status else ""
        tags = db.execute("""
            SELECT t.name FROM tags t
            JOIN node_tags nt ON t.id = nt.tag_id
            WHERE nt.node_id = ?
            ORDER BY t.name
        """, (node["id"],)).fetchall()
        tag_str = " ".join(f"#{t['name']}" for t in tags[:5])
        lines.append(f"{prefix}{node['name']} [{node_type}{status_str}] {tag_str}")
        return "\n".join(lines)
    
    # ── Step 1: Clean props (remove internal/meta) ──
    clean_props = {k: v for k, v in props.items()
                   if k not in ("inlined", "source_file")
                   and v not in (None, "None", "null", True, "True")}
    
    # ── Step 1.5: Entity/Attribute split ──
    # Entity words = words that match this node's name (they FOUND the node)
    # Attribute words = remaining words (they FILTER the output)
    # Synonym expansion for common attribute queries
    # Load synonyms from config (data-driven, not hardcoded)
    _synonyms_raw = get_config(db, "synonyms")
    _attr_synonyms = {}
    for k, v_list in _synonyms_raw.items():
        _attr_synonyms[k] = set([k] + v_list)
    
    entity_words = set()
    attr_words = set()
    if query_context:
        name_lower = node["name"].lower()
        for w in query_context.lower().split():
            if w in name_lower:
                entity_words.add(w)
            else:
                expanded = _attr_synonyms.get(w, {w})
                attr_words.update(expanded)
    
    is_specific = len(attr_words) > 0
    qwords = set(query_context.lower().split()) if query_context else set()
    
    # ── Step 2: Filter props ──
    if query_context and is_specific:
        # SPECIFIC query: only show props matching attribute words
        filtered_props = {}
        for k, v in clean_props.items():
            k_lower = k.lower()
            v_str = str(v).lower()
            match = False
            for aw in attr_words:
                if aw in k_lower or k_lower.startswith(aw[:min(4, len(aw))]):
                    match = True
                if aw in v_str:
                    match = True
            if k == "status":
                match = True  # always show status
            if match:
                filtered_props[k] = v
        high_match = {k: v for k, v in filtered_props.items() if k != "status"}
    elif query_context:
        # BROAD query: show all clean props
        filtered_props = clean_props
        high_match = {}
    else:
        filtered_props = clean_props
        high_match = {}
    
    # ── Step 3: Section-aware content extraction ──
    # Tiered memory: use summary for mid/long tier nodes unless --full
    content = node["content"]
    tier_tag = ""
    if not full and memory_tier in ("mid", "long") and summary:
        content = summary
        tier_tag = f" ⟨{memory_tier}⟩"
    
    # For specific queries with high prop matches: props ARE the answer, minimize content
    if is_specific and high_match:
        # Props answer the question — just show first line as context
        first_line = content.split('\n')[0] if content else ""
        content = first_line
    elif len(content) > 2048 and query_context:
        # Parse markdown into sections
        sections = []
        current_header = ""
        current_lines = []
        for line in content.split('\n'):
            if line.startswith('## ') or line.startswith('# '):
                if current_header or current_lines:
                    sections.append((current_header, '\n'.join(current_lines)))
                current_header = line
                current_lines = []
            else:
                current_lines.append(line)
        if current_header or current_lines:
            sections.append((current_header, '\n'.join(current_lines)))
        
        # For specific queries: only show sections matching attribute words
        # For broad queries: score all sections
        filter_words = attr_words if is_specific else qwords
        
        scored_sections = []
        for header, body in sections:
            combined = (header + ' ' + body).lower()
            hits = sum(2 for w in filter_words if w in combined)
            if any(c in body for c in ['€', '$', '£', '@', 'http', '|']):
                hits += 1
            if any(w in combined for w in ['fix', 'solved', 'solution', 'workaround', 'resolved']):
                hits += 2
            if not scored_sections:
                hits += 1 if is_specific else 3  # less weight on overview for specific queries
            scored_sections.append((hits, header, body))
        
        if is_specific:
            # Only keep sections with attribute matches
            scored_sections = [(h, hdr, b) for h, hdr, b in scored_sections if h > 0]
        
        scored_sections.sort(key=lambda x: -x[0])
        kept_parts = []
        chars_used = 0
        CONTENT_LIMIT = 1024 if is_specific else 2048
        for hits, header, body in scored_sections:
            if hits == 0:
                continue
            section_text = (header + '\n' + body).strip()
            if chars_used + len(section_text) > CONTENT_LIMIT:
                # Partial: take just the header + first few lines
                partial = header + '\n' + '\n'.join(body.split('\n')[:5])
                kept_parts.append(partial)
                break
            kept_parts.append(section_text)
            chars_used += len(section_text)
        
        # Re-sort by original order
        content = '\n'.join(kept_parts) if kept_parts else content[:CONTENT_LIMIT] + '\n[...truncated]'
    elif len(content) > 2048:
        content = content[:2048] + '\n[...truncated]'
    
    # ── Step 4: If props fully answer the query, minimize content ──
    if high_match and len(content) > 500:
        # Props have the answer — show just the first section header as context
        first_line = content.split('\n')[0] if content else ""
        content = first_line
    
    # ── Step 5: Deduplicate props vs content ──
    deduped_props = {}
    content_lower = content.lower()
    for k, v in filtered_props.items():
        v_str = str(v).lower()
        if v_str not in content_lower or k == "status":
            deduped_props[k] = v
    
    if not compact:
        # Standard format (but with deduplication)
        lines.append(f"{prefix}---")
        lines.append(f"{prefix}{node['name']} [{node_type}]{tier_tag}")
        if content:
            lines.append(f"{prefix}  {content}")
        for k, v in deduped_props.items():
            lines.append(f"{prefix}  {k}: {v}")
        tags = db.execute("""
            SELECT t.name FROM tags t
            JOIN node_tags nt ON t.id = nt.tag_id
            WHERE nt.node_id = ?
            ORDER BY t.name
        """, (node["id"],)).fetchall()
        if tags:
            lines.append(f"{prefix}  #{',#'.join(t['name'] for t in tags)}")
        assocs = db.execute("""
            SELECT n.name, a.relation FROM associations a
            JOIN nodes n ON n.id = a.target_id WHERE a.source_id = ? AND a.relation != 'supersedes'
            UNION
            SELECT n.name, a.relation FROM associations a
            JOIN nodes n ON n.id = a.source_id WHERE a.target_id = ? AND a.relation != 'supersedes'
        """, (node["id"], node["id"])).fetchall()
        if assocs:
            for a in assocs:
                lines.append(f"{prefix}  -> {a['relation']}: {a['name']}")
        # Dendrites for standard format too
        dendrites = _find_dendrites(node, db)
        if dendrites:
            lines.append(f"{prefix}  ~ implicit: {', '.join(dendrites)}")
        lines.append(f"{prefix}  @{node['updated_at'][:10]}")
    
    return "\n".join(lines)


# ── RECALL FUSION HELPERS (RRF + usefulness feedback) ──────────────────
# Deep recall (cmd_recall) fuses independent retrieval channels via
# Reciprocal Rank Fusion instead of hand-tuned additive scores. These
# helpers also batch the per-candidate SQL that used to run once per node.

def _rrf_fuse(channels, k=60, weights=None):
    """Reciprocal Rank Fusion. channels: {name: [node_id, ...]} in rank order
    (index 0 = rank 1). weights: optional {channel_name: multiplier}, default
    1.0 for any channel not listed (this is what makes the call sites that
    don't pass weights — e.g. find_matching_methods's fts/sig/sem channels —
    behave exactly as before: uniform 1.0 per channel). Returns
    {node_id: fused_score}."""
    weights = weights or {}
    fused = {}
    for name, ranked_ids in channels.items():
        w = weights.get(name, 1.0)
        for i, nid in enumerate(ranked_ids):
            fused[nid] = fused.get(nid, 0.0) + w / (k + i + 1)
    return fused


_HUB_ENTITY_TYPES = ('person', 'contact', 'organization', 'business')
TAG_PIN_MAX_DF = 25   # a tag on <=25 nodes names a thing; above that it labels a topic
TAG_PIN_MAX_HITS = 5  # how many tag-only pins may reach the pool, rarest tag first
TAG_PIN_MAX_WORD_DF = 400      # ...and its word must be rare in the corpus too (= NAME_MATCH_MAX_DF)


def _node_alias_list(row):
    """`props.aliases` as a list of strings. Aliases answer the vocabulary gap: the query's
    words and the node's name need not overlap at all (measured — "owner contact details"
    vs the node "Alice Johnson"). They cost nothing to carry: the
    props column is already in the FTS index, embeddings.py embeds them, and this helper
    lets the name channel treat each one as an alternative name."""
    try:
        raw = row["props"]
    except (IndexError, KeyError, TypeError):
        return []
    if not raw:
        return []
    try:
        data = json.loads(raw) if isinstance(raw, str) else raw
    except Exception:
        return []
    al = (data or {}).get("aliases") or []
    if isinstance(al, str):
        al = [al]
    return [str(a).strip() for a in al if str(a).strip()]



# Small irregular-verb stem map (buy/bought, not a suffix relationship so
# Porter-style stripping can't reach it) plus regular suffix stripping.
# Deliberately tiny: this is only ever used to compare a query word against
# a NAME or human-authored ALIAS token (see _pin_hub_entities_split), never
# against the wider generic-word/tag-DF gates, so a wrong stem costs at most
# one candidate one extra (harmless) overlap point, not a corpus-wide flood.
_IRREGULAR_STEMS = {
    "bought": "buy", "buys": "buy", "buying": "buy",
    "sold": "sell", "sells": "sell", "selling": "sell",
    "brought": "bring", "brings": "bring", "bringing": "bring",
    "taught": "teach", "caught": "catch", "thought": "think",
    "made": "make", "paid": "pay", "said": "say",
}


def _stem_light(word):
    """Normalize a word to a rough stem: irregular-verb lookup first, then
    plain suffix stripping (-ing/-ed/-es/-s). Good enough to bridge
    buy/bought, phones/phone — not a real morphological analyzer."""
    w = (word or "").lower()
    if w in _IRREGULAR_STEMS:
        return _IRREGULAR_STEMS[w]
    for suf, cut in (("ing", 3), ("ies", 3), ("ed", 2), ("es", 2), ("s", 1)):
        if w.endswith(suf) and len(w) - cut >= 3:
            return w[:-cut]
    return w


def _pin_hub_entities_split(db, query, generic_words):
    """Hub-entity drowning fix: a query like "alice email address" should
    surface the tiny person/contact/org node named "Alice Johnson" even
    though the word "alice" also appears in 300+ other rows (outreach
    prospects, session logs, etc.) that outrank it on raw FTS term
    frequency. Generic mechanism: any node whose NAME contributes a
    distinctive (non-generic, len>=4) token that's also in the query gets
    pinned to the front of the FTS channel — ranked by how much of the
    node's own name the query accounts for, so "Alice Johnson" beats a
    node merely mentioning "alice" in passing. Not type-restricted to a
    hardcoded name; applies to any person/contact/organization/business
    node small enough to plausibly BE the entity rather than just discuss it.
    """
    import re as _re
    import difflib as _difflib
    _raw_q_tokens = {w.lower() for w in _re.findall(r"[A-Za-z][A-Za-z0-9_-]{2,}", query or "")}
    # Strict set (unchanged): feeds tag-surface matching below, where the
    # generic-word/length gate is load-bearing (a rare tag must not be
    # reachable via a common word like "phone" — that's how "alice email
    # address" avoids pinning every contact node with an @ sign).
    q_tokens = {w for w in _raw_q_tokens if w not in generic_words and len(w) >= 4}
    # Loose set: used ONLY to match against NAME/ALIAS surfaces (is_name=True
    # below), never tags. A human-authored alias ("phone", "phone I bought")
    # is that person's own claim about what the node IS — a deliberate,
    # curated label, not incidental text — so it earns a lower evidence bar
    # than a stray word match in a tag or in FTS body text. Without this,
    # "what phone did I buy" has zero q_tokens at all ("phone" is generic,
    # "buy"/"did" are under the length-4 floor) and an exact-alias node can
    # never be found regardless of how well-labeled it is.
    q_tokens_alias = _raw_q_tokens | q_tokens
    q_stems_alias = {_stem_light(w) for w in q_tokens_alias}
    if not _raw_q_tokens:
        return [], []

    def _matches(name_tok, is_name):
        # exact match, or a close fuzzy match for typo tolerance (transposed/
        # dropped letters) — only for longer tokens, where a coincidental
        # short-string collision is unlikely. Returns (matched, exact?).
        target = q_tokens_alias if is_name else q_tokens
        if name_tok in target:
            return True, True
        if is_name and _stem_light(name_tok) in q_stems_alias:
            return True, True
        if len(name_tok) >= 5 and _difflib.get_close_matches(name_tok, target, n=1, cutoff=0.8):
            return True, False
        return False, False

    placeholders = ",".join("?" * len(_HUB_ENTITY_TYPES))
    # An alias makes a node pin-eligible whatever its type. The hub types are a guess
    # about which nodes are entities; an alias is a human saying so. The measured vocabulary
    # misses were all outside the hub types ("Staging Server SSH" is a `credential`), so a
    # type list could never have reached them.
    rows = db.execute(
        f"SELECT * FROM nodes WHERE (type IN ({placeholders}) OR props LIKE '%\"aliases\"%') "
        f"AND length(name) < 60",
        _HUB_ENTITY_TYPES
    ).fetchall()
    # A rare tag is already an alias in everything but name. Measured on this graph:
    # `owner` is on 1 node, `server` on 2, `ssh` on 6, `webshop` on 20, while the median
    # tag is on 1 node and only the top 1% exceed 198. A tag that points at a handful of
    # nodes is as distinctive as a proper name, and it is the vocabulary the user actually
    # types ("owner contact details" -> #18 Alice Johnson, tagged `owner`). Tags above
    # the cap ("project", "outreach", "file-ingest") are topics, not names, and never pin.
    tag_surfaces = {}
    if q_tokens:
        _qmarks = ",".join("?" * len(q_tokens))
        try:
            for _r in db.execute(
                f"""SELECT nt.node_id AS nid, t.name AS tname, COUNT(*) OVER (PARTITION BY t.id) AS df
                    FROM tags t JOIN node_tags nt ON nt.tag_id = t.id
                    WHERE LOWER(t.name) IN ({_qmarks})""", tuple(q_tokens)).fetchall():
                if _r["df"] <= TAG_PIN_MAX_DF:
                    tag_surfaces.setdefault(_r["nid"], []).append((_r["tname"], _r["df"]))
        except sqlite3.OperationalError:
            tag_surfaces = {}
        # A rare tag is not automatically a name, and tag rarity is the wrong measure of it.
        # `oils` is a tag on 2 nodes but the WORD appears in 408; `trading` is a tag on 3
        # and a word in 2,067. Those tags are rare only because nobody reused them. A tag
        # that names something is rare in BOTH senses: `owner` is on 1 node and the word
        # occurs in 187, `semrush` on 21 and 187. So the second gate is the tag word's
        # corpus document frequency, reusing the name channel's own cap.
        # (A flat "tag must cover 30% of the query" rule was tried first and measured worse
        # — it scales with question length, so it threw away `semrush` in a 9-word question
        # while keeping nothing useful. Run 07: paraphrase back to baseline 73%.)
        if tag_surfaces:
            _wdf = {}
            _keep = {}
            for nid, ts in tag_surfaces.items():
                good = []
                for tname, tdf in ts:
                    words = [w for w in _re.findall(r"[a-z0-9]+", tname.lower()) if w in q_tokens]
                    if not words:
                        continue
                    worst = 0
                    for w in words:
                        if w not in _wdf:
                            try:
                                _wdf[w] = db.execute(
                                    "SELECT COUNT(*) FROM nodes_fts WHERE nodes_fts MATCH ?",
                                    (f'"{w}"',)).fetchone()[0]
                            except sqlite3.OperationalError:
                                _wdf[w] = 10 ** 9
                        worst = max(worst, _wdf[w])
                    if worst <= TAG_PIN_MAX_WORD_DF:
                        good.append((tname, tdf))
                if good:
                    _keep[nid] = good
            tag_surfaces = _keep
    if tag_surfaces:
        _have = {r["id"] for r in rows}
        _extra = [n for n in tag_surfaces if n not in _have]
        for _s in range(0, len(_extra), 400):
            _chunk = _extra[_s:_s+400]
            rows = list(rows) + db.execute(
                f"SELECT * FROM nodes WHERE id IN ({','.join('?' * len(_chunk))})",
                _chunk).fetchall()

    pins = []
    for row in rows:
        # Each alias is scored as an alternative name, and the best one wins: a node
        # keeps its real name for display and gains extra ways to be found.
        # (surface, is_name, df). A name or a human-written alias is a claim about what
        # the node IS; a tag is a weaker claim, so it ranks behind both, and among tags the
        # rarer one wins — `server` (2 nodes) outranks `webshop` (20), which is the whole
        # difference between pinning the SSH credential and pinning 20 Belgian webshops.
        surfaces = [(row["name"] or "", True, 0)]
        surfaces += [(a, True, 0) for a in _node_alias_list(row)]
        surfaces += [(t, False, df) for t, df in tag_surfaces.get(row["id"], [])]
        best = None
        for surface, is_name, surf_df in surfaces:
            _tokens = [w.lower() for w in _re.findall(r"[A-Za-z][A-Za-z0-9_-]{2,}", surface)
                       if len(w) >= 3]
            if not _tokens:
                continue
            _flags = [_matches(w, is_name) for w in _tokens]
            _overlap = [w for w, (m, _) in zip(_tokens, _flags) if m]
            if not _overlap:
                continue
            _frac = len(_overlap) / len(_tokens)
            _any_fuzzy = any(m and not exact for m, exact in _flags)
            # A fuzzy (typo-tolerant) match on just a fragment of the name is too
            # easy to hit by coincidence (e.g. "marta" ~ "maria") — only trust it
            # when it accounts for essentially the WHOLE name. Exact matches can
            # still pin on a real chunk of the name (e.g. just the first name).
            # Checked per surface, not once at the end: "Staging Server SSH" matches a
            # third of its own name (below the bar) and all of its `server` tag
            # (above it), and it is the tag that should decide.
            if _frac < (0.9 if _any_fuzzy else 0.4):
                continue
            _cand = ((1 if is_name else 0, _frac, -surf_df), _tokens, _flags, _overlap)
            if best is None or _cand[0] > best[0]:
                best = _cand
        if best is None:
            continue
        (_is_name, overlap_frac, _neg_df), name_tokens, match_flags, overlap = best
        pins.append((_is_name, overlap_frac, _neg_df, len(name_tokens), row))
    pins.sort(key=lambda t: (-t[0], -t[1], -t[2], t[3]))
    # A rare tag can still be shared by twenty organisations ("webshop"). Let the tag-only
    # pins compete, but never let them flood the front of the FTS channel and push the
    # name matches out of the pool they were built to protect.
    named = [t[-1] for t in pins if t[0]]
    tagged = [t[-1] for t in pins if not t[0]][:TAG_PIN_MAX_HITS]
    return named, tagged


