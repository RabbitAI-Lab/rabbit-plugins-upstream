# ── BRIEFING ───────────────────────────────────────────

def cmd_briefing(args):
    """Generate a session startup briefing. Replaces loading MEMORY.md + active-tasks + daily files.
    --compact: only today/tomorrow due + critical blocked items (50% smaller)
    """
    db = get_db()
    budget = args.budget or 1200
    compact = getattr(args, 'compact', False)
    tokens_used = 0
    
    def est(text):
        return len(text) // 4
    
    def emit(text):
        nonlocal tokens_used
        t = est(text)
        if tokens_used + t > budget:
            return False
        print(text)
        tokens_used += t
        return True
    
    emit(f"=== BRIEFING {datetime.now(timezone.utc).strftime('%Y-%m-%d')} ===\n")
    
    # 1. Due today/tomorrow (compact: only today/tomorrow, not full week)
    from datetime import timedelta
    today = datetime.now(timezone.utc).strftime("%Y-%m-%d")
    tomorrow = (datetime.now(timezone.utc) + timedelta(days=1)).strftime("%Y-%m-%d")
    week_end = (datetime.now(timezone.utc) + timedelta(days=7)).strftime("%Y-%m-%d")
    cutoff = tomorrow if compact else week_end
    
    due_nodes = []
    # Exclude lesson/rule/policy nodes from DUE — they use 'date' for when they were created
    EXCLUDE_FROM_DUE = {"lesson", "rule", "policy", "knowledge", "concept", "vision"}
    for row in db.execute("SELECT * FROM nodes"):
        if row["type"] in EXCLUDE_FROM_DUE:
            continue
        props = json.loads(row["props"])
        # Intentions surface by expiry; only armed ones are still live.
        if row["type"] == "intention" and props.get("status", "") != "armed":
            continue
        for key in ("date", "deadline", "follow_up", "call_date", "send_after", "expires_at"):
            d = props.get(key, "")
            if d and d[:10] <= cutoff and props.get("status", "") not in ("done", "inactive", "fired", "expired"):
                due_nodes.append((d[:10], row, key))
                break
    
    due_nodes.sort(key=lambda x: x[0])
    if due_nodes:
        emit("DUE:")
        for date, node, key in due_nodes:
            props = json.loads(node["props"])
            label = "TODAY" if date == today else ("TOMORROW" if date == tomorrow else date)
            if not emit(f"  [{label}] {node['name']} — {props.get('status','')}"):
                break
        emit("")
    
    # 2. Blocked items (compact: only awaiting_owner, not all blocked)
    awaiting_statuses = get_config(db, "status_buckets.awaiting")
    if compact:
        awaiting_statuses = [s for s in awaiting_statuses if "owner" in s.lower()]
    awaiting_like = " OR ".join(f"n.props LIKE '%{s}%'" for s in awaiting_statuses)
    # Exclude nodes with terminal statuses — these should not appear as blocked
    terminal_statuses = ("done", "inactive", "declined", "declined_paid", "bounced", "complete", "superseded")
    terminal_filter = " AND ".join(f"n.props NOT LIKE '%\"{s}\"%'" for s in terminal_statuses)
    blocked = db.execute(f"""
        SELECT n.* FROM nodes n
        JOIN associations a ON a.source_id = n.id
        WHERE a.relation = 'blocked_by'
        AND {terminal_filter}
        UNION
        SELECT n.* FROM nodes n WHERE ({awaiting_like})
        AND {terminal_filter}
    """).fetchall()
    
    if blocked:
        emit("BLOCKED (awaiting action):")
        for node in blocked:
            props = json.loads(node["props"])
            if not emit(f"  {node['name']} — {props.get('blocker', props.get('status',''))}"):
                break
        emit("")
    
    # 3. Active tasks (compact: limit 5 instead of 10)
    task_limit = 5 if compact else 10
    active = db.execute("""
        SELECT * FROM nodes WHERE type = 'task'
        AND props NOT LIKE '%"status": "done"%'
        AND props NOT LIKE '%"status":"done"%'
        AND props NOT LIKE '%"status": "inactive"%'
        AND props NOT LIKE '%"status":"inactive"%'
        ORDER BY updated_at DESC LIMIT ?
    """, (task_limit,)).fetchall()
    
    if active:
        emit("ACTIVE TASKS:")
        for node in active:
            props = json.loads(node["props"])
            # Prefer 'progress' over 'status' — tasks use progress for current state
            status = props.get("progress", props.get("status", ""))
            if not emit(f"  {node['name']} [{status}]"):
                break
        emit("")
    
    # 4. Critical lessons (always worth loading)
    lessons = db.execute("""
        SELECT * FROM nodes WHERE type = 'lesson'
        AND props LIKE '%critical%'
    """).fetchall()
    
    if lessons:
        emit("CRITICAL RULES:")
        for node in lessons:
            if not emit(f"  ! {node['name']}: {node['content'][:80]}"):
                break
        emit("")
    
    # 5. Recent decisions (compact: skip entirely)
    if not compact:
        decisions = db.execute("""
            SELECT * FROM nodes WHERE type = 'decision'
            ORDER BY updated_at DESC LIMIT 5
        """).fetchall()
        
        if decisions:
            emit("STANDING DECISIONS:")
            for node in decisions:
                if not emit(f"  {node['name']}"):
                    break
    
    print(f"\n[{tokens_used}/{budget} tokens]")


