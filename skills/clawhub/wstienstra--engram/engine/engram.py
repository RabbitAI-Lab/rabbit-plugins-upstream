def cmd_stale(args):
    """Find stale nodes: dead contacts (archivable) + never-accessed old nodes (report)."""
    db = get_db()
    ensure_dynamics_columns(db)

    from datetime import timedelta
    cutoff = (datetime.now(timezone.utc) - timedelta(days=args.days)).isoformat()

    stale = db.execute("""
        SELECT n.id, n.name, n.type, n.props, n.touch_count, n.last_touched, n.updated_at
        FROM nodes n
        WHERE (n.props LIKE '%bounced%' OR n.props LIKE '%declined%' OR n.props LIKE '%dead%')
        AND (n.last_touched < ? OR n.last_touched IS NULL OR n.last_touched = '')
        AND (n.touch_count IS NULL OR n.touch_count = 0)
        ORDER BY n.updated_at ASC
    """, (cutoff,)).fetchall()

    print(f"🧹 Dead-status nodes ({len(stale)} found, >{args.days} days untouched, archivable with --archive):\n")
    for s in stale:
        props = json.loads(s["props"]) if s["props"] else {}
        status = props.get("status", "?")
        print(f"  {s['name']} [{s['type']}] status={status} updated={s['updated_at'][:10]}")

    # Never-accessed old nodes — the real staleness signal. Report-only:
    # log-type nodes are expected to sit untouched, so they're split out.
    untouched = db.execute("""
        SELECT n.type, COUNT(*) as cnt FROM nodes n
        WHERE (n.touch_count IS NULL OR n.touch_count = 0)
        AND (n.last_touched IS NULL OR n.last_touched = '' OR n.last_touched < ?)
        AND n.created_at < ?
        GROUP BY n.type ORDER BY cnt DESC
    """, (cutoff, cutoff)).fetchall()
    log_types = {'message_sent', 'message_received', 'heartbeat_log',
                 'project_action', 'extract', 'session_summary'}
    knowledge = [(r['type'], r['cnt']) for r in untouched if r['type'] not in log_types]
    logs = sum(r['cnt'] for r in untouched if r['type'] in log_types)
    total_k = sum(c for _, c in knowledge)
    print(f"\n📉 Never-accessed nodes older than {args.days}d: {total_k} knowledge + {logs} log/comms")
    for t, c in knowledge[:10]:
        print(f"  {t}: {c}")
    if total_k:
        print("  (report-only — review before archiving; these may be reachable via search/recall)")
    
    if args.archive and stale:
        ts = now()
        for s in stale:
            props = json.loads(s["props"]) if s["props"] else {}
            props["status"] = f"archived_{props.get('status', 'stale')}"
            db.execute("UPDATE nodes SET props = ?, updated_at = ? WHERE id = ?",
                       (json.dumps(props), ts, s["id"]))
        db.commit()
        print(f"\n📦 Archived {len(stale)} stale nodes (status prefixed with 'archived_')")


