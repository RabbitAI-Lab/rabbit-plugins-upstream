def generate_summary(content, props, node_type, tier="mid"):
    """Generate a compressed summary for a node's content.
    mid: key facts + decisions + outcomes (2-4 sentences)
    long: sparse anchors — who/what/when/outcome (1 sentence or bullet points)
    """
    props_dict = json.loads(props) if isinstance(props, str) else props
    status = props_dict.get("status", "")

    # Extract key lines: headers, lines with dates/numbers/decisions
    lines = content.split('\n') if content else []
    important = []
    for line in lines:
        line_s = line.strip()
        if not line_s:
            continue
        # Keep headers, lines with key markers
        if (line_s.startswith('#') or line_s.startswith('- ') or
            any(m in line_s.lower() for m in ['decision', 'outcome', 'result', 'agreed', 'confirmed',
                                                'price', 'cost', '€', '$', 'deadline', 'url:', 'http',
                                                'email:', 'phone:', 'contact', '@'])):
            important.append(line_s)

    if tier == "long":
        # Sparse: just the first line + status + any URLs/contacts
        first_line = lines[0].strip() if lines else ""
        anchors = [l for l in important if any(m in l.lower() for m in ['http', '@', '€', '$', 'outcome', 'result'])]
        parts = [first_line] if first_line else []
        parts.extend(anchors[:3])
        if status:
            parts.append(f"Status: {status}")
        return " | ".join(parts) if parts else first_line
    else:
        # Mid: first meaningful paragraph + important lines
        if len(important) > 8:
            important = important[:8]
        if not important and lines:
            important = [l.strip() for l in lines[:5] if l.strip()]
        return "\n".join(important) if important else (content[:200] if content else "")


def cmd_tiered_consolidate(args):
    """Promote nodes to mid/long tier based on age. Generate summaries.
    Short → Mid: nodes updated > 7 days ago (or --mid-days)
    Mid → Long: nodes updated > 30 days ago (or --long-days)
    Original content is NEVER deleted. Summary is additive.
    --dry-run: show what would change without modifying
    --force: re-generate summaries even for already-tiered nodes
    """
    db = get_db()
    mid_days = getattr(args, 'mid_days', 7) or 7
    long_days = getattr(args, 'long_days', 30) or 30
    dry_run = getattr(args, 'dry_run', False)
    force = getattr(args, 'force', False)

    ts = now()
    stats = {"short_to_mid": 0, "mid_to_long": 0, "skipped": 0, "already": 0, "capped": 0}

    # Pre-fetch tag sets per node
    node_tag_map = {}
    for r in db.execute("""
        SELECT nt.node_id, t.name FROM node_tags nt
        JOIN tags t ON t.id = nt.tag_id
    """).fetchall():
        node_tag_map.setdefault(r[0], set()).add(r[1])

    # Pre-fetch association counts per node
    assoc_counts = {}
    for r in db.execute("""
        SELECT node_id, COUNT(*) as cnt FROM (
            SELECT source_id as node_id FROM associations
            UNION ALL
            SELECT target_id as node_id FROM associations
        ) GROUP BY node_id
    """).fetchall():
        assoc_counts[r[0]] = r[1]

    nodes = db.execute("SELECT * FROM nodes").fetchall()

    for node in nodes:
        node_tier = node["memory_tier"] if "memory_tier" in node.keys() else "short"
        node_type = node["type"]
        node_tags = node_tag_map.get(node["id"], set())
        node_assocs = assoc_counts.get(node["id"], 0)
        touch = node["touch_count"] if node["touch_count"] else 0

        # Determine tier_cap for this node
        existing_cap = node["tier_cap"] if "tier_cap" in node.keys() else "long"

        tier_cap = _classify_tier_cap(node_type, node_tags, touch, node_assocs)

        # Update tier_cap if changed
        if tier_cap != existing_cap:
            if not dry_run:
                db.execute("UPDATE nodes SET tier_cap = ? WHERE id = ?", (tier_cap, node["id"]))

        # Skip if trauma (cap=short)
        if tier_cap == "short":
            stats["skipped"] += 1
            continue

        # Use last_relevant if available, else updated_at
        ref_date = node["last_relevant"] if node["last_relevant"] else node["updated_at"]
        try:
            age_days = (datetime.now(timezone.utc) - datetime.fromisoformat(ref_date)).days
        except:
            stats["skipped"] += 1
            continue

        target_tier = "short"
        if age_days >= long_days:
            target_tier = "long"
        elif age_days >= mid_days:
            target_tier = "mid"

        # Apply tier cap: never promote beyond the cap
        tier_order = {"short": 0, "mid": 1, "long": 2}
        if tier_order.get(target_tier, 0) > tier_order.get(tier_cap, 2):
            target_tier = tier_cap
            stats["capped"] += 1

        # Check if promotion needed
        current_level = tier_order.get(node_tier, 0)
        target_level = tier_order.get(target_tier, 0)

        if target_level <= current_level and not force:
            stats["already"] += 1
            continue

        if target_tier == "short":
            stats["already"] += 1
            continue

        # Generate summary
        summary = generate_summary(node["content"], node["props"], node_type, target_tier)

        if dry_run:
            print(f"  {'→' if target_level > current_level else '='} {node['name']} [{node_tier}→{target_tier}] age={age_days}d")
            print(f"    summary: {summary[:100]}{'...' if len(summary) > 100 else ''}")
        else:
            db.execute(
                "UPDATE nodes SET memory_tier = ?, summary = ?, updated_at = ? WHERE id = ?",
                (target_tier, summary, ts, node["id"])
            )

        if target_tier == "mid":
            stats["short_to_mid"] += 1
        elif target_tier == "long":
            stats["mid_to_long"] += 1

    if not dry_run:
        db.commit()

    mode = "DRY RUN" if dry_run else "DONE"
    print(f"\n🧠 Tiered Consolidation ({mode}):")
    print(f"  Short → Mid: {stats['short_to_mid']}")
    print(f"  Mid → Long:  {stats['mid_to_long']}")
    print(f"  Trauma (pinned short): {stats['skipped']}")
    print(f"  Capped at mid:         {stats['capped']}")
    print(f"  Unchanged:             {stats['already']}")
    print(f"\n  Thresholds: mid={mid_days}d, long={long_days}d")
    print(f"  Cap rules: trauma=short (lessons/fixes/rules), important=mid (persons/projects/decisions/touch≥3/assocs≥5)")
    print(f"  ⚠️  Original content preserved — summaries are additive")


