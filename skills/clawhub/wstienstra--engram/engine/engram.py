def hop_recall(db, source_ids, max_depth=2, limit=30):
    """Retrieve nodes reachable via pre-computed hop paths from source_ids."""
    ensure_hop_table(db)
    
    # Check if hop table is populated
    count = db.execute("SELECT COUNT(*) FROM hop_paths").fetchone()[0]
    if count == 0:
        return []  # Not built yet, caller should fall back
    
    if not source_ids:
        return []
    
    placeholders = ",".join("?" * len(source_ids))
    rows = db.execute(f"""
        SELECT DISTINCT h.target_id, h.distance, h.max_weight, h.via_ids, n.*
        FROM hop_paths h
        JOIN nodes n ON n.id = h.target_id
        WHERE h.source_id IN ({placeholders})
        AND h.distance <= ?
        AND h.target_id NOT IN ({placeholders})
        ORDER BY h.distance ASC, h.max_weight ASC
        LIMIT ?
    """, source_ids + [max_depth] + source_ids + [limit]).fetchall()
    
    return rows


# ── REFLECTIVE RETRIEVAL ──────────────────────────────────────────────

def reflective_reformulate(db, original_query, original_results, seen_ids):
    """When initial recall quality is low, auto-reformulate and retry.
    Returns additional results or empty list."""
    
    if not original_query or len(original_query.strip()) < 2:
        return []
    
    words = original_query.split()
    
    # Strategy 1: Try individual significant words (often the query is too specific as AND)
    generic_words = set(get_config(db, "generic_words"))
    significant = [w for w in words if w.lower() not in generic_words and len(w) >= 3]
    
    extra_results = []
    
    # Strategy 2: Fuzzy name match (catches typos, partial names)
    # Threshold 0.55 = must be a plausible match, not random noise
    fuzzy_hits = fuzzy_find_node(db, original_query, limit=5, threshold=0.55)
    for node, score in fuzzy_hits:
        if node["id"] not in seen_ids:
            seen_ids.add(node["id"])
            extra_results.append(("reformulated_fuzzy", node))
    
    # Strategy 3: Try each significant word individually via FTS
    # Only if query words are real words that might exist in the DB
    if len(significant) >= 2:
        for word in significant[:3]:
            if len(word) < 4:  # Skip short fragments
                continue
            try:
                hits = db.execute("""
                    SELECT n.* FROM nodes n
                    JOIN nodes_fts f ON n.id = f.rowid
                    WHERE nodes_fts MATCH ?
                    ORDER BY rank LIMIT 3
                """, (f'"{word}"*',)).fetchall()
                for node in hits:
                    if node["id"] not in seen_ids:
                        seen_ids.add(node["id"])
                        extra_results.append(("reformulated_word", node))
            except:
                pass
    
    # Strategy 4: Props-based search (email, url, domain fragments)
    if '@' in original_query or '.' in original_query:
        props_hits = db.execute("""
            SELECT * FROM nodes WHERE props LIKE ? COLLATE NOCASE
            ORDER BY updated_at DESC LIMIT 5
        """, (f"%{original_query}%",)).fetchall()
        for node in props_hits:
            if node["id"] not in seen_ids:
                seen_ids.add(node["id"])
                extra_results.append(("reformulated_props", node))
    
    return extra_results


def cmd_hot(args):
    """Show or rebuild hot nodes cache — most accessed/linked nodes for fast recall."""
    db = get_db()
    ensure_dynamics_columns(db)
    
    # Create hot cache table
    db.execute("""CREATE TABLE IF NOT EXISTS hot_cache (
        node_id INTEGER PRIMARY KEY,
        name TEXT, type TEXT, score REAL,
        summary TEXT, updated_at TEXT
    )""")
    
    if args.rebuild:
        db.execute("DELETE FROM hot_cache")
        nodes = db.execute("""
            SELECT n.id, n.name, n.type, n.content,
                   COALESCE(n.touch_count, 0) as tc,
                   (SELECT COUNT(*) FROM associations a WHERE a.source_id = n.id OR a.target_id = n.id) as links
            FROM nodes n
            ORDER BY (COALESCE(n.touch_count, 0) * 2 + links) DESC
            LIMIT ?
        """, (args.limit,)).fetchall()
        
        ts = now()
        for n in nodes:
            score = n["tc"] * 2 + n["links"]
            summary = n["content"][:200] if n["content"] else n["name"]
            db.execute("INSERT OR REPLACE INTO hot_cache VALUES (?,?,?,?,?,?)",
                       (n["id"], n["name"], n["type"], score, summary, ts))
        db.commit()
        print(f"🔥 Rebuilt hot cache: {len(nodes)} nodes")
    
    # Display
    cached = db.execute("SELECT * FROM hot_cache ORDER BY score DESC").fetchall()
