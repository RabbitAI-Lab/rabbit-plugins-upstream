def _lexical_grounding(db, query, nodes, trusted=False):
    """Absolute confidence floor helper. RRF fusion rank and embedding cosine
    can both look "confident" for a query the engram has nothing on: generic
    words still rank *something* via FTS (a single coincidental word like
    "password" or "planning" turns up in dozens of unrelated nodes), and
    this embedding model returns 0.8+ cosine for nearly everything, so
    neither signal discriminates real relevance from noise on its own.

    Require a candidate whose name/content/props contains MOST of the
    query's distinctive (non-generic, len>=4) words, not just any one or
    two of them. Two generic-ish infra words like "admin"+"password"
    co-occur in plenty of unrelated credential nodes — that's not evidence
    the query's actual subject (e.g. "kubernetes") is in the engram. A
    real match should account for the bulk of what's distinctive about the
    query, not a coincidental fraction. Single-distinctive-word queries
    (e.g. "kestrel") fall back to requiring just that one word, since
    there's nothing more specific to demand. `trusted=True` short-circuits
    this (used when a stricter upstream signal, e.g. the hub-entity name
    pin, already established genuine relevance)."""
    if trusted:
        return True
    import re as _re
    import math as _math
    generic = set(get_config(db, "generic_words"))
    q_words = {w.lower() for w in _re.findall(r"[A-Za-z][A-Za-z0-9_-]{2,}", query or "")
               if w.lower() not in generic and len(w) >= 4}
    if not q_words:
        return True
    need = 1 if len(q_words) <= 1 else min(3, max(2, _math.ceil(0.6 * len(q_words))))
    for node in nodes:
        if isinstance(node, dict):
            get = node.get
        else:
            keys = node.keys()
            get = lambda k, d=None, _n=node, _keys=keys: _n[k] if k in _keys else d
        blob = " ".join(str(get(k, "") or "") for k in ("name", "content", "props")).lower()
        hits = sum(1 for w in q_words if w in blob)
        if hits >= need:
            return True
    return False


_RRF_TYPE_PRIOR = {
    'rule': 0.02, 'policy': 0.02, 'decision': 0.015,
    'knowledge': 0.015, 'workflow': 0.01,
}


def _type_prior(node_type):
    """Tiny post-fusion nudge for knowledge-rich types — capped well below
    a single RRF channel's rank-1 contribution (1/61 ~= 0.0164)."""
    return _RRF_TYPE_PRIOR.get((node_type or '').lower(), 0.0)


def _recency_tiebreak(node):
    """Tiny recency nudge (0 to 0.005) — only meant to break RRF ties
    between otherwise-equal fused scores, never to out-rank a real gap."""
    try:
        get = node.get if isinstance(node, dict) else node.__getitem__
        lr = get("last_relevant") or get("updated_at")
        age_days = (datetime.now(timezone.utc) - datetime.fromisoformat(lr)).days
        return max(0.0, 1.0 - min(age_days, 365) / 365.0) * 0.005
    except Exception:
        return 0.0


