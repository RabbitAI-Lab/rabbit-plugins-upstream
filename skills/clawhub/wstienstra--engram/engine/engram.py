def check_contradictions(db, name, new_content, new_props_str=None):
    """Check if new content/props contradict existing data for same or similar entities.
    Returns list of warning strings (empty = no contradictions found).
    """
    warnings = []
    if not new_content:
        return warnings
    
    new_props = {}
    if new_props_str:
        try:
            new_props = json.loads(new_props_str) if isinstance(new_props_str, str) else new_props_str
        except:
            pass
    
    # Find existing nodes with similar names
    similar = db.execute(
        "SELECT id, name, content, props FROM nodes WHERE name LIKE ? COLLATE NOCASE AND name != ? LIMIT 5",
        (f"%{name.split()[0]}%", name)
    ).fetchall()
    
    # Check props contradictions (same key, different value)
    for node in similar:
        old_props = {}
        try:
            old_props = json.loads(node["props"]) if node["props"] else {}
        except:
            pass
        
        for key in new_props:
            if key in old_props and str(new_props[key]).lower() != str(old_props[key]).lower():
                # Skip status fields (those change legitimately)
                if key in ('status', 'updated_at', 'last_seen', 'touch_count'):
                    continue
                warnings.append(
                    f"⚡ CONFLICT: '{name}' has {key}='{new_props[key]}' but '{node['name']}' has {key}='{old_props[key]}'"
                )
    
    return warnings


def _validate_node_name(name: str) -> tuple[bool, str]:
    """
    Validate a node name before storing. Returns (is_valid, reason).
    Rejects junk names: pure numbers, semver strings, npm artifact names.
    """
    import re as _re
    if not name or not name.strip():
        return False, "Name is empty"
    n = name.strip()
    # Pure number
    if _re.match(r'^\d+$', n):
        return False, f"Rejected: pure number '{n}'"
    # Semver with artifact suffix: "1 (1.0.1...istanbul)", "3 (3.0.0...test)"
    if _re.match(r'^\d+\s*\([\d\.\-alpha]+\.{0,3}(istanbul|test|build|coverage)\)', n, _re.I):
        return False, f"Rejected: semver artifact '{n}'"
    # Version tuple: "1 (1.10)", "0 (0.4.10)"
    if _re.match(r'^\d+\s*\(\d+\.\d+[\.\d]*\)$', n):
        return False, f"Rejected: version tuple '{n}'"
    # Very short nonsense: 1-3 chars, no vowels, all caps
    if len(n) <= 3 and n.isupper() and not any(c in 'AEIOU' for c in n):
        return False, f"Rejected: short nonsense '{n}'"
    # Pure alphanumeric version string: "2X", "3X"
    if _re.match(r'^\d+[A-Z]$', n):
        return False, f"Rejected: numeric+letter '{n}'"
    return True, "OK"


def cmd_store(args):
    db = get_db()
    ts = now()

    # Validate node name — reject junk before storing
    valid, reason = _validate_node_name(args.name)
    if not valid:
        print(f"❌ {reason} — skipping store")
        sys.exit(1)

    # Check if node exists (case-insensitive to prevent casing duplicates)
    existing = db.execute("SELECT id, name FROM nodes WHERE LOWER(name) = LOWER(?)", (args.name,)).fetchone()
    if existing:
        print(f"⚠️  Node '{existing['name']}' already exists (id={existing['id']}). Use 'update' to modify.")
        sys.exit(1)
    
