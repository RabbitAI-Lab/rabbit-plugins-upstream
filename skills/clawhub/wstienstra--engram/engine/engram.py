# ── IDF bars and corpus size ────────────────────────────────────────────────
# IDF is measured in nats, and nats do not survive a change of corpus size. "Total
# IDF >= 9.0" means "a word in roughly 2 of 19,359 nodes" — but the largest IDF any
# word can have on a 28-node database is log(28) = 3.3, so on a small graph the bar
# is unreachable and the channel it guards goes silent without saying so. Found by
# the CI fixture: one name-lookup case that passed before the bar existed started
# failing, and the cause was arithmetic, not ranking.
#
# Every graph starts small, so the bars are held as a FRACTION of log(corpus size).
# The fractions are the calibrated numbers divided by log(IDF_CALIBRATION_CORPUS), so
# on the graph they were measured on they reproduce 9.0 and 11.0 to the last digit,
# and they scale in the right direction on any other.
IDF_CALIBRATION_CORPUS = 19359   # node count the bars below were measured on


def _idf_bar(calibrated_bar, total_nodes):
    """One IDF bar, rescaled from the corpus it was calibrated on to this one."""
    import math as _math
    return calibrated_bar * (_math.log(max(total_nodes or 0, 2))
                             / _math.log(max(IDF_CALIBRATION_CORPUS, 2)))


