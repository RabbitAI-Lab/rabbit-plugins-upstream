#!/usr/bin/env python3
"""
Engram Auto-Maintenance Script
Runs weekly (Sunday 03:00) via cron.

Detects and auto-fixes known problems:
1. Junk nodes (version strings, numeric names, npm artifact names)
2. Type casing inconsistency (ORGANIZATION → organization)
3. Stale embeddings (nodes changed since last indexed)
4. Orphan nodes → auto-link by shared tags
5. Duplicate detection (logs for manual review, does NOT auto-merge)
6. DB integrity check
7. Rebuilds hot-node cache

Does NOT auto-merge duplicates — logs them for the owner to review.
Does NOT delete nodes with associations — only confirmed junk orphans.

Usage:
    python3 scripts/engram-maintenance.py          # full run
    python3 scripts/engram-maintenance.py --dry-run # preview only
    python3 scripts/engram-maintenance.py --check   # health check only, no fixes
"""

