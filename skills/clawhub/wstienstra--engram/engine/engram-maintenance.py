# Patterns that identify junk nodes (npm/semver artifacts)
JUNK_PATTERNS = [
    r'^\d+$',                           # pure number: "0", "1", "3"
    r'^\d+ \(\d+\.\d+.*\)$',           # "1 (1.0.1...istanbul)"
    r'^\d+X$',                          # "2X"
    r'^[A-Z][a-z]{1,3}$',              # "Izs", "Mple" (3-4 char nonsense)
    r'^\d+\.\d+\.\d+.*istanbul',        # semver with istanbul
    r'^\d+\.\d+\.\d+.*test',           # semver with test
    r'^\d+ \(\d+\.\d+\)',              # "1 (1.10)" etc
]

def is_junk(name):
    for pat in JUNK_PATTERNS:
        if re.match(pat, name):
            return True
    return False

def run_engram(args, capture=True):
    cmd = [sys.executable, ENGRAM] + args
    if capture:
        result = subprocess.run(cmd, capture_output=True, text=True, cwd=WORKSPACE)
        return result.stdout + result.stderr
    else:
        subprocess.run(cmd, cwd=WORKSPACE)

def log_to_engram(message, reason):
    run_engram(['log', message, '--reason', reason])

DUPE_COS = 0.97   # cosine floor for a near-duplicate pair
DUPE_JAC = 0.6    # name-token Jaccard floor for the same pair — the second, independent signal


def _norm_name(s):
    import re
    return re.sub(r'\s+', ' ', re.sub(r'[^a-z0-9]+', ' ', (s or '').lower())).strip()


def _duplicate_groups(db):
    """Duplicate groups worth a human's attention. Two signals, no transitive chaining:
    every member must clear both bars against the group's representative, so a chain
    A~B~C never merges A with C unless A~C clears too. Returns [[(id, name, type), ...]].

    Exhaust is excluded by the same rule `engram.archive_verdict` uses, so the count
    means "things a person could usefully merge" rather than "rows that look alike"."""
    import sys as _sys
    from collections import defaultdict
    _sys.path.insert(0, os.path.join(WORKSPACE, 'engram'))
    try:
        from engram import archive_verdict
    except Exception:
        def archive_verdict(name, ntype):
            return (ntype or '') in ('message_sent', 'message_received', 'heartbeat_log',
                                     'project_action', 'session_summary') \
                   or (name or '').startswith('FILE: ')

    rows = [r for r in db.execute("SELECT id, name, type, LENGTH(content) FROM nodes").fetchall()
            if not archive_verdict(r[1], r[2])]
    live = {r[0]: r for r in rows}

    ex = defaultdict(list)
    for r in rows:
        ex[(_norm_name(r[1]), r[2])].append(r)
    groups = [v for v in ex.values() if len(v) > 1]
    claimed = {r[0] for g in groups for r in g}

    try:
        import numpy as np
    except ImportError:
        return groups   # no numpy: exact duplicates only, which is still honest

    erows = [r for r in db.execute("SELECT node_id, embedding FROM embeddings").fetchall()
             if r[0] in live]
    if not erows:
        return groups
    ids = np.array([r[0] for r in erows])
    M = np.vstack([np.frombuffer(r[1], dtype=np.float32) for r in erows])
    M /= (np.linalg.norm(M, axis=1, keepdims=True) + 1e-9)

    stop = {'the', 'a', 'an', 'of', 'to', 'for', 'and', 'in', 'on', 'is', 'it', 'at', 'with'}
    tok = {int(n): {w for w in _norm_name(live[int(n)][1]).split()
                    if w not in stop and len(w) > 1} for n in ids}

    for s in range(0, len(ids), 2000):
        S = M[s:s + 2000] @ M.T
        for li in range(S.shape[0]):
            rep = int(ids[s + li])
            if rep in claimed:
                continue
            members = [live[rep]]
            for j in np.nonzero(S[li] >= DUPE_COS)[0]:
                other = int(ids[j])
                if other == rep or other in claimed:
                    continue
                a, b = tok[rep], tok[other]
                if not (a | b) or len(a & b) / len(a | b) < DUPE_JAC:
                    continue
                # Third guard, same one the L3 merge uses: if the bodies differ by more
                # than 20% in length these are not duplicates, they are two records of
                # different size that happen to be about one subject (84 scheduler ticks,
                # 10 `CRO faq_schema pid=…` actions). Merging them destroys facts, so
                # they do not belong in a report headed "merge these".
                la, lb = sorted(((live[rep][3] or 0), (live[other][3] or 0)))
                if lb and (lb - la) / lb > 0.20:
                    continue
                members.append(live[other])
            if len(members) > 1:
                claimed.update(m[0] for m in members)
                groups.append(members)
    return groups


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--dry-run', action='store_true', help='Preview only, no changes')
    parser.add_argument('--check', action='store_true', help='Health check only')
    args = parser.parse_args()

    dry = args.dry_run or args.check
    mode = "DRY RUN" if args.dry_run else ("CHECK" if args.check else "LIVE")

    print(f"\n{'='*60}")
    print(f"Engram Maintenance — {datetime.now().strftime('%Y-%m-%d %H:%M')} [{mode}]")
    print(f"{'='*60}")

    db = sqlite3.connect(DB_PATH)
    report = []

    # ── 1. Junk node cleanup ──
    print("\n[1] Scanning for junk nodes...")
    junk_nodes = db.execute("""
        SELECT id, name, type FROM nodes
        WHERE id NOT IN (
            SELECT DISTINCT source_id FROM associations
            UNION SELECT DISTINCT target_id FROM associations
        )
    """).fetchall()

    junk_to_delete = [(n[0], n[1], n[2]) for n in junk_nodes if is_junk(n[1])]
    print(f"    Found {len(junk_to_delete)} junk orphan nodes")

    if junk_to_delete and not dry:
        ids = [j[0] for j in junk_to_delete]
        db.execute(f"DELETE FROM nodes WHERE id IN ({','.join('?'*len(ids))})", ids)
        db.execute(f"DELETE FROM embeddings WHERE node_id IN ({','.join('?'*len(ids))})", ids)
        db.execute(f"DELETE FROM node_tags WHERE node_id IN ({','.join('?'*len(ids))})", ids)
        db.commit()
        print(f"    ✅ Deleted {len(ids)} junk nodes")
        report.append(f"Deleted {len(ids)} junk nodes")
    elif junk_to_delete:
        for j in junk_to_delete[:5]:
            print(f"    Would delete: [{j[2]}] {j[1]}")
        if len(junk_to_delete) > 5:
            print(f"    ... and {len(junk_to_delete)-5} more")

    # ── 2. Type casing normalization ──
    print("\n[2] Checking type casing...")
    upper_types = db.execute("""
        SELECT type, COUNT(*) FROM nodes
        WHERE type != LOWER(type)
        GROUP BY type
    """).fetchall()

    if upper_types:
        total = sum(c for _, c in upper_types)
        print(f"    Found {total} nodes with uppercase types: {[t[0] for t in upper_types]}")
        if not dry:
            db.execute("UPDATE nodes SET type = LOWER(type) WHERE type != LOWER(type)")
            db.commit()
            print(f"    ✅ Normalized {total} node types to lowercase")
            report.append(f"Normalized {total} node type casings")
    else:
        print("    ✅ All types lowercase — OK")

    # ── 3. Stale embeddings ──
    print("\n[3] Checking embedding coverage...")
    total_nodes = db.execute("SELECT COUNT(*) FROM nodes").fetchone()[0]
    indexed = db.execute("SELECT COUNT(*) FROM embeddings").fetchone()[0]
    missing = total_nodes - indexed
    print(f"    {indexed}/{total_nodes} nodes indexed ({missing} missing)")

    if missing > 0:
        print(f"    Reindexing {missing} unindexed nodes...")
        if not dry:
            result = run_engram(['embed'])
            print(f"    ✅ Reindex complete")
            report.append(f"Reindexed {missing} nodes")
    else:
        print("    ✅ 100% coverage — OK")

    # ── 4. Auto-link orphans ──
    print("\n[4] Checking orphan nodes...")
    orphan_count = db.execute("""
        SELECT COUNT(*) FROM nodes
        WHERE id NOT IN (
            SELECT DISTINCT source_id FROM associations
            UNION SELECT DISTINCT target_id FROM associations
        )
    """).fetchone()[0]
    pct = orphan_count / max(total_nodes, 1) * 100
    print(f"    {orphan_count} orphans ({pct:.1f}%)")

    if orphan_count > 50 and not dry:
        result = run_engram(['auto-link'])
        linked = 0
        for line in result.split('\n'):
            if 'Auto-linked' in line:
                import re as re2
                m = re2.search(r'(\d+)', line)
                if m:
                    linked = int(m.group(1))
        print(f"    ✅ Auto-linked {linked} orphans")
        if linked:
            report.append(f"Auto-linked {linked} orphan nodes")
    elif orphan_count > 50:
        print(f"    Would run auto-link")

    # ── 5. Duplicate detection (log only, no auto-merge) ──
    # This used to group nodes by the first three words of the name. On a 19k-node graph
    # that reported 293 "duplicate groups" every Sunday since July and was ignored every
    # Sunday since July — correctly, because 132 of them were `lesson` nodes that all begin
    # "Reflection 2026-06-13:" and are entirely different facts (the measurement log).
    # A warning nobody can act on is not a warning. The rule now needs the same two
    # independent signals the L3 merge uses: an identical normalised name+type, or a high
    # embedding cosine AND real name-token overlap. Exhaust nodes (the July `FILE:` dump,
    # sent/received messages, heartbeat logs) are not counted: they are duplicates by
    # design and nobody is going to merge them.
    print("\n[5] Scanning for real duplicates...")
    real_dupes = _duplicate_groups(db)
    print(f"    Found {len(real_dupes)} duplicate groups (exact name+type, or cosine>={DUPE_COS} "
          f"with name overlap>={DUPE_JAC}; exhaust excluded)")
    for g in real_dupes[:10]:
        print(f"      #{g[0][0]} {g[0][1][:60]}  x{len(g)}")
    if len(real_dupes) > 20:
        report.append(f"WARNING: {len(real_dupes)} duplicate groups found — manual review needed (run: engram.py dupes)")

    # ── 6. DB integrity check ──
    print("\n[6] SQLite integrity check...")
    integrity = db.execute("PRAGMA integrity_check").fetchone()[0]
    if integrity == 'ok':
        print("    ✅ DB integrity OK")
    else:
        print(f"    🔴 INTEGRITY ISSUE: {integrity}")
        report.append(f"CRITICAL: DB integrity check failed: {integrity}")

    # ── 7. Rebuild hot cache ──
    print("\n[7] Rebuilding hot node cache...")
    if not dry:
        run_engram(['hot', '--rebuild'])
        print("    ✅ Hot cache rebuilt")
        report.append("Hot cache rebuilt")
    else:
        print("    Would rebuild hot cache")

    # ── 8. Auto-link fresh orphans ──
    print("\n[8] Auto-linking orphan nodes...")
    if not dry:
        out = run_engram(['auto-link', '--limit', '2000'])
        print('    ' + (out.strip().splitlines()[-2] if out.strip() else 'done'))
        report.append("Auto-linked orphans")
    else:
        print("    Would auto-link orphans")

    # ── 9. Rebuild hop paths (deep-recall index) ──
    # Without this the hop table freezes at whatever the graph looked like at
    # the last manual build and deep recall goes blind to everything newer.
    print("\n[9] Rebuilding hop paths...")
    if not dry:
        out = run_engram(['hop-build'])
        print('    ' + (out.strip().splitlines()[-3] if out.strip() else 'done'))
        report.append("Hop paths rebuilt")
    else:
        print("    Would rebuild hop paths")

    # ── Final summary ──
    print(f"\n{'='*60}")
    node_count_after = db.execute("SELECT COUNT(*) FROM nodes").fetchone()[0]
    assoc_count = db.execute("SELECT COUNT(*) FROM associations").fetchone()[0]
    print(f"Final state: {node_count_after} nodes | {assoc_count} associations")

    if report:
        summary = " | ".join(report)
        print(f"\nActions: {summary}")
        if not dry:
            log_to_engram(
                f"Engram auto-maintenance: {summary}",
                "Weekly scheduled maintenance (engram-maintenance.py)"
            )
    else:
        print("\nNo issues found — DB healthy")

    db.close()
    print(f"{'='*60}\n")

if __name__ == '__main__':
    main()
