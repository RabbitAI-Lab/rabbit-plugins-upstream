STOP = {'the','a','an','of','to','for','and','in','on','is','it','at','with','from','by'}
def norm(s): return re.sub(r'\s+', ' ', re.sub(r'[^a-z0-9]+', ' ', (s or '').lower())).strip()
def toks(s): return {w for w in norm(s).split() if w not in STOP and len(w) > 1}


def step_tier(db, apply_):
    rows = db.execute("SELECT id,name,type FROM nodes").fetchall()
    arch = [r[0] for r in rows if B.archive_verdict(r[1], r[2])]
    print(f"[tier] archive {len(arch)} / {len(rows)} nodes ({len(arch)*100/len(rows):.1f}%)")
    by = defaultdict(int)
    for r in rows:
        if B.archive_verdict(r[1], r[2]): by[r[2]] += 1
    for k, v in sorted(by.items(), key=lambda x: -x[1])[:10]: print(f"         {v:6d}  {k}")
    if apply_:
        db.executemany("UPDATE nodes SET tier='archive' WHERE id=?", [(i,) for i in arch])
        db.commit()
        print("[tier] applied")


def _need_numpy(step):
    if np is None:
        print(f"[{step}] needs numpy for the embedding comparison: pip install numpy")
        sys.exit(4)


def _groups(db, cos, jac, review_path=None):
    """Duplicate groups. Two independent signals, no transitive chaining: every member
    must clear BOTH bars against the group's own representative, so A~B~C never merges
    A with C unless A~C also clears. scripts/engram-sleep.py records what happens
    without that guard — distinct daily reflections collapse into one node."""
    # Exhaust is not merged. Measured: merging the whole graph, exhaust included,
    # cost property_lookup 80% -> 60% and the negative class 85% -> 77%, because the merge
    # deletes node ids and rewrites content in an archive nobody reads. Duplicates among
    # sent messages and `FILE:` ingests are duplicates by design. Merge what a person would
    # merge: the knowledge nodes.
    rows = [r for r in db.execute(
        "SELECT id,name,type,content,created_at,touch_count FROM nodes").fetchall()
        if not B.archive_verdict(r[1], r[2])]
    info = {r[0]: {'name': r[1], 'type': r[2], 'content': r[3] or '', 'created': r[4],
                   'touch': r[5] or 0} for r in rows}
    ex = defaultdict(list)
    for r in rows: ex[(norm(r[1]), r[2])].append(r[0])
    exact = [sorted(v) for v in ex.values() if len(v) > 1]

    erows = [r for r in db.execute("SELECT node_id,embedding FROM embeddings").fetchall()
             if r[0] in info]
    if not erows:
        # No vectors: report the exact name+type duplicates, which need no embedding,
        # and say why the near-duplicate pass found nothing. Silence here would read
        # as "no duplicates" on a database that was simply never indexed.
        print("[merge] no embeddings in this database — exact name+type matches only "
              "(run `embed` first for the near-duplicate pass)")
        return exact, [], [], info
    ids = [r[0] for r in erows]
    idx = {n: i for i, n in enumerate([r[0] for r in erows])}
    M = np.vstack([np.frombuffer(r[1], dtype=np.float32) for r in erows])
    M /= (np.linalg.norm(M, axis=1, keepdims=True) + 1e-9)
    allids = np.array([r[0] for r in erows])
    tk = {n: toks(info[n]['name']) for n in ids}

    claimed = set(i for g in exact for i in g)
    near, review = [], []
    order = sorted(ids, key=lambda n: info[n]['created'])
    sims = {}
    for s in range(0, len(allids), 2000):
        S = M[s:s+2000] @ M.T
        for li in range(S.shape[0]):
            gi = int(allids[s+li])
            if gi not in info: continue
            js = np.nonzero(S[li] >= cos)[0]
            sims[gi] = {int(allids[j]): float(S[li][j]) for j in js if int(allids[j]) != gi}

    for rep in order:
        if rep in claimed or rep not in sims: continue
        A, members = tk.get(rep, set()), [rep]
        for other, sc in sorted(sims[rep].items(), key=lambda x: -x[1]):
            if other in claimed or other not in info: continue
            Bt = tk.get(other, set())
            if not (A | Bt) or len(A & Bt) / len(A | Bt) < jac: continue
            ca, cb = info[rep]['content'], info[other]['content']
            lo, hi = sorted((len(ca), len(cb)))
            if hi and (hi - lo) / hi > 0.20:
                review.append((rep, other, round(sc, 4), len(ca), len(cb)))
                continue      # content differs >20% — a human decides, not this script
            members.append(other)
        if len(members) > 1:
            claimed.update(members)
            near.append(sorted(members))
    if review_path:
        with open(review_path, 'w') as f:
            f.write("# Ambiguous duplicate pairs, NOT merged\n\n")
            f.write(f"cosine >= {cos}, name-token Jaccard >= {jac}, but content length differs\n"
                    f">20% — merging would drop text. {len(review)} pairs, newest first.\n\n")
            f.write("| cosine | keep? | A | len | B | len |\n|---|---|---|---|---|---|\n")
            for a, b, sc, la, lb in sorted(review, key=lambda x: -x[2])[:400]:
                f.write(f"| {sc} | ? | #{a} {info[a]['name'][:58]} | {la} | "
                        f"#{b} {info[b]['name'][:58]} | {lb} |\n")
    return exact, near, review, info


def step_merge(db, apply_, cos, jac, review_path):
    _need_numpy('merge')
    exact, near, review, info = _groups(db, cos, jac, review_path)
    print(f"[merge] exact groups {len(exact)} ({sum(len(g) for g in exact)} nodes)")
    print(f"[merge] near  groups {len(near)} ({sum(len(g) for g in near)} nodes), "
          f"cos>={cos} jac>={jac}")
    print(f"[merge] ambiguous pairs held for review: {len(review)} -> {review_path}")
    if not apply_: return
    ts = datetime.now(timezone.utc).isoformat()
    merged = 0
    for g in exact + near:
        keep = min(g, key=lambda n: info[n]['created'])          # oldest survives
        losers = [n for n in g if n != keep]
        best = max(g, key=lambda n: len(info[n]['content']))     # longest content wins
        if best != keep:
            db.execute("UPDATE nodes SET content=? WHERE id=?", (info[best]['content'], keep))
        tot = sum(info[n]['touch'] for n in g)
        db.execute("UPDATE nodes SET touch_count=?, updated_at=? WHERE id=?", (tot, ts, keep))
        for l in losers:
            # union of associations: repoint, then drop self-edges and collisions
            db.execute("UPDATE OR IGNORE associations SET source_id=? WHERE source_id=?", (keep, l))
            db.execute("UPDATE OR IGNORE associations SET target_id=? WHERE target_id=?", (keep, l))
            db.execute("UPDATE OR IGNORE node_tags SET node_id=? WHERE node_id=?", (keep, l))
            db.execute("DELETE FROM associations WHERE source_id=target_id")
            # Keep the loser's name reachable instead of losing the string — but under
            # `merged_names`, NOT `aliases`. A curated alias is new vocabulary and makes a
            # node pin-eligible (engram.py::_node_alias_list); a merge leftover is only a
            # second spelling of a name the survivor already has. The two spellings measure
            # identically on a 74-case battery, so this picks the one whose meaning is
            # right. props is in nodes_fts either way, so the string stays searchable.
            row = db.execute("SELECT props FROM nodes WHERE id=?", (keep,)).fetchone()
            try: props = json.loads(row[0]) if row[0] else {}
            except Exception: props = {}
            al = props.get('merged_names') or []
            if info[l]['name'] not in al and info[l]['name'] != info[keep]['name']:
                al.append(info[l]['name']); props['merged_names'] = al
                db.execute("UPDATE nodes SET props=? WHERE id=?", (json.dumps(props), keep))
            db.execute("DELETE FROM nodes WHERE id=?", (l,))
            merged += 1
    db.commit()
    print(f"[merge] applied: {merged} nodes folded into {len(exact)+len(near)} survivors")


def step_link(db, apply_, min_sim=0.60, top=2):
    _need_numpy('link')
    orph = [r[0] for r in db.execute(
        "SELECT id FROM nodes n WHERE NOT EXISTS (SELECT 1 FROM associations a "
        "WHERE a.source_id=n.id OR a.target_id=n.id)").fetchall()]
    erows = db.execute("SELECT node_id,embedding FROM embeddings").fetchall()
    if not erows:
        print(f"[link] orphans {len(orph)}, but this database has no embeddings — "
              f"nothing to link by (run `embed` first)")
        return
    allids = np.array([r[0] for r in erows])
    M = np.vstack([np.frombuffer(r[1], dtype=np.float32) for r in erows])
    M /= (np.linalg.norm(M, axis=1, keepdims=True) + 1e-9)
    pos = {int(n): i for i, n in enumerate(allids)}
    # never anchor an orphan to another orphan or to archived exhaust: the edge must
    # attach it to the live graph, or it is decoration.
    try:
        live = {r[0] for r in db.execute(
            "SELECT id FROM nodes WHERE tier!='archive'").fetchall()} - set(orph)
    except sqlite3.OperationalError:
        # No tier column yet: nothing is archived, so every node is a live anchor.
        # A dry run on a database that has never been migrated still gets a count.
        live = {r[0] for r in db.execute("SELECT id FROM nodes").fetchall()} - set(orph)
    livemask = np.array([1.0 if int(n) in live else 0.0 for n in allids], dtype=np.float32)
    ts = datetime.now(timezone.utc).isoformat()
    edges, skipped = [], 0
    cand = [o for o in orph if o in pos]
    for s in range(0, len(cand), 500):
        blk = [pos[o] for o in cand[s:s+500]]
        S = (M[blk] @ M.T) * livemask
        for li, o in enumerate(cand[s:s+500]):
            row = S[li]
            best = np.argpartition(row, -top)[-top:]
            for j in sorted(best, key=lambda j: -row[j]):
                if row[j] >= min_sim: edges.append((o, int(allids[j]), float(row[j])))
                else: skipped += 1
    print(f"[link] orphans {len(orph)}, embedded {len(cand)}, edges proposed {len(edges)}, "
          f"below {min_sim}: {skipped}")
    linked = len({e[0] for e in edges})
    print(f"[link] orphans that would gain an edge: {linked} "
          f"({linked*100/max(len(orph),1):.1f}% of orphans)")
    if apply_:
        db.executemany(
            "INSERT OR IGNORE INTO associations (source_id,target_id,relation,created_at,"
            "weight,strength) VALUES (?,?,'auto-link',?,1,?)",
            [(a, b, ts, round(sc, 4)) for a, b, sc in edges])
        db.commit()
        print("[link] applied")


if __name__ == '__main__':
    ap = argparse.ArgumentParser()
    ap.add_argument('db'); ap.add_argument('steps')
    ap.add_argument('--cos', type=float, default=0.97)
    ap.add_argument('--jac', type=float, default=0.6)
    ap.add_argument('--apply', action='store_true')
    ap.add_argument('--review', default='/tmp/dedup-review.md')
    ap.add_argument('--min-sim', type=float, default=0.60)
    ap.add_argument('--top', type=int, default=2)
    ap.add_argument('--force', action='store_true',
                    help='re-run a step this database already carries a marker for')
    a = ap.parse_args()
    if not os.path.exists(a.db):
        print(f"no such database: {a.db}"); sys.exit(2)
    # A dry run opens the database READ-ONLY. The old version of this script guarded
    # one hardcoded path instead, which protected exactly one machine and silently
    # granted write access everywhere else. `ensure_retrieval_tier` ALTERs the table,
    # so "dry run" and "read-write connection" were never compatible anyway.
    if a.apply:
        db = sqlite3.connect(a.db)
        B.ensure_retrieval_tier(db)
    else:
        db = sqlite3.connect(f"file:{os.path.abspath(a.db)}?mode=ro", uri=True)
    # Once-only guard. `merge` is NOT idempotent — a second pass merges the survivors of
    # the first — and two workers were live on this ticket at the same time. The marker
    # lives in the DB, not on disk, so it travels with the database it describes.
    if a.apply:
        db.execute("CREATE TABLE IF NOT EXISTS config (key TEXT PRIMARY KEY, value TEXT NOT NULL,"
                   " description TEXT DEFAULT '')")
        for st in a.steps.split(','):
            k = f"hygiene_migration.{st}"
            prev = db.execute("SELECT value FROM config WHERE key=?", (k,)).fetchone()
            if prev and not a.force:
                print(f"REFUSING: step '{st}' already applied to this DB at {prev[0]}. "
                      f"Pass --force only if you know why.")
                sys.exit(3)
    for st in a.steps.split(','):
        if st == 'tier': step_tier(db, a.apply)
        elif st == 'merge': step_merge(db, a.apply, a.cos, a.jac, a.review)
        elif st == 'link': step_link(db, a.apply, a.min_sim, a.top)
        else: print("unknown step", st); sys.exit(2)
        if a.apply:
            db.execute("INSERT OR REPLACE INTO config (key,value,description) VALUES (?,?,?)",
                       (f"hygiene_migration.{st}", datetime.now(timezone.utc).isoformat(),
                        "graph hygiene migration marker"))
            db.commit()
    db.close()
