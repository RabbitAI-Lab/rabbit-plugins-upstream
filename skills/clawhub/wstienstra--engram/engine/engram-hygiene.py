#!/usr/bin/env python3
"""Graph hygiene migration. Each step is separately runnable and separately reversible.

  tier     mark exhaust nodes tier='archive' (nothing deleted; `recall --all` still sees them)
  merge    merge duplicate nodes: union associations, sum touch_count, keep longest content
  link     give orphans an edge to their nearest embedding neighbour (relation auto-link)

usage: engram-hygiene.py <db> <step>[,<step>…] [--cos 0.97] [--jac 0.6] [--apply] [--review out.md]

Without --apply it only counts, on a read-only connection. Every write runs in one
transaction per step, and each applied step leaves a marker in `config` so a
non-idempotent step (merge) cannot run twice by accident.
"""

