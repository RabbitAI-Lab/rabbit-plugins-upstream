'use strict';
function badge(res) {
  const color = res.grade === 'A' ? 'brightgreen' : res.grade === 'B' ? 'green' : res.grade === 'C' ? 'yellow' : res.grade === 'D' ? 'orange' : 'red';
  const label = encodeURIComponent('skill-audit ' + res.grade + ' (' + res.score + ')');
  return '![skill-audit](https://img.shields.io/badge/' + label + '-' + color + ')';
}
function toMarkdown(res) {
  const lines = [];
  lines.push('# Skill audit report: ' + res.skill.name);
  lines.push('');
  lines.push(badge(res));
  lines.push('');
  lines.push('- **Score**: ' + res.score + '/100 (grade ' + res.grade + ')');
  lines.push('- **Description**: ' + (res.skill.description || '(none)'));
  lines.push('- **Stats**: ' + res.stats.size + ' bytes, ' + res.stats.headings + ' sections, ' + res.stats.codeBlocks + ' code blocks');
  lines.push('');
  lines.push('## Findings');
  for (const f of res.findings) lines.push('- ' + (f.pass ? 'PASS' : '**FAIL**') + ' [' + f.id + ' ' + f.category + '] ' + f.msg);
  if (res.stats.urls.length) { lines.push(''); lines.push('## URLs referenced'); for (const u of res.stats.urls) lines.push('- ' + u); }
  lines.push('');
  lines.push('_Generated ' + res.generatedAt + ' by skill-audit_');
  return lines.join('\n');
}
function toHtml(res) {
  const ring = Math.round(2 * Math.PI * 45);
  const dash = Math.round(ring * res.score / 100);
  const items = res.findings.map(f => '<li class="' + (f.pass ? 'pass' : 'fail') + '"><span class="tag">' + f.id + '</span> ' + esc(f.msg) + ' <em>' + f.category + '</em></li>').join('\n');
  const urls = res.stats.urls.map(u => '<li>' + esc(u) + '</li>').join('');
  return '<!doctype html><html><head><meta charset="utf-8"><title>skill-audit: ' + esc(res.skill.name) + '</title><style>' +
    'body{font-family:system-ui,sans-serif;background:#0f1420;color:#e6e9f0;max-width:720px;margin:40px auto;padding:0 16px}' +
    '.card{background:#1a2233;border-radius:14px;padding:24px;margin:16px 0}' +
    'h1{font-size:1.4rem}' +
    '.score{display:flex;align-items:center;gap:20px}' +
    'svg{transform:rotate(-90deg)}' +
    '.grade{font-size:3rem;font-weight:700}' +
    'ul{list-style:none;padding:0}li{padding:6px 10px;border-radius:8px;margin:4px 0;background:#232d42}' +
    'li.pass:before{content:"✔ ";color:#4ade80}li.fail:before{content:"✘ ";color:#f87171}li.fail{background:#3a2333}' +
    '.tag{font-family:monospace;background:#0f1420;padding:2px 6px;border-radius:6px;font-size:.8rem}' +
    'em{color:#8b93a7;font-size:.8rem;float:right}' +
    '</style></head><body>' +
    '<div class="card"><h1>' + esc(res.skill.name) + '</h1><div class="score">' +
    '<svg width="110" height="110"><circle cx="55" cy="55" r="45" stroke="#2a3550" stroke-width="10" fill="none"/>' +
    '<circle cx="55" cy="55" r="45" stroke="#4ade80" stroke-width="10" fill="none" stroke-dasharray="' + dash + ' ' + ring + '"/></svg>' +
    '<div><div class="grade">' + res.grade + '</div><div>' + res.score + '/100</div></div></div>' +
    '<p>' + esc(res.skill.description || '') + '</p></div>' +
    '<div class="card"><h2>Findings</h2><ul>' + items + '</ul></div>' +
    (urls ? '<div class="card"><h2>URLs referenced</h2><ul>' + urls + '</ul></div>' : '') +
    '<p>Generated by <strong>skill-audit</strong> · ' + res.generatedAt + '</p></body></html>';
}
function esc(s) { return String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;'); }
module.exports = { toMarkdown, toHtml, badge };